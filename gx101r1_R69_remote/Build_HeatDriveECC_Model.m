function model_path = Build_HeatDriveECC_Model(options)
% Build the Simulink full-cycle model for the 1D51 heat-driven ECC.

    if nargin < 1 || isempty(options)
        options = Build_HeatDriveECC_Article_Defaults();
    end

    model_name = options.model_name;
    model_path = options.model_path;
    if bdIsLoaded(model_name)
        set_param(model_name, 'Dirty', 'off');
        close_system(model_name, 0);
    end
    if exist(model_path, 'file')
        delete(model_path);
    end

    new_system(model_name);
    load_system(model_name);
    set_param(model_name, ...
        'StopTime', sprintf('%.15g', options.simulation.stop_time_s), ...
        'Solver', options.simulation.solver, ...
        'FixedStep', sprintf('%.15g', options.simulation.fixed_step_s), ...
        'ReturnWorkspaceOutputs', 'on', ...
        'SaveOutput', 'on', ...
        'OutputSaveName', 'yout');

    add_block('simulink/Sources/Clock', [model_name, '/SimulinkTime'], ...
        'Position', [70 95 100 125]);
    add_block('simulink/User-Defined Functions/Interpreted MATLAB Function', ...
        [model_name, '/HeatDriveECC_1D51_FullCycleCore'], ...
        'MATLABFcn', 'HeatDriveECC_SimulinkCoreStep', ...
        'OutputDimensions', '773', ...
        'Position', [180 55 390 165]);
    add_block('simulink/Sinks/To Workspace', [model_name, '/heatdrive_ecc_yout'], ...
        'VariableName', 'heatdrive_ecc_yout', ...
        'SaveFormat', 'Structure With Time', ...
        'Position', [500 78 620 132]);
    add_block('simulink/Sinks/Out1', [model_name, '/yout_vec'], ...
        'Position', [500 150 530 170]);
    add_line(model_name, 'SimulinkTime/1', 'HeatDriveECC_1D51_FullCycleCore/1', ...
        'autorouting', 'on');
    add_line(model_name, 'HeatDriveECC_1D51_FullCycleCore/1', 'heatdrive_ecc_yout/1', ...
        'autorouting', 'on');
    add_line(model_name, 'HeatDriveECC_1D51_FullCycleCore/1', 'yout_vec/1', ...
        'autorouting', 'on');

    save_system(model_name, model_path);
end

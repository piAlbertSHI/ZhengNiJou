function Integrate_HeatDriveECC_Constitutive21_Interface(model_name, options, save_changes)
% Add the coupled 21-node constitutive heat-source interface to the main SLX.

    if nargin < 1 || isempty(model_name)
        model_name = 'heatdrive_ecc_coupled_se21';
    end
    if nargin < 2 || isempty(options)
        options = Build_HeatDriveECC_EighthRound_Defaults();
    end
    if nargin < 3
        save_changes = true;
    end
    if options.node_count ~= 21
        error('HeatDriveECC:ConstitutiveInterfaceNodeCount', ...
            'The constitutive Simulink interface expects 21 nodes.');
    end

    assign_exchange_workspace(options);
    assign_article_pipe_workspace(options);
    assign_constitutive_workspace(options);
    load_system(model_name);
    configure_shex_boundary(model_name);
    configure_sma_valve_manifolds(model_name, options);
    configure_se_shared_regenerator_fluid_path(model_name, options);
    configure_sma_hydraulic_area(model_name, options);
    configure_article_component_pipe_geometry(model_name, 'SMA', 'sma');
    configure_article_component_pipe_geometry(model_name, 'SE', 'se');
    configure_hhex_dual_channel_UA(model_name);
    configure_valve_minimum_opening(model_name, options);
    configure_valve_command_blocks(model_name);
    configure_sma_pressure_bias_command(model_name);
    configure_sma_flow_target_command(model_name);
    configure_sma_pressure_feedback_enable(model_name);
    configure_sma_pressure_integrator_reset(model_name);
    configure_se_pressure_bias_command(model_name);
    configure_se_flow_target_command(model_name);
    configure_se_pressure_feedback_enable(model_name);
    configure_se_route_pressure_integrators(model_name);
    configure_independent_pressure_saturation_limits(model_name);
    expose_component(model_name, 'SMA');
    expose_component(model_name, 'SE');
    configure_component_solid_state(model_name, 'SMA', 'sma');
    configure_component_solid_state(model_name, 'SE', 'se');
    configure_component_solid_axial_conduction(model_name, 'SMA', ...
        'sma', options);
    configure_component_solid_axial_conduction(model_name, 'SE', ...
        'se', options);
    configure_component_pipe_initial_temperature(model_name, 'SMA', ...
        'sma_hold_fluid_T_init', 'sma_cooldown_fluid_T_init');
    configure_component_pipe_initial_temperature(model_name, 'SE', ...
        'se_hold_fluid_T_init', 'se_cooldown_fluid_T_init');
    configure_sma_dynamic_thermal_gates(model_name);
    configure_se_dynamic_thermal_gates(model_name);
    add_top_level_constitutive_loop(model_name, options);
    add_top_level_eighth_round_output_loop(model_name, options);
    add_sma_stage13_observability(model_name);
    configure_se_route_probe_names(model_name);
    add_pressure_command_observability(model_name);
    add_sma_internal_pipe_observability(model_name);
    add_shex_hot_pipe_pressure_observability(model_name);
    add_component_pipe_heat_flow_observability(model_name, 'SMA');
    add_component_pipe_heat_flow_observability(model_name, 'SE');
    add_hhex_sma_branch_observability(model_name);
    apply_sma_stage13_visual_layout(model_name);
    make_to_workspace_names_unique(model_name);
    add_or_update_note(model_name);
    if save_changes
        set_param(model_name, 'SimulationCommand', 'update');
        save_system(model_name);
    end
end

function configure_se_route_probe_names(model_name)
% Remove the inherited SMA labels from the four physical SE route probes.
    suffixes = { ...
        'hold_inlet_fluid_temp_out', ...
        'hold_outlet_fluid_temp_out', ...
        'cooldown_inlet_fluid_temp_out', ...
        'cooldown_outlet_fluid_temp_out'};
    for idx = 1:numel(suffixes)
        old_name = ['ToWorkspace_sma_' suffixes{idx}];
        new_name = ['ToWorkspace_se_' suffixes{idx}];
        old_path = [model_name '/' old_name];
        new_path = [model_name '/' new_name];
        if exist_block(old_path)
            set_param(old_path, 'Name', new_name);
        elseif ~exist_block(new_path)
            error('HeatDriveECC:MissingSERouteTemperatureProbe', ...
                'Missing physical SE route probe sink: %s.', new_name);
        end
        set_param(new_path, 'VariableName', ['se_' suffixes{idx}]);
    end
end

function configure_sma_valve_manifolds(model_name, options)
% Retain Qian's connecting-pipe fluid inventory at both pump manifolds.

    v1 = [model_name '/SMA_V1_SHEX_to_pump'];
    v2 = [model_name '/SMA_V2_HHEX_to_pump'];
    pressure_source = [model_name '/SMA Pressure Source (TL)'];
    inlet_plenum = [model_name '/SMA_PumpInletConnectingPipeVolume'];
    old_junction = [model_name '/SMA_TJ_SourceSelect'];
    if ~(exist_block(v1) && exist_block(v2) && exist_block(pressure_source))
        error('HeatDriveECC:MissingSMASourceSelectBlocks', ...
            'SMA V1/V2 or the SMA pressure source is missing.');
    end
    ensure_sma_pump_manifold_volume(inlet_plenum, options, ...
        [-1715 365 -1625 455]);

    if exist_block(old_junction)
        ports = get_param(old_junction, 'PortHandles');
        kinds = {'LConn', 'RConn'};
        line_handles = zeros(0, 1);
        for kind_idx = 1:numel(kinds)
            kind = kinds{kind_idx};
            for port_idx = 1:numel(ports.(kind))
                line_handle = get_param(ports.(kind)(port_idx), 'Line');
                if isnumeric(line_handle) && line_handle ~= -1
                    line_handles(end + 1, 1) = line_handle; %#ok<AGROW>
                end
            end
        end
        line_handles = unique(line_handles);
        for idx = 1:numel(line_handles)
            try
                delete_line(line_handles(idx));
            catch
            end
        end
        delete_block(old_junction);
    end

    source_sensor_names = { ...
        'SMAStage1V1PumpSideFluidTempSensor', ...
        'SMAStage3V2PumpSideFluidTempSensor'};
    source_ports = [get_port(v1, 'RConn', 1), ...
        get_port(v2, 'RConn', 1), get_port(pressure_source, 'LConn', 1), ...
        get_port(inlet_plenum, 'LConn', 1), ...
        get_port(inlet_plenum, 'RConn', 1)];
    for sensor_idx = 1:numel(source_sensor_names)
        sensor_path = [model_name '/' source_sensor_names{sensor_idx}];
        if exist_block(sensor_path)
            source_ports(end + 1) = get_port(sensor_path, 'LConn', 1); %#ok<AGROW>
        end
    end
    disconnect_conserving_ports(source_ports);
    safe_add_line_handle(model_name, get_port(v1, 'RConn', 1), ...
        get_port(inlet_plenum, 'LConn', 1));
    safe_add_line_handle(model_name, get_port(inlet_plenum, 'LConn', 1), ...
        get_port(v2, 'RConn', 1));
    for sensor_idx = 1:numel(source_sensor_names)
        sensor_path = [model_name '/' source_sensor_names{sensor_idx}];
        if exist_block(sensor_path)
            safe_add_line_handle(model_name, get_port(inlet_plenum, 'LConn', 1), ...
                get_port(sensor_path, 'LConn', 1));
        end
    end
    safe_add_line_handle(model_name, get_port(inlet_plenum, 'RConn', 1), ...
        get_port(pressure_source, 'LConn', 1));

    pump_sensor = [model_name '/FlowSensor_SMA_stage13_loop'];
    v3 = [model_name '/SMA_V3_pump_to_heat_path'];
    v4 = [model_name '/SMA_V4_pump_to_cool_path'];
    outlet_plenum = [model_name '/SMA_PumpOutletConnectingPipeVolume'];
    pump_junction = [model_name '/SMA_TJ_PumpOutlet'];
    if ~(exist_block(pump_sensor) && exist_block(v3) && exist_block(v4))
        error('HeatDriveECC:MissingSMARouteSelectBlocks', ...
            'The SMA pump flow sensor or V3/V4 route valves are missing.');
    end
    remove_tl_junction(pump_junction);
    ensure_sma_pump_manifold_volume(outlet_plenum, options, ...
        [-1255 365 -1165 455]);
    stage1_route_sensor = [model_name '/FlowSensor_SMA_stage1_route'];
    stage3_route_sensor = [model_name '/FlowSensor_SMA_stage3_route'];
    ensure_sma_route_flow_probe(model_name, ...
        'FlowSensor_SMA_stage1_route', 'FlowSensor_SMA_stage1_route_PS', ...
        'ToWorkspace_mass_flow_sma_stage1_route_kgps', ...
        'mass_flow_sma_stage1_route_kgps', ...
        [-1145 235 -1090 290], [-1135 175 -1080 210], ...
        [-1045 175 -760 200]);
    ensure_sma_route_flow_probe(model_name, ...
        'FlowSensor_SMA_stage3_route', 'FlowSensor_SMA_stage3_route_PS', ...
        'ToWorkspace_mass_flow_sma_stage3_route_kgps', ...
        'mass_flow_sma_stage3_route_kgps', ...
        [-1145 535 -1090 590], [-1135 615 -1080 650], ...
        [-1045 615 -760 640]);
    outlet_sensor = [model_name '/SMAStage13PumpOutletFluidTempSensor'];
    outlet_ports = [get_port(pump_sensor, 'RConn', 1), ...
        get_port(v3, 'LConn', 1), get_port(v4, 'LConn', 1), ...
        get_port(stage1_route_sensor, 'LConn', 1), ...
        get_port(stage1_route_sensor, 'RConn', 1), ...
        get_port(stage3_route_sensor, 'LConn', 1), ...
        get_port(stage3_route_sensor, 'RConn', 1), ...
        get_port(outlet_plenum, 'LConn', 1), ...
        get_port(outlet_plenum, 'RConn', 1)];
    if exist_block(outlet_sensor)
        outlet_ports(end + 1) = get_port(outlet_sensor, 'LConn', 1);
    end
    disconnect_conserving_ports(outlet_ports);
    safe_add_line_handle(model_name, get_port(pump_sensor, 'RConn', 1), ...
        get_port(outlet_plenum, 'LConn', 1));
    safe_add_line_handle(model_name, get_port(outlet_plenum, 'RConn', 1), ...
        get_port(stage1_route_sensor, 'LConn', 1));
    safe_add_line_handle(model_name, get_port(stage1_route_sensor, 'RConn', 1), ...
        get_port(v3, 'LConn', 1));
    safe_add_line_handle(model_name, get_port(outlet_plenum, 'RConn', 1), ...
        get_port(stage3_route_sensor, 'LConn', 1));
    safe_add_line_handle(model_name, get_port(stage3_route_sensor, 'RConn', 1), ...
        get_port(v4, 'LConn', 1));
    if exist_block(outlet_sensor)
        safe_add_line_handle(model_name, get_port(outlet_plenum, 'RConn', 1), ...
            get_port(outlet_sensor, 'LConn', 1));
    end
end

function ensure_sma_route_flow_probe(model_name, sensor_name, ps_name, ...
        workspace_name, variable_name, sensor_position, ps_position, ...
        workspace_position)
    sensor = [model_name '/' sensor_name];
    ps = [model_name '/' ps_name];
    workspace = [model_name '/' workspace_name];
    sensor_template = [model_name '/FlowSensor_SMA_stage13_loop'];
    ps_template = [model_name '/FlowSensor_SMA_stage13_loop_PS'];
    workspace_template = [model_name '/ToWorkspace_mass_flow_sma_stage13_kgps'];
    if ~exist_block(sensor)
        add_block(sensor_template, sensor, 'Position', sensor_position);
    end
    if ~exist_block(ps)
        add_block(ps_template, ps, 'Position', ps_position);
    end
    if ~exist_block(workspace)
        add_block(workspace_template, workspace, 'Position', workspace_position);
    end
    set_param(sensor, 'Position', sensor_position);
    set_param(ps, 'Position', ps_position);
    set_param(workspace, 'Position', workspace_position, ...
        'VariableName', variable_name);
    safe_add_line_handle(model_name, get_port(sensor, 'RConn', 2), ...
        get_port(ps, 'LConn', 1));
    safe_add_line_handle(model_name, get_port(ps, 'Outport', 1), ...
        get_port(workspace, 'Inport', 1));
end

function disconnect_conserving_ports(port_handles)
    line_handles = zeros(0, 1);
    for port_idx = 1:numel(port_handles)
        try
            line_handle = get_param(port_handles(port_idx), 'Line');
            if isnumeric(line_handle) && line_handle ~= -1
                line_handles(end + 1, 1) = line_handle; %#ok<AGROW>
            end
        catch
        end
    end
    line_handles = unique(line_handles);
    for line_idx = 1:numel(line_handles)
        try
            delete_line(line_handles(line_idx));
        catch ME
            if ~contains(ME.message, '句柄无效') && ...
                    ~contains(lower(ME.message), 'invalid')
                rethrow(ME);
            end
        end
    end
end

function ensure_sma_pump_manifold_volume(block_path, options, position)
    if ~exist_block(block_path)
        add_block(['fl_lib/Thermal Liquid/Elements/', ...
            'Constant Volume Chamber (TL)'], block_path, 'Position', position);
    end
    set_param(block_path, ...
        'num_ports', 'foundation.enum.num_ports.two', ...
        'volume', 'sma_pump_manifold_volume_m3', ...
        'area_A', 'sma_connecting_pipe_flow_area_m2', ...
        'area_B', 'sma_connecting_pipe_flow_area_m2', ...
        'p_I_specify', 'on', ...
        'p_I_priority', 'Low', ...
        'p_I', 'sma_pump_manifold_p_init_MPa', ...
        'T_I_specify', 'on', ...
        'T_I_priority', 'Low', ...
        'T_I', 'sma_pump_manifold_T_init_K');
    if abs(options.branch.sma_pump_manifold_volume_m3 - ...
            options.branch.connecting_pipe_flow_area_m2 * ...
            options.branch.connecting_pipe_length_m) > 1.0e-15
        error('HeatDriveECC:SMAPumpManifoldVolumeContract', ...
            'SMA pump manifold volume must equal one Qian connecting pipe.');
    end
end

function remove_tl_junction(junction_path)
    if ~exist_block(junction_path)
        return;
    end
    ports = get_param(junction_path, 'PortHandles');
    kinds = {'LConn', 'RConn'};
    line_handles = zeros(0, 1);
    for kind_idx = 1:numel(kinds)
        kind = kinds{kind_idx};
        for port_idx = 1:numel(ports.(kind))
            line_handle = get_param(ports.(kind)(port_idx), 'Line');
            if isnumeric(line_handle) && line_handle ~= -1
                line_handles(end + 1, 1) = line_handle; %#ok<AGROW>
            end
        end
    end
    line_handles = unique(line_handles);
    for idx = 1:numel(line_handles)
        try
            delete_line(line_handles(idx));
        catch
        end
    end
    delete_block(junction_path);
end


    safe_add_line_handle(model_name, get_port(error_sum, 'Outport', 1), ...
        get_port(ki, 'Inport', 1));
    safe_add_line_handle(model_name, get_port(error_sum, 'Outport', 1), ...
        get_port(stage4_ki, 'Inport', 1));
    safe_add_line_handle(model_name, get_port(ki, 'Outport', 1), ...
        get_port(stage2_input_gate, 'Inport', 1));
    safe_add_line_handle(model_name, get_port(stage2_enable, 'Outport', 1), ...
        get_port(stage2_input_gate, 'Inport', 2));
    safe_add_line_handle(model_name, ...
        get_port(stage2_input_gate, 'Outport', 1), ...
        get_port(stage2_integrator, 'Inport', 1));

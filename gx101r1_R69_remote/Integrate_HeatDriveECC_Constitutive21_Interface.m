function sim_params = apply_full_cycle_valve_commands(sim_params, options)
    [t, se_values, sma_values, sma_pressure_bias_values, ...
        se_pressure_bias_values, ...
        sma_hold_gate_values, sma_cooldown_gate_values] = ...
        build_full_cycle_valve_profiles(options);
    sim_params.L_valve_command = timeseries(se_values, t);
    sim_params.L_valve_command_time_s = t;
    sim_params.L_valve_command_values = se_values;
    sim_params.SMA_L_valve_command = timeseries(sma_values, t);
    sim_params.SMA_L_valve_command_time_s = t;
    sim_params.SMA_L_valve_command_values = sma_values;
    sim_params.SMA_pressure_bias_command = ...
        timeseries(sma_pressure_bias_values, t);
    sim_params.SMA_pressure_bias_command_time_s = t;
    sim_params.SMA_pressure_bias_command_values = sma_pressure_bias_values;
    se_switch_pressure_MPa = abs(get_branch_option(options, ...
        'valve_switch_pressure_MPa', 0.0));
    sma_switch_pressure_MPa = abs(get_branch_option(options, ...
        'sma_valve_switch_pressure_MPa', se_switch_pressure_MPa));
    sma_active_pressure_floor_MPa = max(10.0 * sma_switch_pressure_MPa, eps);
    se_active_pressure_floor_MPa = max(10.0 * se_switch_pressure_MPa, eps);
    sma_flow_target_values = options.branch.m_dot_sma_shex_kg_per_s .* ...
        double(any(sma_values > 0.5, 2) & ...
        abs(sma_pressure_bias_values) > sma_active_pressure_floor_MPa);
    sim_params.SMA_mdot_target_command = ...
        timeseries(sma_flow_target_values, t);
    sim_params.SMA_mdot_target_command_time_s = t;
    sim_params.SMA_mdot_target_command_values = sma_flow_target_values;
    sma_feedback_enable_values = double(sma_flow_target_values > 0.0);
    sma_feedback_enable_values = disable_sma_feedback_during_commutation( ...
        sma_feedback_enable_values, t, options);
    sim_params.SMA_pressure_feedback_enable_command = ...
        timeseries(sma_feedback_enable_values, t);
    sim_params.SMA_pressure_feedback_enable_command_time_s = t;
    sim_params.SMA_pressure_feedback_enable_command_values = ...
        sma_feedback_enable_values;
    sma_feedback_reset_values = 1.0 - sma_feedback_enable_values;
    sim_params.SMA_pressure_feedback_reset_command = ...
        timeseries(sma_feedback_reset_values, t);
    sim_params.SMA_pressure_feedback_reset_command_time_s = t;
    sim_params.SMA_pressure_feedback_reset_command_values = ...
        sma_feedback_reset_values;
    sim_params.SE_pressure_bias_command = ...
        timeseries(se_pressure_bias_values, t);
    sim_params.SE_pressure_bias_command_time_s = t;
    sim_params.SE_pressure_bias_command_values = se_pressure_bias_values;
    se_flow_target_values = options.branch.m_dot_se_the_kg_per_s .* ...
        double(any(se_values > 0.5, 2) & ...
        abs(se_pressure_bias_values) > se_active_pressure_floor_MPa);
    sim_params.SE_mdot_target_command = ...
        timeseries(se_flow_target_values, t);
    sim_params.SE_mdot_target_command_time_s = t;
    sim_params.SE_mdot_target_command_values = se_flow_target_values;
    se_feedback_enable_values = double(se_flow_target_values > 0.0);
    se_stage2_integrator_enable_values = double( ...
        mean(se_values(:, 1:3), 2) > 0.5 & ...
        se_feedback_enable_values > 0.5);
    se_stage4_integrator_enable_values = double( ...
        mean(se_values(:, 4:6), 2) > 0.5 & ...
        se_feedback_enable_values > 0.5);
    stage2_kp = get_branch_option(options, ...
        'se_stage2_pressure_pi_kp_MPa_per_kgps', ...
        options.branch.se_pressure_pi_kp_MPa_per_kgps);
    stage4_kp = get_branch_option(options, ...
        'se_stage4_pressure_pi_kp_MPa_per_kgps', stage2_kp);
    stage4_initial_kp = get_branch_option(options, ...
        'se_stage4_pressure_pi_initial_kp_MPa_per_kgps', stage4_kp);
    stage4_transition_start_s = get_branch_option(options, ...
        'se_stage4_pressure_pi_transition_start_s', 0.0);
    stage4_transition_duration_s = get_branch_option(options, ...
        'se_stage4_pressure_pi_transition_duration_s', 0.0);
    if stage4_transition_duration_s > 0.0
        transition_fraction = min(max((t - stage4_transition_start_s) ./ ...
            stage4_transition_duration_s, 0.0), 1.0);
        stage4_kp_values = stage4_initial_kp + ...
            (stage4_kp - stage4_initial_kp) .* transition_fraction;
    else
        stage4_kp_values = stage4_kp .* ones(size(t));
    end
    se_pressure_p_scale_values = se_stage2_integrator_enable_values + ...
        (stage4_kp_values ./ stage2_kp) .* ...
        se_stage4_integrator_enable_values;
    sim_params.SE_pressure_feedback_enable_command = ...
        timeseries(se_pressure_p_scale_values, t);
    sim_params.SE_pressure_feedback_enable_command_time_s = t;
    sim_params.SE_pressure_feedback_enable_command_values = ...
        se_pressure_p_scale_values;
    sim_params.SE_stage4_pressure_kp_command_MPa_per_kgps = ...
        timeseries(stage4_kp_values, t);
    sim_params.SE_stage4_pressure_kp_command_time_s = t;
    sim_params.SE_stage4_pressure_kp_command_values = stage4_kp_values;
    sim_params.SE_stage2_pressure_integrator_enable_command = ...
        timeseries(se_stage2_integrator_enable_values, t);
    sim_params.SE_stage2_pressure_integrator_enable_command_time_s = t;
    sim_params.SE_stage2_pressure_integrator_enable_command_values = ...
        se_stage2_integrator_enable_values;
    sim_params.SE_stage4_pressure_integrator_enable_command = ...
        timeseries(se_stage4_integrator_enable_values, t);
    sim_params.SE_stage4_pressure_integrator_enable_command_time_s = t;
    sim_params.SE_stage4_pressure_integrator_enable_command_values = ...
        se_stage4_integrator_enable_values;
    se_hold_activity = mean(se_values(:, 1:3), 2);
    se_cooldown_activity = mean(se_values(:, 4:6), 2);
    sim_params.SE_stage2_pressure_feedforward_activity_command = ...
        timeseries(se_hold_activity, t);
    sim_params.SE_stage4_pressure_feedforward_activity_command = ...
        timeseries(se_cooldown_activity, t);
    sim_params.se_pressure_feedforward_temperature_K = ...
        options.branch.se_pressure_feedforward_temperature_K;
    sim_params.se_pressure_feedforward_log_mu_Pa_s = log( ...
        options.branch.se_pressure_feedforward_mu_Pa_s);
    sim_params.se_pressure_feedforward_reference_mu_Pa_s = ...
        options.branch.se_pressure_feedforward_reference_mu_Pa_s;
    sim_params.se_pressure_feedforward_initial_temperature_K = ...
        options.branch.se_pressure_feedforward_initial_temperature_K;
    sim_params.se_pressure_feedforward_sample_time_s = ...
        options.branch.se_pressure_feedforward_sample_time_s;
    sim_params.SMA_hold_pipe_to_sma_G_command = ...
        timeseries(sma_hold_gate_values, t);
    sim_params.SMA_hold_pipe_to_sma_G_command_time_s = t;
    sim_params.SMA_hold_pipe_to_sma_G_command_values = sma_hold_gate_values;
    sim_params.SMA_cooldown_pipe_to_sma_G_command = ...
        timeseries(sma_cooldown_gate_values, t);
    sim_params.SMA_cooldown_pipe_to_sma_G_command_time_s = t;
    sim_params.SMA_cooldown_pipe_to_sma_G_command_values = sma_cooldown_gate_values;
    se_active_G = options.branch.se_pipe_thermal_gate_active_G_W_per_K;
    se_inactive_G = options.branch.se_pipe_thermal_gate_inactive_G_W_per_K;
    se_natural_G = options.branch.se_natural_thermal_gate_G_W_per_K;
    sma_hold_activity = mean(sma_values(:, [1 3 5]), 2);
    sma_cooldown_activity = mean(sma_values(:, [2 4 6]), 2);
    se_hold_gate_values = se_inactive_G .* ones(size(t));
    se_cooldown_gate_values = se_inactive_G .* ones(size(t));
    if logical(get_branch_option(options, ...
            'se_shared_regenerator_fluid_path', true))
        % One resident SE fluid column remains naturally coupled during
        % Stages 1/3 and is forced in opposite directions in Stages 2/4.
        se_hold_gate_values(:) = se_natural_G;
        se_hold_gate_values(se_hold_activity > 0.5 | ...
            se_cooldown_activity > 0.5) = se_active_G;
    else
        se_hold_gate_values(sma_cooldown_activity > 0.5) = se_natural_G;
        se_cooldown_gate_values(sma_hold_activity > 0.5) = se_natural_G;
        se_hold_gate_values(se_hold_activity > 0.5) = se_active_G;
        se_cooldown_gate_values(se_cooldown_activity > 0.5) = se_active_G;
    end
    initial_deadband = se_hold_activity <= 0.5 & ...
        se_cooldown_activity <= 0.5 & sma_hold_activity <= 0.5 & ...
        sma_cooldown_activity <= 0.5;
    se_cooldown_gate_values(initial_deadband) = se_natural_G;
    sim_params.SE_hold_pipe_to_se_G_command = ...
        timeseries(se_hold_gate_values, t);
    sim_params.SE_hold_pipe_to_se_G_command_time_s = t;
    sim_params.SE_hold_pipe_to_se_G_command_values = se_hold_gate_values;
    sim_params.SE_cooldown_pipe_to_se_G_command = ...
        timeseries(se_cooldown_gate_values, t);
    sim_params.SE_cooldown_pipe_to_se_G_command_time_s = t;
    sim_params.SE_cooldown_pipe_to_se_G_command_values = se_cooldown_gate_values;
    sim_params.full_cycle_valve_command_source = ...
        'article_four_stage_continuous_simulink_valve_pressure_and_thermal_gate_profile';
end


        get_port(stage2_output_gate, 'Inport', 2));

    safe_add_line_handle(model_name, get_port(stage4_ki, 'Outport', 1), ...
        get_port(stage4_input_gate, 'Inport', 1));
    safe_add_line_handle(model_name, get_port(stage4_enable, 'Outport', 1), ...
        get_port(stage4_input_gate, 'Inport', 2));
    safe_add_line_handle(model_name, ...
        get_port(stage4_input_gate, 'Outport', 1), ...
        get_port(stage4_integrator, 'Inport', 1));
    safe_add_line_handle(model_name, ...
        get_port(stage4_integrator, 'Outport', 1), ...
        get_port(stage4_output_gate, 'Inport', 1));
    safe_add_line_handle(model_name, get_port(stage4_enable, 'Outport', 1), ...
        get_port(stage4_output_gate, 'Inport', 2));

    safe_add_line_handle(model_name, ...
        get_port(stage2_output_gate, 'Outport', 1), ...
        get_port(route_sum, 'Inport', 1));
    safe_add_line_handle(model_name, ...
        get_port(stage4_output_gate, 'Outport', 1), ...
        get_port(route_sum, 'Inport', 2));
    safe_add_line_handle(model_name, get_port(route_sum, 'Outport', 1), ...
        get_port(bias_sum, 'Inport', 2));

    old_reset = [model_name '/SEPressureFeedbackResetFromWorkspace'];
    if exist_block(old_reset)
        ports = get_param(old_reset, 'PortHandles');
        if ~isempty(ports.Outport)
            delete_line_at_port(ports.Outport(1));
        end
        delete_block(old_reset);
    end
    obsolete_route_resets = { ...
        [model_name '/SEStage2PressureIResetFromWorkspace'], ...
        [model_name '/SEStage4PressureIResetFromWorkspace']};
    for reset_idx = 1:numel(obsolete_route_resets)
        if exist_block(obsolete_route_resets{reset_idx})
            delete_block(obsolete_route_resets{reset_idx});
        end
    end
end

function configure_independent_pressure_saturation_limits(model_name)
    sma_saturation = [model_name '/SMAPressurePI_Saturation'];
    se_saturation = [model_name '/PressurePI_Saturation'];
    if ~exist_block(sma_saturation) || ~exist_block(se_saturation)
        error('HeatDriveECC:MissingPressureSaturation', ...
            'Independent SMA/SE pressure saturation blocks are required.');
    end
    set_param(sma_saturation, 'LowerLimit', 'sma_pressure_pi_min_MPa');
    set_param(se_saturation, 'LowerLimit', 'se_pressure_pi_min_MPa');
    sma_kp = [model_name '/SMAPressurePI_Kp'];
    sma_ki = [model_name '/SMAPressurePI_Ki'];
    se_kp = [model_name '/PressurePI_Kp'];
    se_ki = [model_name '/PressurePI_Ki'];
    se_stage4_ki = [model_name '/SEStage4PressurePI_Ki'];
    gain_blocks = {sma_kp, sma_ki, se_kp, se_ki, se_stage4_ki};
    if ~all(cellfun(@exist_block, gain_blocks))
        error('HeatDriveECC:MissingIndependentPressureGains', ...
            'Independent SMA/SE pressure PI gain blocks are required.');
    end
    set_param(sma_kp, 'Gain', 'sma_pressure_pi_kp_MPa_per_kgps');
    set_param(sma_ki, 'Gain', 'sma_pressure_pi_ki_MPa_per_kgps_s');
    set_param(se_kp, 'Gain', ...
        'se_stage2_pressure_pi_kp_MPa_per_kgps');
    set_param(se_ki, 'Gain', ...
        'se_stage2_pressure_pi_ki_MPa_per_kgps_s');
    set_param(se_stage4_ki, 'Gain', ...
        'se_stage4_pressure_pi_ki_MPa_per_kgps_s');
    se_stage2_integrator = ...
        [model_name '/SEStage2PressurePI_Integrator'];
    se_stage4_integrator = ...
        [model_name '/SEStage4PressurePI_Integrator'];
    if ~exist_block(se_stage2_integrator) || ...
            ~exist_block(se_stage4_integrator)
        error('HeatDriveECC:MissingSERoutePressureIntegrator', ...
            'Both SE route-memory pressure integrators are required.');
    end
    set_param(se_stage2_integrator, ...
        'LowerSaturationLimit', ...
            'se_stage2_pressure_integrator_min_MPa', ...
        'UpperSaturationLimit', 'se_pressure_integrator_max_MPa');
    set_param(se_stage4_integrator, ...
        'LowerSaturationLimit', ...
            'se_stage4_pressure_integrator_min_MPa', ...
        'UpperSaturationLimit', 'se_pressure_integrator_max_MPa');
end


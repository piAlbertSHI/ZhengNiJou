function pass = HeatDriveECC_SEPressureLowerBoundContract(options)
% Legacy limits remain unchanged unless an actual inspected domain closure exists.
    b=options.branch;
    if ~isfield(b,'pressure_command_domain_closure_enabled') || ...
            ~b.pressure_command_domain_closure_enabled
        pass=abs(b.se_pressure_pi_min_MPa+0.50)<1e-12;
        return;
    end
    pass=false;
    if ~isfield(options.validation,'pressure_command_domain_contract'),return;end
    c=options.validation.pressure_command_domain_contract;
    if ~strcmp(c.schema,'heatdrive_ecc_pressure_command_domain_v1') || ...
            c.physical_tables_modified || c.controller_gains_modified || c.integrator_states_modified
        return;
    end
    expected=HeatDriveECC_PressureCommandInterval(c.datum_MPa, ...
        c.minimum_absolute_MPa,c.maximum_absolute_MPa,c.declared_margin_MPa, ...
        [c.requested.se_min_MPa,c.requested.maximum_MPa]);
    pass=abs(c.datum_MPa-b.network_absolute_pressure_MPa)<1e-12 && ...
        c.minimum_absolute_MPa>=options.validation.minimum_valid_liquid_pressure_MPa && ...
        abs(c.declared_margin_MPa-b.pressure_command_domain_margin_MPa)<1e-12 && ...
        max(abs(c.se_interval_MPa(:)-expected(:)))<1e-12 && ...
        abs(b.se_pressure_pi_min_MPa-expected(1))<1e-12 && ...
        b.pressure_pi_max_MPa<=expected(2)+1e-12;
end

function summary = Validate_GX101R1_Static_Contract(options)
% Validate gx101r1 exchange contracts without running Simulink.

    if nargin < 1 || isempty(options)
        options = struct();
    end

    root_dir = fileparts(mfilename('fullpath'));
    outputs_dir = get_field(options, 'outputs_dir', fullfile(root_dir, 'Output', 'r3_static'));
    if ~exist(outputs_dir, 'dir')
        mkdir(outputs_dir);
    end

    state_in = build_synthetic_checkpoint();
    [stage_descriptors, ~] = Build_FourStage_Cycle_Schedule(struct('P_max', 0.59e6));

    exchange_options = default_exchange_options(root_dir);
    user_exchange_options = get_field(options, 'exchange_options', struct());
    exchange_options = merge_struct(exchange_options, user_exchange_options);

    hold_config = Resolve_Exchange_Stage_Config(stage_descriptors(2), exchange_options);
    cooldown_config = Resolve_Exchange_Stage_Config(stage_descriptors(4), exchange_options);
    hold_params = Build_Simulink_Exchange_Params(state_in, hold_config, exchange_options);
    cooldown_params = Build_Simulink_Exchange_Params(state_in, cooldown_config, exchange_options);

    N = state_in.grid.N;
    T_idx = 2 * N + (1:N);
    y_contract_ok = isequal(T_idx, 103:153) && numel(state_in.Y) == 4 * N;
    hot_capacity_ok = abs(hold_params.hot_sink_C_J_per_K - 41.8) < 1.0e-12 && ...
        abs(cooldown_params.hot_sink_C_J_per_K - 41.8) < 1.0e-12;
    cold_capacity_ok = abs(hold_params.cold_sink_C_J_per_K - 4.18) < 1.0e-12 && ...
        abs(cooldown_params.cold_sink_C_J_per_K - 4.18) < 1.0e-12;
    ambient_G_ok = abs(hold_params.hot_sink_ambient_G_W_per_K - 0.05) < 1.0e-12 && ...
        abs(cooldown_params.hot_sink_ambient_G_W_per_K - 0.05) < 1.0e-12 && ...
        hold_params.cold_sink_ambient_G_W_per_K <= 1.0e-9 && ...
        cooldown_params.cold_sink_ambient_G_W_per_K <= 1.0e-9 && ...
        hold_params.cold_load_ambient_G_W_per_K <= 1.0e-9 && ...
        cooldown_params.cold_load_ambient_G_W_per_K <= 1.0e-9 && ...
        hold_params.chip_ambient_G_W_per_K <= 1.0e-9 && ...
        cooldown_params.chip_ambient_G_W_per_K <= 1.0e-9;
    cold_sink_fluid_G_ok = hold_params.cold_sink_fluid_G_W_per_K <= 1.0e-9 && ...
        abs(cooldown_params.cold_sink_fluid_G_W_per_K - 500.0) < 1.0e-12;
    cold_sink_stage_policy_ok = contains(hold_params.cold_sink_stage_coupling_policy, 'frozen') && ...
        contains(cooldown_params.cold_sink_stage_coupling_policy, 'coupled');
    cold_gate_ok = hold_params.cold_load_to_cold_sink_G_W_per_K <= 1.0e-9 && ...
        abs(cooldown_params.cold_load_to_cold_sink_G_W_per_K - ...
        exchange_options.cold_load_to_cold_sink_G_cooldown_W_per_K) < 1.0e-12;
    flow_contract_ok = strcmp(hold_params.flow_control_mode, 'target_duty_pressure_v1') && ...
        strcmp(cooldown_params.flow_control_mode, 'target_duty_pressure_v1') && ...
        isfinite(hold_params.pressure_control_flow_scale) && ...
        isfinite(cooldown_params.pressure_control_flow_scale);
    pipe_contract_ok = isfield(hold_params, 'sma_fluid_T_init_source') && ...
        isfield(cooldown_params, 'sma_fluid_T_init_source') && ...
        (contains(hold_params.sma_fluid_T_init_source, 'active_inlet_cold_buffer') || ...
        contains(hold_params.sma_fluid_T_init_source, 'stage2_path_pipe_state_or_cold_buffer')) && ...
        (contains(cooldown_params.sma_fluid_T_init_source, 'active_inlet_hot_buffer') || ...
        contains(cooldown_params.sma_fluid_T_init_source, 'stage4_path_pipe_state_or_hot_buffer')) && ...
        isfield(hold_params, 'sma_fluid_T_carryover_diagnostic_K') && ...
        isfield(cooldown_params, 'sma_fluid_T_carryover_diagnostic_K') && ...
        isfield(hold_params, 'stage2_path_pipe_T_state_in_K') && ...
        isfield(cooldown_params, 'stage4_path_pipe_T_state_in_K') && ...
        isfield(hold_params, 'stage2_path_pipe_unreleased_cumulative_in_J') && ...
        isfield(cooldown_params, 'stage4_path_pipe_unreleased_cumulative_in_J');
    official_end_contract_ok = contains(hold_params.official_hot_end_definition, 'external_hot_end_mixer') && ...
        contains(cooldown_params.official_cold_end_definition, 'entity_cold_end_storage_sum') && ...
        contains(hold_params.cold_fluid_buffer_stage2_role, 'source_boundary') && ...
        ~hold_params.cold_buffer_hold_writeback_allowed && ...
        contains(cooldown_params.hot_fluid_buffer_stage4_role, 'source_boundary') && ...
        ~cooldown_params.hot_buffer_cooldown_writeback_allowed;
    transit_pipe_contract_ok = isfield(cooldown_params, 'transit_pipe_volume_m3') && ...
        cooldown_params.transit_pipe_volume_m3 > 0 && ...
        isfield(cooldown_params, 'transit_pipe_internal_fluid_C_J_per_K') && ...
        cooldown_params.transit_pipe_internal_fluid_C_J_per_K > 0 && ...
        isfield(cooldown_params, 'transit_pipe_T_state_source') && ...
        ~contains(cooldown_params.transit_pipe_T_state_source, 'residual') && ...
        isfield(cooldown_params, 'transit_pipe_geometry_source') && ...
        contains(cooldown_params.transit_pipe_geometry_source, 'independent_of_energy_residual');
    object_contract = Generate_GX101R1_Thermal_Object_Contract(exchange_options, outputs_dir);

    summary = struct();
    summary.ok = y_contract_ok && hot_capacity_ok && cold_capacity_ok && ...
        ambient_G_ok && cold_sink_fluid_G_ok && cold_sink_stage_policy_ok && ...
        cold_gate_ok && flow_contract_ok && pipe_contract_ok && official_end_contract_ok && ...
        transit_pipe_contract_ok;
    summary.y_contract_ok = y_contract_ok;
    summary.T_idx = T_idx;
    summary.solver_Pmax_Pa = state_in.params.Pmax;
    summary.solver_Pmax_MPa = state_in.params.Pmax / 1.0e6;
    summary.schedule_P_max_Pa = stage_descriptors(2).pressure_end_Pa;
    summary.schedule_P_max_MPa = stage_descriptors(2).pressure_end_Pa / 1.0e6;
    summary.hot_capacity_ok = hot_capacity_ok;
    summary.cold_capacity_ok = cold_capacity_ok;
    summary.cold_sink_fluid_G_ok = cold_sink_fluid_G_ok;
    summary.cold_sink_stage_policy_ok = cold_sink_stage_policy_ok;
    summary.hold_hot_sink_C_J_per_K = hold_params.hot_sink_C_J_per_K;
    summary.cooldown_hot_sink_C_J_per_K = cooldown_params.hot_sink_C_J_per_K;
    summary.hot_sink_effective_water_volume_ml = hold_params.hot_sink_effective_water_volume_ml;
    summary.hold_cold_sink_C_J_per_K = hold_params.cold_sink_C_J_per_K;
    summary.cooldown_cold_sink_C_J_per_K = cooldown_params.cold_sink_C_J_per_K;
    summary.cold_sink_effective_water_volume_ml = hold_params.cold_sink_effective_water_volume_ml;
    summary.ambient_G_ok = ambient_G_ok;
    summary.hot_sink_ambient_G_W_per_K = hold_params.hot_sink_ambient_G_W_per_K;
    summary.hold_cold_sink_ambient_G_W_per_K = hold_params.cold_sink_ambient_G_W_per_K;
    summary.cooldown_cold_sink_ambient_G_W_per_K = cooldown_params.cold_sink_ambient_G_W_per_K;
    summary.hold_cold_load_ambient_G_W_per_K = hold_params.cold_load_ambient_G_W_per_K;
    summary.cooldown_cold_load_ambient_G_W_per_K = cooldown_params.cold_load_ambient_G_W_per_K;
    summary.hold_chip_ambient_G_W_per_K = hold_params.chip_ambient_G_W_per_K;
    summary.cooldown_chip_ambient_G_W_per_K = cooldown_params.chip_ambient_G_W_per_K;
    summary.hold_cold_sink_fluid_G_W_per_K = hold_params.cold_sink_fluid_G_W_per_K;
    summary.cooldown_cold_sink_fluid_G_W_per_K = cooldown_params.cold_sink_fluid_G_W_per_K;
    summary.hold_cold_sink_ambient_G_W_per_K = hold_params.cold_sink_ambient_G_W_per_K;
    summary.cooldown_cold_sink_ambient_G_W_per_K = cooldown_params.cold_sink_ambient_G_W_per_K;
    summary.hold_cold_sink_stage_coupling_policy = hold_params.cold_sink_stage_coupling_policy;
    summary.cooldown_cold_sink_stage_coupling_policy = cooldown_params.cold_sink_stage_coupling_policy;
    summary.cold_gate_ok = cold_gate_ok;
    summary.hold_cold_load_to_cold_sink_G_W_per_K = hold_params.cold_load_to_cold_sink_G_W_per_K;
    summary.cooldown_cold_load_to_cold_sink_G_W_per_K = cooldown_params.cold_load_to_cold_sink_G_W_per_K;
    summary.flow_contract_ok = flow_contract_ok;
    summary.hold_flow_control_mode = hold_params.flow_control_mode;
    summary.cooldown_flow_control_mode = cooldown_params.flow_control_mode;
    summary.hold_pressure_control_duty_capacity_ratio = hold_params.pressure_control_duty_capacity_ratio;
    summary.cooldown_pressure_control_duty_capacity_ratio = cooldown_params.pressure_control_duty_capacity_ratio;
    summary.pipe_contract_ok = pipe_contract_ok;
    summary.hold_sma_fluid_T_init_source = hold_params.sma_fluid_T_init_source;
    summary.cooldown_sma_fluid_T_init_source = cooldown_params.sma_fluid_T_init_source;
    summary.official_end_contract_ok = official_end_contract_ok;
    summary.official_hot_end_definition = hold_params.official_hot_end_definition;
    summary.official_cold_end_definition = cooldown_params.official_cold_end_definition;
    summary.cold_fluid_buffer_stage2_role = hold_params.cold_fluid_buffer_stage2_role;
    summary.cold_buffer_hold_writeback_allowed = hold_params.cold_buffer_hold_writeback_allowed;
    summary.hot_fluid_buffer_stage4_role = cooldown_params.hot_fluid_buffer_stage4_role;
    summary.hot_buffer_cooldown_writeback_allowed = cooldown_params.hot_buffer_cooldown_writeback_allowed;
    summary.transit_pipe_contract_ok = transit_pipe_contract_ok;
    summary.transit_pipe_length_m = get_field(cooldown_params, 'transit_pipe_length_m', NaN);
    summary.transit_pipe_volume_m3 = get_field(cooldown_params, 'transit_pipe_volume_m3', NaN);
    summary.transit_pipe_volume_ml = get_field(cooldown_params, 'transit_pipe_volume_ml', NaN);
    summary.transit_pipe_internal_fluid_C_J_per_K = get_field(cooldown_params, 'transit_pipe_internal_fluid_C_J_per_K', NaN);
    summary.transit_pipe_T_state_source = get_field(cooldown_params, 'transit_pipe_T_state_source', '');
    summary.transit_pipe_geometry_source = get_field(cooldown_params, 'transit_pipe_geometry_source', '');
    summary.transit_pipe_T_init = get_field(cooldown_params, 'transit_pipe_T_init', NaN);
    summary.thermal_object_contract_csv_path = object_contract.csv_path;
    summary.thermal_object_contract_txt_path = object_contract.txt_path;
    summary.outputs_dir = outputs_dir;

    save(fullfile(outputs_dir, 'static_contract_summary.mat'), 'summary');
    write_json(fullfile(outputs_dir, 'static_contract_summary.json'), summary);
end


        'cold_sink_ambient_G_cooldown_W_per_K', 1.0e-12, ...
        'flush_volume_target_ratio', 1.0, ...
        'flow_control_mode', 'target_duty_pressure_v1', ...
        'actual_flush_pressure_control_enable_for_target_duty', true, ...
        'sma_pipe_internal_volume_target_ml', 0.5, ...
        'sma_pipe_volume_calibration_mode', 'hydraulic_resistance_preserving_volume_v1');
end

function checkpoint = build_synthetic_checkpoint()
    N = 51;
    R = 40e-3;
    r = linspace(0, R, N).';
    grid = struct('N', N, 'R', R, 'r', r, 'dr', r(2) - r(1));
    params = struct('Pmax', 0.59e6, 't_delta', 0.2e-3);
    Y = zeros(4 * N, 1);
    Y(2 * N + (1:N)) = 293.0;
    checkpoint = struct('Y', Y, 'state', struct(), 'grid', grid, ...
        'params', params, 'pressure_MPa', 0.59, 'time_s', 0.0);
end

function out = merge_struct(base, overlay)
    out = base;
    if ~isstruct(overlay)
        return;
    end
    names = fieldnames(overlay);
    for idx = 1:numel(names)
        out.(names{idx}) = overlay.(names{idx});
    end
end

function value = get_field(s, field_name, default_value)
    if isstruct(s) && isfield(s, field_name) && ~isempty(s.(field_name))
        value = s.(field_name);
    else
        value = default_value;
    end
end

function write_json(path_value, value)
    fid = fopen(path_value, 'w', 'n', 'UTF-8');
    if fid < 0
        error('Validate_GX101R1_Static_Contract:CannotWriteJson', ...
            'Cannot write %s.', path_value);
    end
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '%s', jsonencode(value, 'PrettyPrint', true));
end

function record = Instrument_HeatDriveECC_Stage4ControllerProbes(model_name, output_root)
% Add diagnostic-only To Workspace taps to the Stage-4 pressure chain.
% The model is modified in memory only; the production SLX is never saved.

    if nargin < 2 || isempty(output_root)
        output_root = pwd;
    end
    assert(bdIsLoaded(model_name), ...
        'HeatDriveECC:Stage4ProbeModelNotLoaded', ...
        'The diagnostic model must be loaded before instrumentation.');

    names = { ...
        'SEStage4PressureFFInletTemperatureDelay', ...
        'SEStage4PressureFFOutletTemperatureDelay', ...
        'SEStage4PressureFFActivityFromWorkspace', ...
        'SEStage4InletViscosityExp', ...
        'SEStage4OutletViscosityExp', ...
        'SEStage4ViscosityMean', ...
        'SEStage4BlendedViscosity', ...
        'SEStage4ViscosityRatio', ...
        'SEStage4EndpointViscosityWeightedDelta', ...
        'SEPressureFFRatioSum', ...
        'SEPressureDynamicFeedforward', ...
        'PressurePI_ErrorNormalizer', ...
        'PressurePI_ErrorLag', ...
        'SEPressurePEnableProduct', ...
        'SEPressureFeedbackEnableFromWorkspace', ...
        'PressurePI_ErrorSum', ...
        'SEStage4PressureIInputGate', ...
        'SEStage4PressurePI_Integrator', ...
        'SEStage4PressureIOutputGate', ...
        'SERoutePressureISum', ...
        'PressurePI_BiasSum', ...
        'PressurePI_Saturation'};
    prefixes = { ...
        'stage4_inlet_temperature_delay', ...
        'stage4_outlet_temperature_delay', ...
        'stage4_feedforward_activity', ...
        'stage4_inlet_viscosity', ...
        'stage4_outlet_viscosity', ...
        'stage4_endpoint_viscosity_mean', ...
        'stage4_blended_viscosity', ...
        'stage4_viscosity_ratio', ...
        'stage4_weighted_viscosity_delta', ...
        'stage4_feedforward_ratio_sum', ...
        'stage4_dynamic_feedforward', ...
        'stage4_normalized_error', ...
        'stage4_filtered_error', ...
        'stage4_p_output', ...
        'stage4_p_enable_scale', ...
        'stage4_flow_error', ...
        'stage4_integrator_input', ...
        'stage4_integrator_state', ...
        'stage4_integrator_output_gate', ...
        'stage4_route_integral', ...
        'stage4_bias_sum', ...
        'stage4_pressure_command'};
    assert(numel(names) == numel(prefixes), ...
        'HeatDriveECC:Stage4ProbeContractLength', ...
        'Stage-4 probe names and variables are inconsistent.');

    records = cell(numel(names), 1);
    for idx = 1:numel(names)
        source = [model_name '/' names{idx}];
        assert(getSimulinkBlockHandle(source) ~= -1, ...
            'HeatDriveECC:MissingStage4ProbeSource', ...
            'Required Stage-4 controller block is missing: %s', source);
        ports = get_param(source, 'PortHandles');
        assert(~isempty(ports.Outport), ...
            'HeatDriveECC:Stage4ProbeNoOutput', ...
            'Required Stage-4 controller block has no output: %s', source);
        sink = [model_name '/ToWorkspace_' prefixes{idx}];
        delete_block_with_lines(sink);
        add_block('simulink/Sinks/To Workspace', sink, ...
            'VariableName', prefixes{idx}, ...
            'SaveFormat', 'Structure With Time', ...
            'MaxDataPoints', 'inf', ...
            'Decimation', '1', ...
            'Position', probe_position(idx));
        sink_ports = get_param(sink, 'PortHandles');
        add_line_safe(model_name, ports.Outport(1), sink_ports.Inport(1));
        records{idx} = struct( ...
            'source_block', names{idx}, ...
            'workspace_variable', prefixes{idx}, ...
            'unit', 'model_signal', ...
            'simulation_run', false);
    end

    record = struct( ...
        'schema', 'heatdrive_ecc_stage4_controller_probe_contract_v3', ...
        'model_name', model_name, ...
        'simulation_run', false, ...
        'state_imported', false, ...
        'production_recovery_allowed', false, ...
        'probe_count', numel(records), ...
        'probes', {records}, ...
        'output_root', output_root);
    if ~exist(output_root, 'dir')
        mkdir(output_root);
    end
    write_json(fullfile(output_root, 'stage4_controller_probe_contract.json'), record);
end

function position = probe_position(index)
    x = -420 + mod(index - 1, 6) * 180;
    y = 1700 + floor((index - 1) / 6) * 90;
    position = [x y x + 150 y + 25];
end

function delete_block_with_lines(block_path)
    if getSimulinkBlockHandle(block_path) == -1
        return;
    end
    ports = get_param(block_path, 'PortHandles');
    groups = fieldnames(ports);
    for group_idx = 1:numel(groups)
        handles = ports.(groups{group_idx});
        for handle_idx = 1:numel(handles)
            try
                line = get_param(handles(handle_idx), 'Line');
                if isnumeric(line) && line ~= -1
                    delete_line(line);
                end
            catch
            end
        end
    end
    delete_block(block_path);
end

function add_line_safe(system_path, source_handle, destination_handle)
    try
        add_line(system_path, source_handle, destination_handle, 'autorouting', 'on');
    catch ME
        if ~contains(ME.message, 'already has a line') && ...
                ~contains(ME.message, 'already connected') && ...
                ~contains(ME.message, 'There is already a line')
            rethrow(ME);
        end
    end
end

function write_json(file_path, value)
    fid = fopen(file_path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:Stage4ProbeContractOpenFailed', ...
        'Cannot write %s.', file_path);
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(value, 'PrettyPrint', true));
    clear cleanup
end

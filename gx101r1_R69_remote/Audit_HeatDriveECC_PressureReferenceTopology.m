function record=Audit_HeatDriveECC_PressureReferenceTopology(model,options)
% Exact named physical wires establish reference sides, not whole-network safety.
    scratch=[model '_reference_pressure_mapping'];assert(~bdIsLoaded(scratch));
    new_system(scratch);cleanup=onCleanup(@() close_system(scratch,0));
    cache=containers.Map('KeyType','char','ValueType','any');
    pairs={ ...
        'SE_Stage2_PistonPressureSource','B','SE_ColdChamberJunction','C'; ...
        'SE_ColdChamberJunction','A','ColdFluidBuffer','A'; ...
        'SE_Stage2_PistonPressureSource','A','V1_cold_inlet','A'; ...
        'SE_Stage4_PistonPressureSource','B','SE_HotChamberJunction','C'; ...
        'SE_HotChamberJunction','A','HotFluidBuffer','A'; ...
        'SE_Stage4_PistonPressureSource','A','V4_hot_inlet','A'; ...
        'SMA Pressure Source (TL)','A','SMA_PumpInletConnectingPipeVolume','B'; ...
        'SMA_PumpInletConnectingPipeVolume','A','SMA_V1_SHEX_to_pump','B'; ...
        'SMA_PumpInletConnectingPipeVolume','A','SMA_V2_HHEX_to_pump','B'; ...
        'SMA_V1_SHEX_to_pump','A','SHEXFluidBuffer','A'; ...
        'SMA_V2_HHEX_to_pump','A','SMAHotFluidBuffer','A'; ...
        'SMA Pressure Source (TL)','B','FlowSensor_SMA_stage13_loop','A'};
    wires=cell(size(pairs,1),1);
    for k=1:size(pairs,1)
        a=named_port(pairs{k,1},pairs{k,2});b=named_port(pairs{k,3},pairs{k,4});
        connectivity=get_param(a.block_path,'PortConnectivity');
        key=[a.side,num2str(a.index)];row=connectivity(strcmp({connectivity.Type},key));
        pass=isscalar(row) && ismember(b.handle,row.DstPort);
        assert(pass,'Named pressure reference wire missing: %s:%s -> %s:%s',pairs{k,:});
        wires{k}=struct('from',a.key,'to',b.key,'direct_named_wire_verified',pass);
    end
    names={'SMA Pressure Source (TL)','SE_Stage2_PistonPressureSource','SE_Stage4_PistonPressureSource'};
    for k=1:3
        source=[model '/' names{k}];
        assert(strcmp(get_param(source,'SourceFile'),'foundation.thermal_liquid.sources.pressure_source') && ...
            strcmp(get_param(source,'source_type'),'foundation.enum.constant_controlled.controlled'), ...
            'Require the native controlled pressure-difference source.');
    end
    tanks={'ColdFluidBuffer','HotFluidBuffer','SHEXFluidBuffer','SMAHotFluidBuffer'};
    boundary=cell(4,1);
    for k=1:4
        block=[model '/' tanks{k}];
        assert(strcmp(get_param(block,'SourceFile'),'fluids.thermal_liquid.tanks_accumulators.tank'), ...
            'This pre-replacement reference audit requires the original native tank.');
        assert(endsWith(get_param(block,'pressure_spec'),'.Specified') && ...
            endsWith(get_param(block,'num_inlet'),'.One'));
        p0=value(simscape.Value(slResolve(get_param(block,'tank_pressure'),block), ...
            get_param(block,'tank_pressure_unit')),'MPa');
        assert(abs(p0-options.branch.network_absolute_pressure_MPa)<1e-12, ...
            'Reference tank datum differs from the actual network datum.');
        boundary{k}=struct('block',block,'native_tank_pressure_MPa',p0);
    end
    source_file=fullfile(matlabroot,'toolbox','physmod','simscape','library','m', ...
        '+foundation','+thermal_liquid','+sources','pressure_source.ssc');
    text=fileread(source_file);
    assert(contains(text,'B.p - A.p == p_diff;') && contains(text,'p_diff = P;'));
    record=struct('schema','heatdrive_ecc_named_pressure_reference_topology_v1', ...
        'named_wires',{wires},'boundaries',{boundary},'source_names',{names}, ...
        'reference_ports',{{'A','B','B'}},'source_equation','B.p-A.p=P', ...
        'installed_source_sha256',file_hash(source_file),'pass',true, ...
        'source_or_boundary_modified',false,'entire_network_pressure_proven',false, ...
        'actual_pressure_observation_required',true,'production_recovery_allowed',false);

    function row=named_port(relative,name)
        block=[model '/' relative];assert(getSimulinkBlockHandle(block)>0);
        if ~isKey(cache,block)
            ports=Map_HeatDriveECC_PhysicalPortHandles(block,scratch,'foundation.thermal_liquid.thermal_liquid');
            for j=1:numel(ports),ports{j}.block_path=block;ports{j}.key=[block ':' ports{j}.name];end
            cache(block)=ports;
        end
        ports=cache(block);match=ports(cellfun(@(p) strcmp(p.name,name),ports));
        assert(isscalar(match),'Ambiguous named pressure-reference port.');row=match{1};
    end
end

function hash=file_hash(file)
    fid=fopen(file,'rb');assert(fid>=0);cleanup=onCleanup(@() fclose(fid));
    digest=java.security.MessageDigest.getInstance('SHA-256');
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    hash=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

function roles = Build_HeatDriveECC_EighthRound_BranchRoles(options)
% Physical four-branch role definitions for the eighth-round ECC model.

    roles = [
        role_struct('SMA_SHEX', 1, 'SMA', options.system.Th_K, ...
            options.branch.UA_sma_shex_W_per_K, ...
            options.branch.boundary_UA_shex_W_per_K, 'source_to_solid')
        role_struct('SMA_THE', 3, 'SMA', options.system.T0_K, ...
            options.branch.UA_sma_the_W_per_K, ...
            options.branch.boundary_UA_the_W_per_K, 'solid_to_sink')
        role_struct('SE_THE', 2, 'SE', options.system.T0_K, ...
            options.branch.UA_se_the_W_per_K, ...
            options.branch.boundary_UA_the_W_per_K, 'solid_to_sink')
        role_struct('SE_RHE', 4, 'SE', options.system.Tc_K, ...
            options.branch.UA_se_rhe_W_per_K, ...
            options.branch.boundary_UA_rhe_W_per_K, 'source_to_solid')];
end

function role = role_struct(name, active_stage, solid, boundary_T_K, UA_W_per_K, boundary_UA_W_per_K, heat_role)
    role = struct('name', name, ...
        'active_stage', active_stage, ...
        'solid', solid, ...
        'boundary_T_K', boundary_T_K, ...
        'UA_W_per_K', UA_W_per_K, ...
        'boundary_UA_W_per_K', boundary_UA_W_per_K, ...
        'heat_role', heat_role);
end

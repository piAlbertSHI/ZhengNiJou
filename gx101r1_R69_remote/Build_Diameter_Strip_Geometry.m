function geometry = Build_Diameter_Strip_Geometry(proxy_options)
% Build the 101-strip proxy geometry used by the external exchange layer.

    if nargin < 1 || isempty(proxy_options)
        proxy_options = struct();
    end

    radius_m = get_option_field(proxy_options, 'radius_m', 40e-3);
    thickness_m = get_option_field(proxy_options, 'thickness_m', 0.20e-3);
    sma_density_kg_per_m3 = get_option_field(proxy_options, 'rho_sma', ...
        get_option_field(proxy_options, 'rho', 6500.0));
    physical_mass = sma_density_kg_per_m3 * pi * radius_m ^ 2 * thickness_m;
    total_mass = get_option_field(proxy_options, 'total_mass', physical_mass);
    mass_consistency_ratio = total_mass / max(physical_mass, eps);
    node_cp = get_option_field(proxy_options, 'node_cp', 450);
    radial_node_count = get_option_field(proxy_options, 'radial_node_count', 51);
    strip_count = get_option_field(proxy_options, 'strip_count', 2 * radial_node_count - 1);

    if radial_node_count < 2 || strip_count < 3 || mod(strip_count, 2) == 0
        error('Build_Diameter_Strip_Geometry:InvalidNodeCount', ...
            'radial_node_count must be >= 2 and strip_count must be odd and >= 3.');
    end
    if strip_count ~= 2 * radial_node_count - 1
        error('Build_Diameter_Strip_Geometry:IncompatibleNodeCount', ...
            'strip_count must satisfy strip_count = 2 * radial_node_count - 1.');
    end

    r_nodes_m = linspace(0.0, radius_m, radial_node_count).';
    x_strip_m = linspace(-radius_m, radius_m, strip_count).';
    center_index = (strip_count + 1) / 2;

    if strip_count > 1
        dx_uniform_m = x_strip_m(2) - x_strip_m(1);
    else
        dx_uniform_m = 0.0;
    end

    strip_width_m = repmat(dx_uniform_m, strip_count, 1);
    if strip_count >= 2
        strip_width_m(1) = dx_uniform_m / 2.0;
        strip_width_m(end) = dx_uniform_m / 2.0;
    end

    chord_length_m = 2.0 * sqrt(max(radius_m ^ 2 - x_strip_m .^ 2, 0.0));
    strip_planform_area_m2 = chord_length_m .* strip_width_m;
    area_sum = sum(strip_planform_area_m2);
    if ~(area_sum > 0.0)
        error('Build_Diameter_Strip_Geometry:InvalidArea', ...
            'Strip planform area must be strictly positive.');
    end

    strip_mass_kg = total_mass * (strip_planform_area_m2 / area_sum);
    strip_cp_J_per_kgK = repmat(node_cp, strip_count, 1);
    strip_heat_capacity_J_per_K = strip_mass_kg .* strip_cp_J_per_kgK;
    strip_surface_area_m2 = 2.0 * strip_planform_area_m2;

    geometry = struct( ...
        'radius_m', radius_m, ...
        'thickness_m', thickness_m, ...
        'total_mass_kg', total_mass, ...
        'sma_density_kg_per_m3', sma_density_kg_per_m3, ...
        'sma_physical_mass_kg', physical_mass, ...
        'sma_proxy_mass_kg', total_mass, ...
        'sma_mass_consistency_ratio', mass_consistency_ratio, ...
        'sma_mass_contract_ok', isfinite(mass_consistency_ratio) && ...
            mass_consistency_ratio >= 0.95 && mass_consistency_ratio <= 1.05, ...
        'sma_heat_capacity_total_J_per_K', total_mass * node_cp, ...
        'default_cp_J_per_kgK', node_cp, ...
        'radial_node_count', radial_node_count, ...
        'strip_count', strip_count, ...
        'strip_index', (1:strip_count).', ...
        'center_index', center_index, ...
        'r_nodes_m', r_nodes_m, ...
        'x_strip_m', x_strip_m, ...
        'dx_uniform_m', dx_uniform_m, ...
        'strip_width_m', strip_width_m, ...
        'chord_length_m', chord_length_m, ...
        'strip_planform_area_m2', strip_planform_area_m2, ...
        'strip_surface_area_m2', strip_surface_area_m2, ...
        'strip_mass_kg', strip_mass_kg, ...
        'strip_cp_J_per_kgK', strip_cp_J_per_kgK, ...
        'strip_heat_capacity_J_per_K', strip_heat_capacity_J_per_K, ...
        'cold_side_index', 1, ...
        'hot_side_index', strip_count, ...
        'left_to_right_order', (1:strip_count).', ...
        'right_to_left_order', (strip_count:-1:1).', ...
        'positive_strip_indices', center_index:strip_count, ...
        'negative_strip_indices', 1:center_index, ...
        'default_average_mode', 'enthalpy_frozen_xi');
end

function value = get_option_field(s, field_name, default_value)
    if isstruct(s) && isfield(s, field_name) && ~isempty(s.(field_name))
        value = s.(field_name);
    else
        value = default_value;
    end
end

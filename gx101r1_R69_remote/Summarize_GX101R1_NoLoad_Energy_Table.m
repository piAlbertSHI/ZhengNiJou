function summary = Summarize_GX101R1_NoLoad_Energy_Table(run_result_path, outputs_dir)
% Build a compact no-load stage energy table from a saved run_result.mat.

    if nargin < 1 || isempty(run_result_path)
        error('Summarize_GX101R1_NoLoad_Energy_Table:MissingInput', ...
            'run_result_path is required.');
    end
    if nargin < 2 || isempty(outputs_dir)
        outputs_dir = fileparts(run_result_path);
    end
    if ~exist(outputs_dir, 'dir')
        mkdir(outputs_dir);
    end

    data = load(run_result_path, 'run_result');
    run_result = data.run_result;
    rows = repmat(empty_row(), 1, 0);

    cycles = reshape(get_field(run_result, 'cycle_results', struct([])), 1, []);
    for cidx = 1:numel(cycles)
        reports = reshape(get_field(cycles(cidx), 'stage_reports', struct([])), 1, []);
        rows(end + 1) = row_from_report(cycles(cidx).cycle_index, get_stage_report(reports, 'hold_exchange')); %#ok<AGROW>
        rows(end + 1) = row_from_report(cycles(cidx).cycle_index, get_stage_report(reports, 'cooldown_exchange')); %#ok<AGROW>
    end

    table_out = struct2table(rows);
    csv_path = fullfile(outputs_dir, 'no_load_energy_table.csv');
    stage2_csv_path = fullfile(outputs_dir, 'no_load_stage2_hot_end_energy_chain_table.csv');
    stage4_csv_path = fullfile(outputs_dir, 'no_load_stage4_energy_chain_table.csv');
    stage4_cold_chain_csv_path = fullfile(outputs_dir, 'no_load_stage4_cold_end_energy_chain_table.csv');
    r12_theory_csv_path = fullfile(outputs_dir, 'r12_exchange_theory_bound_table.csv');
    json_path = fullfile(outputs_dir, 'no_load_energy_table.json');
    writetable(table_out, csv_path);
    writetable(table_out, r12_theory_csv_path);
    if ~isempty(table_out)
        stage2_mask = strcmp(string(table_out.stage_name), "hold_exchange");
        writetable(table_out(stage2_mask, :), stage2_csv_path);
        stage4_mask = strcmp(string(table_out.stage_name), "cooldown_exchange");
        writetable(table_out(stage4_mask, :), stage4_csv_path);
        writetable(table_out(stage4_mask, :), stage4_cold_chain_csv_path);
    end

    summary = struct( ...
        'run_result_path', run_result_path, ...
        'outputs_dir', outputs_dir, ...
        'csv_path', csv_path, ...
        'stage2_hot_end_energy_chain_csv_path', stage2_csv_path, ...
        'stage4_energy_chain_csv_path', stage4_csv_path, ...
        'stage4_cold_end_energy_chain_csv_path', stage4_cold_chain_csv_path, ...
        'r12_exchange_theory_bound_csv_path', r12_theory_csv_path, ...
        'json_path', json_path, ...
        'row_count', numel(rows), ...
        'rows', rows);
    write_json(json_path, summary);
    save(fullfile(outputs_dir, 'no_load_energy_table.mat'), 'summary', 'table_out');
end


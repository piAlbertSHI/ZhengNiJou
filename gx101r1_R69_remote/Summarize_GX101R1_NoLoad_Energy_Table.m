    if isempty(values)
        value = NaN;
    else
        value = min(values);
    end
end

function value = effective_htf_delta_T(Q_sma_htf_J, mdot_integral_kg, cp_water)
    if all(isfinite([Q_sma_htf_J, mdot_integral_kg, cp_water])) && ...
            abs(mdot_integral_kg) > 1.0e-12 && cp_water > 0
        value = Q_sma_htf_J / (abs(mdot_integral_kg) * cp_water);
    else
        value = NaN;
    end
end

function write_json(path_value, value)
    fid = fopen(path_value, 'w', 'n', 'UTF-8');
    if fid < 0
        error('Summarize_GX101R1_NoLoad_Energy_Table:CannotWriteJson', ...
            'Cannot write %s.', path_value);
    end
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '%s', jsonencode(value, 'PrettyPrint', true));
end

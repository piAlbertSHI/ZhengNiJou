function options = Build_HeatDriveECC_SixthRound_Defaults(overrides)
% Defaults for the sixth-round four-physical-branch ECC model.

    if nargin < 1
        overrides = struct();
    end

    root_dir = fileparts(mfilename('fullpath'));
    article = Build_HeatDriveECC_Article_Defaults();

    options = struct();
    options.schema_version = 'heatdrive_ecc_sixth_round_defaults_v1';
    options.model_name = 'heatdrive_ecc_four_branch_physical';
    options.model_path = fullfile(root_dir, [options.model_name '.slx']);
    options.source_model_name = 'nixunhuan_solver101_internal';
    options.source_model_path = fullfile(root_dir, [options.source_model_name '.slx']);
    options.fifth_model_name = 'heatdrive_ecc_reconfigured_from_solver101';
    options.cycle_count = 3;
    options.stage_names = {'sma_heat_load','se_reject_heat', ...
        'sma_cool_unload','se_absorb_heat'};
    options.stage_max_duration_s = article.schedule.stage_durations_s;
    options.command_ramp_s = 0.005;
    options.outputs_dir = fullfile(root_dir, 'outputs_heatdrive_ecc_sixth_round');
    options.force_rebuild_model = false;

    options.system = struct( ...
        'T0_K', 308.0, ...
        'Tc_K', 288.0, ...
        'Th_K', article.equilibrium.T_h_K, ...
        'cp_fluid_J_per_kgK', 4180.0, ...
        'article_Qh_W', article.equilibrium.Qh_W, ...
        'article_Qr_W', article.equilibrium.Qr_W, ...
        'article_PECC_W', article.equilibrium.PECC_W, ...
        'article_etaECC', article.equilibrium.etaECC, ...
        'article_nu_Hz', article.equilibrium.nu_Hz, ...
        'article_qa_J_per_kg', article.equilibrium.qa_J_per_kg, ...
        'article_qr_J_per_kg', article.equilibrium.qr_J_per_kg);

    options.geometry = struct( ...
        'L_a_m', 1.0, ...
        'S_a_m2', 1.0e-6, ...
        'L_r_m', 0.4, ...
        'S_r_m2', 0.2e-6);

    options.material = struct( ...
        'rho_kg_per_m3', 6500.0, ...
        'cp_J_per_kgK', 500.0, ...
        'k_W_per_mK', 18.0, ...
        'latent_J_per_kg', 1.0e4, ...
        'epsilon_T', 0.03, ...
        'E_Pa', 30.0e9, ...
        'C_M_Pa_per_K', 7.3e6, ...
        'C_A_Pa_per_K', 7.6e6);

    options.preflight = struct( ...
        'short_stop_s', 0.02, ...
        'medium_stop_s', 0.1, ...
        'wall_time_limit_s', 120, ...
        'closed_route_threshold_kgps', 1.0e-5, ...
        'min_temperature_delta_K', 1.0e-3);

    options.validation = struct( ...
        'max_eq6_scaled', 1.0e-6, ...
        'max_eq7_scaled', 1.0e-3, ...
        'max_stage_energy_residual_fraction', 0.05, ...
        'max_cycle_energy_residual_fraction', 0.05, ...
        'min_samples_per_stage', 50);

    options.branch_roles = { ...
        branch_role('SMA_SHEX', 'sma', 1, 'hold', options.system.Th_K, ...
            'SHEX heats SMA during Stage1'), ...
        branch_role('SMA_THE', 'sma', 3, 'cooldown', options.system.T0_K, ...
            'THE rejects heat from SMA during Stage3'), ...
        branch_role('SE_THE', 'se', 2, 'hold', options.system.T0_K, ...
            'THE rejects heat from SE during Stage2'), ...
        branch_role('SE_RHE', 'se', 4, 'cooldown', options.system.Tc_K, ...
            'RHE/CHEX supplies heat to SE during Stage4')};

    options = merge_struct(options, overrides);
end

function role = branch_role(name, solid_role, active_stage, active_path, boundary_T_K, description)
    role = struct('name', name, ...
        'solid_role', solid_role, ...
        'active_stage', active_stage, ...
        'active_path', active_path, ...
        'boundary_T_K', boundary_T_K, ...
        'description', description);
end

function out = merge_struct(out, overrides)
    if ~isstruct(overrides)
        return;
    end
    names = fieldnames(overrides);
    for idx = 1:numel(names)
        name = names{idx};
        if isfield(out, name) && isstruct(out.(name)) && ...
                isstruct(overrides.(name)) && isscalar(overrides.(name))
            out.(name) = merge_struct(out.(name), overrides.(name));
        else
            out.(name) = overrides.(name);
        end
    end
end

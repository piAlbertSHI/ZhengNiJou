function values = read_on_grid(sim_out, name, query_time_s, method)
    [time_s, raw_values] = read_raw_signal(sim_out, name);
    if isscalar(time_s)
        values = repmat(raw_values(1, :), numel(query_time_s), 1);
        return;
    end
    [time_s, unique_idx] = unique(time_s, 'last');
    raw_values = raw_values(unique_idx, :);
    values = interp1(time_s, raw_values, query_time_s, method, 'extrap');
end

function sampled_values = read_simscape_on_grid( ...
        sim_out, model_name, block_path, variable_name, query_time_s, unit)
% Read one native Simscape variable without adding a sensor to the network.
    simlog = sim_out.get('simlog');
    full_block_path = [model_name '/' block_path];
    if ~isa(simlog, 'simscape.logging.Node')
        error('Run:EighthRound:MissingSimscapeLogNode', ...
            'Required Simscape log root is missing for %s.', full_block_path);
    end
    block_node = simscape.logging.findNode(simlog, full_block_path);
    if isempty(block_node) || ~block_node.hasChild(variable_name)
        error('Run:EighthRound:MissingSimscapeLogNode', ...
            'Required Simscape log node is missing: %s/%s.', ...
            full_block_path, variable_name);
    end
    node = block_node.child(variable_name);
    log_series = node.series;
    raw_time_s = double(time(log_series));
    raw_values = double(values(log_series, Units = unit));
    raw_time_s = raw_time_s(:);
    raw_values = squeeze(raw_values);
    if isvector(raw_values)
        raw_values = raw_values(:);
    end
    if size(raw_values, 1) ~= numel(raw_time_s)
        error('Run:EighthRound:BadSimscapeLogShape', ...
            'Simscape log node %s has incompatible time and value shapes.', ...
            [block_path '/' variable_name]);
    end
    [raw_time_s, unique_idx] = unique(raw_time_s, 'last');
    raw_values = raw_values(unique_idx, :);
    sampled_values = NaN(numel(query_time_s), size(raw_values, 2));
    if isscalar(raw_time_s)
        exact = abs(query_time_s(:) - raw_time_s) <= ...
            10.0 * eps(max(abs(raw_time_s), 1.0));
        sampled_values(exact, :) = repmat(raw_values(1, :), nnz(exact), 1);
        return;
    end
    covered = query_time_s(:) >= raw_time_s(1) & ...
        query_time_s(:) <= raw_time_s(end);
    sampled_values(covered, :) = interp1(raw_time_s, raw_values, ...
        query_time_s(covered), 'linear');
end

function sampled_values = read_optional_simscape_on_grid( ...
        sim_out, model_name, block_path, variable_name, query_time_s, unit)
% Keep diagnostic absence explicit without rejecting the production signal.
    try
        sampled_values = read_simscape_on_grid(sim_out, model_name, ...
            block_path, variable_name, query_time_s, unit);
    catch exception
        if strcmp(exception.identifier, ...
                'Run:EighthRound:MissingSimscapeLogNode')
            sampled_values = NaN(numel(query_time_s), 1);
        else
            rethrow(exception);
        end
    end
end

function [time_s, values] = read_raw_signal(sim_out, name)
    raw = sim_out.get(name);
    if isa(raw, 'timeseries')
        time_s = double(raw.Time(:));
        values = double(raw.Data);
    elseif isstruct(raw) && isfield(raw, 'time') && isfield(raw, 'signals')
        time_s = double(raw.time(:));
        values = double(raw.signals.values);
    else
        error('Run:EighthRound:UnsupportedPhysicalSignal', ...
            'Signal %s has unsupported class %s.', name, class(raw));
    end
    values = squeeze(values);
    if isvector(values)
        values = values(:);
    elseif size(values, 1) ~= numel(time_s) && ...
            size(values, 2) == numel(time_s)
        values = values.';
    end
    if size(values, 1) ~= numel(time_s)
        error('Run:EighthRound:BadPhysicalSignalShape', ...
            'Signal %s has %d time samples and data size [%d %d].', ...
            name, numel(time_s), size(values, 1), size(values, 2));
    end
end

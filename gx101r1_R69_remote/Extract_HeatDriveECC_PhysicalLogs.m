function relative = relative_block_path(model_name, full_path)
    prefix = [model_name '/'];
    assert(startsWith(full_path, prefix), ...
        'Run:EighthRound:EnergyBoundaryPathOutsideModel', ...
        'Block is not inside %s: %s.', model_name, full_path);
    relative = extractAfter(full_path, strlength(prefix));
    relative = char(relative);
end


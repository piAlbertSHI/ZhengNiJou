function physical = Extract_HeatDriveECC_PhysicalLogs(sim_out, options, model_name, include_legacy_inventory)
% Shared physical extraction; new native diagnostics never import legacy inventory.
    if nargin < 4, include_legacy_inventory = true; end
    required = { ...
        'SMA_Tx21_internal', 'SE_Tx21_internal', ...
        'ECC_constitutive21_output', ...
        'ECC_Q_SMA_constitutive_W', 'ECC_Q_SE_constitutive_W', ...
        'SHEX_hot_sink_temp_out', 'hot_sink_temp_out', ...
        'cold_sink_temp_out', 'shex_buffer_temp_out', ...
        'shex_source_heat_flow_W', 'simlog', ...
        'Qdot_cold_sink_mass_to_hx_pipe_W', ...
        'hot_buffer_temp_out', 'sma_hot_buffer_temp_out', ...
        'cold_buffer_temp_out', ...
        'mass_flow_sma_stage13_kgps', ...
        'mass_flow_sma_stage1_route_kgps', ...
        'mass_flow_sma_stage3_route_kgps', ...
        'mass_flow_v1_cold_inlet_kgps', ...
        'mass_flow_v3_sma_to_hot_kgps', ...
        'mass_flow_v4_hot_inlet_kgps', ...
        'mass_flow_v6_sma_to_chip_cold_kgps', ...
        'pressure_command_se_MPa', 'pressure_command_sma_MPa', ...
        'sma_stage1_inlet_fluid_temp_out', ...
        'sma_stage1_outlet_fluid_temp_out', ...
        'sma_stage3_inlet_fluid_temp_out', ...
        'sma_stage3_outlet_fluid_temp_out', ...
        'probe_sma_stage2_port1_v1_side_T_K', ...
        'probe_sma_stage2_port2_v3_side_T_K', ...
        'probe_sma_stage4_port3_v4_side_T_K', ...
        'probe_sma_stage4_port4_v6_side_T_K'};
    required = [required, pipe_heat_flow_variable_names()];
    required = [required, sma_pressure_probe_names()];
    available = sim_out.who;
    missing = setdiff(required, available);
    if ~isempty(missing)
        error('Run:EighthRound:MissingPhysicalSignals', ...
            'Missing required physical Simscape logs: %s', ...
            strjoin(missing, ', '));
    end

    [time_s, sma_T_21] = read_raw_signal(sim_out, ...
        'SMA_Tx21_internal');
    if size(sma_T_21, 2) ~= options.node_count
        error('Run:EighthRound:BadSMANodeCount', ...
            'SMA physical log has %d columns; expected %d.', ...
            size(sma_T_21, 2), options.node_count);
    end

    physical = struct();
    physical.time_s = time_s;
    physical.SMA_T_21_K = sma_T_21;
    physical.SE_T_21_K = read_on_grid(sim_out, ...
        'SE_Tx21_internal', time_s, 'linear');
    [physical.cycle_index, physical.stage_id, ...
        physical.stage_elapsed_s] = HeatDriveECC_CycleStageFromTime(time_s, options);

    physical.SHEX_T_K = read_on_grid(sim_out, ...
        'SHEX_hot_sink_temp_out', time_s, 'linear');
    physical.HHEX_T_K = read_on_grid(sim_out, ...
        'hot_sink_temp_out', time_s, 'linear');
    physical.CHEX_T_K = read_on_grid(sim_out, ...
        'cold_sink_temp_out', time_s, 'linear');
    physical.Q_CHEX_reservoir_to_hx_W = read_on_grid(sim_out, ...
        'Qdot_cold_sink_mass_to_hx_pipe_W', time_s, 'linear');
    physical.Q_SHEX_source_to_sink_W = read_on_grid(sim_out, ...
        'shex_source_heat_flow_W', time_s, 'linear');
    physical.Q_SHEX_sink_to_fluid_W = read_simscape_on_grid(sim_out, ...
        model_name, 'SHEX/HotSinkFluidLink', 'Q', time_s, 'W');
    physical.Q_SHEX_source_sensor_native_W = ...
        read_optional_simscape_on_grid(sim_out, model_name, ...
        'SHEX/SHEXSourceToSinkHeatFlowSensor', 'Q', time_s, 'W');
    physical.Q_SHEX_source_conductor_W = ...
        read_optional_simscape_on_grid(sim_out, model_name, ...
        'SHEX/HotSinkAmbientLink', 'Q', time_s, 'W');
    physical.Q_SHEX_sink_mass_W = read_optional_simscape_on_grid( ...
        sim_out, model_name, 'SHEX/HotSinkMass', 'Q', time_s, 'W');
    physical = collect_exchanger_energy_boundaries( ...
        physical, sim_out, model_name, time_s);
    if include_legacy_inventory
        physical = collect_fluid_inventory_energy( ...
            physical, sim_out, model_name, time_s);
    end
    [physical.P_pressure_source_native_W, ...
        physical.pump_pressure_port_A_MPa, ...
        physical.pump_pressure_port_B_MPa, ...
        physical.pump_pressure_port_names] = ...
        collect_pressure_source_native_power(sim_out, model_name, time_s);
    physical.SHEX_buffer_T_K = read_on_grid(sim_out, ...
        'shex_buffer_temp_out', time_s, 'linear');
    physical.HHEX_buffer_T_K = read_on_grid(sim_out, ...
        'hot_buffer_temp_out', time_s, 'linear');
    physical.SMA_HHEX_buffer_T_K = read_on_grid(sim_out, ...
        'sma_hot_buffer_temp_out', time_s, 'linear');
    physical.CHEX_buffer_T_K = read_on_grid(sim_out, ...
        'cold_buffer_temp_out', time_s, 'linear');

    physical.mdot_SMA_kgps = read_on_grid(sim_out, ...
        'mass_flow_sma_stage13_kgps', time_s, 'linear');
    physical.mdot_SMA_stage1_route_kgps = read_on_grid(sim_out, ...
        'mass_flow_sma_stage1_route_kgps', time_s, 'linear');
    physical.mdot_SMA_stage3_route_kgps = read_on_grid(sim_out, ...
        'mass_flow_sma_stage3_route_kgps', time_s, 'linear');
    physical.mdot_SE_stage2_in_kgps = read_on_grid(sim_out, ...
        'mass_flow_v1_cold_inlet_kgps', time_s, 'linear');
    physical.mdot_SE_stage2_out_kgps = read_on_grid(sim_out, ...
        'mass_flow_v3_sma_to_hot_kgps', time_s, 'linear');
    physical.mdot_SE_stage4_in_kgps = read_on_grid(sim_out, ...
        'mass_flow_v4_hot_inlet_kgps', time_s, 'linear');
    physical.mdot_SE_stage4_out_kgps = read_on_grid(sim_out, ...
        'mass_flow_v6_sma_to_chip_cold_kgps', time_s, 'linear');
    physical.pressure_command_SE_MPa = read_on_grid(sim_out, ...
        'pressure_command_se_MPa', time_s, 'previous');
    physical.pressure_command_SMA_MPa = read_on_grid(sim_out, ...
        'pressure_command_sma_MPa', time_s, 'previous');
    physical = collect_control_volume_aliases(physical);
    pressure_names = sma_pressure_probe_names();
    physical.SMA_water_pressure_MPa = zeros( ...
        numel(time_s), numel(pressure_names));
    for pressure_idx = 1:numel(pressure_names)
        physical.SMA_water_pressure_MPa(:, pressure_idx) = read_on_grid( ...
            sim_out, pressure_names{pressure_idx}, time_s, 'linear');
    end
    physical.SMA_water_pressure_names = pressure_names;

    physical.SMA_stage1_Tin_K = read_on_grid(sim_out, ...
        'sma_stage1_inlet_fluid_temp_out', time_s, 'linear');
    physical.SMA_stage1_Tout_K = read_on_grid(sim_out, ...
        'sma_stage1_outlet_fluid_temp_out', time_s, 'linear');
    physical.SMA_stage3_Tin_K = read_on_grid(sim_out, ...
        'sma_stage3_inlet_fluid_temp_out', time_s, 'linear');
    physical.SMA_stage3_Tout_K = read_on_grid(sim_out, ...
        'sma_stage3_outlet_fluid_temp_out', time_s, 'linear');
    physical.SE_stage2_Tin_K = read_on_grid(sim_out, ...
        'probe_sma_stage2_port1_v1_side_T_K', time_s, 'linear');
    physical.SE_stage2_Tout_K = read_on_grid(sim_out, ...
        'probe_sma_stage2_port2_v3_side_T_K', time_s, 'linear');
    physical.SE_stage4_Tin_K = read_on_grid(sim_out, ...
        'probe_sma_stage4_port3_v4_side_T_K', time_s, 'linear');
    physical.SE_stage4_Tout_K = read_on_grid(sim_out, ...
        'probe_sma_stage4_port4_v6_side_T_K', time_s, 'linear');

    physical.Q_SMA_constitutive_21_W = read_on_grid(sim_out, ...
        'ECC_Q_SMA_constitutive_W', time_s, 'previous');
    physical.Q_SE_constitutive_21_W = read_on_grid(sim_out, ...
        'ECC_Q_SE_constitutive_W', time_s, 'previous');
    physical.Q_SMA_hold_pipe_to_solid_21_W = read_pipe_heat_flow_matrix( ...
        sim_out, time_s, 'sma', 'hold', options.node_count);
    physical.Q_SMA_cooldown_pipe_to_solid_21_W = read_pipe_heat_flow_matrix( ...
        sim_out, time_s, 'sma', 'cooldown', options.node_count);
    physical.Q_SE_hold_pipe_to_solid_21_W = read_pipe_heat_flow_matrix( ...
        sim_out, time_s, 'se', 'hold', options.node_count);
    physical.Q_SE_cooldown_pipe_to_solid_21_W = ...
        zeros(numel(time_s), options.node_count);
    constitutive = read_on_grid(sim_out, ...
        'ECC_constitutive21_output', time_s, 'previous');
    physical = unpack_constitutive_state(physical, constitutive, options);
    physical = collect_temperature_probes(physical, sim_out, available, time_s);

    rho_fluid = 997.0;
    physical.fluid_density_kg_per_m3 = rho_fluid;
    physical.pump_power_SMA_W = abs(physical.pressure_command_SMA_MPa) * ...
        1.0e6 .* abs(physical.mdot_SMA_kgps) / rho_fluid;
    se_flow = max(abs(physical.mdot_SE_stage2_in_kgps), ...
        abs(physical.mdot_SE_stage4_in_kgps));
    physical.pump_power_SE_W = abs(physical.pressure_command_SE_MPa) * ...
        1.0e6 .* se_flow / rho_fluid;
end

function physical = collect_control_volume_aliases(physical)
% Export explicit control-volume names without changing any model signal.
% The route-specific fields remain available so a single scalar alias cannot
% hide the two active SE paths or the separate SMA HHEX channel.
    physical.control_volume_observation_schema = ...
        'heatdrive_ecc_control_volume_observation_v1';
    physical.SHEX_mdot_kgps = physical.mdot_SMA_kgps;
    physical.HHEX_mdot_SE_kgps = physical.mdot_SE_stage2_out_kgps;
    physical.HHEX_mdot_SMA_kgps = physical.mdot_SMA_stage3_route_kgps;
    physical.CHEX_mdot_SE_kgps = physical.mdot_SE_stage4_out_kgps;
    physical.Q_SHEX_fluid_W = physical.Q_SHEX_sink_to_fluid_W;
    physical.Q_HHEX_fluid_W = physical.Q_HHEX_sink_to_SE_fluid_W;
    physical.Q_CHEX_fluid_W = physical.Q_CHEX_sink_to_fluid_W;
    physical.control_volume_derivation = struct( ...
        'SHEX_mdot', 'direct workspace route signal: mdot_SMA_kgps', ...
        'HHEX_mdot_SE', 'direct workspace route signal: mdot_SE_stage2_out_kgps', ...
        'HHEX_mdot_SMA', 'direct workspace route signal: mdot_SMA_stage3_route_kgps', ...
        'CHEX_mdot_SE', 'direct workspace route signal: mdot_SE_stage4_out_kgps', ...
        'SHEX_fluid_heat', 'native Simscape log: SHEX/HotSinkFluidLink/Q', ...
        'HHEX_fluid_heat', 'native Simscape log: HHEX HotSinkFluidLink/Q', ...
        'CHEX_fluid_heat', 'native Simscape log: CHEX ColdSinkFluidLink/Q');
end

function physical = collect_exchanger_energy_boundaries( ...
        physical, sim_out, model_name, time_s)
% Preserve native sign conventions; audits assign source/sink roles.

    hhex_sma_link = find_unique_block(model_name, 'HotSinkSMAFluidLink');
    hhex_parent = get_param(hhex_sma_link, 'Parent');
    physical.Q_HHEX_sink_to_ambient_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [hhex_parent '/HotSinkAmbientLink']), 'Q', time_s, 'W');
    physical.Q_HHEX_sink_to_SE_fluid_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [hhex_parent '/HotSinkFluidLink']), 'Q', time_s, 'W');
    physical.Q_HHEX_sink_to_SMA_fluid_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [hhex_parent '/HotSinkSMAFluidLink']), 'Q', time_s, 'W');
    physical.Q_HHEX_sink_mass_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [hhex_parent '/HotSinkMass']), 'Q', time_s, 'W');

    chex_sensor = find_unique_block( ...
        model_name, 'ColdSinkMassToPipeHeatFlowSensor');
    chex_parent = get_param(chex_sensor, 'Parent');
    physical.Q_CHEX_sink_to_fluid_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [chex_parent '/ColdSinkFluidLink']), 'Q', time_s, 'W');
    physical.Q_CHEX_sink_mass_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [chex_parent '/ColdSinkMass']), 'Q', time_s, 'W');
    physical.Q_CHEX_load_to_sink_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [chex_parent '/ColdLoadToColdSinkLink']), 'Q', time_s, 'W');
    physical.Q_CHEX_sensor_native_W = read_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, chex_sensor), ...
        'Q', time_s, 'W');
    physical.Q_CHEX_fixed_source_W = read_optional_simscape_on_grid( ...
        sim_out, model_name, relative_block_path(model_name, ...
        [chex_parent '/CHEXFixedReservoirTemperatureSource']), ...
        'Q', time_s, 'W');
end

function physical = collect_fluid_inventory_energy( ...
        physical, sim_out, model_name, time_s)
% Sum every finite-volume TL storage block on the runtime model.

    U_pipe_J = zeros(numel(time_s), 1);
    U_buffer_J = zeros(numel(time_s), 1);
    U_manifold_J = zeros(numel(time_s), 1);
    M_pipe_kg = zeros(numel(time_s), 1);
    M_buffer_kg = zeros(numel(time_s), 1);
    M_manifold_kg = zeros(numel(time_s), 1);

    pipe_blocks = find_system(model_name, 'LookUnderMasks', 'all', ...
        'FollowLinks', 'on', 'Type', 'Block', 'MaskType', 'Pipe (TL)');
    pipe_names = cell(numel(pipe_blocks), 1);
    pipe_mass_kg = zeros(numel(time_s), numel(pipe_blocks));
    pipe_internal_energy_J = zeros(numel(time_s), numel(pipe_blocks));
    pipe_specific_internal_energy_J_per_kg = zeros( ...
        numel(time_s), numel(pipe_blocks));
    pipe_port_mdot_A_kgps = NaN(numel(time_s), numel(pipe_blocks));
    pipe_port_mdot_B_kgps = NaN(numel(time_s), numel(pipe_blocks));
    pipe_port_energy_A_W = NaN(numel(time_s), numel(pipe_blocks));
    pipe_port_energy_B_W = NaN(numel(time_s), numel(pipe_blocks));
    for idx = 1:numel(pipe_blocks)
        path = pipe_blocks{idx};
        volume_m3 = evaluate_mask_parameter(path, 'area') * ...
            evaluate_mask_parameter(path, 'length');
        [U_J, M_kg, ~, u_J_per_kg] = finite_volume_internal_energy( ...
            sim_out, model_name, path, volume_m3, time_s);
        U_pipe_J = U_pipe_J + U_J;
        M_pipe_kg = M_pipe_kg + M_kg;
        pipe_names{idx} = relative_block_path(model_name, path);
        pipe_mass_kg(:, idx) = M_kg;
        pipe_internal_energy_J(:, idx) = U_J;
        pipe_specific_internal_energy_J_per_kg(:, idx) = u_J_per_kg;
        relative = relative_block_path(model_name, path);
        [mdot_A, mdot_A_name] = read_optional_simscape_candidates( ...
            sim_out, model_name, relative, {'mdot_A', 'm_dot_A'}, ...
            time_s, 'kg/s');
        [mdot_B, mdot_B_name] = read_optional_simscape_candidates( ...
            sim_out, model_name, relative, {'mdot_B', 'm_dot_B'}, ...
            time_s, 'kg/s');
        [phi_A, phi_A_name] = read_optional_simscape_candidates( ...
            sim_out, model_name, relative, {'Phi_A'}, ...
            time_s, 'W');
        [phi_B, phi_B_name] = read_optional_simscape_candidates( ...
            sim_out, model_name, relative, {'Phi_B'}, ...
            time_s, 'W');
        pipe_port_mdot_A_kgps(:, idx) = mdot_A;
        pipe_port_mdot_B_kgps(:, idx) = mdot_B;
        if ~isempty(mdot_A_name) && ~isempty(mdot_B_name) && ...
                ~isempty(phi_A_name) && ~isempty(phi_B_name)
            pipe_port_energy_A_W(:, idx) = phi_A;
            pipe_port_energy_B_W(:, idx) = phi_B;
        end
    end

    buffer_blocks = find_system(model_name, 'LookUnderMasks', 'all', ...
        'FollowLinks', 'on', 'Type', 'Block', 'MaskType', 'Tank (TL)');
    buffer_names = cell(numel(buffer_blocks), 1);
    buffer_mass_kg = zeros(numel(time_s), numel(buffer_blocks));
    buffer_internal_energy_J = zeros(numel(time_s), numel(buffer_blocks));
    buffer_specific_internal_energy_J_per_kg = zeros( ...
        numel(time_s), numel(buffer_blocks));
    buffer_port_mdot_A_kgps = NaN(numel(time_s), numel(buffer_blocks));
    buffer_port_mdot_B_kgps = NaN(numel(time_s), numel(buffer_blocks));
    for idx = 1:numel(buffer_blocks)
        path = buffer_blocks{idx};
        relative = relative_block_path(model_name, path);
        mass_kg = read_simscape_on_grid( ...
            sim_out, model_name, relative, 'mass', time_s, 'kg');
        u_J_per_kg = read_simscape_on_grid( ...
            sim_out, model_name, relative, 'u_I', time_s, 'J/kg');
        U_buffer_J = U_buffer_J + mass_kg .* u_J_per_kg;
        M_buffer_kg = M_buffer_kg + mass_kg;
        buffer_names{idx} = relative;
        buffer_mass_kg(:, idx) = mass_kg;
        buffer_internal_energy_J(:, idx) = mass_kg .* u_J_per_kg;
        buffer_specific_internal_energy_J_per_kg(:, idx) = u_J_per_kg;
        [buffer_port_mdot_A_kgps(:, idx), ~] = ...
            read_optional_simscape_candidates(sim_out, model_name, ...
            relative, {'mdot_A', 'm_dot_A'}, time_s, 'kg/s');
        [buffer_port_mdot_B_kgps(:, idx), ~] = ...
            read_optional_simscape_candidates(sim_out, model_name, ...
            relative, {'mdot_B', 'm_dot_B'}, time_s, 'kg/s');
    end

    manifold_blocks = find_system(model_name, 'LookUnderMasks', 'all', ...
        'FollowLinks', 'on', 'Type', 'Block', ...
        'MaskType', 'Constant Volume Chamber (TL)');
    manifold_names = cell(numel(manifold_blocks), 1);
    manifold_mass_kg = zeros(numel(time_s), numel(manifold_blocks));
    manifold_internal_energy_J = zeros(numel(time_s), numel(manifold_blocks));
    manifold_specific_internal_energy_J_per_kg = zeros( ...
        numel(time_s), numel(manifold_blocks));
    for idx = 1:numel(manifold_blocks)
        path = manifold_blocks{idx};
        volume_m3 = evaluate_mask_parameter(path, 'volume');
        [U_J, M_kg, ~, u_J_per_kg] = finite_volume_internal_energy( ...
            sim_out, model_name, path, volume_m3, time_s);
        U_manifold_J = U_manifold_J + U_J;
        M_manifold_kg = M_manifold_kg + M_kg;
        manifold_names{idx} = relative_block_path(model_name, path);
        manifold_mass_kg(:, idx) = M_kg;
        manifold_internal_energy_J(:, idx) = U_J;
        manifold_specific_internal_energy_J_per_kg(:, idx) = u_J_per_kg;
    end

    physical.U_pipe_inventory_J = U_pipe_J;
    physical.U_buffer_inventory_J = U_buffer_J;
    physical.U_manifold_inventory_J = U_manifold_J;
    physical.U_fluid_inventory_J = U_pipe_J + U_buffer_J + U_manifold_J;
    physical.M_pipe_inventory_kg = M_pipe_kg;
    physical.M_buffer_inventory_kg = M_buffer_kg;
    physical.M_manifold_inventory_kg = M_manifold_kg;
    physical.M_fluid_inventory_kg = M_pipe_kg + M_buffer_kg + M_manifold_kg;
    physical.pipe_inventory_names = pipe_names;
    physical.pipe_inventory_mass_kg = pipe_mass_kg;
    physical.pipe_inventory_internal_energy_J = pipe_internal_energy_J;
    physical.pipe_inventory_specific_internal_energy_J_per_kg = ...
        pipe_specific_internal_energy_J_per_kg;
    physical.buffer_inventory_names = buffer_names;
    physical.buffer_inventory_mass_kg = buffer_mass_kg;
    physical.buffer_inventory_internal_energy_J = buffer_internal_energy_J;
    physical.buffer_inventory_specific_internal_energy_J_per_kg = ...
        buffer_specific_internal_energy_J_per_kg;
    physical.buffer_port_mdot_A_kgps = buffer_port_mdot_A_kgps;
    physical.buffer_port_mdot_B_kgps = buffer_port_mdot_B_kgps;
    [physical.buffer_inlet_mdot_kgps, physical.buffer_outlet_mdot_kgps] = ...
        signed_single_port_in_out(buffer_port_mdot_A_kgps);
    physical.buffer_port_topology = repmat( ...
        {'Tank (TL): single conserving port A; port B not applicable'}, ...
        numel(buffer_blocks), 1);
    physical.manifold_inventory_names = manifold_names;
    physical.manifold_inventory_mass_kg = manifold_mass_kg;
    physical.manifold_inventory_internal_energy_J = ...
        manifold_internal_energy_J;
    physical.manifold_inventory_specific_internal_energy_J_per_kg = ...
        manifold_specific_internal_energy_J_per_kg;
    physical.pipe_port_mdot_A_kgps = pipe_port_mdot_A_kgps;
    physical.pipe_port_mdot_B_kgps = pipe_port_mdot_B_kgps;
    physical.pipe_port_energy_A_W = pipe_port_energy_A_W;
    physical.pipe_port_energy_B_W = pipe_port_energy_B_W;
    [physical.pipe_inlet_energy_flow_W, ...
        physical.pipe_outlet_energy_flow_W] = signed_port_in_out( ...
        pipe_port_energy_A_W, pipe_port_energy_B_W);
end

function [U_J, M_kg, rho_kg_per_m3, u_J_per_kg] = finite_volume_internal_energy( ...
        sim_out, model_name, full_path, volume_m3, time_s)
    assert(isfinite(volume_m3) && volume_m3 > 0.0, ...
        'Run:EighthRound:InvalidFluidInventoryVolume', ...
        'Invalid TL storage volume for %s.', full_path);
    relative = relative_block_path(model_name, full_path);
    rho_kg_per_m3 = read_simscape_on_grid( ...
        sim_out, model_name, relative, 'rho_I', time_s, 'kg/m^3');
    u_J_per_kg = read_simscape_on_grid( ...
        sim_out, model_name, relative, 'u_I', time_s, 'J/kg');
    M_kg = rho_kg_per_m3 .* volume_m3;
    U_J = M_kg .* u_J_per_kg;
end

function value = evaluate_mask_parameter(block_path, parameter_name)
    expression = get_param(block_path, parameter_name);
    try
        value = evalin('base', expression);
    catch exception
        error('Run:EighthRound:FluidInventoryParameterEvaluationFailed', ...
            'Cannot evaluate %s=%s for %s: %s', parameter_name, ...
            expression, block_path, exception.message);
    end
    assert(isnumeric(value) && isscalar(value) && isfinite(value), ...
        'Run:EighthRound:InvalidFluidInventoryParameter', ...
        '%s must evaluate to one finite number for %s.', ...
        parameter_name, block_path);
    value = double(value);
end

function [total_W, pressure_A_MPa, pressure_B_MPa, names] = ...
        collect_pressure_source_native_power( ...
        sim_out, model_name, time_s)
    blocks = find_system(model_name, 'LookUnderMasks', 'all', ...
        'FollowLinks', 'on', 'Type', 'Block', ...
        'MaskType', 'Pressure Source (TL)');
    assert(numel(blocks) == 3, ...
        'Run:EighthRound:PressureSourceCountMismatch', ...
        'Expected three TL pressure-source faces, found %d.', numel(blocks));
    total_W = zeros(numel(time_s), 1);
    pressure_A_MPa = NaN(numel(time_s), numel(blocks));
    pressure_B_MPa = NaN(numel(time_s), numel(blocks));
    names = cell(numel(blocks), 1);
    for idx = 1:numel(blocks)
        names{idx} = relative_block_path(model_name, blocks{idx});
        total_W = total_W + read_simscape_on_grid( ...
            sim_out, model_name, names{idx}, ...
            'power', time_s, 'W');
        [pressure_A_MPa(:, idx), ~] = ...
            read_optional_simscape_candidates(sim_out, model_name, ...
            names{idx}, {'p_A', 'P_A', 'p'}, time_s, 'MPa');
        [pressure_B_MPa(:, idx), ~] = ...
            read_optional_simscape_candidates(sim_out, model_name, ...
            names{idx}, {'p_B', 'P_B', 'p'}, time_s, 'MPa');
    end
end

function [values, selected_name] = read_optional_simscape_candidates( ...
        sim_out, model_name, block_path, candidates, query_time_s, unit)
% Try native log spellings without converting a missing port to a pass.
    values = NaN(numel(query_time_s), 1);
    selected_name = '';
    for idx = 1:numel(candidates)
        try
            values = read_simscape_on_grid(sim_out, model_name, ...
                block_path, candidates{idx}, query_time_s, unit);
            selected_name = candidates{idx};
            return
        catch exception
            if ~strcmp(exception.identifier, ...
                    'Run:EighthRound:MissingSimscapeLogNode')
                rethrow(exception);
            end
        end
    end
end

function [inlet, outlet] = signed_port_in_out(port_A, port_B)
% Simscape TL port flow is signed into the logged component.
    inlet = sum(max(cat(3, port_A, port_B), 0), 3);
    outlet = sum(max(-cat(3, port_A, port_B), 0), 3);
end

function [inlet, outlet] = signed_single_port_in_out(port_A)
% Tank (TL) has one conserving port; its signed mdot_A is sufficient.
    inlet = max(port_A, 0);
    outlet = max(-port_A, 0);
end


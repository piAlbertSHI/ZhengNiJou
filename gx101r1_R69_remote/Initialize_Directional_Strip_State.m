function [T_strip_101_in, init_report] = Initialize_Directional_Strip_State(T_r_51, strip_geometry)
% Initialize a directional 101-strip state from the solver's 51-point radial state.

    if nargin < 2 || isempty(strip_geometry)
        strip_geometry = Build_Diameter_Strip_Geometry();
    end

    T_r_51 = T_r_51(:);
    if numel(T_r_51) ~= strip_geometry.radial_node_count
        error('Initialize_Directional_Strip_State:NodeCountMismatch', ...
            'Expected %d radial values, got %d.', ...
            strip_geometry.radial_node_count, numel(T_r_51));
    end
    if any(~isfinite(T_r_51))
        error('Initialize_Directional_Strip_State:InvalidTemperature', ...
            'T_r_51 must contain only finite values.');
    end

    if strip_geometry.strip_count ~= 2 * strip_geometry.radial_node_count - 1
        error('Initialize_Directional_Strip_State:UnsupportedGeometry', ...
            'AF-1 requires strip_count = 2 * radial_node_count - 1.');
    end

    T_strip_101_in = [flipud(T_r_51(2:end)); T_r_51];
    init_report = struct( ...
        'initial_state_kind', 'axisymmetric_expansion', ...
        'final_exchange_state_must_be_directional', true, ...
        'source_node_count', numel(T_r_51), ...
        'target_strip_count', numel(T_strip_101_in), ...
        'source_min_T', min(T_r_51), ...
        'source_max_T', max(T_r_51), ...
        'target_min_T', min(T_strip_101_in), ...
        'target_max_T', max(T_strip_101_in));
end

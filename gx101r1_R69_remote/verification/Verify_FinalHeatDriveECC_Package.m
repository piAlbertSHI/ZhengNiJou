        'periodic steady state:\s*([01])', 'tokens', 'once');
    strict_match = regexp(report_text, ...
        'strict_table4_reproduction_pass:\s*([01])', 'tokens', 'once');
    c200_contract = jsondecode(fileread(c200_contract_path));
    c200_strict_restore = jsondecode(fileread(c200_strict_restore_path));
    initial_summary = jsondecode(fileread(initial_summary_path));
    refined_summary = jsondecode(fileread(refined_summary_path));
    initial_effects = readtable(initial_effects_path, 'TextType', 'string');
    refined_effects = readtable(refined_effects_path, 'TextType', 'string');
    ultrafine_summary = jsondecode(fileread(ultrafine_summary_path));
    ultrafine_effects = readtable(ultrafine_effects_path, ...
        'TextType', 'string');
    source_c240 = jsondecode(fileread(source_c240_contract_path));

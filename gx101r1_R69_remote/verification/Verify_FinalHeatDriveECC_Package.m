        runtime_tc_clean11_outer_path));
    runtime_tc_clean11_records = runtime_tc_clean11_outer.records;
    runtime_tc_clean11_idx = find(abs([runtime_tc_clean11_records.Tc_K] - ...
        276.94) < 1.0e-9);

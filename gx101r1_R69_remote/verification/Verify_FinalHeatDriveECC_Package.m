    audit.runtime_tc_window_rejection_pass = ...
        strcmp(runtime_tc_window_outer.status, 'no_valid_bracket') && ...
        runtime_tc_window_outer.accepted_count == 1 && ...
        runtime_tc_window_outer.rejected_count == 1 && ...
        isscalar(runtime_tc_window_idx) && ...
        ~logical(runtime_tc_window_records(runtime_tc_window_idx).admissible) && ...
        ~logical(runtime_tc_window_records(runtime_tc_window_idx).mechanism_pass) && ...

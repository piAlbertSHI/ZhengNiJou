    audit.all_required_pass = logical(last.all_required_pass);
    audit.strict_table4_reproduction = ~isempty(strict_match) && ...
        logical(str2double(strict_match{1}));
    audit.c200_state_recovery_allowed_current_model = logical( ...
        c200_contract.resume_policy.state_recovery_allowed_current_model);
    audit.c200_strict_restore_pass_current_model = logical( ...
        c200_strict_restore.strict_restore_pass);
    audit.c200_contents_checksum_mismatch_current_model = logical( ...
        c200_strict_restore.contents_checksum_mismatch_detected);
    audit.initial_local_completed_count = initial_summary.completed_count;
    audit.initial_local_admissible_count = initial_summary.admissible_count;
    audit.initial_local_strict_pair_count = ...
        initial_summary.strict_local_pair_count;
    audit.refined_local_completed_count = refined_summary.completed_count;
    audit.refined_local_admissible_count = refined_summary.admissible_count;
    audit.refined_local_pending_count = refined_summary.pending_count;
    audit.refined_local_strict_pair_count = ...
        refined_summary.strict_local_pair_count;
    audit.ultrafine_endpoint_completed_count = ultrafine_summary.completed_count;
    audit.ultrafine_endpoint_admissible_count = ultrafine_summary.admissible_count;
    audit.ultrafine_endpoint_rejected_count = ultrafine_summary.rejected_count;
    audit.ultrafine_endpoint_pending_count = ultrafine_summary.pending_count;
    audit.ultrafine_endpoint_strict_pair_count = ...
        ultrafine_summary.strict_local_pair_count;
    audit.local_sensitivity_completed_count = 12;
    audit.local_sensitivity_admissible_count = 11;
    audit.local_sensitivity_strict_pair_count = ...
        numel(consolidated_pair_names);
    audit.local_sensitivity_strict_pair_factors = ...
        consolidated_pair_names;
    audit.source_heatflow_c240_cycles = source_c240.completed_cycles;
    audit.source_heatflow_c240_mechanism_pass = logical( ...
        source_c240.mechanism_pass);
    audit.source_heatflow_c240_periodic_steady_state = logical( ...
        source_c240.periodic_steady_state);
    audit.source_heatflow_c240_direction_pass = logical( ...
        source_c240.source_heat_flow_direction_pass);

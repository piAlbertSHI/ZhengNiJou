            all(isnan(refined_effects{idx, effect_names}));
    end
    ultrafine_effect_names = ultrafine_effects.Properties.VariableNames;
    ultrafine_effect_names = ultrafine_effect_names(endsWith( ...
        ultrafine_effect_names, '_derivative_per_fraction'));
    ultrafine_unavailable_effects_are_nan = ...
        ~any(ultrafine_strict) && all(all(isnan(ultrafine_effects{:, ...
        ultrafine_effect_names})));
    assert(~isempty(mechanism_match) && ~isempty(periodic_match), ...
        'Validation report is missing authoritative mechanism/periodic fields.');


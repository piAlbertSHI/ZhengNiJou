        'Missing runtime builder determinism audit.');
    assert(isfile(runtime_tc_window_outer_path), ...
        'Missing C249 transition-window outer summary.');
    assert(isfile(runtime_tc_window_audit_path), ...
        'Missing C249 transition-window system-energy audit.');

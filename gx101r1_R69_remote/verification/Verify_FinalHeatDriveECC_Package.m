            ~audit.system_c243_complete_device_first_law_closure, ...
        'runtime_c246_performance_evidence_and_restore_rejection_pass', ...
            audit.runtime_c246_cycles == 246 && ...
            ~audit.runtime_c246_bridge_pass && ...
            audit.runtime_c246_runtime_configurability && ...
            logical(runtime_c246_bridge.Tc_unchanged) && ...
            logical(runtime_c246_bridge.checkpoint_restart_used) && ...
            logical(runtime_c246_bridge.checkpoint_chain_verified) && ...
            logical(runtime_c246_bridge.time_continuity_verified) && ...
            logical(runtime_c246_bridge.segment_start_matches_authority) && ...
            logical(runtime_c246_bridge.state_reset) && ...
            ~logical(runtime_c246_bridge.complete_operating_point_restore_verified) && ...
            logical(runtime_c246_bridge.contents_checksum_mismatch_detected) && ...
            ~audit.runtime_c246_state_recovery_allowed && ...
            ~audit.runtime_c246_strict_restore_pass && ...
            audit.runtime_c246_contents_checksum_mismatch && ...
            audit.runtime_c246_mechanism_pass && ...
            audit.runtime_c246_periodic_steady_state && ...
            audit.runtime_c246_modeled_thermal_closure_pass && ...
            audit.runtime_c246_fluid_mass_conservation_pass && ...
            logical(runtime_c246_audit.production_pass) && ...
            runtime_c246_audit.modeled_thermal_residual_relative <= 1.0e-3 && ...
            runtime_c246_audit.fluid_mass_drift_relative <= 1.0e-5 && ...
            ~logical(runtime_c246_audit.complete_device_first_law_closure), ...
        'runtime_tc_window_rejection_pass', ...
            audit.runtime_tc_window_rejection_pass, ...
        'runtime_tc_clean11_rejection_pass', ...
            audit.runtime_tc_clean11_rejection_pass, ...
        'runtime_builder_determinism_pass', ...

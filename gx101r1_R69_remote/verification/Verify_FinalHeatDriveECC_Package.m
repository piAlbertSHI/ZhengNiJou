        shex_control.sink_to_fluid_heat_flow_mean_W;
    audit.shex_control_volume_c240_transfer_ratio = ...
        shex_control.transfer_ratio;
    audit.shex_control_volume_c240_complete_system_closure = logical( ...
        shex_control.system_energy_closure_complete);
    audit.system_c243_cycles = system_c243.completed_cycles;

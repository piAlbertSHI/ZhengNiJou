function audit = Verify_FinalHeatDriveECC_Package(package_root)
% Result-only audit for the completed fixed-CHEX C200 package.
% This function does not start a simulation and does not alter checkpoints.

    if nargin < 1 || isempty(package_root)
        package_root = fileparts(fileparts(mfilename('fullpath')));
    end
    package_root = char(string(package_root));
    main_root = fullfile(package_root, 'outputs', ...
        'qian_table4_fixed_Tc_276p950K_kp136_255_steady_from_valid107_20260821');
    progress_path = fullfile(main_root, 'steady_continuation_progress.csv');
    report_path = fullfile(main_root, ...
        'qian2019_table2_table4_simscape_200cycle_20260821_121246', ...
        'physical_validation_report.txt');
    manifest_path = fullfile(main_root, 'fixed_reservoir_point_manifest.txt');
    initial_root = fullfile(package_root, 'outputs', ...
        'qian_table4_local_oat_sensitivity_20260824');
    refined_root = fullfile(package_root, 'outputs', ...
        'qian_table4_local_oat_refined_sensitivity_20260826');
    initial_summary_path = fullfile(initial_root, 'sensitivity_summary.json');
    initial_effects_path = fullfile(initial_root, 'sensitivity_effects.csv');
    refined_summary_path = fullfile(refined_root, 'sensitivity_summary.json');
    refined_effects_path = fullfile(refined_root, 'sensitivity_effects.csv');
    ultrafine_root = fullfile(package_root, 'outputs', ...
        'qian_table4_endpoint_capacity_ultrafine_20260830');
    ultrafine_summary_path = fullfile(ultrafine_root, 'sensitivity_summary.json');
    ultrafine_effects_path = fullfile(ultrafine_root, 'sensitivity_effects.csv');
    source_c240_contract_path = fullfile(package_root, 'verification', ...
        'source_heatflow_c240_recovery_contract.json');
    shex_control_summary_path = fullfile(package_root, ...
        'outputs_storage_audit', 'shex_control_volume_c240_20260903', ...
        'shex_control_volume_summary.json');

    assert(isfile(progress_path), 'Missing steady_continuation_progress.csv.');
    assert(isfile(report_path), 'Missing C200 physical validation report.');
    assert(isfile(manifest_path), 'Missing fixed-reservoir manifest.');
    assert(isfile(initial_summary_path), 'Missing initial local OAT summary.');
    assert(isfile(initial_effects_path), 'Missing initial local OAT effects.');
    assert(isfile(refined_summary_path), 'Missing refined local OAT summary.');
    assert(isfile(refined_effects_path), 'Missing refined local OAT effects.');
    assert(isfile(ultrafine_summary_path), ...
        'Missing ultrafine endpoint-capacity summary.');
    assert(isfile(ultrafine_effects_path), ...
        'Missing ultrafine endpoint-capacity effects.');
    assert(isfile(source_c240_contract_path), ...
        'Missing C240 source heat-flow recovery contract.');
    assert(isfile(shex_control_summary_path), ...
        'Missing frozen C240 SHEX control-volume summary.');

    progress = readtable(progress_path, 'TextType', 'string');
    last = progress(end, :);
    report_text = fileread(report_path);
    mechanism_match = regexp(report_text, ...
        'coupled_mechanism_pass:\s*([01])', 'tokens', 'once');
    periodic_match = regexp(report_text, ...
        'periodic steady state:\s*([01])', 'tokens', 'once');
    strict_match = regexp(report_text, ...
        'strict_table4_reproduction_pass:\s*([01])', 'tokens', 'once');
    initial_summary = jsondecode(fileread(initial_summary_path));
    refined_summary = jsondecode(fileread(refined_summary_path));
    initial_effects = readtable(initial_effects_path, 'TextType', 'string');
    refined_effects = readtable(refined_effects_path, 'TextType', 'string');
    ultrafine_summary = jsondecode(fileread(ultrafine_summary_path));
    ultrafine_effects = readtable(ultrafine_effects_path, ...
        'TextType', 'string');
    source_c240 = jsondecode(fileread(source_c240_contract_path));
    shex_control = jsondecode(fileread(shex_control_summary_path));
    initial_strict = logical(initial_effects.strict_local_pair_available);
    refined_strict = logical(refined_effects.strict_local_pair_available);
    initial_pair_names = sort(initial_effects.factor(initial_strict));
    refined_pair_names = sort(refined_effects.factor(refined_strict));
    ultrafine_strict = logical(ultrafine_effects.strict_local_pair_available);
    expected_initial_names = sort(["SE_buffer"; ...
        "regenerator_utilization"]);
    expected_refined_names = sort(["UA"; "fluid_inventory"; ...
        "regenerator_utilization"; "latent_heat"]);
    consolidated_pair_names = sort(unique(["SE_buffer"; ...
        refined_pair_names]));
    expected_consolidated_names = sort(["UA"; "SE_buffer"; ...
        "fluid_inventory"; "regenerator_utilization"; "latent_heat"]);
    unavailable_effects_are_nan = true;
    effect_names = refined_effects.Properties.VariableNames;
    effect_names = effect_names(endsWith(effect_names, ...
        '_derivative_per_fraction'));
    for idx = find(~refined_strict)'
        unavailable_effects_are_nan = unavailable_effects_are_nan && ...
            all(isnan(refined_effects{idx, effect_names}));
    end
    ultrafine_effect_names = ultrafine_effects.Properties.VariableNames;
    ultrafine_effect_names = ultrafine_effect_names(endsWith( ...
        ultrafine_effect_names, '_derivative_per_fraction'));
    ultrafine_unavailable_effects_are_nan = ...
        ~any(ultrafine_strict) && all(all(isnan(ultrafine_effects{:, ...
        ultrafine_effect_names})));
    assert(~isempty(mechanism_match) && ~isempty(periodic_match), ...
        'Validation report is missing authoritative mechanism/periodic fields.');

    audit = struct();
    audit.schema = 'heatdrive_ecc_result_only_audit_v2';
    audit.progress_rows = height(progress);
    audit.completed_cycles = last.total_cycles;
    % The progress CSV retains the historical all-required-pass field. The
    % authoritative robust periodic gate is the final validation report,
    % which includes P99/RMS statistics for the full same-phase fields.
    audit.csv_periodic_field = logical(last.periodic_steady_state);
    audit.mechanism_pass = logical(str2double(mechanism_match{1}));
    audit.periodic_steady_state = logical(str2double(periodic_match{1}));
    audit.endpoint_drift_K = last.endpoint_drift_K;
    audit.same_phase_temperature_drift_K = last.same_phase_temperature_drift_K;
    audit.same_phase_phase_drift = last.same_phase_phase_drift;
    audit.eq9_lift_K = last.eq9_lift_K;
    audit.eq10_SCP_W_per_g = last.eq10_SCP_W_per_g;
    audit.all_required_pass = logical(last.all_required_pass);
    audit.strict_table4_reproduction = ~isempty(strict_match) && ...
        logical(str2double(strict_match{1}));
    audit.initial_local_completed_count = initial_summary.completed_count;
    audit.initial_local_admissible_count = initial_summary.admissible_count;
    audit.initial_local_strict_pair_count = ...
        initial_summary.strict_local_pair_count;
    audit.refined_local_completed_count = refined_summary.completed_count;
    audit.refined_local_admissible_count = refined_summary.admissible_count;
    audit.refined_local_pending_count = refined_summary.pending_count;
    audit.refined_local_strict_pair_count = ...
        refined_summary.strict_local_pair_count;
    audit.ultrafine_endpoint_completed_count = ultrafine_summary.completed_count;
    audit.ultrafine_endpoint_admissible_count = ultrafine_summary.admissible_count;
    audit.ultrafine_endpoint_rejected_count = ultrafine_summary.rejected_count;
    audit.ultrafine_endpoint_pending_count = ultrafine_summary.pending_count;
    audit.ultrafine_endpoint_strict_pair_count = ...
        ultrafine_summary.strict_local_pair_count;
    audit.local_sensitivity_completed_count = 12;
    audit.local_sensitivity_admissible_count = 11;
    audit.local_sensitivity_strict_pair_count = ...
        numel(consolidated_pair_names);
    audit.local_sensitivity_strict_pair_factors = ...
        consolidated_pair_names;
    audit.source_heatflow_c240_cycles = source_c240.completed_cycles;
    audit.source_heatflow_c240_mechanism_pass = logical( ...
        source_c240.mechanism_pass);
    audit.source_heatflow_c240_periodic_steady_state = logical( ...
        source_c240.periodic_steady_state);
    audit.source_heatflow_c240_direction_pass = logical( ...
        source_c240.source_heat_flow_direction_pass);
    audit.source_heatflow_c240_system_energy_closure_complete = logical( ...
        source_c240.system_energy_closure_complete);
    audit.source_heatflow_c240_COP = source_c240.heat_driven_system_COP;
    audit.shex_control_volume_c240_pass = logical( ...
        shex_control.production_pass);
    audit.shex_control_volume_c240_sink_to_fluid_W = ...
        shex_control.sink_to_fluid_heat_flow_mean_W;
    audit.shex_control_volume_c240_transfer_ratio = ...
        shex_control.transfer_ratio;
    audit.shex_control_volume_c240_complete_system_closure = logical( ...
        shex_control.system_energy_closure_complete);
    audit.checks = struct( ...
        'cycles_200', audit.completed_cycles == 200, ...
        'mechanism_pass', audit.mechanism_pass, ...
        'periodic_steady_state', audit.periodic_steady_state, ...
        'strict_table4_not_claimed', ~audit.strict_table4_reproduction, ...
        'initial_oat_completed_12', ...
            audit.initial_local_completed_count == 12, ...
        'initial_oat_strict_pairs_2', ...
            audit.initial_local_strict_pair_count == 2 && ...
            isequal(initial_pair_names, expected_initial_names), ...
        'refined_oat_completed_10', ...
            audit.refined_local_completed_count == 10 && ...
            audit.refined_local_pending_count == 2, ...
        'refined_oat_strict_pairs_4', ...
            audit.refined_local_strict_pair_count == 4 && ...
            isequal(refined_pair_names, expected_refined_names), ...
        'ultrafine_endpoint_completed_2', ...
            audit.ultrafine_endpoint_completed_count == 2 && ...
            audit.ultrafine_endpoint_pending_count == 10, ...
        'ultrafine_endpoint_admissible_1', ...
            audit.ultrafine_endpoint_admissible_count == 1 && ...
            audit.ultrafine_endpoint_rejected_count == 1, ...
        'ultrafine_endpoint_strict_pair_0', ...
            audit.ultrafine_endpoint_strict_pair_count == 0 && ...
            ultrafine_unavailable_effects_are_nan, ...
        'consolidated_local_pairs_5', ...
            audit.local_sensitivity_strict_pair_count == 5 && ...
            isequal(consolidated_pair_names, ...
                expected_consolidated_names), ...
        'unavailable_local_derivatives_are_nan', ...
            unavailable_effects_are_nan, ...
        'source_heatflow_c240_production_pass', ...
            audit.source_heatflow_c240_cycles == 240 && ...
            audit.source_heatflow_c240_mechanism_pass && ...
            audit.source_heatflow_c240_periodic_steady_state && ...
            audit.source_heatflow_c240_direction_pass && ...
            ~audit.source_heatflow_c240_system_energy_closure_complete && ...
            isfinite(audit.source_heatflow_c240_COP) && ...
            audit.source_heatflow_c240_COP > 0.0, ...
        'shex_control_volume_c240_production_pass', ...
            audit.shex_control_volume_c240_pass && ...
            logical(shex_control.periodic_steady_state) && ...
            logical(shex_control.source_direction_pass) && ...
            logical(shex_control.sink_to_fluid_direction_pass) && ...
            shex_control.cycle_count == 240 && ...
            shex_control.window_start_s == 2300.0 && ...
            shex_control.window_end_s == 2400.0 && ...
            abs(audit.shex_control_volume_c240_transfer_ratio - 1.0) ...
                <= 1.0e-8 && ...
            ~audit.shex_control_volume_c240_complete_system_closure);
    audit.report_path = report_path;
    audit.manifest_path = manifest_path;
    audit.result_package_pass = all(struct2array(audit.checks));

    fprintf('C200 cycles=%d mechanism=%d periodic=%d CSV_periodic_field=%d ALL_REQUIRED_PASS=%d\n', ...
        audit.completed_cycles, audit.mechanism_pass, ...
        audit.periodic_steady_state, audit.csv_periodic_field, audit.all_required_pass);
    fprintf('Eq9=%.12g K SCP=%.12g W/g endpoint=%.12g K same_phase_T=%.12g K phase=%.12g\n', ...
        audit.eq9_lift_K, audit.eq10_SCP_W_per_g, audit.endpoint_drift_K, ...
        audit.same_phase_temperature_drift_K, audit.same_phase_phase_drift);
    fprintf(['LOCAL_OAT consolidated_points=%d admissible=%d ', ...
        'strict_pairs=%d factors=%s\n'], ...
        audit.local_sensitivity_completed_count, ...
        audit.local_sensitivity_admissible_count, ...
        audit.local_sensitivity_strict_pair_count, ...
        strjoin(cellstr(consolidated_pair_names), ','));
    fprintf(['ULTRAFINE_ENDPOINT completed=%d admissible=%d rejected=%d ', ...
        'pending=%d strict_pairs=%d\n'], ...
        audit.ultrafine_endpoint_completed_count, ...
        audit.ultrafine_endpoint_admissible_count, ...
        audit.ultrafine_endpoint_rejected_count, ...
        audit.ultrafine_endpoint_pending_count, ...
        audit.ultrafine_endpoint_strict_pair_count);
    fprintf('RESULT_PACKAGE_PASS=%d STRICT_TABLE4_REPRODUCTION=%d\n', ...
        audit.result_package_pass, audit.strict_table4_reproduction);
    fprintf(['SOURCE_HEATFLOW_C240 cycles=%d mechanism=%d periodic=%d ', ...
        'direction=%d COP=%.12g full_system_closure=%d\n'], ...
        audit.source_heatflow_c240_cycles, ...
        audit.source_heatflow_c240_mechanism_pass, ...
        audit.source_heatflow_c240_periodic_steady_state, ...
        audit.source_heatflow_c240_direction_pass, ...
        audit.source_heatflow_c240_COP, ...
        audit.source_heatflow_c240_system_energy_closure_complete);
    fprintf(['SHEX_CONTROL_VOLUME_C240 pass=%d sink_to_fluid_W=%.12g ', ...
        'ratio=%.12g complete_system_closure=%d\n'], ...
        audit.shex_control_volume_c240_pass, ...
        audit.shex_control_volume_c240_sink_to_fluid_W, ...
        audit.shex_control_volume_c240_transfer_ratio, ...
        audit.shex_control_volume_c240_complete_system_closure);
end

            ultrafine_unavailable_effects_are_nan, ...
        'consolidated_local_pairs_5', ...
            audit.local_sensitivity_strict_pair_count == 5 && ...
            isequal(consolidated_pair_names, ...
                expected_consolidated_names), ...
        'unavailable_local_derivatives_are_nan', ...
            unavailable_effects_are_nan, ...
        'c240_historical_claim_bounded', ...
            ~audit.source_heatflow_c240_system_energy_closure_complete && ...
            ~audit.shex_control_volume_c240_complete_system_closure, ...
        'system_c243_modeled_thermal_production_pass', ...
            audit.system_c243_cycles == 243 && ...
            audit.system_c243_mechanism_pass && ...
            audit.system_c243_periodic_steady_state && ...
            audit.system_c243_local_exchanger_kcl_pass && ...
            audit.system_c243_fluid_mass_conservation_pass && ...
            audit.system_c243_modeled_thermal_closure_pass && ...

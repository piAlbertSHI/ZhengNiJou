function contract = Configure_HeatDriveECC_DistributedPressureFeedforward(model, options)
% Independent cold diagnostic only: delayed native fluid states, not solid T.
    assert(bdIsLoaded(model) && options.node_count == 21, ...
        'HeatDriveECC:DistributedFFModel', 'Require the loaded 21-node model.');
    parent = [model '/SE'];
    settings = [model '/SE_ThermalLiquidSettings'];
    T = slResolve(get_param(settings, 'T_TLU'), settings);
    nu = slResolve(get_param(settings, 'nu_TLU_2'), settings);
    assert(strcmp(get_param(settings, 'T_TLU_unit'), 'K') && ...
        strcmp(get_param(settings, 'nu_TLU_2_unit'), 'mm^2/s'), ...
        'HeatDriveECC:DistributedFFUnits', 'Unexpected native property units.');
    T = double(T(:)); nu = double(nu(:)) * 1.0e-6;
    assert(numel(T) == numel(nu) && all(diff(T) > 0) && ...
        all(isfinite(nu) & nu > 0), ...
        'HeatDriveECC:DistributedFFTable', 'Invalid native kinematic-viscosity table.');
    area = options.branch.se_pipe_flow_area_m2;
    diameter = options.branch.se_pipe_hydraulic_diameter_m;
    lengths = zeros(21, 1);
    dt = options.simulation.fixed_step_s;
    assert(dt == options.simscape.local_solver_sample_time_s && dt > 0, ...
        'HeatDriveECC:DistributedFFClock', 'Require the unchanged shared solver clock.');
    tag = 'HeatDriveECC_DiagnosticNativeSEFluidTemperature21';
    mux = [parent '/DistributedFFTemperatureMux'];
    add_block('simulink/Signal Routing/Mux', mux, 'Inputs', '21', ...
        'Position', [-500 1800 -490 2450]);
    sources = cell(21, 1);
    for idx = 1:21
        pipe = sprintf('%s/HoldPipe_%03d', parent, idx);
        lengths(idx) = slResolve(get_param(pipe, 'length'), pipe);
        assert(strcmp(get_param(pipe, 'length_unit'), 'm') && ...
            strcmp(get_param(pipe, 'area_unit'), 'm^2') && ...
            strcmp(get_param(pipe, 'Dh_unit'), 'm') && ...
            abs(slResolve(get_param(pipe, 'Dh'), pipe) - diameter) < 1e-15 && ...
            abs(slResolve(get_param(pipe, 'area'), pipe) - area) < 1e-15 && ...
            strcmp(get_param(pipe, 'dynamic_compressibility'), 'false') && ...
            strcmp(get_param(pipe, 'inertia'), 'false'), ...
            'HeatDriveECC:DistributedFFGeometry', 'Unexpected distributed bed geometry/mode.');
        probe = sprintf('%s/DistributedFFProbe_%03d', parent, idx);
        add_block('nesl_utility/Probe', probe, ...
            'Position', [-720 1800+30*idx -600 1820+30*idx]);
        simscape.probe.setBoundBlock(probe, pipe);
        table = simscape.probe.VariableTable;
        table('T_I') = simscape.probe.VariableConfiguration;
        table('T_I').Unit = 'K';
        table('T_I').Probing = true;
        simscape.probe.setVariableTable(probe, table);
        ports = get_param(probe, 'PortHandles');
        mux_ports = get_param(mux, 'PortHandles');
        add_line(parent, ports.Outport(1), mux_ports.Inport(idx), 'autorouting', 'on');
        sources{idx} = struct('block', pipe, 'variable', 'T_I', 'unit', 'K');
    end
    assert(all(lengths > 0) && abs(sum(lengths) - ...
        options.branch.se_pipe_length_m) < 1e-12, ...
        'HeatDriveECC:DistributedFFLength', 'Bed length contract differs.');
    goto = [parent '/DistributedFFTemperatureGoto'];
    add_block('simulink/Signal Routing/Goto', goto, 'GotoTag', tag, ...
        'TagVisibility', 'global', 'Position', [-440 2050 -280 2080]);
    connect(parent, mux, 1, goto, 1);
    from = [model '/DistributedFFTemperatureFrom'];
    delay = [model '/DistributedFFTemperatureDelay'];
    lookup = [model '/DistributedFFKinematicViscosity'];
    weighted = [model '/DistributedFFSegmentResistance'];
    sum_block = [model '/DistributedFFBedResistance'];
    target = [model '/DistributedFFFlowTarget'];
    product = [model '/DistributedFFPressureProduct'];
    output = [model '/SEPressureDynamicFeedforward'];
    add_block('simulink/Signal Routing/From', from, 'GotoTag', tag, ...
        'Position', [-500 2200 -300 2230]);
    add_block('simulink/Discrete/Unit Delay', delay, ...
        'SampleTime', num2str(dt, '%.17g'), 'InitialCondition', ...
        mat2str(repmat(options.branch.se_pressure_feedforward_initial_temperature_K,21,1),17), ...
        'Position', [-230 2200 -150 2230]);
    add_block('simulink/Lookup Tables/1-D Lookup Table', lookup, ...
        'BreakpointsForDimension1', mat2str(T,17), 'Table', mat2str(nu,17), ...
        'InterpMethod', 'Linear point-slope', 'ExtrapMethod', 'Clip', ...
        'Position', [-80 2200 30 2230]);
    % nu=mu/rho is read from the same table as the physical pipe.
    coefficients = 32 * lengths / (area * diameter^2) / 1e6;
    add_block('simulink/Math Operations/Gain', weighted, ...
        'Gain', mat2str(coefficients,17), 'Multiplication', 'Element-wise(K.*u)', ...
        'Position', [90 2200 180 2230]);
    add_block('simulink/Math Operations/Sum of Elements', sum_block, ...
        'Position', [240 2200 320 2230]);
    add_block([model '/SEFlowTargetFromWorkspace'], target, ...
        'Position', [240 2280 360 2310]);
    add_block('simulink/Math Operations/Product', product, 'Inputs', '**', ...
        'Position', [410 2200 470 2230]);
    old_ports = get_param(output, 'PortHandles');
    groups = {'Inport','Outport'};
    for g = 1:numel(groups)
        for port = old_ports.(groups{g})
            line = get_param(port, 'Line');
            if line ~= -1, delete_line(line); end
        end
    end
    delete_block(output);
    add_block('simulink/Math Operations/Gain', output, 'Gain', '-1', ...
        'Position', [530 2200 600 2230]);
    connect(model, from, 1, delay, 1);
    connect(model, delay, 1, lookup, 1);
    connect(model, lookup, 1, weighted, 1);
    connect(model, weighted, 1, sum_block, 1);
    connect(model, sum_block, 1, product, 1);
    connect(model, target, 1, product, 2);
    connect(model, product, 1, output, 1);
    connect(model, output, 1, [model '/PressurePI_BiasSum'], 3);
    tap(model, from, 'distributed_fluid_temperature21_K');
    tap(model, delay, 'distributed_delayed_temperature21_K');
    tap(model, lookup, 'distributed_kinematic_viscosity21_m2_s');
    tap(model, sum_block, 'distributed_bed_resistance_MPa_per_kgps');
    tap(model, target, 'distributed_target_flow_kg_s');
    tap(model, output, 'distributed_pressure_feedforward_MPa');
    contract = struct('schema','heatdrive_ecc_distributed_pressure_ff_v1', ...
        'diagnostic_only',true,'simulation_run',false, ...
        'causal_delay_s',dt,'sources',{sources},'segment_length_m',lengths, ...
        'area_m2',area,'hydraulic_diameter_m',diameter, ...
        'property_temperature_K',T,'kinematic_viscosity_m2_s',nu, ...
        'segment_coefficients_MPa_per_kgps_per_m2ps',coefficients, ...
        'formula','-m_dot_target * sum(32*L_i*nu(T_I_i[t-dt])/(A*Dh^2))/1e6', ...
        'native_table_authority',settings,'legacy_reference_multiplier_used',false, ...
        'legacy_endpoint_probes_are_command_authority',false, ...
        'PI_route_memory_reset',false,'physical_storage_or_constitutive_parameters_changed',false, ...
        'production_recovery_allowed',false,'checkpoint_saved',false, ...
        'source_function','Configure_HeatDriveECC_DistributedPressureFeedforward');
end

function connect(parent, source, source_port, sink, sink_port)
    a = get_param(source,'PortHandles'); b = get_param(sink,'PortHandles');
    add_line(parent,a.Outport(source_port),b.Inport(sink_port),'autorouting','on');
end

function tap(model, source, name)
    sink = [model '/ToWorkspace_' name];
    add_block('simulink/Sinks/To Workspace',sink,'VariableName',name, ...
        'SaveFormat','Structure With Time','MaxDataPoints','inf','Decimation','1');
    connect(model,source,1,sink,1);
end

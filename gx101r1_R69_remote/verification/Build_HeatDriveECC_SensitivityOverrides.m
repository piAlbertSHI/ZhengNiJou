function [model,branch,fields]=Build_HeatDriveECC_SensitivityOverrides(row,baseline,branch,gate_start)
% Shared legacy factor mapping; callers supply their own explicitly scoped controller.
    ua={'UA_sma_shex_W_per_K','UA_sma_the_W_per_K','UA_se_the_W_per_K','UA_se_chex_W_per_K', ...
        'sma_pipe_Nu','se_pipe_Nu','se_natural_convection_UA_W_per_K','se_natural_thermal_gate_G_W_per_K', ...
        'endpoint_UA_sma_shex_W_per_K','endpoint_UA_sma_the_W_per_K','endpoint_UA_se_the_W_per_K', ...
        'endpoint_UA_se_chex_W_per_K','boundary_UA_shex_W_per_K','boundary_UA_the_W_per_K','boundary_UA_chex_W_per_K'};
    capacity={'shex_sink_C_J_per_K','hot_sink_C_J_per_K','cold_sink_C_J_per_K'};
    flow={'m_dot_kg_per_s','m_dot_se_the_kg_per_s','m_dot_se_chex_kg_per_s'};
    model=struct('system',struct(),'material',struct());
    for k=1:numel(ua),branch.(ua{k})=baseline.branch.(ua{k})*row.UA_multiplier;end
    for k=1:numel(capacity),model.system.(capacity{k})=baseline.system.(capacity{k})*row.endpoint_capacity_multiplier;end
    model.system.se_buffer_volume_m3=baseline.system.se_buffer_volume_m3*row.SE_buffer_multiplier;
    branch.sma_pump_manifold_volume_m3=baseline.branch.sma_pump_manifold_volume_m3*row.fluid_inventory_multiplier;
    for k=1:numel(flow),branch.(flow{k})=baseline.branch.(flow{k})*row.regenerator_utilization_multiplier;end
    for material={'SMA','SE'}
        name=material{1};model.material.(name)=struct( ...
            'Delta_h_J_per_kg',baseline.material.(name).Delta_h_J_per_kg*row.latent_heat_multiplier, ...
            'Delta_s0_J_per_kgK',baseline.material.(name).Delta_s0_J_per_kgK*row.latent_heat_multiplier);
    end
    fields=[strcat('branch.',ua),strcat('system.',capacity),{'system.se_buffer_volume_m3', ...
        'branch.sma_pump_manifold_volume_m3'},strcat('branch.',flow), ...
        {'material.SMA.Delta_h_J_per_kg','material.SMA.Delta_s0_J_per_kgK', ...
         'material.SE.Delta_h_J_per_kg','material.SE.Delta_s0_J_per_kgK'}];
    model.validation=struct('sensitivity_mode',true,'sensitivity_declared_transition_fields',{fields}, ...
        'mechanism_gate_start_cycle',gate_start,'strict_table4_reproduction_applicable',false);
end

function source=Require_HeatDriveECC_RuntimeRecordingSource(pointer,q,options)
% Only an intact same-runtime-family transient endpoint may seed this warmup.
    assert(pointer.snapshot_time_s==q.snapshot_time_s && pointer.total_cycles==q.total_cycles && ...
        pointer.snapshot_time_s==10*pointer.total_cycles && mod(pointer.snapshot_time_s,20)==0 && ...
        ~pointer.production_recovery_allowed && ~pointer.outer_solve_eligible && ...
        ~q.production_recovery_allowed && ~q.outer_solve_eligible && ...
        q.temperature_K==276.95 && strcmp(q.temperature_configurability,'runtime') && ...
        strcmp(q.checksum_policy,'error/error') && q.native_history_cap_cycles==2 && ...
        q.state_history_cap_cycles==11 && q.command_horizon_cycles==200 && ...
        strcmp(pointer.operating_point_path,q.operating_point_path) && ...
        strcmp(pointer.operating_point_sha256,q.operating_point_sha256), ...
        'Require a sealed same-family runtime endpoint; C200/C72 are not interchangeable.');
    if strcmp(q.schema,'heatdrive_ecc_runtime_boundary_cold_endpoint_v1')
        assert(q.snapshot_time_s==20 && q.independent_model_family && ...
            q.original_73_mechanism_checks_pass && q.six_local_inventory_gates_pass && ...
            q.modeled_energy_closure_pass && q.cold_baseline_complete_OP_loaded_after_all_gates && ...
            q.unchanged_restore_initial_states_and_native_bitwise_equal && ...
            q.runtime_0p1K_change_strict_restore_pass && q.all_four_memories_initial_bitwise_equal && ...
            ~q.old_model_OP_imported);
    else
        assert(strcmp(q.schema,'heatdrive_ecc_runtime_boundary_warmup_endpoint_v1') && ...
            q.transient_continuation_allowed && q.all_original_packet_gates_pass && ...
            q.all_recorded_boundaries_pass && ~q.source_state_edited && ~q.old_model_OP_imported);
    end
    assert(options.system.Tchex_K==276.95 && ...
        strcmp(options.system.cold_boundary_temperature_configurability,'runtime'));
    source=struct('packet_root',q.source_packet_root,'snapshot_s',pointer.snapshot_time_s, ...
        'OP_sha256',pointer.operating_point_sha256);
end

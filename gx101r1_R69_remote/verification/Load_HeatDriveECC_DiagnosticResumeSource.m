function [op, contract] = Load_HeatDriveECC_DiagnosticResumeSource(options)
% State-qualified independent diagnostic input, never a failed or production state.
    source=char(options.restore_source_root);verified=char(options.restore_verification_root);
    execution=jsondecode(fileread(fullfile(source,'cold_chamber_execution.json')));
    capture=jsondecode(fileread(fullfile(source,'native','diagnostic_state_capture.json')));
    proof_file=fullfile(verified,'native','rebuilt_cycle_restore.json');
    proof=jsondecode(fileread(proof_file));
    assert(execution.state_restore_preflight_pass && isempty(execution.error_message) && ...
        ~execution.c200_state_imported && ~execution.production_recovery_allowed && ...
        execution.stop_time_s==20 && execution.cycle_count==2 && ...
        proof.rebuilt_complete_cycle_pass && proof.strict_restore_completed && ...
        proof.continuous_reference_pass && isempty(proof.error_message) && ...
        proof.start_time_s==20 && proof.stop_time_s==30 && ...
        strcmp(proof.source_root,source) && strcmp(proof.checksum_policy,'error/error') && ...
        ~proof.source_state_edited && ~proof.partial_state_restore_used && ...
        ~proof.production_recovery_allowed && ...
        strcmp(proof.source_operating_point_sha256,capture.operating_point_sha256) && ...
        strcmp(proof.source_history_sha256,capture.history_sha256), ...
        'Diagnostic source lacks successful complete-cycle strict restore evidence.');
    comparisons=[proof.state_comparisons(:);proof.signal_comparisons(:)];
    assert(numel(proof.state_comparisons)==74 && numel(proof.signal_comparisons)==201 && ...
        all([comparisons.values_exact]) && all([comparisons.clock_pass]) && ...
        all([comparisons.samples]==10001), 'Incomplete full-period restore coverage.');
    comparison_file=fullfile(verified,'native','rebuilt_cycle_comparison.mat');
    comparison=load(comparison_file,'record');
    assert(isequaln(jsondecode(jsonencode(comparison.record)),proof), ...
        'Comparison MAT and restore receipt disagree.');
    op_file=fullfile(source,'native','diagnostic_complete_operating_point.mat');
    history_file=fullfile(source,'native','diagnostic_state_observation.mat');
    assert(strcmp(file_hash(op_file),capture.operating_point_sha256) && ...
        strcmp(file_hash(history_file),capture.history_sha256),'Intact source hash changed.');
    saved=load(op_file,'diagnostic_operating_point','production_recovery_allowed');
    op=saved.diagnostic_operating_point;
    assert(~saved.production_recovery_allowed && abs(op.snapshotTime-20)<=1e-9 && ...
        (isa(op,'Simulink.op.ModelOperatingPoint') || isa(op,'Simulink.SimulationOperatingPoint')), ...
        'Require the untouched vendor complete OP.');
    contract=struct('schema','heatdrive_ecc_state_qualified_diagnostic_resume_v1', ...
        'source_root',source,'verification_root',verified,'snapshot_time_s',20, ...
        'operating_point_sha256',capture.operating_point_sha256,'history_sha256',capture.history_sha256, ...
        'restore_receipt_sha256',file_hash(proof_file),'comparison_sha256',file_hash(comparison_file), ...
        'full_cycle_state_restore_verified',true,'source_physical_gates_evaluated',false, ...
        'failed_state_propagated',false,'source_state_edited',false,'partial_state_restore_used',false, ...
        'production_recovery_allowed',false,'diagnostic_trial_only',true);
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');
    assert(fid>=0,'Missing diagnostic source evidence.');cleanup=onCleanup(@() fclose(fid));
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

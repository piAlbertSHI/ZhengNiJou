function record=Read_HeatDriveECC_KernelQualification(path)
% This admits only a bounded cold implementation comparison, never an old OP.
    record=jsondecode(fileread(path));
    assert(strcmp(record.schema,'heatdrive_ecc_stable_kernel_candidate_comparison_v1') && ...
        isempty(record.error_message) && record.all_captured_samples_bitwise_equal && ...
        record.reference_matches_captured_physical_output && record.all_original_L8_option_cases_bitwise_equal && ...
        record.captured_samples==200 && record.edge_samples==180 && record.invalid_contracts_rejected==8 && ...
        isequal([record.original_L8_option_cases.case_index],0:8) && ...
        all([record.original_L8_option_cases.bitwise_equal]) && ...
        ~record.candidate_installed_in_model && ~record.coupled_acceleration_qualified && ...
        ~record.production_recovery_allowed && ~record.operating_point_loaded && ~record.simulation_executed);
    assert(strcmp(file_hash(which('HeatDriveECC_StableKernelCandidate')),record.candidate_source_sha256), ...
        'Candidate changed after the actual offline comparison.');
end
function h=file_hash(path)
    d=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'rb');assert(fid>=0);c=onCleanup(@() fclose(fid));
    while ~feof(fid),d.update(fread(fid,8*1024*1024,'*uint8'));end
    h=upper(reshape(dec2hex(typecast(d.digest(),'uint8'),2).',1,[]));
end

function record=Require_HeatDriveECC_BoundedStateCandidate(source_root)
% A passed physics candidate with a post-sim transport error may undergo a
% stricter full-cycle state-interface experiment; this grants no continuation.
    execution=jsondecode(fileread(fullfile(source_root,'cold_chamber_execution.json')));
    mechanism=jsondecode(fileread(fullfile(source_root,'native','cold_mechanism_audit.json')));
    capture=jsondecode(fileread(fullfile(source_root,'native','diagnostic_state_capture.json')));
    config=jsondecode(fileread([source_root,'.state_preflight_config.json']));
    assert(strcmp(execution.error_message,'The actual Node does not support regular MAT save/load.') && ...
        execution.checkpoint_saved && ~execution.state_restore_preflight_pass && ...
        execution.cycle_count==2 && execution.stop_time_s==20 && execution.start_time_s==0 && ...
        ~execution.c200_state_imported && ~execution.production_recovery_allowed && ...
        mechanism.mechanism_pass && mechanism.original_production_predicates_evaluated && ...
        numel(fieldnames(mechanism.checks))==72 && all(structfun(@logical,mechanism.checks)) && ...
        ~mechanism.production_recovery_allowed && ...
        strcmp(mechanism.execution_commit,execution.execution_commit) && ...
        strcmp(file_hash(mechanism.observation_file),mechanism.observation_sha256) && ...
        capture.snapshot_time_s==20 && ~capture.source_op_edited && ...
        strcmp(file_hash(capture.operating_point_file),capture.operating_point_sha256) && ...
        strcmp(file_hash(capture.history_file),capture.history_sha256) && ...
        config.pressure_command_domain_closure_enabled && ...
        config.diagnostic_state_options.command_horizon_cycles==200 && ...
        ~isfile(fullfile(source_root,'REJECTED_DO_NOT_RESUME.json')), ...
        'Not the exact passed bounded C2 candidate with the diagnosed transport-only failure.');
    record=struct('schema','heatdrive_ecc_bounded_state_interface_candidate_v1', ...
        'source_root',source_root,'mechanism_receipt_sha256', ...
        file_hash(fullfile(source_root,'native','cold_mechanism_audit.json')), ...
        'original_mechanism_predicates_pass',true,'diagnosed_post_sim_transport_only_error',true, ...
        'one_step_restore_not_yet_evaluated',true,'full_cycle_state_experiment_only',true, ...
        'source_state_edited',false,'diagnostic_continuation_allowed',false, ...
        'production_recovery_allowed',false);
end

function hash=file_hash(file)
    fid=fopen(file,'rb');assert(fid>=0);cleanup=onCleanup(@() fclose(fid));
    digest=java.security.MessageDigest.getInstance('SHA-256');
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    hash=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

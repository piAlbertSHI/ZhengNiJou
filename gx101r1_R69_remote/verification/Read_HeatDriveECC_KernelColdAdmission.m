function record=Read_HeatDriveECC_KernelColdAdmission(path)
% Admit a declared independent cold implementation, never translate an old OP.
    record=jsondecode(fileread(path));repo=fileparts(fileparts(path));
    assert(strcmp(record.schema,'heatdrive_ecc_kernel_independent_cold_admission_v1') && ...
        record.independent_cold_20cycle_admitted && ~record.old_backend_OP_import_allowed && ...
        record.strict_vendor_restore_required && record.same_case_split_test_required_before_long_continuation && ...
        ~record.production_recovery_allowed && ~record.outer_solve_allowed && ~record.table4_reproduction_claim);
    assert(strcmp(record.wrapper_name,'HeatDriveECC_ConstitutiveStateVectorStep21_KernelCandidate') && ...
        strcmp(record.kernel_name,'HeatDriveECC_StableKernelCandidate'));
    assert(strcmp(file_hash(which(record.wrapper_name)),record.wrapper_sha256) && ...
        strcmp(file_hash(which(record.kernel_name)),record.kernel_sha256),'Candidate implementation changed.');
    offline=fullfile(repo,record.offline_relative);coupled=fullfile(repo,record.coupled_relative);
    assert(strcmp(file_hash(offline),record.offline_sha256) && strcmp(file_hash(coupled),record.coupled_sha256));
    proof=Read_HeatDriveECC_KernelQualification(offline); %#ok<NASGU>
    proof=jsondecode(fileread(coupled));
    assert(proof.coupled_cold_trajectory_equivalence_verified && proof.replay_physical_cycles==4 && ...
        ~proof.production_recovery_allowed && ~proof.table4_reproduction_claim && ...
        isequal(sort([proof.records.case_index]),[0 1]) && ...
        all([proof.records.pass_all_original_gates]) && all([proof.records.all_actual_arrays_bitwise_equal]) && ...
        strcmp(proof.offline_sha256,record.offline_sha256));
end

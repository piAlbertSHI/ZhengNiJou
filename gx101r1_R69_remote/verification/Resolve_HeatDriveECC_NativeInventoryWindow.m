function cycles = Resolve_HeatDriveECC_NativeInventoryWindow(state, cycle_count, pressure_only, arm, endpoint_all)
% Observe more native samples without changing equations, commands, or states.
    cycles=min(cycle_count,2);
    if isfield(state,'native_inventory_window_cycles')
        assert(state.native_inventory_window_cycles==10 && cycle_count==20 && ...
            strcmp(state.mode,'diagnostic_resume') && pressure_only && ...
            strcmp(arm,'native') && endpoint_all && ...
            all(isfield(state,{'storage_state_audit_path','storage_complete_cycle_audit_path'})), ...
            'Ten-cycle native recording requires typed unchanged-model storage warmup.');
        cycles=10;
    end
end

function record = Audit_HeatDriveECC_SavedPerformanceWindow(source_root, mechanism_root, output_file)
% Read-only ten-cycle performance using the existing extractor and equations.
    assert(~isfile(output_file), 'Never overwrite performance evidence.');
    receipt_file=fullfile(mechanism_root,'saved_mechanism_audit.json');
    receipt=jsondecode(fileread(receipt_file));
    execution_file=fullfile(source_root,'cold_chamber_execution.json');
    execution=jsondecode(fileread(execution_file));
    observation_file=fullfile(source_root,'native','observations.mat');
    configuration_file=fullfile(source_root,'native','configuration.mat');
    assert(receipt.mechanism_pass && numel(fieldnames(receipt.checks))==73 && ...
        all(structfun(@logical,receipt.checks)) && ...
        strcmp(receipt.source_execution_sha256,file_hash(execution_file)) && ...
        strcmp(receipt.source_observation_sha256,file_hash(observation_file)) && ...
        strcmp(receipt.source_configuration_sha256,file_hash(configuration_file)) && ...
        execution.requested_arm_collection_pass && isempty(execution.error_message), ...
        'Require the same complete mechanism-passing source.');
    configured=load(configuration_file,'options');options=configured.options;
    saved=load(observation_file,'signals','thermal_boundary_signals');
    stop=execution.stop_time_s;start=stop-10*options.schedule.tau_cycle_s;
    observation=Slice_HeatDriveECC_SavedMechanismObservation(saved,start,stop, ...
        options.simulation.fixed_step_s);
    physical=Extract_HeatDriveECC_PhysicalLogs(observation,options,'',false);
    physical.authority='physical_simscape_to_workspace_logs';
    physical.legacy_surrogate_used_for_results=false;physical.sim_call_count=1;
    physical.walltime_s=NaN;
    provenance=struct('checkpoint_restart_used',true,'checkpoint_chain_verified',true,'sim_call_count',1);
    view=Make_HeatDriveECC_MechanismWindow(physical,options,provenance,fileparts(output_file));
    summary=Summarize_HeatDriveECC_EighthRound_Output(view.physical,view.options);
    p=summary.performance;
    assert(p.qian_window_cycles==10 && numel(view.physical.time_s)==100001 && ...
        all(isfinite([p.temperature_lift_eq9_K,p.cooling_power_eq10_W, ...
        p.specific_cooling_eq10_W_per_g,p.cooling_power_CHEX_sensor_W])), ...
        'Require exact complete finite ten-cycle performance.');
    assert(p.specific_cooling_eq10_W_per_g==p.cooling_power_eq10_W/(1000*options.equilibrium.m_r_kg), ...
        'SCP mass basis changed.');
    b=observation.thermal_boundary_signals;
    names=fieldnames(b.fields);boundaries=struct();
    for k=1:numel(names)
        row=b.fields.(names{k});v=row.values;
        finite_rows=all(isfinite(v),2);finite_times=row.time_s(finite_rows);
        finite_window=[];
        if ~isempty(finite_times),finite_window=[finite_times(1),finite_times(end)];end
        boundaries.(names{k})=struct('sample_count',numel(row.time_s), ...
            'channel_count',size(v,2),'finite',all(isfinite(v),'all'), ...
            'finite_sample_count',nnz(finite_rows),'finite_window_s',finite_window, ...
            'absolute_window_s',[row.time_s(1),row.time_s(end)]);
    end
    t=view.physical.time_s;
    pump_sma=trapz(t,view.physical.pump_power_SMA_W)/(stop-start);
    pump_se=trapz(t,view.physical.pump_power_SE_W)/(stop-start);
    record=struct('schema','heatdrive_ecc_saved_performance_window_v1', ...
        'source_root',source_root,'source_execution_commit',execution.execution_commit, ...
        'total_cycles',execution.cycle_count,'analysis_window',view.analysis_window, ...
        'sample_count',numel(t),'window_cycles',10,'quadrature','trapz_including_both_endpoints', ...
        'eq9_outlet_hot_signal','hot_hx_inlet_fluid_temp_out', ...
        'eq9_outlet_cold_signal','cold_hx_inlet_fluid_temp_out', ...
        'eq10_inlet_cold_signal','cold_hx_outlet_fluid_temp_out', ...
        'eq10_flow_signal','mass_flow_v4_hot_inlet_kgps; abs(flow)*I_stage4', ...
        'eq10_cp_J_per_kgK',options.system.cp_fluid_J_per_kgK, ...
        'scp_active_SE_solid_mass_kg',options.equilibrium.m_r_kg, ...
        'performance',p,'cycles',summary.cycle,'boundary_coverage',boundaries, ...
        'all_boundary_fields_finite_over_ten_cycles',all(structfun(@(r) r.finite,boundaries)), ...
        'sensor_crosscheck_scope','public CHEX sensor only; native sensor finite window reported separately', ...
        'pump_proxy_mean_SMA_W',pump_sma,'pump_proxy_mean_SE_W',pump_se, ...
        'pump_proxy_contract','abs(command_pressure)*1e6*abs(route_mass_flow)/997; not electric power', ...
        'pump_dissipation_heat_included_in_native_ledger',false, ...
        'native_inventory_window_s',[stop-20,stop], ...
        'public_temperature_phase_periodic_gate_pass',p.periodic_steady_state, ...
        'simulation_executed',false,'operating_point_loaded',false, ...
        'source_state_edited',false,'production_recovery_allowed',false, ...
        'complete_internal_state_periodicity_verified',false,'full_device_first_law_verified',false, ...
        'outer_solve_eligible',false,'table4_reproduction_claim',false, ...
        'input_sha256',struct('execution',file_hash(execution_file), ...
            'observation',file_hash(observation_file),'configuration',file_hash(configuration_file), ...
            'mechanism',file_hash(receipt_file), ...
            'extractor',file_hash(which('Extract_HeatDriveECC_PhysicalLogs')), ...
            'summarizer',file_hash(which('Summarize_HeatDriveECC_EighthRound_Output'))));
    mkdir(fileparts(output_file));fid=fopen(output_file,'w','n','UTF-8');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(record,'PrettyPrint',true));
    fprintf('FINAL_JSON=%s\n',jsonencode(struct('cycles',record.total_cycles, ...
        'lift_K',p.temperature_lift_eq9_K,'cooling_W',p.cooling_power_eq10_W, ...
        'SCP_W_per_g',p.specific_cooling_eq10_W_per_g, ...
        'sensor_difference_W',p.eq10_sensor_absolute_difference_W, ...
        'sensor_consistency_pass',p.eq10_sensor_consistency_pass, ...
        'pump_proxy_W',pump_sma+pump_se,'outer_solve_eligible',false)));
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

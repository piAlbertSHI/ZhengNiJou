function passed = Evaluate_HeatDriveECC_StorageClosureColdQualification(audit)
% C1 evidence authorizes only a new cold C2 experiment, not state recovery.
    assert(strcmp(audit.schema,'heatdrive_ecc_manifold_storage_closure_comparison_v1') && ...
        audit.geometry_property_tables_commands_and_wiring_identical && ...
        audit.candidate_numerical_inventory_qualification && ...
        ~audit.real_fluid_EOS_claim && ~audit.paper_exact_accessory_model_claim && ...
        ~audit.production_recovery_allowed && ~audit.outer_solve_eligible && ...
        ~audit.diagnostic_warmup_continuation_allowed && ~audit.table4_reproduction_claim && ...
        numel(audit.cases)==2,'Require the bounded storage-formulation comparison.');
    initial=audit.initial_coordinates;
    assert(initial.actual_initial_coordinates_match && initial.own_actual_coordinates_match_targets && ...
        initial.strict_coordinate_match_count==204 && numel(initial.coordinates)==204, ...
        'Require all actual C1 physical initial coordinates, without waived tolerances.');
    candidate=audit.cases(2);runtime=candidate.runtime_mechanism_subset;
    assert(strcmp(candidate.storage_closure,'pressure_only_density') && ...
        candidate.formulation_specific_local_inventory_pass && numel(candidate.local_inventory_gates)==6 && ...
        all(candidate.local_inventory_gates) && candidate.retained_differential_mass_energy_states && ...
        candidate.mass_budget.buffer_mass_equations_pass && ...
        candidate.mass_budget.buffer_plus_chamber_stage_closure_pass && ...
        candidate.model_energy_balance.model_equation_energy_closure_pass && ...
        candidate.model_energy_balance.energy_tolerance_J==1e-8 && ...
        runtime.distributed_controller_runtime_pass && runtime.selected_flow_gates_pass && ...
        runtime.phase_bounds_pass && runtime.solid_energy_pass && ...
        runtime.pressure_boundary.pressure_range_gate && runtime.pressure_boundary.hydraulic_diagnostic_gate, ...
        'The new cold structure lacks the original local inventory/flow/pressure/phase/energy gates.');
    tags=candidate.compiled_chamber_state_tags;
    selected=ismember({tags.variable_name},{'stored_mass','stored_energy'});
    assert(numel(tags)==8 && sum(selected)==4 && ...
        all([tags(selected).isDifferential]) && all([tags(selected).isRetained]), ...
        'Both chamber mass/energy states must remain differential and retained.');
    passed=true;
end

function contract = Require_HeatDriveECC_StorageClosureCheckpoint(source_root, audit_path)
% An intact new-model C2 input for complete-cycle verification, not recovery authority.
    source_root=char(java.io.File(source_root).getCanonicalPath());
    audit=jsondecode(fileread(audit_path));
    assert(strcmp(audit.schema,'heatdrive_ecc_storage_closure_state_qualification_audit_v1') && ...
        strcmp(char(java.io.File(audit.source_root).getCanonicalPath()),source_root) && ...
        audit.rebuilt_cycle_test_allowed && audit.full_mechanism_pass && audit.full_mechanism_checks_passed==73 && ...
        audit.local_inventory_pass && all(audit.local_inventory_gates) && ...
        numel(audit.local_inventory_gates)==6 && audit.differential_inventory_states_preserved && ...
        audit.modeled_energy_balance.model_equation_energy_closure_pass && ...
        audit.same_model_state_roundtrip_pass && audit.state_groups_exact==74 && audit.signals_exact==201 && ...
        ~audit.complete_cycle_restore_verified && ~audit.production_recovery_allowed && ...
        ~audit.diagnostic_warmup_continuation_allowed && ~audit.outer_solve_eligible, ...
        'Require the bounded new-model C2 physics/state qualification.');
    files={'observations.mat','configuration.mat','inventory_metadata.json','tl_connectivity.json', ...
        'thermal_connectivity.json','buffer_replacement_contract.json','compiled_inventory_tags.json', ...
        'cold_mechanism_audit.json','cold_mechanism_observation.mat','diagnostic_state_capture.json', ...
        'diagnostic_complete_operating_point.mat','diagnostic_state_observation.mat', ...
        'state_restore_preflight.json','restore_preflight_comparison.mat','se_reference_contract.json', ...
        'pressure_only_inverse_density_map_1.json','pressure_only_inverse_density_map_2.json'};
    names=cellfun(@matlab.lang.makeValidName,files,'UniformOutput',false);
    assert(isequal(sort(names(:)),sort(fieldnames(audit.input_sha256))),'Incomplete C2 hash inventory.');
    for k=1:numel(files)
        assert(strcmp(file_hash(fullfile(source_root,'native',files{k})),audit.input_sha256.(names{k})), ...
            'C2 input changed: %s',files{k});
    end
    study_path=fullfile(audit.study_root,'storage_state_execution.json');
    study=jsondecode(fileread(study_path));
    assert(strcmp(file_hash(study_path),audit.manifest_sha256) && ...
        strcmp(study.candidate_root,source_root) && ~study.existing_OP_imported && ...
        strcmp(study.status,'collected_requires_inventory_and_complete_cycle_restore_audit') && ...
        strcmp(file_hash(fullfile(audit.study_root,'candidate_config.json')),audit.candidate_config_sha256) && ...
        strcmp(file_hash(fullfile(source_root,'cold_chamber_execution.json')),audit.execution_sha256) && ...
        ~isfile(fullfile(source_root,'REJECTED_DO_NOT_RESUME.json')) && ...
        ~isfile(fullfile(source_root,'INCOMPLETE_DO_NOT_RESUME.json')), 'Changed or rejected C2 source.');
    capture=jsondecode(fileread(fullfile(source_root,'native','diagnostic_state_capture.json')));
    assert(capture.snapshot_time_s==20 && strcmp(capture.operating_point_sha256,audit.source_operating_point_sha256) && ...
        strcmp(capture.history_sha256,audit.source_history_sha256), 'C2 checkpoint identity changed.');
    contract=struct('schema','heatdrive_ecc_storage_closure_c2_rebuilt_input_v1', ...
        'source_root',source_root,'source_audit_sha256',file_hash(audit_path), ...
        'operating_point_sha256',capture.operating_point_sha256,'history_sha256',capture.history_sha256, ...
        'snapshot_time_s',20,'complete_cycle_restore_verified',false, ...
        'production_recovery_allowed',false,'outer_solve_eligible',false);
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

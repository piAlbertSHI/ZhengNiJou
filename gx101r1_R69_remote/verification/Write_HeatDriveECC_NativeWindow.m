function header = Write_HeatDriveECC_NativeWindow(path, native, observed, settings)
% Store one shared time vector and lossless double matrices, without model/OP data.
    assert(~isfile(path), 'HeatDriveECC:ExistingNativeWindow', 'Do not overwrite native evidence.');
    for field = {'source_result_sha256', 'source_checkpoint_sha256'}
        value = settings.(field{1});
        assert(ischar(value) && ~isempty(regexp(value, '^[A-Fa-f0-9]{64}$', 'once')), ...
            'HeatDriveECC:NativeSourceHash', 'Missing source SHA-256.');
    end
    start = settings.start_s; finish = settings.stop_s; dt = settings.fixed_step_s;
    tau = settings.cycle_period_s;
    assert(all(isfinite([start finish dt tau])) && dt > 0 && tau > 0 && finish > start, ...
        'HeatDriveECC:NativeWindowGrid', 'Invalid window settings.');
    count = round((finish - start) / dt) + 1;
    tolerance = 16 * eps(max([abs(start) abs(finish) 1]));
    assert(abs((count - 1) * dt - (finish - start)) <= tolerance, ...
        'HeatDriveECC:NativeWindowGrid', 'Window is not an integer number of steps.');
    assert(numel(native) == 1240 && numel(observed) == 73, ...
        'HeatDriveECC:NativeWindowInventory', 'Unexpected trace inventory.');
    time_s = native{1}.time_s(:);
    assert(numel(time_s) == count && all(isfinite(time_s)) && ...
        abs(time_s(1) - start) <= tolerance && abs(time_s(end) - finish) <= tolerance && ...
        all(abs(diff(time_s) - dt) <= tolerance), ...
        'HeatDriveECC:NativeWindowGrid', 'Window samples or endpoints are missing.');
    [native_values, native_columns] = pack(native, time_s);
    [observed_values, observed_columns] = pack(observed, time_s);
    assert(size(native_values, 2) == 1240 && size(observed_values, 2) == 1376 && ...
        numel(unique(cellfun(@(r) r.block_path, native, 'UniformOutput', false))) == 119, ...
        'HeatDriveECC:NativeWindowInventory', 'Native/state coordinate inventory changed.');
    header = struct('schema', 'heatdrive_ecc_native_window_samples_v1', ...
        'source_result_sha256', settings.source_result_sha256, ...
        'source_checkpoint_sha256', settings.source_checkpoint_sha256, ...
        'start_s', start, 'stop_s', finish, 'fixed_step_s', dt, 'cycle_period_s', tau, ...
        'sample_count', count, 'native_columns', {native_columns}, 'observed_columns', {observed_columns}, ...
        'native_component_count', 119, 'native_coordinate_count', size(native_values, 2), ...
        'observed_coordinate_count', size(observed_values, 2), ...
        'storage_only_no_operating_point', true, 'production_recovery_allowed', false, ...
        'strict_restore_verified_by_writer', false, 'full_internal_periodicity_verified', false, ...
        'equation_matched_cycle_closure_verified', false);
    header_json = jsonencode(header);
    parent = fileparts(path);
    if ~isempty(parent) && ~isfolder(parent), mkdir(parent); end
    save(path, 'header_json', 'time_s', 'native_values', 'observed_values', '-v7.3');
end

function [data, columns] = pack(traces, time_s)
    sizes = cellfun(@(r) r.channel_count, traces);
    assert(all(isfinite(sizes)) && all(sizes >= 1 & sizes == fix(sizes)), ...
        'HeatDriveECC:NativeWindowShape', 'Invalid channel counts.');
    data = zeros(numel(time_s), sum(sizes));
    columns = cell(size(traces));
    keys = cell(size(traces));
    column = 1;
    for k = 1:numel(traces)
        row = traces{k};
        assert(ischar(row.block_path) && ischar(row.state_name) && ischar(row.unit), ...
            'HeatDriveECC:NativeWindowIdentity', 'Trace descriptors must be character vectors.');
        assert(isequal(row.time_s(:), time_s), ...
            'HeatDriveECC:NativeWindowGrid', 'Shared time storage forbids interpolation or shifted samples.');
        assert(isa(row.values, 'double') && isequal(size(row.values), [numel(time_s) sizes(k)]) && ...
            all(isfinite(row.values), 'all'), 'HeatDriveECC:NativeWindowShape', 'Invalid native values.');
        data(:, column:column + sizes(k) - 1) = row.values;
        columns{k} = struct('block_path', row.block_path, 'state_name', row.state_name, ...
            'unit', row.unit, 'first_column_1based', column, 'channel_count', sizes(k));
        keys{k} = [row.block_path '::' row.state_name];
        column = column + sizes(k);
    end
    assert(numel(unique(keys)) == numel(keys), ...
        'HeatDriveECC:NativeWindowInventory', 'Duplicate trace identity.');
end

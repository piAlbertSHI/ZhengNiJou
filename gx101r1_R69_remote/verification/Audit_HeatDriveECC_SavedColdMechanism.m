function record=Audit_HeatDriveECC_SavedColdMechanism(source_root,output_root,arm,window_cycles,component_proof_path)
% Original physical predicates on an explicit, immutable cold observation arm.
    if nargin<3,arm='native';end
    if nargin<4,window_cycles=2;end
    if nargin<5,component_proof_path='';end
    assert(~isfolder(output_root),'Never overwrite an analysis result.');
    folder=fullfile(source_root,arm);
    execution_path=fullfile(source_root,'cold_chamber_execution.json');
    completion=jsondecode(fileread(fullfile(folder,'arm_completion.json')));
    execution=jsondecode(fileread(execution_path));
    scope=Resolve_HeatDriveECC_ColdAnalysisScope(execution,completion,arm,window_cycles);
    observation_path=fullfile(folder,'observations.mat');
    configuration_path=fullfile(folder,'configuration.mat');
    observation_hash=file_hash(observation_path);
    configuration_hash=file_hash(configuration_path);
    assert(strcmp(observation_hash,completion.observation_sha256), ...
        'Completed arm observations changed.');
    configured=load(configuration_path,'options');options=configured.options;
    source_options=options;component_proof_sha256='';
    chosen=execution.cases(strcmp({execution.cases.arm},arm));
    assert(ismember(chosen.simulation_mode,{'normal','accelerator'}) && ...
        (strcmp(chosen.simulation_mode,execution.diagnostic_simulation_mode) || ...
         (strcmp(arm,'conservative') && strcmp(chosen.simulation_mode,'normal'))), ...
        'Actual arm mode is not authorized by the cold runner contract.');
    % Cold runner sets SimulationInput mode independently of defaults.mode.
    % Preserve the untouched requested options, but audit the executed mode.
    options.simulation.mode=chosen.simulation_mode;
    if ~isempty(component_proof_path)
        proof=jsondecode(fileread(component_proof_path));
        assert(strcmp(arm,'conservative') && ...
            strcmp(proof.schema,'heatdrive_ecc_saved_specific_inventory_mask_v1') && ...
            strcmp(proof.source_root,source_root) && ...
            strcmp(proof.source_configuration_sha256,configuration_hash) && ...
            strcmp(proof.source_observation_sha256,observation_hash) && ...
            proof.exact_specific_source_and_geometry_pass && ...
            proof.only_component_audit_metadata_changed && ...
            proof.negative_component_cases_rejected==3 && ...
            ~proof.simulation_executed && ~proof.operating_point_loaded && ...
            ~proof.production_recovery_allowed && ...
            strcmp(proof.verifier_sha256,file_hash(which('Verify_HeatDriveECC_SavedSpecificManifold'))) && ...
            strcmp(proof.manifold_auditor_sha256,file_hash(which('Audit_HeatDriveECC_ManifoldMask'))) && ...
            strcmp(proof.source_metadata_sha256,file_hash(fullfile(folder,'inventory_metadata.json'))) && ...
            strcmp(proof.source_topology_sha256,file_hash(fullfile(folder,'tl_connectivity.json'))) && ...
            proof.loaded_model_matches_requested && ...
            proof.validation_rebuild_equivalence.applied_pressure_bounds_unchanged && ...
            proof.validation_rebuild_equivalence.other_validation_identical && ...
            isequaln(jsondecode(jsonencode(options.validation.article_component_pipe_UA_audit)), ...
                proof.original_article_audit), 'Specific component proof does not match the immutable source.');
        options.validation.article_component_pipe_UA_audit=proof.corrected_article_audit;
        options.validation.article_component_pipe_UA_implemented=proof.corrected_article_audit.ok;
        component_proof_sha256=file_hash(component_proof_path);
    end
    saved=load(observation_path,'signals','thermal_boundary_signals');
    observed=Slice_HeatDriveECC_SavedMechanismObservation(saved, ...
        scope.absolute_start_s,scope.absolute_stop_s,options.simulation.fixed_step_s);
    fields=fieldnames(observed.thermal_boundary_signals.fields);
    assert(all(cellfun(@(n) all(isfinite(observed.thermal_boundary_signals.fields.(n).values),'all'),fields)), ...
        'Requested window lacks measured thermal boundaries; do not shorten it silently.');
    physical=Extract_HeatDriveECC_PhysicalLogs(observed,options,'',false);
    assert(isequaln(physical.SMA_T_21_K,observed.signals.SMA_Tx21_internal.values) && ...
        isequaln(physical.SE_T_21_K,observed.signals.SE_Tx21_internal.values) && ...
        isequaln(physical.xM_SMA_21,observed.signals.ECC_constitutive21_output.values(:,43:63)) && ...
        isequaln(physical.xM_SE_21,observed.signals.ECC_constitutive21_output.values(:,64:84)), ...
        'Shared extraction changed actual material coordinates.');
    physical.authority='physical_simscape_to_workspace_logs';
    physical.legacy_surrogate_used_for_results=false;
    physical.sim_call_count=1;physical.walltime_s=NaN;
    provenance=struct('checkpoint_restart_used',false,'checkpoint_chain_verified',false, ...
        'sim_call_count',1,'simulation_executed_by_this_audit',false, ...
        'solver',source_options.simulation.solver,'fixed_step_s',source_options.simulation.fixed_step_s, ...
        'simulation_mode',chosen.simulation_mode, ...
        'configuration_requested_mode',source_options.simulation.mode, ...
        'source_arm',arm,'execution_commit',execution.execution_commit, ...
        'observation_sha256',observation_hash,'production_recovery_allowed',false);
    mkdir(output_root);
    view=Make_HeatDriveECC_MechanismWindow(physical,options,provenance,output_root);
    audit=Validate_HeatDriveECC_EighthRound_Physics(view);
    summary=Summarize_HeatDriveECC_EighthRound_Output(view.physical,view.options);
    names=fieldnames(audit.checks);
    failed=names(~cellfun(@(n) logical(audit.checks.(n)),names));
    p=summary.performance;
    record=struct('schema','heatdrive_ecc_saved_cold_operating_mechanism_v1', ...
        'source_root',source_root,'source_arm',arm,'scope',scope, ...
        'source_execution_commit',execution.execution_commit, ...
        'source_observation_sha256',observation_hash, ...
        'source_configuration_sha256',configuration_hash, ...
        'numerical_provenance',provenance, ...
        'source_execution_sha256',file_hash(execution_path), ...
        'component_audit_metadata_proof_sha256',component_proof_sha256, ...
        'validator_sha256',file_hash(which('Validate_HeatDriveECC_EighthRound_Physics')), ...
        'summarizer_sha256',file_hash(which('Summarize_HeatDriveECC_EighthRound_Output')), ...
        'extractor_sha256',file_hash(which('Extract_HeatDriveECC_PhysicalLogs')), ...
        'analysis_window',view.analysis_window,'original_production_predicates_evaluated',true, ...
        'checks',audit.checks,'failed_checks',{failed},'diagnostics',audit.diagnostics, ...
        'operating_window_mechanism_pass',audit.passed,'performance',p, ...
        'public_periodic_gate_evaluated',window_cycles==10, ...
        'public_temperature_phase_periodic_gate_pass',window_cycles==10 && p.periodic_steady_state, ...
        'simulation_executed',false,'operating_point_loaded',false, ...
        'source_state_edited',false,'checkpoint_restart_claim',false, ...
        'complete_internal_state_periodicity_verified',false, ...
        'full_device_first_law_verified',false,'production_recovery_allowed',false, ...
        'outer_solve_eligible',false,'paired_table4_evaluated',false, ...
        'table4_reproduction_claim',false);
    assert(strcmp(observation_hash,file_hash(observation_path)) && ...
        strcmp(configuration_hash,file_hash(configuration_path)), ...
        'Read-only source changed during analysis.');
    % The sliced waveforms are reproducible from the hash-bound observations.
    % Retain the compact predicates/provenance, not another full MAT copy.
    fid=fopen(fullfile(output_root,'saved_cold_mechanism_audit.json'),'w','n','UTF-8');
    assert(fid>=0);c=onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(record,'PrettyPrint',true));clear c
    fprintf('COLD_MECHANISM_JSON=%s\n',jsonencode(struct('arm',arm, ...
        'window_cycles',window_cycles,'checks',numel(names), ...
        'mechanism_pass',audit.passed,'failed_checks',{failed}, ...
        'public_periodic_gate_evaluated',window_cycles==10, ...
        'public_periodic_pass',record.public_temperature_phase_periodic_gate_pass)));
end

function hash=file_hash(path)
    md=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'rb');assert(fid>=0);
    c=onCleanup(@() fclose(fid));
    while ~feof(fid),md.update(fread(fid,8*1024*1024,'*uint8'));end
    hash=upper(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end

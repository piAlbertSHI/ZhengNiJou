function contract = Configure_HeatDriveECC_DiagnosticStateCapture(model, history_cycles)
% Bounded numerical history plus untouched complete OP; no recovery authority.
    validateattributes(history_cycles,{'numeric'},{'scalar','integer','>=',1,'<=',11});
    dt=str2double(get_param(model,'FixedStep'));
    assert(dt==.001,'Diagnostic state capture requires the unchanged 1 ms clock.');
    max_points=round(history_cycles*10/dt)+2;
    set_param(model,'SaveState','on','StateSaveName','diagnostic_state_log', ...
        'SaveFormat','Dataset','SaveFinalState','on','FinalStateName','diagnostic_final_op', ...
        'SaveOperatingPoint','on','LimitDataPoints','on', ...
        'MaxDataPoints',num2str(max_points),'Decimation','1', ...
        'OperatingPointContentsChecksumMismatchMsg','error', ...
        'OperatingPointInterfaceChecksumMismatchMsg','error');
    contract=struct('schema','heatdrive_ecc_diagnostic_state_capture_settings_v1', ...
        'history_cycles',history_cycles,'sample_time_s',dt, ...
        'max_points_per_logged_group',max_points, ...
        'complete_operating_point_requested',true,'numerical_history_bounded',true, ...
        'decimation',1,'hidden_state_reconstruction_used',false, ...
        'production_recovery_allowed',false);
end

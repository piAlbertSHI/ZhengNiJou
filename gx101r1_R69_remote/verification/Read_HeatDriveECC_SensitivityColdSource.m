function source=Read_HeatDriveECC_SensitivityColdSource(path,index)
% Resolve one sealed case without loading or translating its vendor state.
    q=jsondecode(fileread(path));
    assert(strcmp(q.schema,'heatdrive_ecc_runtime_sensitivity_cold_closeout_v1') && ...
        q.case_index==index && q.completed_cycles==20 && q.all_ten_original_packet_gates_pass && ...
        q.nine_recorded_boundaries_bitwise_equal && ~q.production_recovery_allowed && ...
        ~q.C200_gap_attribution_authorized && ~q.full_orthogonal_effects_evaluated);
    assert(strcmp(file_hash(q.source_result_path),q.source_result_sha256));
    r=jsondecode(fileread(q.source_result_path));
    assert(r.experiment_completed && r.all_original_packet_gates_pass && r.coordinate_match_pass && ...
        r.last_verified_snapshot_time_s==200 && r.completed_cold_cycles==20 && ...
        r.case_index==index && ~r.source_state_imported && ~r.production_recovery_allowed);
    root=fileparts(fileparts(fileparts(q.source_result_path)));
    contract_path=fullfile(root,'native','sensitivity_case_contract.json');
    assert(strcmp(file_hash(contract_path),q.case_contract_sha256));
    c=jsondecode(fileread(contract_path));
    assert(c.design.run_index==index && c.fixed_Tc_K==276.95 && ...
        ~c.source_state_imported && ~c.original_scientific_thresholds_changed && ...
        strcmp(file_hash(c.fresh_native_source_path),c.fresh_native_source_sha256));
    packet=r.last_verified_packet_root;
    assert(strcmp(file_hash(fullfile(packet,'comparison_only_complete_op.mat')),q.final_operating_point_sha256) && ...
        ~isfile(fullfile(packet,'REJECTED_DO_NOT_RESUME.json')));
    source=struct('root',root,'producer',q.producer,'packet_root',packet,'case_contract_path',contract_path, ...
        'case_contract',c,'case_contract_sha256',q.case_contract_sha256, ...
        'source_closeout_sha256',file_hash(path),'operating_point_sha256',q.final_operating_point_sha256, ...
        'fresh_native_path',c.fresh_native_source_path, ...
        'origin_measured_window_path',r.current_public_periodicity.measured_window_path, ...
        'origin_measured_window_sha256',r.current_public_periodicity.measured_window_sha256);
    assert(strcmp(file_hash(source.origin_measured_window_path),source.origin_measured_window_sha256));
end

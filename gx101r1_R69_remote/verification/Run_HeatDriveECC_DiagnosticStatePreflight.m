function record = Run_HeatDriveECC_DiagnosticStatePreflight(template_config_path, warmup_root, warmup_audit_path, output_root)
% New independent cold two-cycle state-interface experiment, never a warmup resume.
    assert(~isfolder(output_root),'Never overwrite a state experiment.');
    config=jsondecode(fileread(template_config_path));repo=char(config.repo_root);
    approved=jsondecode(fileread(warmup_audit_path));
    execution=jsondecode(fileread(fullfile(warmup_root,'cold_chamber_execution.json')));
    assert(~isempty(regexp(approved.producer,'^[0-9a-f]{40}$','once')), ...
        'Require the exact producer commit.');
    assert(strcmp(file_hash(fullfile(warmup_root,'cold_chamber_execution.json')), ...
        approved.input_sha256.cold_chamber_execution_json),'Completed execution contract changed.');
    assert(strcmp(approved.schema,'heatdrive_ecc_completed_warmup_physics_v1') && ...
        approved.cycles_run==20 && approved.mechanism_subset_pass && ...
        ~approved.production_recovery_allowed && ~approved.seed_eligible && ...
        strcmp(approved.producer,execution.execution_commit), ...
        'State preflight requires the actual completed twenty-cycle physics evidence.');
    assert(execution.collection_pass && execution.cycle_count==20 && ~execution.c200_state_imported && ...
        ~execution.checkpoint_saved && ~execution.production_recovery_allowed, ...
        'The qualified warmup must not contain a failed or imported checkpoint.');
    for name={'native','conservative'}
        relative=[name{1},'/observations.mat'];
        expected=approved.input_sha256.(matlab.lang.makeValidName(relative));
        assert(strcmp(file_hash(fullfile(warmup_root,name{1},'observations.mat')),expected), ...
            'Qualified warmup observation changed: %s',name{1});
    end
    assert(isequaln(Build_HeatDriveECC_IndependentColdBranchOverrides(config),execution.diagnostic_branch_overrides), ...
        'Template controller parameters differ from the actual qualified warmup.');
    pairs={'scale_inventory','new_inventory_nominal_scaling'; ...
        'buffer_mass_guess','physical_buffer_mass_guess';'buffer_mass_targets','physical_buffer_mass_high_targets'; ...
        'pipe_energy_targets','physical_pipe_energy_high_targets';'conservative_buffers','conservative_buffers'; ...
        'initial_flux_compensation','initial_flux_compensation';'buffer_mass_formulation','buffer_mass_formulation'; ...
        'endpoint_chamber_diagnostic','endpoint_chamber_diagnostic';'endpoint_all_arms','endpoint_all_arms'; ...
        'network_absolute_pressure_MPa','diagnostic_network_absolute_pressure_MPa';'formulation','inventory_formulation'};
    for k=1:size(pairs,1)
        assert(isequaln(config.(pairs{k,1}),execution.(pairs{k,2})), ...
            'Template physical option differs: %s',pairs{k,1});
    end
    assert(strcmpi(file_hash(fullfile(char(config.initial_observation_root),'native','observations.mat')), ...
        approved.initialization_source_chains.native.source_sha256), ...
        'Original t=0 source changed. Do not import the warmup endpoint.');
    workspace=fileparts(repo);
    [status,dirty]=system(sprintf('git -C "%s" status --porcelain',workspace));
    assert(status==0 && isempty(strtrim(dirty)),'Execute state preflight in the clean managed checkout.');
    physical={'Build_HeatDriveECC_EighthRound_Defaults.m','Build_HeatDriveECC_EighthRound_Simulink_Model.m', ...
        'Integrate_HeatDriveECC_Constitutive21_Interface.m','heatdrive_ecc_coupled_se21.slx', ...
        'verification/Configure_HeatDriveECC_DistributedPressureFeedforward.m', ...
        'verification/Build_HeatDriveECC_DistributedPressureEnvelope.m'};
    paths=strjoin(cellfun(@(p) ['"gx101r1_R69_remote/',p,'"'],physical,'UniformOutput',false),' ');
    [status,~]=system(sprintf('git -C "%s" diff --quiet %s HEAD -- %s',workspace,approved.producer,paths));
    assert(status==0,'Physical/control implementation changed since the qualified warmup.');
    config.output_root=output_root;config.duration_s=20;config.cycle_count=2;config.diagnostic_arm='native';
    config.diagnostic_state_options=struct('mode','restore_preflight','command_horizon_cycles',200);
    config_path=[output_root,'.state_preflight_config.json'];
    assert(~isfile(config_path),'Never overwrite preflight configuration.');
    fid=fopen(config_path,'w','n','UTF-8');assert(fid>=0,'Cannot save prepared config.');
    fprintf(fid,'%s\n',jsonencode(config,'PrettyPrint',true));fclose(fid);
    record=Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(config_path);
    assert(record.state_restore_preflight_pass && ~record.collection_pass && ...
        ~record.requested_arm_collection_pass && ~record.production_recovery_allowed, ...
        'State preflight is not a complete physical package or recovery authority.');
    fprintf('%s\n',jsonencode(struct('state_restore_preflight_pass',true, ...
        'command_horizon_cycles',200,'warmup_endpoint_imported',false, ...
        'full_physical_collection_pass',false,'production_recovery_allowed',false)));
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');
    assert(fid>=0,'Missing hash-bound evidence.');cleanup=onCleanup(@() fclose(fid));
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

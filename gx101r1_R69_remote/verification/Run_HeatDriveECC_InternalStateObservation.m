function state = Run_HeatDriveECC_InternalStateObservation(output_root)
% One same-parameter 20-cycle observation segment from strict runtime C180.
% It does not authorize a Table 4 point or complete internal-state steadiness.
    repo = fileparts(fileparts(mfilename('fullpath')));
    contract_path = fullfile(repo, 'verification', 'runtime_c180_recovery_contract.json');
    authority = Resolve_HeatDriveECC_SourceHeatFlowRecovery(struct( ...
        'contract_path', contract_path, 'verify_large_result_hash', true));
    probe_path = fullfile(repo, 'outputs_storage_audit', ...
        'extended_state_observability_20260906', 'production_smoke', ...
        'extended_logging_restore_audit.json');
    probe = jsondecode(fileread(probe_path));
    assert(probe.strict_restore_pass && probe.state_logging_enabled && ...
        probe.observed_checkpoint_round_trip_pass && ...
        probe.simscape_history_cycles == 1 && ...
        strcmpi(probe.source_result_sha256, authority.result_sha256) && ...
        strcmpi(probe.source_checkpoint_sha256, authority.checkpoint_sha256), ...
        'HeatDriveECC:StateObservationRestoreNotVerified', ...
        'State logging must pass the exact production strict-restore smoke test.');
    source_state = fullfile(fileparts(fileparts(authority.result_path)), ...
        'steady_continuation_state.mat');
    saved = load(source_state, 'settings', 'state');
    assert(saved.state.current_cycles == authority.completed_cycles && ...
        strcmp(saved.state.status, 'periodic_steady_state') && ...
        same_path(saved.state.prior_result_path, authority.result_path) && ...
        same_path(saved.state.checkpoint_path, authority.checkpoint_path), ...
        'HeatDriveECC:StateObservationSourceMismatch', ...
        'Source settings must belong to the frozen runtime C180 chain.');
    output_root = char(java.io.File(output_root).getCanonicalPath());
    outputs = char(java.io.File(fullfile(repo, 'outputs')).getCanonicalPath());
    assert(startsWith(lower(output_root), [lower(outputs), filesep]), ...
        'HeatDriveECC:StateObservationPathEscape', 'Output must stay inside outputs.');
    assert(~isfile(fullfile(output_root, 'steady_continuation_state.mat')), ...
        'HeatDriveECC:StateObservationAlreadyStarted', ...
        'Do not restart this observation over an existing state file.');
    settings = saved.settings;
    settings.output_root = output_root;
    settings.initial_prior_result_path = authority.result_path;
    settings.initial_checkpoint_path = authority.checkpoint_path;
    settings.initial_state_policy = 'validated_recovery_contract_only';
    settings.mainline_contract_path = contract_path;
    settings.segment_cycles = 20;
    settings.maximum_cycles = authority.completed_cycles + 20;
    settings.capture_internal_states = true;
    settings.generate_intermediate_figures = false;
    settings.compact_superseded_segments = false;
    settings.resume_existing_state = false;
    assert(isempty(settings.checkpoint_transition_fields) && ...
        isempty(settings.checkpoint_append_signal_fields), ...
        'HeatDriveECC:StateObservationParameterTransitionForbidden', ...
        'This branch permits observation only, without a physical parameter transition.');
    state = Run_HeatDriveECC_LongSteadyContinuation(settings);
    if state.current_cycles == settings.maximum_cycles && ...
            ~strcmp(state.status, 'mechanism_failure')
        energy = Audit_HeatDriveECC_SystemEnergyResult(state.prior_result_path);
        assert(energy.production_pass, 'HeatDriveECC:StateObservationEnergyFailure', ...
            'The observed segment must not be promoted after an energy/mass failure.');
    end
end

function yes = same_path(a, b)
    yes = strcmpi(char(java.io.File(a).getCanonicalPath()), ...
        char(java.io.File(b).getCanonicalPath()));
end

function result = Diagnose_HeatDriveECC_SwitchBoundary(overrides)
% Capture the physical state immediately before a late-cycle route switch.

    if nargin < 1
        overrides = struct();
    end
    root_dir = fileparts(fileparts(mfilename('fullpath')));
    cd(root_dir);
    defaults = struct( ...
        'cycle_count', 40, ...
        'outputs_dir', fullfile(root_dir, 'outputs', 'diagnostics'), ...
        'simulation', struct('stop_time_s', 395.099), ...
        'validation', struct('error_on_mechanism_failure', false), ...
        'system', struct('cold_load_mode', 'no_load', ...
            'cold_load_heat_W', 0.0));
    run_overrides = merge_structs(defaults, overrides);
    stop_token = strrep(sprintf('%.6f', ...
        run_overrides.simulation.stop_time_s), '.', 'p');
    diagnostic_dir = fullfile(run_overrides.outputs_dir, ...
        ['physical_prefault_t' stop_token]);
    if ~exist(diagnostic_dir, 'dir')
        mkdir(diagnostic_dir);
    end
    status_path = fullfile(diagnostic_dir, 'status.json');
    started_at = datetime('now', 'TimeZone', 'local');
    write_status(status_path, struct( ...
        'status', 'running', ...
        'pid', feature('getpid'), ...
        'started_at', char(started_at), ...
        'stop_time_s', run_overrides.simulation.stop_time_s));

    model_name = '';
    try
        [model_name, options] = ...
            Build_HeatDriveECC_EighthRound_Simulink_Model(run_overrides);
        cleanup = onCleanup(@() close_runtime_model(model_name));
        assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
        sim_in = Simulink.SimulationInput(model_name);
        sim_in = sim_in.setModelParameter( ...
            'StopTime', num2str(options.simulation.stop_time_s, '%.15g'), ...
            'Solver', options.simulation.solver, ...
            'ReturnWorkspaceOutputs', 'on', ...
            'CaptureErrors', 'on', ...
            'SaveFinalState', 'on', ...
            'FinalStateName', 'xFinal', ...
            'SaveCompleteFinalSimState', 'on');
        fixed_step_solvers = {'ode1','ode2','ode3','ode4','ode5', ...
            'ode8','ode14x','FixedStepDiscrete'};
        if any(strcmpi(options.simulation.solver, fixed_step_solvers))
            sim_in = sim_in.setModelParameter('FixedStep', ...
                num2str(options.simulation.fixed_step_s, '%.15g'));
        else
            sim_in = sim_in.setModelParameter( ...
                'MaxStep', num2str(options.simulation.fixed_step_s, '%.15g'), ...
                'RelTol', '1e-2', 'AbsTol', '1e-3');
        end
        sim_in = sim_in.setVariable('EIGHTH_ROUND_OPTIONS', options);

        wall_start = tic;
        sim_out = sim(sim_in);
        walltime_s = toc(wall_start);
        if isprop(sim_out, 'ErrorMessage') && ~isempty(sim_out.ErrorMessage)
            error('HeatDriveECC:SwitchDiagnosticSimulationFailed', ...
                '%s', sim_out.ErrorMessage);
        end

        available = sim_out.who;
        signal_names = { ...
            'SMA_Tx21_internal', 'SE_Tx21_internal', ...
            'ECC_constitutive21_output', ...
            'SHEX_hot_sink_temp_out', 'shex_buffer_temp_out', ...
            'hot_sink_temp_out', 'sma_hot_buffer_temp_out', ...
            'mass_flow_sma_stage13_kgps', ...
            'mass_flow_sma_stage1_route_kgps', ...
            'mass_flow_sma_stage3_route_kgps', ...
            'pressure_command_sma_MPa', ...
            'sma_stage1_inlet_fluid_temp_out', ...
            'sma_stage1_outlet_fluid_temp_out', ...
            'sma_stage3_inlet_fluid_temp_out', ...
            'sma_stage3_outlet_fluid_temp_out', ...
            'probe_sma_stage1_v1_shex_side_T_K', ...
            'probe_sma_stage1_v1_pump_side_T_K', ...
            'probe_sma_stage13_pump_outlet_T_K', ...
            'probe_sma_stage1_v5_shex_side_T_K', ...
            'probe_sma_stage3_v2_hhex_side_T_K', ...
            'probe_sma_stage3_v2_pump_side_T_K', ...
            'probe_sma_stage3_v6_hhex_side_T_K', ...
            'sma_hold_pipe_node01_fluid_temp_out', ...
            'sma_hold_pipe_node11_fluid_temp_out', ...
            'sma_hold_pipe_node21_fluid_temp_out', ...
            'sma_cooldown_pipe_node01_fluid_temp_out', ...
            'sma_cooldown_pipe_node11_fluid_temp_out', ...
            'sma_cooldown_pipe_node21_fluid_temp_out', ...
            'sma_hold_pipe_node01_pressure_MPa', ...
            'sma_hold_pipe_node11_pressure_MPa', ...
            'sma_hold_pipe_node21_pressure_MPa', ...
            'sma_cooldown_pipe_node01_pressure_MPa', ...
            'sma_cooldown_pipe_node11_pressure_MPa', ...
            'sma_cooldown_pipe_node21_pressure_MPa', ...
            'shex_hot_pipe_portA_pressure_MPa', ...
            'shex_hot_pipe_portB_pressure_MPa', ...
            'shex_hot_pipe_portA_fluid_temp_out', ...
            'shex_hot_pipe_portB_fluid_temp_out'};
        window = struct();
        window_start_s = options.simulation.stop_time_s - 0.25;
        for idx = 1:numel(signal_names)
            name = signal_names{idx};
            if any(strcmp(available, name))
                window.(name) = read_signal_window( ...
                    sim_out.get(name), window_start_s);
            end
        end
        commands = capture_command_profiles(window_start_s, ...
            options.simulation.stop_time_s);
        if ~any(strcmp(available, 'xFinal'))
            error('HeatDriveECC:MissingCompleteFinalState', ...
                'Complete final simulation state xFinal was not returned.');
        end
        final_state = sim_out.get('xFinal');
        provenance = struct( ...
            'authority', 'physical_simscape_prefault_diagnostic', ...
            'continuous_sim_call_count', 1, ...
            'model_name', model_name, ...
            'stop_time_s', options.simulation.stop_time_s, ...
            'window_start_s', window_start_s, ...
            'walltime_s', walltime_s);
        result_path = fullfile(diagnostic_dir, 'prefault_state_and_window.mat');
        save(result_path, 'window', 'commands', 'final_state', 'options', ...
            'provenance', 'available', '-v7.3');
        result = struct( ...
            'status', 'completed', ...
            'result_path', result_path, ...
            'status_path', status_path, ...
            'walltime_s', walltime_s, ...
            'stop_time_s', options.simulation.stop_time_s);
        write_status(status_path, struct( ...
            'status', 'completed', ...
            'pid', feature('getpid'), ...
            'started_at', char(started_at), ...
            'completed_at', char(datetime('now', 'TimeZone', 'local')), ...
            'stop_time_s', options.simulation.stop_time_s, ...
            'walltime_s', walltime_s, ...
            'result_path', result_path));
        fprintf('SWITCH_PREFAULT_DIAGNOSTIC=%s\n', result_path);
        clear cleanup
    catch ME
        write_status(status_path, struct( ...
            'status', 'failed', ...
            'pid', feature('getpid'), ...
            'started_at', char(started_at), ...
            'failed_at', char(datetime('now', 'TimeZone', 'local')), ...
            'identifier', ME.identifier, ...
            'message', ME.message));
        if ~isempty(model_name)
            close_runtime_model(model_name);
        end
        rethrow(ME);
    end
end

function sample = read_signal_window(raw, start_time_s)
    if isa(raw, 'timeseries')
        time_s = double(raw.Time(:));
        values = double(raw.Data);
    elseif isstruct(raw) && isfield(raw, 'time') && isfield(raw, 'signals')
        time_s = double(raw.time(:));
        values = double(raw.signals.values);
    else
        error('HeatDriveECC:UnsupportedDiagnosticSignal', ...
            'Unsupported diagnostic signal class %s.', class(raw));
    end
    values = squeeze(values);
    if isvector(values)
        values = values(:);
    elseif size(values, 1) ~= numel(time_s) && ...
            size(values, 2) == numel(time_s)
        values = values.';
    end
    if size(values, 1) ~= numel(time_s)
        error('HeatDriveECC:BadDiagnosticSignalShape', ...
            'Diagnostic signal has %d times and data size [%d %d].', ...
            numel(time_s), size(values, 1), size(values, 2));
    end
    keep = time_s >= start_time_s;
    sample = struct('time_s', time_s(keep), 'values', values(keep, :));
end

function commands = capture_command_profiles(start_time_s, stop_time_s)
    names = { ...
        'SMA_L_valve_command', ...
        'SMA_pressure_bias_command', ...
        'SMA_mdot_target_command', ...
        'SMA_pressure_feedback_enable_command', ...
        'SMA_hold_pipe_to_sma_G_command', ...
        'SMA_cooldown_pipe_to_sma_G_command'};
    commands = struct();
    for idx = 1:numel(names)
        name = names{idx};
        raw = evalin('base', name);
        sample = read_signal_window(raw, start_time_s);
        keep = sample.time_s <= stop_time_s;
        sample.time_s = sample.time_s(keep);
        sample.values = sample.values(keep, :);
        commands.(name) = sample;
    end
end

function merged = merge_structs(base, update)
    merged = base;
    names = fieldnames(update);
    for idx = 1:numel(names)
        name = names{idx};
        if isfield(merged, name) && isstruct(merged.(name)) && ...
                isstruct(update.(name))
            merged.(name) = merge_structs(merged.(name), update.(name));
        else
            merged.(name) = update.(name);
        end
    end
end

function write_status(path, value)
    fid = fopen(path, 'w', 'n', 'UTF-8');
    if fid < 0
        error('HeatDriveECC:CannotWriteDiagnosticStatus', ...
            'Cannot write diagnostic status: %s', path);
    end
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid, jsonencode(value, PrettyPrint=true), 'char');
    clear cleanup
end

function close_runtime_model(model_name)
    if bdIsLoaded(model_name)
        set_param(model_name, 'Dirty', 'off');
        close_system(model_name, 0);
    end
end

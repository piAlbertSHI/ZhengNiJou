function classification = Classify_HeatDriveECC_ObservationGates(energy, output_json)
% Distinguish physical failure from a completed nonperiodic observation.
    required = {'mechanism_pass','periodic_steady_state', ...
        'local_exchanger_kcl_pass','boundary_direction_pass', ...
        'fluid_mass_conservation_pass','modeled_thermal_closure_pass','production_pass'};
    assert(all(isfield(energy, required)), 'HeatDriveECC:MissingObservationGate', ...
        'Observation energy audit is missing required gate fields.');
    for k = 1:numel(required)
        value = energy.(required{k});
        assert(isscalar(value) && (islogical(value) || ...
            (isnumeric(value) && isfinite(value) && ismember(value, [0 1]))), ...
            'HeatDriveECC:InvalidObservationGate', 'Gate must be scalar boolean.');
    end
    thermal_mass_pass = energy.local_exchanger_kcl_pass && ...
        energy.boundary_direction_pass && energy.fluid_mass_conservation_pass && ...
        energy.modeled_thermal_closure_pass;
    physical_pass = thermal_mass_pass && energy.mechanism_pass;
    assert(logical(energy.production_pass) == ...
        (physical_pass && energy.periodic_steady_state), ...
        'HeatDriveECC:InconsistentObservationGate', 'Production aggregate is inconsistent.');
    if ~physical_pass
        status = 'physical_gate_failure';
    elseif ~energy.periodic_steady_state
        status = 'transient_observation_complete';
    else
        status = 'declared_scope_periodic_observation_complete';
    end
    classification = struct('schema', 'heatdrive_ecc_observation_completion_v1', ...
        'status', status, 'mechanism_pass', logical(energy.mechanism_pass), ...
        'thermal_mass_gates_pass', logical(thermal_mass_pass), ...
        'physical_gates_pass', logical(physical_pass), ...
        'declared_periodic_steady_state', logical(energy.periodic_steady_state), ...
        'production_pass', logical(energy.production_pass), ...
        'complete_internal_state_periodicity_verified', false, ...
        'steady_parameter_study_allowed', false, ...
        'checkpoint_recovery_authorized_by_this_audit', false);
    if nargin >= 2 && ~isempty(output_json)
        fid = fopen(output_json, 'w', 'n', 'UTF-8');
        assert(fid >= 0, 'Cannot write observation completion audit.');
        cleanup = onCleanup(@() fclose(fid));
        fprintf(fid, '%s\n', jsonencode(classification, 'PrettyPrint', true));
        clear cleanup
    end
end

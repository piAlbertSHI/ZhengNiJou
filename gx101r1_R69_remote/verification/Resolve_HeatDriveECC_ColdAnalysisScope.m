function scope=Resolve_HeatDriveECC_ColdAnalysisScope(execution,completion,arm,window_cycles)
% Cold observations are not restart-qualified segments; never invent a chain.
    assert(ismember(arm,{'native','conservative'}),'Unknown observation arm.');
    assert(ismember(window_cycles,[2 10]),'Declare a two- or ten-cycle analysis window.');
    assert(strcmp(execution.schema,'heatdrive_ecc_independent_cold_chamber_v2') && ...
        execution.user_authorized_independent_cold_start && ...
        ~execution.c200_state_imported && ~execution.production_recovery_allowed && ...
        ~execution.checkpoint_saved && strcmp(execution.diagnostic_state_options.mode,'off') && ...
        isempty(fieldnames(execution.diagnostic_resume_contract)) && ...
        execution.collection_pass && execution.requested_arm_collection_pass && ...
        isempty(execution.error_message) && execution.start_time_s==0 && ...
        execution.stop_time_s==200 && execution.cycle_count==20 && ...
        execution.segment_cycle_count==20, ...
        'Require a complete independent cold C20, not a resumed or partial trajectory.');
    cases=execution.cases;
    assert(numel(cases)==2 && numel(unique({cases.arm}))==2 && ...
        all(ismember({'native','conservative'},{cases.arm})), ...
        'Require both separately identified completed arms.');
    chosen=cases(strcmp({cases.arm},arm));
    assert(strcmp(completion.arm,arm) && completion.start_time_s==0 && ...
        completion.stop_time_s==200 && completion.cycle_count==20 && ...
        strcmp(completion.execution_commit,execution.execution_commit) && ...
        strcmp(completion.observation_sha256,chosen.observation_sha256) && ...
        numel(completion.observation_sha256)==64, ...
        'Arm completion, producer or observation binding differs.');
    scope=struct('arm',arm,'window_cycles',window_cycles, ...
        'absolute_start_s',200-10*window_cycles,'absolute_stop_s',200, ...
        'checkpoint_restart_used',false,'checkpoint_chain_verified',false, ...
        'sim_call_count',1,'operating_point_loaded',false, ...
        'analysis_window_only',true,'full_run_startup_gates_evaluated',false, ...
        'production_recovery_allowed',false);
end

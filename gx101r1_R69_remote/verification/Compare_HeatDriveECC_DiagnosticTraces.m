function audit = Compare_HeatDriveECC_DiagnosticTraces(reference, candidate)
% Compare every named coordinate at identical samples, including both ends.
    absolute_tolerance = 1e-12;
    relative_tolerance = 1e-11;
    keys = cellfun(@trace_key, reference, 'UniformOutput', false);
    other_keys = cellfun(@trace_key, candidate, 'UniformOutput', false);
    assert(numel(unique(keys)) == numel(keys) && ...
        numel(unique(other_keys)) == numel(other_keys) && ...
        isequal(sort(keys), sort(other_keys)), ...
        'HeatDriveECC:TraceInventoryMismatch', 'Named trace inventories differ.');
    rows = cell(size(candidate));
    for k = 1:numel(candidate)
        a = reference{find(strcmp(keys, other_keys{k}), 1)};
        b = candidate{k};
        assert(strcmp(a.unit, b.unit), 'Trace units differ.');
        ta = a.time_s(:); tb = b.time_s(:);
        assert(~isempty(tb) && all(isfinite([ta; tb])) && ...
            all(diff(ta) > 0) && all(diff(tb) > 0), 'Trace times must strictly increase.');
        time_tolerance = 16 * eps(max(1, max(abs([ta; tb]))));
        selected = ta >= tb(1) - time_tolerance & ta <= tb(end) + time_tolerance;
        ta = ta(selected);
        assert(numel(ta) == numel(tb) && all(abs(ta - tb) <= time_tolerance), ...
            'HeatDriveECC:TraceGridMismatch', 'No interpolation or omitted boundary samples allowed.');
        va = a.values(selected, :); vb = b.values;
        assert(isa(va, 'double') && isa(vb, 'double') && ...
            isequal(size(va), size(vb)) && size(vb, 1) == numel(tb) && ...
            all(isfinite(va), 'all') && all(isfinite(vb), 'all'), ...
            'HeatDriveECC:TraceValuesInvalid', 'Nonfinite values or mismatched trace dimensions.');
        difference = abs(va - vb);
        scale = max(abs(va), [], 1);
        threshold = absolute_tolerance + relative_tolerance * scale;
        maximum = max(difference, [], 1);
        rows{k} = struct('key', other_keys{k}, 'unit', a.unit, ...
            'sample_count', numel(tb), 'channel_count', size(vb, 2), ...
            'start_s', tb(1), 'end_s', tb(end), ...
            'reference_scale', scale, 'allowed_abs_error', threshold, ...
            'max_abs_error', maximum, 'max_tolerance_ratio', max(maximum ./ threshold), ...
            'bitwise_values_equal', isequal(typecast(va(:), 'uint64'), ...
                typecast(vb(:), 'uint64')), 'pass', all(maximum <= threshold));
    end
    audit = struct('schema', 'heatdrive_ecc_diagnostic_trace_comparison_v1', ...
        'absolute_tolerance', absolute_tolerance, 'relative_tolerance', relative_tolerance, ...
        'scope', 'Numerical repeatability at matched samples, not physical validation or periodicity.', ...
        'trace_count', numel(rows), 'channel_count', sum(cellfun(@(r) r.channel_count, rows)), ...
        'pass', all(cellfun(@(r) r.pass, rows)), ...
        'bitwise_values_equal', all(cellfun(@(r) r.bitwise_values_equal, rows)), ...
        'max_tolerance_ratio', max(cellfun(@(r) r.max_tolerance_ratio, rows)), 'traces', {rows});
end

function key = trace_key(row)
    key = [row.block_path '::' row.state_name];
end

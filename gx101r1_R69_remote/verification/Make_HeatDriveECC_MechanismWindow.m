function result = Make_HeatDriveECC_MechanismWindow(physical, options, provenance, output_dir)
% A read-only analysis view; never feed this local clock/options into sim or OP.
    absolute_time = physical.time_s(:);
    tau = options.schedule.tau_cycle_s;
    dt = options.simulation.fixed_step_s;
    start = absolute_time(1); finish = absolute_time(end);
    tolerance = 16 * eps(max(abs([start finish 1])));
    first_cycle = round(start / tau) + 1;
    cycle_count = round((finish - start) / tau);
    assert(cycle_count >= 1 && abs(start - (first_cycle - 1) * tau) <= tolerance && ...
        abs(finish - start - cycle_count * tau) <= tolerance && ...
        numel(absolute_time) == round(cycle_count * tau / dt) + 1 && ...
        all(abs(diff(absolute_time) - dt) <= tolerance), ...
        'HeatDriveECC:IncompleteMechanismWindow', 'Require complete aligned cycles and both endpoints.');
    assert(first_cycle >= options.validation.mechanism_gate_start_cycle, ...
        'HeatDriveECC:MechanismWindowBeforeGate', 'Window precedes the original global mechanism gate.');
    assert(provenance.checkpoint_chain_verified && provenance.checkpoint_restart_used && ...
        provenance.sim_call_count == physical.sim_call_count, ...
        'HeatDriveECC:UnverifiedMechanismSource', 'A strictly restored source is required.');
    view_options = options;
    view_options.cycle_count = cycle_count;
    view_options.simulation.stop_time_s = finish - start;
    view_options.validation.mechanism_gate_start_cycle = 1;
    view_options.validation.error_on_mechanism_failure = false;
    view = physical;
    view.time_s = absolute_time - start;
    [view.cycle_index, view.stage_id, view.stage_elapsed_s] = ...
        HeatDriveECC_CycleStageFromTime(view.time_s, view_options);
    result = struct('physical', view, 'options', view_options, 'provenance', provenance, ...
        'output_dir', output_dir, 'authority', physical.authority, ...
        'used_simulink_sim', true, 'legacy_surrogate_used_for_results', false, ...
        'analysis_window', struct('absolute_start_s', start, 'absolute_stop_s', finish, ...
            'global_first_cycle', first_cycle, 'global_last_cycle', first_cycle + cycle_count - 1, ...
            'original_mechanism_gate_start_cycle', options.validation.mechanism_gate_start_cycle, ...
            'time_shift_for_analysis_only', true, 'simulation_options_modified', false, ...
            'operating_point_modified', false, 'production_recovery_allowed', false));
end

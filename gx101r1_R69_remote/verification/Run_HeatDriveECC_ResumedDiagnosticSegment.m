function record = Run_HeatDriveECC_ResumedDiagnosticSegment(source_root, verified_root, output_root)
% Twenty new cycles from an intact state-qualified candidate, without C200 state import.
    assert(~isfolder(output_root) && ~isfile([output_root,'.resumed_config.json']), ...
        'Never overwrite a diagnostic continuation.');
    config=jsondecode(fileread([source_root,'.state_preflight_config.json']));
    source=jsondecode(fileread(fullfile(source_root,'cold_chamber_execution.json')));
    assert(strcmp(config.output_root,source_root) && source.state_restore_preflight_pass && ...
        strcmp(config.diagnostic_state_options.mode,'restore_preflight') && ...
        config.diagnostic_state_options.command_horizon_cycles==200, ...
        'Require the original fixed-horizon state experiment.');
    workspace=fileparts(char(config.repo_root));
    [status,dirty]=system(sprintf('git -C "%s" status --porcelain',workspace));
    assert(status==0 && isempty(strtrim(dirty)),'Use the clean managed checkout.');
    physical={'Build_HeatDriveECC_EighthRound_Defaults.m','Build_HeatDriveECC_EighthRound_Simulink_Model.m', ...
        'Integrate_HeatDriveECC_Constitutive21_Interface.m','heatdrive_ecc_coupled_se21.slx', ...
        'verification/Configure_HeatDriveECC_DistributedPressureFeedforward.m', ...
        'verification/Build_HeatDriveECC_DistributedPressureEnvelope.m', ...
        'verification/Build_HeatDriveECC_IndependentColdBranchOverrides.m', ...
        'verification/Configure_HeatDriveECC_DiagnosticStateCapture.m', ...
        'verification/Instrument_HeatDriveECC_PumpPressureProbes.m', ...
        'verification/Instrument_HeatDriveECC_Stage4ControllerProbes.m'};
    paths=strjoin(cellfun(@(p) ['"gx101r1_R69_remote/',p,'"'],physical,'UniformOutput',false),' ');
    assert(~isempty(regexp(source.execution_commit,'^[0-9a-f]{40}$','once')),'Require exact producer.');
    [status,~]=system(sprintf('git -C "%s" diff --quiet %s HEAD -- %s',workspace,source.execution_commit,paths));
    assert(status==0,'Physical/control/probe code changed since state qualification.');
    config.output_root=output_root;config.duration_s=200;config.cycle_count=20;
    config.diagnostic_arm='native';
    config.diagnostic_state_options=struct('mode','diagnostic_resume','command_horizon_cycles',200, ...
        'restore_source_root',source_root,'restore_verification_root',verified_root);
    path=[output_root,'.resumed_config.json'];
    fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'Cannot save diagnostic resume config.');
    fprintf(fid,'%s\n',jsonencode(config,'PrettyPrint',true));fclose(fid);
    record=Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(path);
    assert(record.requested_arm_collection_pass && ~record.collection_pass && ...
        record.start_time_s==20 && record.stop_time_s==220 && record.cycle_count==22 && ...
        record.checkpoint_saved && ~record.production_recovery_allowed, ...
        'Require the complete single-arm diagnostic trial, never production recovery.');
end

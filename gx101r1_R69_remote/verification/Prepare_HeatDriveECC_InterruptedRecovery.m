function record = Prepare_HeatDriveECC_InterruptedRecovery( ...
        state_path, result_path, output_root)
% Audit a fully saved segment interrupted before promotion; prepare, do not run.
    state_path = canonical(state_path);
    result_path = canonical(result_path);
    output_root = canonical(output_root);
    repo_root = fileparts(fileparts(mfilename('fullpath')));
    outputs_prefix = [canonical(fullfile(repo_root, 'outputs')), filesep];
    assert(startsWith(lower(output_root), lower(outputs_prefix)), ...
        'HeatDriveECC:RecoveryOutputEscape', 'Recovery output must be inside outputs.');
    assert(~isfolder(output_root), 'HeatDriveECC:RecoveryOutputExists', ...
        'Use a new output root; recovery never overwrites a prior run.');
    saved = load(state_path, 'state', 'settings');
    assert(strcmp(saved.state.status, 'running'), ...
        'HeatDriveECC:RecoveryStateNotInterrupted', 'Only interrupted runs qualify.');
    candidate = load(result_path, 'options', 'provenance');
    checkpoint_path = fullfile(fileparts(result_path), 'final_operating_point.mat');
    checkpoint = load(checkpoint_path, 'checkpoint_meta');
    prior_cycles = saved.state.current_cycles;
    cycles = candidate.options.cycle_count;
    tau = candidate.options.schedule.tau_cycle_s;
    assert(cycles == min(prior_cycles + saved.settings.segment_cycles, ...
            saved.settings.maximum_cycles), 'HeatDriveECC:RecoverySegmentMismatch', ...
        'The candidate is not the next segment of the interrupted run.');
    assert(same_path(candidate.options.simulation.prior_result_path, ...
            saved.state.prior_result_path) && ...
        same_path(candidate.options.simulation.resume_checkpoint_path, ...
            saved.state.checkpoint_path), 'HeatDriveECC:RecoveryParentMismatch', ...
        'The candidate must descend from the last recorded result and OP.');
    p = candidate.provenance;
    assert(p.checkpoint_restart_used && p.checkpoint_chain_verified && ...
        p.checkpoint_time_continuity_verified && p.checkpoint_complete_restore_verified && ...
        strcmp(p.checkpoint_restore_policy, 'strict') && ...
        abs(p.segment_start_time_s - prior_cycles * tau) < 1e-9 && ...
        abs(p.segment_stop_time_s - cycles * tau) < 1e-9 && ...
        checkpoint.checkpoint_meta.cycle_count == cycles && ...
        abs(checkpoint.checkpoint_meta.time_s - cycles * tau) < 1e-9, ...
        'HeatDriveECC:RecoveryContinuityMismatch', 'Strict segment continuity is required.');
    assert(saved.state.rows.total_cycles(end) == prior_cycles && ...
        saved.state.rows.mechanism_pass(end), 'HeatDriveECC:RecoveryPriorNotAccepted', ...
        'The recorded parent segment did not pass mechanism validation.');
    assert(~isfile(fullfile(fileparts(result_path), 'REJECTED_DO_NOT_RESUME.txt')) && ...
        ~isfile(fullfile(fileparts(fileparts(result_path)), 'REJECTED_DO_NOT_RESUME.txt')), ...
        'HeatDriveECC:RejectedRecoveryCandidate', 'Rejected results cannot be recovered.');

    result_hash = sha256(result_path);
    checkpoint_hash = sha256(checkpoint_path);
    audit = Audit_HeatDriveECC_SavedResult(result_path);
    assert(audit.mechanism_pass, 'HeatDriveECC:RecoveryMechanismFailed', ...
        'All original mechanism gates must pass.');
    energy_path = fullfile(fileparts(result_path), 'interrupted_system_energy_audit.json');
    energy = Audit_HeatDriveECC_SystemEnergyResult(result_path, energy_path);
    assert(energy.local_exchanger_kcl_pass && energy.boundary_direction_pass && ...
        energy.modeled_thermal_closure_pass && energy.fluid_mass_conservation_pass, ...
        'HeatDriveECC:RecoveryEnergyFailed', 'Thermal and mass gates must pass.');
    strict_path = fullfile(fileparts(result_path), 'interrupted_strict_restore_audit.json');
    strict = Audit_HeatDriveECC_OperatingPointRestore(result_path, checkpoint_path, strict_path);
    assert(strict.strict_restore_pass && strict.complete_operating_point_restore_verified, ...
        'HeatDriveECC:RecoveryStrictRestoreFailed', 'Strict OP restoration must pass.');
    assert(strcmp(result_hash, sha256(result_path)) && ...
        strcmp(checkpoint_hash, sha256(checkpoint_path)), ...
        'HeatDriveECC:RecoveryInputChanged', 'Recovery inputs changed during audit.');

    settings = saved.settings;
    settings.output_root = output_root;
    settings.initial_prior_result_path = result_path;
    settings.initial_checkpoint_path = checkpoint_path;
    % This transient continuation is fully checked above; the periodic-only
    % source contract is reserved for later steady-state parameter studies.
    settings.initial_state_policy = 'unrestricted';
    settings.mainline_contract_path = '';
    settings.resume_existing_state = false;
    settings.generate_intermediate_figures = false;
    settings.compact_superseded_segments = true;
    record = struct('schema', 'heatdrive_ecc_interrupted_recovery_v1', ...
        'source_state_path', state_path, 'source_state_sha256', sha256(state_path), ...
        'source_recorded_cycles', prior_cycles, 'recovered_cycles', cycles, ...
        'result_path', result_path, 'result_sha256', result_hash, ...
        'checkpoint_path', checkpoint_path, 'checkpoint_sha256', checkpoint_hash, ...
        'mechanism_pass', audit.mechanism_pass, ...
        'periodic_steady_state', audit.performance.periodic_steady_state, ...
        'strict_restore_pass', strict.strict_restore_pass, ...
        'energy_audit_path', energy_path, 'strict_audit_path', strict_path, ...
        'original_state_modified', false, 'state_reset', false, ...
        'steady_parameter_study_allowed', false, 'table4_reproduction_claimed', false, ...
        'mechanism_gate_start_cycle', candidate.options.validation.mechanism_gate_start_cycle, ...
        'output_root', output_root);
    mkdir(output_root);
    save(fullfile(output_root, 'audited_recovery_settings.mat'), 'settings', 'record');
    fid = fopen(fullfile(output_root, 'audited_recovery_contract.json'), 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:RecoveryContractWriteFailed', 'Cannot write contract.');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(record, 'PrettyPrint', true));
    fprintf('INTERRUPTED_RECOVERY_PREPARED=%d cycles=%d output=%s\n', ...
        record.strict_restore_pass, cycles, output_root);
end

function path = canonical(path)
    path = char(java.io.File(char(string(path))).getCanonicalPath());
end

function equal = same_path(first, second)
    equal = strcmpi(canonical(first), canonical(second));
end

function hash = sha256(path)
    stream = System.IO.File.OpenRead(path);
    cleanup = onCleanup(@() stream.Dispose());
    digest = System.Security.Cryptography.SHA256.Create();
    hash = upper(reshape(dec2hex(uint8(digest.ComputeHash(stream)), 2).', 1, []));
    digest.Dispose();
end

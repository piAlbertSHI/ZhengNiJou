function audit = Audit_HeatDriveECC_RuntimeBuilderDeterminism(output_path)
% Prove that two runtime-model builds support an exact OP handoff.

    repo_root = fileparts(fileparts(mfilename('fullpath')));
    if nargin < 1 || isempty(output_path)
        output_path = fullfile(repo_root, 'outputs_storage_audit', ...
            'runtime_builder_determinism_20260904', ...
            'runtime_builder_determinism_audit.json');
    end
    output_path = char(string(output_path));
    overrides = struct( ...
        'cycle_count', 1, ...
        'system', struct( ...
            'cold_boundary_temperature_configurability', 'runtime'), ...
        'output', struct('generate_figures', false));
    audit = audit_template();
    try
        [model_name, options] = ...
            Build_HeatDriveECC_EighthRound_Simulink_Model(overrides);
        cleanup = onCleanup(@() close_without_saving(model_name));
        assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
        checksum_1 = Simulink.BlockDiagram.getChecksum(model_name);
        first = base_simulation_input(model_name, options, ...
            options.simulation.fixed_step_s);
        first_out = sim(first);
        if ~isempty(first_out.ErrorMessage)
            audit.first_run_error = char(string(first_out.ErrorMessage));
            clear cleanup
            write_json(output_path, audit);
            print_result(audit, output_path);
            return
        end
        first_operating_point = first_out.xFinal;
        audit.first_cold_step_pass = true;
        clear cleanup

        [model_name, options] = ...
            Build_HeatDriveECC_EighthRound_Simulink_Model(overrides);
        cleanup = onCleanup(@() close_without_saving(model_name));
        assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
        checksum_2 = Simulink.BlockDiagram.getChecksum(model_name);
        audit.model_checksum_equal = isequaln(checksum_1, checksum_2);
        second = base_simulation_input(model_name, options, ...
            2.0 * options.simulation.fixed_step_s);
        second = second.setModelParameter( ...
            'OperatingPointContentsChecksumMismatchMsg', 'error', ...
            'OperatingPointInterfaceChecksumMismatchMsg', 'error');
        second = second.setInitialState(first_operating_point);
        second_out = sim(second);
        audit.second_run_error = char(string(second_out.ErrorMessage));
        audit.strict_restore_pass = isempty(audit.second_run_error);
        audit.complete_operating_point_restore_verified = ...
            audit.strict_restore_pass;
        audit.production_runtime_cold_start_allowed = all([ ...
            audit.first_cold_step_pass, audit.model_checksum_equal, ...
            audit.strict_restore_pass]);
        clear cleanup
    catch exception
        audit.error_identifier = exception.identifier;
        audit.error_message = exception.message;
    end
    write_json(output_path, audit);
    print_result(audit, output_path);
end

function sim_in = base_simulation_input(model_name, options, stop_time_s)
    sim_in = Simulink.SimulationInput(model_name);
    sim_in = sim_in.setModelParameter( ...
        'StartTime', '0', ...
        'StopTime', num2str(stop_time_s, '%.15g'), ...
        'Solver', options.simulation.solver, ...
        'FixedStep', num2str(options.simulation.fixed_step_s, '%.15g'), ...
        'SimulationMode', options.simulation.mode, ...
        'CaptureErrors', 'on', ...
        'ReturnWorkspaceOutputs', 'on', ...
        'SaveFinalState', 'on', ...
        'FinalStateName', 'xFinal', ...
        'SaveOperatingPoint', 'on', ...
        'SaveTime', 'off', ...
        'SaveOutput', 'off', ...
        'SignalLogging', 'off');
    sim_in = sim_in.setVariable('EIGHTH_ROUND_OPTIONS', options);
end

function audit = audit_template()
    audit = struct( ...
        'schema', 'heatdrive_ecc_runtime_builder_determinism_v1', ...
        'generated_at', char(datetime('now', 'TimeZone', 'local')), ...
        'cold_boundary_temperature_configurability', 'runtime', ...
        'first_stop_time_s', 0.001, 'second_stop_time_s', 0.002, ...
        'first_cold_step_pass', false, 'model_checksum_equal', false, ...
        'strict_restore_pass', false, ...
        'complete_operating_point_restore_verified', false, ...
        'production_runtime_cold_start_allowed', false, ...
        'first_run_error', '', 'second_run_error', '', ...
        'error_identifier', '', 'error_message', '');
end

function print_result(audit, output_path)
    fprintf(['RUNTIME_BUILDER_DETERMINISM_PASS=%d first=%d ', ...
        'checksum=%d strict_restore=%d output=%s\n'], ...
        audit.production_runtime_cold_start_allowed, ...
        audit.first_cold_step_pass, audit.model_checksum_equal, ...
        audit.strict_restore_pass, output_path);
end

function write_json(path, value)
    parent = fileparts(path);
    if ~isempty(parent) && ~isfolder(parent)
        mkdir(parent);
    end
    fid = fopen(path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:BuilderAuditWriteFailed', ...
        'Cannot write %s.', path);
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid, jsonencode(value, 'PrettyPrint', true), 'char');
    fwrite(fid, newline, 'char');
    clear cleanup
end

function close_without_saving(model_name)
    if bdIsLoaded(model_name)
        set_param(model_name, 'Dirty', 'off');
        close_system(model_name, 0);
    end
end

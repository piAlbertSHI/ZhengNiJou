function contract = Save_HeatDriveECC_DiagnosticStateCapture(output, folder, settings, expected_time)
% Preserve the vendor OP before expensive postprocessing; it is a candidate only.
    assert(isempty(output.ErrorMessage),'Never save a failed trajectory as a state candidate.');
    state_path=fullfile(folder,'diagnostic_complete_operating_point.mat');
    history_path=fullfile(folder,'diagnostic_state_observation.mat');
    assert(~isfile(state_path) && ~isfile(history_path),'Never overwrite diagnostic state evidence.');
    diagnostic_operating_point=output.diagnostic_final_op;
    assert(isa(diagnostic_operating_point,'Simulink.SimulationOperatingPoint') && ...
        abs(diagnostic_operating_point.snapshotTime-expected_time)<=1e-9, ...
        'Expected an untouched complete OP at the physical terminal time.');
    production_recovery_allowed=false;
    save(state_path,'diagnostic_operating_point','production_recovery_allowed','settings','-v7.3');
    observation=Extract_HeatDriveECC_ObservedStates(output.diagnostic_state_log,10,settings.history_cycles);
    for k=1:numel(observation.states)
        row=observation.states{k};
        assert(numel(row.time_s)<=settings.max_points_per_logged_group && ...
            abs(row.time_s(end)-expected_time)<=1e-9 && row.complete_requested_window, ...
            'Incomplete or unbounded numerical state history: %s',row.block_path);
    end
    save(history_path,'observation','production_recovery_allowed','-v7.3');
    contract=struct('schema','heatdrive_ecc_diagnostic_state_capture_v1', ...
        'snapshot_time_s',diagnostic_operating_point.snapshotTime, ...
        'complete_op_class',class(diagnostic_operating_point), ...
        'operating_point_file',state_path,'operating_point_sha256',file_hash(state_path), ...
        'history_file',history_path,'history_sha256',file_hash(history_path), ...
        'logged_group_count',observation.logged_state_group_count, ...
        'numeric_history_bytes',observation.numeric_bytes,'settings',settings, ...
        'physical_mechanism_gate_evaluated',false, ...
        'current_model_roundtrip_verified',false,'complete_periodicity_verified',false, ...
        'diagnostic_continuation_allowed',false,'production_recovery_allowed',false, ...
        'source_op_edited',false,'state_reconstruction_used',false);
    fid=fopen(fullfile(folder,'diagnostic_state_capture.json'),'w','n','UTF-8');
    assert(fid>=0,'Cannot save capture receipt.');cleanup=onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(contract,'PrettyPrint',true));
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');
    assert(fid>=0,'Cannot hash saved evidence.');cleanup=onCleanup(@() fclose(fid));
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

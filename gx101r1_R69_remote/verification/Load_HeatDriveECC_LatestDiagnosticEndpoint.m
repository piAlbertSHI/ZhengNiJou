function [op, contract] = Load_HeatDriveECC_LatestDiagnosticEndpoint(options)
% Full vendor endpoint, qualified for transient warmup only, without state edits.
    source=char(options.restore_source_root);verified=char(options.restore_verification_root);
    path=fullfile(verified,'diagnostic_resume_qualification.json');
    receipt=jsondecode(fileread(path));
    execution=jsondecode(fileread(fullfile(source,'cold_chamber_execution.json')));
    capture=jsondecode(fileread(fullfile(source,'native','diagnostic_state_capture.json')));
    assert(strcmp(receipt.schema,'heatdrive_ecc_latest_diagnostic_endpoint_qualification_v1') && ...
        strcmp(receipt.source_root,source) && receipt.qualification_pass && ...
        receipt.warmup_continuation_allowed && receipt.full_mechanism_count==73 && ...
        receipt.local_inventory_pass && receipt.complete_logged_state_coverage && ...
        receipt.ancestor_complete_cycle_restore_verified && ...
        ~receipt.latest_endpoint_complete_cycle_reference_compared && ...
        ~receipt.source_state_edited && ~receipt.partial_state_restore_used && ...
        ~receipt.production_recovery_allowed && ~receipt.steady_outer_solve_allowed && ...
        ~receipt.table4_reproduction_claim && receipt.command_horizon_cycles==200 && ...
        strcmp(receipt.producer,execution.execution_commit), 'Invalid latest warmup endpoint authority.');
    assert(execution.requested_arm_collection_pass && ~execution.collection_pass && ...
        strcmp(execution.diagnostic_state_options.mode,'diagnostic_resume') && ...
        execution.segment_cycle_count==20 && execution.checkpoint_saved && ...
        isempty(execution.error_message) && ~execution.c200_state_imported && ...
        ~execution.production_recovery_allowed && ...
        execution.stop_time_s-execution.start_time_s==200 && ...
        receipt.snapshot_time_s==execution.stop_time_s && receipt.total_cycles==execution.cycle_count && ...
        receipt.total_cycles>=22 && receipt.snapshot_time_s==10*receipt.total_cycles && ...
        execution.diagnostic_state_options.command_horizon_cycles==200, 'Incomplete prior segment.');
    assert(~isfile(fullfile(source,'INCOMPLETE_DO_NOT_RESUME.json')) && ...
        ~isfile(fullfile(source,'REJECTED_DO_NOT_RESUME.json')) && ...
        ~isfile(fullfile(source,'REJECTED_DO_NOT_RESUME.txt')), 'A rejected endpoint cannot propagate.');
    roles={receipt.files.role};required={'execution','capture','operating_point','history','observation', ...
        'configuration','physics_audit','mechanism_audit','state_audit','steadiness_audit'};
    assert(numel(roles)==10 && numel(unique(roles))==10 && all(ismember(required,roles)), ...
        'Incomplete or duplicated endpoint evidence roles.');
    relative={'cold_chamber_execution.json','native/diagnostic_state_capture.json', ...
        'native/diagnostic_complete_operating_point.mat','native/diagnostic_state_observation.mat', ...
        'native/observations.mat','native/configuration.mat'};
    for idx=1:numel(receipt.files)
        row=receipt.files(idx);local=find(strcmp(required(1:6),row.role));
        if ~isempty(local)
            expected=char(java.io.File(fullfile(source,relative{local})).getCanonicalPath());
            actual=char(java.io.File(row.path).getCanonicalPath());
            assert(strcmpi(actual,expected),'Substituted local endpoint evidence.');
        end
        assert(strcmp(file_hash(row.path),row.sha256),'Changed qualified endpoint evidence: %s',row.role);
    end
    op_row=receipt.files(strcmp(roles,'operating_point'));history_row=receipt.files(strcmp(roles,'history'));
    physical_row=receipt.files(strcmp(roles,'physics_audit'));
    mechanism_row=receipt.files(strcmp(roles,'mechanism_audit'));
    state_row=receipt.files(strcmp(roles,'state_audit'));
    physical=jsondecode(fileread(physical_row.path));mechanism=jsondecode(fileread(mechanism_row.path));
    states=jsondecode(fileread(state_row.path));
    assert(physical.mechanism_subset_pass && physical.cycles_run==receipt.total_cycles && ...
        numel(physical.arms)==1 && all(structfun(@logical,physical.arms.mechanism_subset_gates)) && ...
        numel(fieldnames(mechanism.checks))==73 && all(structfun(@logical,mechanism.checks)) && ...
        mechanism.original_production_predicates_evaluated && mechanism.exact_saved_window_pass && ...
        strcmp(mechanism.source_execution_commit,execution.execution_commit) && ...
        strcmp(states.observation_sha256,history_row.sha256) && states.logged_group_count==74 && ...
        states.logged_coordinate_count==1414 && states.all_logged_groups_have_ten_cycle_comparisons && ...
        states.all_three_PI_memories_observed, 'Scientific evidence does not qualify a complete warmup endpoint.');
    assert(strcmp(capture.operating_point_sha256,op_row.sha256) && ...
        strcmp(capture.history_sha256,history_row.sha256) && ...
        capture.snapshot_time_s==receipt.snapshot_time_s && ~capture.production_recovery_allowed && ...
        ~capture.source_op_edited && ~capture.state_reconstruction_used, 'Capture and endpoint disagree.');
    saved=load(op_row.path,'diagnostic_operating_point','production_recovery_allowed');
    op=saved.diagnostic_operating_point;
    assert(~saved.production_recovery_allowed && abs(op.snapshotTime-receipt.snapshot_time_s)<=1e-9 && ...
        (isa(op,'Simulink.op.ModelOperatingPoint') || isa(op,'Simulink.SimulationOperatingPoint')), ...
        'Require intact complete vendor state at the latest physical endpoint.');
    contract=struct('schema','heatdrive_ecc_latest_qualified_diagnostic_resume_v2', ...
        'source_root',source,'verification_root',verified,'snapshot_time_s',receipt.snapshot_time_s, ...
        'operating_point_sha256',op_row.sha256,'history_sha256',history_row.sha256, ...
        'qualification_sha256',file_hash(path),'ancestor_complete_cycle_restore_verified',true, ...
        'ancestor_complete_cycle_proof',receipt.ancestor_complete_cycle_proof, ...
        'latest_endpoint_complete_cycle_reference_compared',false, ...
        'source_physical_gates_evaluated',true,'source_state_edited',false, ...
        'partial_state_restore_used',false,'failed_state_propagated',false, ...
        'production_recovery_allowed',false,'diagnostic_trial_only',true);
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');
    assert(fid>=0,'Missing qualified endpoint evidence.');cleanup=onCleanup(@() fclose(fid));
    while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

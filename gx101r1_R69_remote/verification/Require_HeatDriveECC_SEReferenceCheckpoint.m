function contract = Require_HeatDriveECC_SEReferenceCheckpoint(source_root, audit_path)
% Bind the coherent C2 checkpoint to its physical evidence, not a warmup authority.
    source_root=char(java.io.File(source_root).getCanonicalPath());
    audit_path=char(java.io.File(audit_path).getCanonicalPath());
    audit=jsondecode(fileread(audit_path));
    assert(strcmp(audit.schema,'heatdrive_ecc_se_reference_state_qualification_audit_v1') && ...
        audit.OP20_is_intact_diagnostic_checkpoint && ~audit.production_recovery_allowed && ...
        ~audit.outer_solve_eligible && ~audit.diagnostic_warmup_continuation_allowed && ...
        numel(audit.cases)==2,'Require the bounded paired C2 audit.');
    manifest_path=fullfile(audit.source_root,'state_qualification_execution.json');
    manifest=jsondecode(fileread(manifest_path));
    assert(strcmp(file_hash(manifest_path),audit.manifest_sha256) && ...
        strcmp(manifest.status,'collected_requires_physical_and_complete_cycle_restore_audit') && ...
        ~manifest.existing_OP_imported && strcmp(manifest.cases(2).name,'coherent') && ...
        strcmp(char(java.io.File(manifest.case_roots{2}).getCanonicalPath()),source_root), ...
        'The paired manifest does not bind this coherent source.');
    evidence=audit.cases(2);arm=fullfile(source_root,'native');
    files={'diagnostic_complete_operating_point.mat','diagnostic_state_observation.mat', ...
        'observations.mat','state_restore_preflight.json','cold_mechanism_audit.json'};
    hashes={evidence.OP_sha256,evidence.history_sha256,evidence.source_observation_sha256, ...
        evidence.state_restore_sha256,evidence.mechanism_audit_sha256};
    for k=1:numel(files)
        assert(strcmp(file_hash(fullfile(arm,files{k})),hashes{k}), ...
            'Changed coherent checkpoint evidence: %s',files{k});
    end
    execution_path=fullfile(source_root,'cold_chamber_execution.json');
    execution=jsondecode(fileread(execution_path));
    assert(strcmp(file_hash(execution_path),manifest.cases(2).execution_sha256) && ...
        execution.requested_arm_collection_pass && execution.state_restore_preflight_pass && ...
        execution.checkpoint_saved && isempty(execution.error_message) && ...
        execution.start_time_s==0 && execution.stop_time_s==20 && execution.cycle_count==2 && ...
        ~execution.c200_state_imported && ~execution.production_recovery_allowed, ...
        'Require the complete coherent C2 execution.');
    mechanism=jsondecode(fileread(fullfile(arm,'cold_mechanism_audit.json')));
    restore=jsondecode(fileread(fullfile(arm,'state_restore_preflight.json')));
    assert(evidence.physical_input_hashes_verified && evidence.full_mechanism_pass && ...
        evidence.mechanism_subset_pass && evidence.mechanism_checks_passed==73 && ...
        evidence.modeled_energy_balance.model_equation_energy_closure_pass && ...
        mechanism.mechanism_pass && numel(fieldnames(mechanism.checks))==73 && ...
        all(structfun(@logical,mechanism.checks)) && ...
        strcmp(file_hash(fullfile(arm,'cold_mechanism_observation.mat')),mechanism.observation_sha256) && ...
        restore.same_model_restore_preflight_pass && strcmp(restore.checksum_policy,'error/error') && ...
        ~restore.source_state_edited && ~restore.partial_state_restore_used && ...
        ~isfile(fullfile(source_root,'INCOMPLETE_DO_NOT_RESUME.json')) && ...
        ~isfile(fullfile(source_root,'REJECTED_DO_NOT_RESUME.json')), ...
        'A failed or unqualified C2 source cannot enter rebuilt verification.');
    contract=struct('schema','heatdrive_ecc_coherent_c2_rebuilt_input_v1', ...
        'source_root',source_root,'audit_sha256',file_hash(audit_path), ...
        'operating_point_sha256',evidence.OP_sha256,'history_sha256',evidence.history_sha256, ...
        'snapshot_time_s',20,'complete_cycle_restore_verified',false, ...
        'production_recovery_allowed',false,'outer_solve_eligible',false);
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

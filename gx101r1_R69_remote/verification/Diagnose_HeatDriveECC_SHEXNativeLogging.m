function diagnostic = Diagnose_HeatDriveECC_SHEXNativeLogging( ...
        checkpoint_path, result_path, duration_s, output_json)
% Inspect raw SHEX Simscape branch logs over a short OP continuation.

    arguments
        checkpoint_path (1, :) char
        result_path (1, :) char
        duration_s (1, 1) double {mustBePositive} = 0.02
        output_json (1, :) char = ''
    end
    assert(isfile(checkpoint_path) && isfile(result_path), ...
        'HeatDriveECC:MissingSHEXDiagnosticInput', ...
        'Checkpoint and result are both required.');
    checkpoint = load(checkpoint_path, 'operating_point', 'checkpoint_meta');
    prior = load(result_path, 'options');
    assert(isfield(checkpoint, 'operating_point') && ...
        isfield(checkpoint, 'checkpoint_meta') && isfield(prior, 'options'), ...
        'HeatDriveECC:InvalidSHEXDiagnosticInput', ...
        'Checkpoint or result is missing its required contract.');

    snapshot_s = double(checkpoint.checkpoint_meta.time_s);
    options_override = prior.options;
    options_override.cycle_count = ceil((snapshot_s + duration_s) / ...
        options_override.schedule.tau_cycle_s);
    options_override.output.generate_figures = false;
    options_override.simulation.stop_time_s = snapshot_s + duration_s;
    options_override.simulation.save_final_operating_point = false;
    options_override.simulation.resume_checkpoint_path = '';
    options_override.simulation.prior_result_path = '';

    [model_name, options] = ...
        Build_HeatDriveECC_EighthRound_Simulink_Model(options_override);
    cleanup = onCleanup(@() close_runtime_model(model_name));
    assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
    sim_in = Simulink.SimulationInput(model_name);
    sim_in = sim_in.setModelParameter( ...
        'StartTime', '0', ...
        'StopTime', num2str(snapshot_s + duration_s, '%.15g'), ...
        'Solver', options.simulation.solver, ...
        'SimulationMode', 'normal', ...
        'ReturnWorkspaceOutputs', 'on', ...
        'CaptureErrors', 'on', ...
        'OperatingPointContentsChecksumMismatchMsg', 'warning', ...
        'SimscapeLogLimitData', 'on', ...
        'SimscapeLogDataHistory', ...
            required_simscape_history_steps(options), ...
        'SaveFinalState', 'off', ...
        'SaveOperatingPoint', 'off');
    sim_in = sim_in.setModelParameter( ...
        'FixedStep', num2str(options.simulation.fixed_step_s, '%.15g'));
    sim_in = sim_in.setVariable('EIGHTH_ROUND_OPTIONS', options);
    sim_in = sim_in.setInitialState(checkpoint.operating_point);
    sim_out = sim(sim_in);
    if isprop(sim_out, 'ErrorMessage') && ~isempty(sim_out.ErrorMessage)
        error('HeatDriveECC:SHEXDiagnosticSimulationFailed', ...
            '%s', sim_out.ErrorMessage);
    end

    diagnostic = struct();
    diagnostic.schema = 'heatdrive_ecc_shex_native_logging_diagnostic_v1';
    diagnostic.checkpoint_path = checkpoint_path;
    diagnostic.result_path = result_path;
    diagnostic.snapshot_time_s = snapshot_s;
    diagnostic.stop_time_s = snapshot_s + duration_s;
    diagnostic.requested_duration_s = duration_s;
    diagnostic.workspace_source = workspace_signal_statistics( ...
        sim_out.get('shex_source_heat_flow_W'));

    simlog = sim_out.get('simlog');
    assert(isa(simlog, 'simscape.logging.Node'), ...
        'HeatDriveECC:MissingSHEXDiagnosticSimlog', ...
        'Simscape logging root was not returned.');
    blocks = { ...
        'SHEX/SHEXSourceToSinkHeatFlowSensor', ...
        'SHEX/HotSinkAmbientLink', ...
        'SHEX/HotSinkMass', ...
        'SHEX/HotSinkFluidLink'};
    names = { ...
        'source_sensor_native', ...
        'source_conductor', ...
        'sink_mass', ...
        'sink_to_fluid'};
    for idx = 1:numel(blocks)
        diagnostic.(names{idx}) = node_statistics( ...
            simlog, [model_name '/' blocks{idx}], 'Q', 'W');
    end
    diagnostic.temperature = workspace_signal_statistics( ...
        sim_out.get('SHEX_hot_sink_temp_out'));

    series_names = {'workspace_source','source_sensor_native', ...
        'source_conductor','sink_mass','sink_to_fluid'};
    common_start_s = max(cellfun(@(name) ...
        diagnostic.(name).time_start_s, series_names));
    common_end_s = min(cellfun(@(name) ...
        diagnostic.(name).time_end_s, series_names));
    assert(common_end_s > common_start_s, ...
        'HeatDriveECC:NoCommonSHEXDiagnosticWindow', ...
        'SHEX native diagnostic series have no common time window.');
    common_t = diagnostic.workspace_source.time_s;
    common_t = common_t(common_t >= common_start_s & ...
        common_t <= common_end_s);
    source = interp1(diagnostic.workspace_source.time_s, ...
        diagnostic.workspace_source.value, common_t, 'linear');
    source_native = interpolate_node(diagnostic.source_sensor_native, common_t);
    conductor = interpolate_node(diagnostic.source_conductor, common_t);
    mass = interpolate_node(diagnostic.sink_mass, common_t);
    fluid = interpolate_node(diagnostic.sink_to_fluid, common_t);
    diagnostic.common_grid_sample_count = numel(common_t);
    diagnostic.common_time_start_s = common_start_s;
    diagnostic.common_time_end_s = common_end_s;
    diagnostic.common_duration_s = common_end_s - common_start_s;
    diagnostic.workspace_source_minus_native_rms_W = ...
        sqrt(mean((source - source_native) .^ 2));
    diagnostic.node_kcl_conductor_plus_mass_plus_fluid_rms_W = ...
        sqrt(mean((conductor + mass + fluid) .^ 2));
    diagnostic.node_kcl_conductor_plus_mass_plus_fluid_mean_W = ...
        mean(conductor + mass + fluid);

    if ~isempty(output_json)
        parent = fileparts(output_json);
        if ~isempty(parent) && ~isfolder(parent)
            mkdir(parent);
        end
        text = jsonencode(strip_series(diagnostic), PrettyPrint = true);
        fid = fopen(output_json, 'w');
        assert(fid >= 0, 'HeatDriveECC:SHEXDiagnosticWriteFailed', ...
            'Cannot create diagnostic JSON: %s', output_json);
        file_cleanup = onCleanup(@() fclose(fid));
        fprintf(fid, '%s\n', text);
        clear file_cleanup
    end
    fprintf(['SHEX_NATIVE_DIAGNOSTIC source_workspace=%.12g ', ...
        'source_native=%.12g conductor=%.12g mass=%.12g fluid=%.12g ', ...
        'kcl_rms=%.12g\n'], ...
        diagnostic.workspace_source.time_weighted_mean, ...
        diagnostic.source_sensor_native.time_weighted_mean, ...
        diagnostic.source_conductor.time_weighted_mean, ...
        diagnostic.sink_mass.time_weighted_mean, ...
        diagnostic.sink_to_fluid.time_weighted_mean, ...
        diagnostic.node_kcl_conductor_plus_mass_plus_fluid_rms_W);
    clear cleanup
end

function statistics = workspace_signal_statistics(raw)
    assert(isstruct(raw) && isfield(raw, 'time') && ...
        isfield(raw, 'signals'), ...
        'HeatDriveECC:UnsupportedSHEXWorkspaceSignal', ...
        'Expected a Structure With Time workspace signal.');
    statistics = series_statistics(double(raw.time(:)), ...
        double(raw.signals.values(:)));
end

function statistics = node_statistics(simlog, block_path, variable, unit)
    block_node = simscape.logging.findNode(simlog, block_path);
    assert(~isempty(block_node) && block_node.hasChild(variable), ...
        'HeatDriveECC:MissingSHEXDiagnosticNode', ...
        'Missing Simscape node: %s/%s.', block_path, variable);
    series = block_node.child(variable).series;
    statistics = series_statistics(double(time(series)), ...
        double(values(series, Units = unit)));
end

function statistics = series_statistics(time_s, value)
    time_s = time_s(:);
    value = squeeze(value);
    assert(isvector(value), 'HeatDriveECC:NonScalarSHEXDiagnosticNode', ...
        'SHEX diagnostic expects a scalar logged variable.');
    value = value(:);
    [time_s, unique_idx] = unique(time_s, 'last');
    value = value(unique_idx);
    assert(numel(time_s) >= 2 && all(isfinite(time_s)) && ...
        all(isfinite(value)) && all(diff(time_s) > 0.0), ...
        'HeatDriveECC:InvalidSHEXDiagnosticSeries', ...
        'SHEX diagnostic series must be finite and strictly increasing.');
    duration_s = time_s(end) - time_s(1);
    statistics = struct( ...
        'time_start_s', time_s(1), ...
        'time_end_s', time_s(end), ...
        'sample_count', numel(time_s), ...
        'minimum', min(value), ...
        'maximum', max(value), ...
        'sample_mean', mean(value), ...
        'time_integral', trapz(time_s, value), ...
        'time_weighted_mean', trapz(time_s, value) / duration_s, ...
        'time_s', time_s, ...
        'value', value);
end

function value = interpolate_node(statistics, query_time_s)
    value = interp1(statistics.time_s, statistics.value, ...
        query_time_s, 'linear');
end

function steps = required_simscape_history_steps(options)
    cycle_steps = ceil(options.schedule.tau_cycle_s / ...
        options.simulation.fixed_step_s);
    steps = max(2, cycle_steps + 2);
end

function value = strip_series(value)
    names = {'workspace_source','source_sensor_native','source_conductor', ...
        'sink_mass','sink_to_fluid','temperature'};
    for idx = 1:numel(names)
        value.(names{idx}) = rmfield(value.(names{idx}), {'time_s','value'});
    end
end

function close_runtime_model(model_name)
    if bdIsLoaded(model_name)
        set_param(model_name, 'Dirty', 'off');
        close_system(model_name, 0);
    end
end

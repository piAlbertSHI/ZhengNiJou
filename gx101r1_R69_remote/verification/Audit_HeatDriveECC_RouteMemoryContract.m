function record = Audit_HeatDriveECC_RouteMemoryContract(model)
% Check directed port-specific gates; integral update and output are distinct.
    rows = cell(2, 1);
    for k = 1:2
        stage = 2*k;
        prefix = sprintf('SEStage%dPressureI', stage);
        input_enable = [model '/' prefix 'EnableFromWorkspace'];
        output_enable = [model '/' prefix 'OutputEnableFromWorkspace'];
        input_gate = [model '/' prefix 'InputGate'];
        output_gate = [model '/' prefix 'OutputGate'];
        integrator = sprintf('%s/SEStage%dPressurePI_Integrator', model, stage);
        expected_input = sprintf('SE_stage%d_pressure_integrator_enable_command', stage);
        expected_output = sprintf('SE_stage%d_pressure_integrator_output_enable_command', stage);
        rows{k} = struct('stage', stage, ...
            'input_enable_variable_ok', strcmp(get_param(input_enable, 'VariableName'), expected_input), ...
            'output_enable_variable_ok', strcmp(get_param(output_enable, 'VariableName'), expected_output), ...
            'input_gate_source_ok', directed(input_enable, 1, input_gate, 2), ...
            'output_gate_source_ok', directed(output_enable, 1, output_gate, 2), ...
            'input_to_integrator_ok', directed(input_gate, 1, integrator, 1), ...
            'integrator_to_output_ok', directed(integrator, 1, output_gate, 1), ...
            'reset_disabled', strcmp(get_param(integrator, 'ExternalReset'), 'none'), ...
            'legacy_same_enable_to_output', directed(input_enable, 1, output_gate, 2));
        fields = {'input_enable_variable_ok','output_enable_variable_ok', ...
            'input_gate_source_ok','output_gate_source_ok','input_to_integrator_ok', ...
            'integrator_to_output_ok','reset_disabled'};
        rows{k}.pass = all(cellfun(@(name) rows{k}.(name), fields));
    end
    record = struct('schema', 'heatdrive_ecc_route_memory_contract_v1', ...
        'routes', {rows}, 'pass', all(cellfun(@(row) row.pass, rows)), ...
        'simulation_executed', false, 'model_modified', false, ...
        'production_recovery_allowed', false);
end

function pass = directed(source, source_port, destination, destination_port)
    a = get_param(source, 'PortHandles'); b = get_param(destination, 'PortHandles');
    line = get_param(b.Inport(destination_port), 'Line');
    pass = line ~= -1 && get_param(line, 'SrcPortHandle') == a.Outport(source_port);
end

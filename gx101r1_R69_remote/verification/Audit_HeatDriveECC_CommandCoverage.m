function audit = Audit_HeatDriveECC_CommandCoverage(model, options, required_end_s)
% Inspect actual From Workspace inputs, not the inherited model StopTime field.
    paths = find_system(model, 'LookUnderMasks', 'all', 'FollowLinks', 'on', ...
        'Type', 'Block', 'BlockType', 'FromWorkspace');
    assert(~isempty(paths), 'HeatDriveECC:MissingCommandInputs', 'No time-based commands found.');
    rows = cell(size(paths));
    for k = 1:numel(paths)
        expression = get_param(paths{k}, 'VariableName');
        value = slResolve(expression, paths{k});
        assert(isa(value, 'timeseries'), 'HeatDriveECC:UnknownCommandRepresentation', ...
            'Expected the established timeseries command at %s.', paths{k});
        t = double(value.Time(:));
        assert(numel(t) >= 2 && all(isfinite(t)) && all(diff(t) > 0) && ...
            t(1) <= 0 && t(end) >= required_end_s && all(isfinite(value.Data), 'all'), ...
            'HeatDriveECC:CommandCoverageFailed', 'Command input does not cover the experiment: %s.', paths{k});
        rows{k} = struct('block_path', paths{k}, 'expression', expression, ...
            'start_s', t(1), 'stop_s', t(end), 'sample_count', numel(t));
    end
    audit = struct('schema', 'heatdrive_ecc_command_coverage_v1', 'command_count', numel(paths), ...
        'required_end_s', required_end_s, 'configured_schedule_end_s', options.schedule.total_time_s, ...
        'nominal_model_stop_time_s', options.simulation.stop_time_s, ...
        'minimum_command_end_s', min(cellfun(@(r) r.stop_s, rows)), ...
        'commands', {rows}, 'coverage_pass', true, 'model_modified_by_audit', false);
end

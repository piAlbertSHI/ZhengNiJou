function contract = Configure_HeatDriveECC_PressureOnlyInventoryMap(chamber, options, reference_T)
% Invert the exact 30-pressure-point density slice, keeping M as the state.
    domain=options.validation.dual_fluid_domain_audit;
    assert(domain.ok && strcmp(get_param(chamber,'SourceFile'), ...
        'ecc_inventory_pressure_only.conservative_chamber'));
    settings=domain.sma_settings_path;
    assert(strcmp(get_param(settings,'table_dimensions'),'1') && ...
        strcmp(get_param(settings,'rho_parameterization_1D'),'1'), ...
        'Require the already audited 1D density-vector fluid parameterization.');
    temperature=quantity(settings,'T_TLU','K');
    density=quantity(settings,'rho_TLU_4','kg/m^3');
    minimum=quantity(settings,'p_min_1D','Pa');maximum=quantity(settings,'p_max_1D','Pa');
    reference_p=quantity(settings,'p_ref_4','Pa');bulk=quantity(settings,'beta_const_4','Pa');
    assert(reference_T>=min(temperature) && reference_T<=max(temperature) && bulk>0);
    pressure=10.^((0:29).'/29*(log10(maximum)-log10(minimum))+log10(minimum));
    rho=interp1(temperature,density,reference_T,'linear')*exp((pressure-reference_p)/bulk);
    assert(numel(rho)==30 && all(diff(rho)>0) && all(diff(pressure)>0));
    set_param(chamber,'inventory_reference_temperature',num2str(reference_T,'%.17g'), ...
        'inventory_reference_temperature_unit','K', ...
        'inventory_pressure_grid',mat2str(pressure,17),'inventory_pressure_grid_unit','Pa', ...
        'inventory_density_grid',mat2str(rho,17),'inventory_density_grid_unit','kg/m^3');
    contract=struct('schema','heatdrive_ecc_pressure_only_inverse_density_map_v1', ...
        'block_path',chamber,'settings_path',settings,'reference_temperature_K',reference_T, ...
        'pressure_grid_Pa',pressure,'density_grid_kg_m3',rho,'forward_EOS_changed',false, ...
        'interpolation','piecewise linear forward table inverted segment by segment', ...
        'mass_and_energy_equations_changed',false,'production_recovery_allowed',false);
end

function q=quantity(block,name,unit)
    q=value(simscape.Value(slResolve(get_param(block,name),block),get_param(block,[name '_unit'])),unit);
    q=double(q(:));assert(all(isfinite(q)));
end

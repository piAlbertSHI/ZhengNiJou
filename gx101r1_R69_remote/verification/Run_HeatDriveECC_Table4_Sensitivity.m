function [count, bytes] = compact_candidate_raw(candidate_root, output_root)
    root = canonical_path(output_root);
    candidate = canonical_path(candidate_root);
    assert(startsWith(candidate, [root, filesep], 'IgnoreCase', true), ...
        'HeatDriveECC:SensitivityCompactionEscapedOutputRoot', ...
        'Candidate root escaped the declared sensitivity output root.');
    names = {'physical_simscape_result.mat', ...
        'final_operating_point.mat', 'stage_temperature_probes_50samples.csv'};
    count = 0;
    bytes = 0;
    removed = strings(0, 1);
    for idx = 1:numel(names)
        matches = dir(fullfile(candidate, '**', names{idx}));
        for file_idx = 1:numel(matches)
            path = canonical_path(fullfile(matches(file_idx).folder, ...
                matches(file_idx).name));
            assert(startsWith(path, [candidate, filesep], ...
                'IgnoreCase', true), ...
                'HeatDriveECC:SensitivityCompactionEscapedCandidate', ...
                'Compaction target escaped the candidate root.');
            bytes = bytes + matches(file_idx).bytes;
            delete(path);
            count = count + 1;
            removed(end + 1, 1) = string(path); %#ok<AGROW>
        end
    end
    marker = fullfile(candidate, 'COMPACTED_AFTER_SCALAR_EXTRACTION.txt');
    fid = fopen(marker, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:SensitivityCompactionMarkerFailed', ...
        'Cannot write %s.', marker);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, 'schema=heatdrive_ecc_sensitivity_compaction_v1\n');
    fprintf(fid, 'compacted_at=%s\n', char(datetime('now', ...
        'TimeZone', 'local')));
    fprintf(fid, 'deleted_file_count=%d\n', count);
    fprintf(fid, 'deleted_bytes=%.0f\n', bytes);
    fprintf(fid, 'resume_allowed=0\n');
    fprintf(fid, ['retained=validation report, cycle summary, parameter ', ...
        'contract, continuation progress/state, scalar record, markers\n']);
    for idx = 1:numel(removed)
        fprintf(fid, 'deleted=%s\n', removed(idx));
    end
    clear cleaner
end

function path = canonical_path(path)

function [command, evidence] = Build_HeatDriveECC_DistributedPressureEnvelope(options, bias, valves)
% Preserve the existing pressure ramp, not the sparsely interpolated PI target.
    if nargin<2
        bias = evalin('base', 'SE_pressure_bias_command');
        valves = evalin('base', 'L_valve_command');
    end
    assert(isa(bias,'timeseries') && isa(valves,'timeseries') && ...
        isequal(bias.Time,valves.Time), ...
        'HeatDriveECC:DistributedFFSchedule','Pressure/valve clocks differ.');
    switch_pressure = options.branch.valve_switch_pressure_MPa;
    assert(switch_pressure < 0 && ...
        options.branch.se_inactive_pressure_bias_MPa == switch_pressure && ...
        options.branch.se_stage4_commutation_precharge_fraction == 0, ...
        'HeatDriveECC:DistributedFFSwitch','Unsupported inactive/precharge contract.');
    p = double(bias.Data(:)); v = double(valves.Data);
    assert(size(v,1)==numel(p) && size(v,2)==6 && ...
        all(isfinite(p)) && all(isfinite(v),'all'),'Invalid valve schedule.');
    route2 = any(v(:,1:3)>0,2); route4 = any(v(:,4:6)>0,2);
    assert(~any(route2 & route4),'Simultaneously open SE routes.');
    alpha = zeros(size(p));
    active_pressure = [options.branch.se_stage2_pressure_bias_MPa, ...
        options.branch.se_stage4_pressure_bias_MPa];
    assert(all(active_pressure < switch_pressure),'Invalid active pressure normalization.');
    for stage = 1:2
        route = route2; if stage==2, route=route4; end
        alpha(route) = (p(route)-switch_pressure) / ...
            (active_pressure(stage)-switch_pressure);
    end
    tolerance = 1e-12;
    assert(all(abs(p(~(route2|route4))-switch_pressure)<=tolerance) && ...
        all(alpha>=-tolerance & alpha<=1+tolerance), ...
        'HeatDriveECC:DistributedFFEnvelope','Pressure envelope is not normalized.');
    % Only roundoff is bounded; an incompatible schedule fails above.
    alpha = min(max(alpha,0),1);
    command = timeseries(alpha,bias.Time);
    evidence = struct('time_s',double(bias.Time(:)), ...
        'pressure_fraction',alpha,'original_pressure_MPa',p, ...
        'normalization_only_active_pressure_MPa',active_pressure, ...
        'switch_pressure_MPa',switch_pressure, ...
        'interpolation','linear, same knots as original pressure command', ...
        'PI_flow_target_modified',false,'active_pressure_is_bed_resistance_authority',false);
end

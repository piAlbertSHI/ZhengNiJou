function record = Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(config_path)
% Execute an independent cold diagnostic from a JSON contract.
% JSON avoids PowerShell-to-MATLAB boolean and quoting conversions.
    config = jsondecode(fileread(config_path));
    assert(isfield(config,'distributed_pressure_feedforward_diagnostic') && ...
        islogical(config.distributed_pressure_feedforward_diagnostic) && ...
        isscalar(config.distributed_pressure_feedforward_diagnostic), ...
        'HeatDriveECC:MissingControllerConfig', ...
        'Require an explicit logical distributed-controller mode before model construction.');
    overrides = Build_HeatDriveECC_IndependentColdBranchOverrides(config);
    constitutive_options = struct();
    if isfield(config, 'diagnostic_constitutive_step_function')
        constitutive_options.diagnostic_step_function = ...
            char(config.diagnostic_constitutive_step_function);
    end
    if isfield(config, 'diagnostic_constitutive_substeps')
        constitutive_options.diagnostic_substeps = ...
            double(config.diagnostic_constitutive_substeps);
    end
    diagnostic_arm='both';
    if isfield(config,'diagnostic_arm'), diagnostic_arm=char(config.diagnostic_arm); end
    state_options=struct();
    if isfield(config,'diagnostic_state_options'),state_options=config.diagnostic_state_options;end
    inventory_options=struct();
    if isfield(config,'diagnostic_inventory_options'),inventory_options=config.diagnostic_inventory_options;end
    reference_options=struct();
    if isfield(config,'diagnostic_se_reference_options'),reference_options=config.diagnostic_se_reference_options;end

    record = Run_HeatDriveECC_ColdChamberDiagnostic( ...
        char(config.repo_root), char(config.output_root), config.duration_s, ...
        logical(config.scale_inventory), logical(config.buffer_mass_guess), ...
        logical(config.buffer_mass_targets), logical(config.pipe_energy_targets), ...
        logical(config.conservative_buffers), char(config.formulation), ...
        config.network_absolute_pressure_MPa, overrides, false, ...
        logical(config.initial_flux_compensation), char(config.buffer_mass_formulation), ...
        config.cycle_count, char(config.initial_observation_root), ...
        char(config.simulation_mode), logical(config.endpoint_chamber_diagnostic), ...
        logical(config.endpoint_all_arms), diagnostic_arm, state_options, constitutive_options, inventory_options, reference_options);
    record.runtime_evidence_only = ~logical(config.initial_flux_compensation);
    record.seed_authority_granted = false;
    save(fullfile(char(config.output_root), 'runtime_evidence_contract.mat'), ...
        'record', '-v7.3');
end

function audit = Audit_HeatDriveECC_SystemEnergyResult(result_path, output_json)
% Audit final-cycle exchanger KCL and the modeled thermal-system ledger.

    arguments
        result_path (1, :) char
        output_json (1, :) char = ''
    end
    assert(isfile(result_path), 'HeatDriveECC:MissingSystemEnergyResult', ...
        'Result file does not exist: %s.', result_path);
    data = load(result_path, 'physical', 'summary', 'options');
    assert(all(isfield(data, {'physical','summary','options'})), ...
        'HeatDriveECC:InvalidSystemEnergyResult', ...
        'Result must contain physical, summary, and options.');

    p = data.physical;
    s = data.summary;
    o = data.options;
    required = { ...
        'Q_SHEX_source_to_sink_W','Q_SHEX_source_conductor_W', ...
        'Q_SHEX_sink_mass_W','Q_SHEX_sink_to_fluid_W', ...
        'Q_HHEX_sink_to_ambient_W','Q_HHEX_sink_to_SE_fluid_W', ...
        'Q_HHEX_sink_to_SMA_fluid_W','Q_HHEX_sink_mass_W', ...
        'Q_CHEX_sink_to_fluid_W','Q_CHEX_sink_mass_W', ...
        'Q_CHEX_load_to_sink_W','Q_CHEX_sensor_native_W', ...
        'Q_CHEX_fixed_source_W','U_pipe_inventory_J', ...
        'U_buffer_inventory_J','U_manifold_inventory_J', ...
        'U_fluid_inventory_J','M_pipe_inventory_kg', ...
        'M_buffer_inventory_kg','M_manifold_inventory_kg', ...
        'M_fluid_inventory_kg','P_pressure_source_native_W'};
    missing = required(~cellfun(@(name) isfield(p, name), required));
    assert(isempty(missing), 'HeatDriveECC:MissingSystemEnergySignals', ...
        'Result is missing system-energy signals: %s.', ...
        strjoin(missing, ', '));

    [idx, cycle_time_s, duration_s] = final_complete_cycle(p, o);
    assert(all(cellfun(@(name) all(isfinite(p.(name)(idx)), 'all'), ...
        required)), 'HeatDriveECC:NonfiniteSystemEnergyWindow', ...
        'All system-energy signals must be finite over the final cycle.');

    audit = struct();
    audit.schema = 'heatdrive_ecc_system_energy_result_audit_v1';
    audit.generated_at = char(datetime('now', 'TimeZone', 'local'));
    audit.result_path = result_path;
    audit.completed_cycles = o.cycle_count;
    audit.window_contract = 'final_complete_cycle_only';
    audit.window_start_s = cycle_time_s(1);
    audit.window_end_s = cycle_time_s(end);
    audit.window_duration_s = duration_s;
    audit.window_sample_count = nnz(idx);
    audit.periodic_steady_state = logical(s.performance.periodic_steady_state);
    audit.mechanism_pass = read_mechanism_pass(fileparts(result_path));

    shex_kcl_W = p.Q_SHEX_source_conductor_W(idx) + ...
        p.Q_SHEX_sink_mass_W(idx) + p.Q_SHEX_sink_to_fluid_W(idx);
    hhex_kcl_W = p.Q_HHEX_sink_to_ambient_W(idx) + ...
        p.Q_HHEX_sink_to_SE_fluid_W(idx) + ...
        p.Q_HHEX_sink_to_SMA_fluid_W(idx) + ...
        p.Q_HHEX_sink_mass_W(idx);
    chex_kcl_W = p.Q_CHEX_fixed_source_W(idx) + ...
        p.Q_CHEX_load_to_sink_W(idx) + p.Q_CHEX_sink_to_fluid_W(idx) + ...
        p.Q_CHEX_sink_mass_W(idx);

    audit.SHEX_node_kcl_rms_W = rms_value(shex_kcl_W);
    audit.HHEX_node_kcl_rms_W = rms_value(hhex_kcl_W);
    audit.CHEX_node_kcl_rms_W = rms_value(chex_kcl_W);
    audit.CHEX_workspace_native_rms_W = rms_value( ...
        p.Q_CHEX_reservoir_to_hx_W(idx) - p.Q_CHEX_sensor_native_W(idx));

    audit.SHEX_source_input_W = cycle_mean( ...
        cycle_time_s, p.Q_SHEX_source_to_sink_W(idx));
    audit.CHEX_cooling_input_W = cycle_mean( ...
        cycle_time_s, p.Q_CHEX_sink_to_fluid_W(idx));
    audit.CHEX_fixed_source_to_sink_W = -cycle_mean( ...
        cycle_time_s, p.Q_CHEX_fixed_source_W(idx));
    audit.CHEX_declared_load_to_sink_W = -cycle_mean( ...
        cycle_time_s, p.Q_CHEX_load_to_sink_W(idx));
    audit.HHEX_ambient_rejection_W = cycle_mean( ...
        cycle_time_s, p.Q_HHEX_sink_to_ambient_W(idx));
    audit.external_thermal_net_input_W = audit.SHEX_source_input_W + ...
        audit.CHEX_fixed_source_to_sink_W + ...
        audit.CHEX_declared_load_to_sink_W - ...
        audit.HHEX_ambient_rejection_W;

    audit.pipe_storage_rate_W = endpoint_rate( ...
        p.U_pipe_inventory_J(idx), duration_s);
    audit.buffer_storage_rate_W = endpoint_rate( ...
        p.U_buffer_inventory_J(idx), duration_s);
    audit.manifold_storage_rate_W = endpoint_rate( ...
        p.U_manifold_inventory_J(idx), duration_s);
    audit.fluid_storage_rate_W = endpoint_rate( ...
        p.U_fluid_inventory_J(idx), duration_s);

    audit.SHEX_mass_storage_rate_W = o.system.shex_sink_C_J_per_K * ...
        endpoint_rate(p.SHEX_T_K(idx), duration_s);
    audit.HHEX_mass_storage_rate_W = o.system.hot_sink_C_J_per_K * ...
        endpoint_rate(p.HHEX_T_K(idx), duration_s);
    audit.CHEX_mass_storage_rate_W = o.system.cold_sink_C_J_per_K * ...
        endpoint_rate(p.CHEX_T_K(idx), duration_s);

    audit.SMA_sensible_storage_rate_W = o.equilibrium.m_a_kg * ...
        o.material.SMA.cp_J_per_kgK * endpoint_rate( ...
        mean(p.SMA_T_21_K(idx, :), 2), duration_s);
    audit.SE_sensible_storage_rate_W = o.equilibrium.m_r_kg * ...
        o.material.SE.cp_J_per_kgK * endpoint_rate( ...
        mean(p.SE_T_21_K(idx, :), 2), duration_s);
    audit.SMA_latent_storage_rate_W = o.equilibrium.m_a_kg * ...
        o.material.SMA.Delta_h_J_per_kg * endpoint_rate( ...
        mean(p.xM_SMA_21(idx, :), 2), duration_s);
    audit.SE_latent_storage_rate_W = o.equilibrium.m_r_kg * ...
        o.material.SE.Delta_h_J_per_kg * endpoint_rate( ...
        mean(p.xM_SE_21(idx, :), 2), duration_s);
    audit.solid_storage_rate_W = audit.SMA_sensible_storage_rate_W + ...
        audit.SE_sensible_storage_rate_W + ...
        audit.SMA_latent_storage_rate_W + ...
        audit.SE_latent_storage_rate_W;
    audit.endpoint_mass_storage_rate_W = ...
        audit.SHEX_mass_storage_rate_W + audit.HHEX_mass_storage_rate_W + ...
        audit.CHEX_mass_storage_rate_W;
    audit.total_modeled_storage_rate_W = audit.fluid_storage_rate_W + ...
        audit.solid_storage_rate_W + audit.endpoint_mass_storage_rate_W;
    audit.modeled_thermal_residual_W = audit.external_thermal_net_input_W - ...
        audit.total_modeled_storage_rate_W;
    audit.modeled_thermal_residual_relative = abs( ...
        audit.modeled_thermal_residual_W) / max([ ...
        abs(audit.SHEX_source_input_W), ...
        abs(audit.HHEX_ambient_rejection_W), 1.0]);

    final_cycle = s.cycle(end);
    audit.internal_mechanical_transfer_net_W = ...
        final_cycle.mechanical_source_net_J / duration_s;
    audit.internal_mechanical_transfer_balance_fraction = ...
        final_cycle.mechanical_source_balance_fraction;
    audit.parasitic_pump_power_SMA_W = ...
        final_cycle.pump_work_SMA_J / duration_s;
    audit.parasitic_pump_power_SE_W = ...
        final_cycle.pump_work_SE_J / duration_s;
    audit.parasitic_pump_power_total_W = ...
        audit.parasitic_pump_power_SMA_W + audit.parasitic_pump_power_SE_W;
    audit.native_pressure_source_power_W = cycle_mean( ...
        cycle_time_s, p.P_pressure_source_native_W(idx));
    audit.pump_thermal_coupling_contract = ...
        ['Pressure Source (TL) power_spec=none: parasitic pump work is ', ...
        'reported but is not injected into the modeled thermal balance.'];

    initial_mass_kg = p.M_fluid_inventory_kg(find(idx, 1, 'first'));
    final_mass_kg = p.M_fluid_inventory_kg(find(idx, 1, 'last'));
    audit.fluid_mass_start_kg = initial_mass_kg;
    audit.fluid_mass_end_kg = final_mass_kg;
    audit.fluid_mass_drift_kg = final_mass_kg - initial_mass_kg;
    audit.fluid_mass_drift_relative = abs(audit.fluid_mass_drift_kg) / ...
        max(abs(initial_mass_kg), eps);

    audit.local_kcl_limit_W = 1.0e-6;
    audit.thermal_residual_relative_limit = 1.0e-3;
    audit.fluid_mass_drift_relative_limit = 1.0e-8;
    audit.local_exchanger_kcl_pass = max([audit.SHEX_node_kcl_rms_W, ...
        audit.HHEX_node_kcl_rms_W, audit.CHEX_node_kcl_rms_W, ...
        audit.CHEX_workspace_native_rms_W]) <= audit.local_kcl_limit_W;
    audit.boundary_direction_pass = audit.SHEX_source_input_W > 0.0 && ...
        audit.CHEX_cooling_input_W > 0.0 && ...
        audit.CHEX_fixed_source_to_sink_W > 0.0 && ...
        audit.HHEX_ambient_rejection_W > 0.0;
    audit.fluid_mass_conservation_pass = ...
        audit.fluid_mass_drift_relative <= ...
        audit.fluid_mass_drift_relative_limit;
    audit.modeled_thermal_closure_pass = ...
        audit.modeled_thermal_residual_relative <= ...
        audit.thermal_residual_relative_limit;
    audit.production_pass = audit.mechanism_pass && ...
        audit.periodic_steady_state && audit.local_exchanger_kcl_pass && ...
        audit.boundary_direction_pass && audit.fluid_mass_conservation_pass && ...
        audit.modeled_thermal_closure_pass;
    audit.complete_device_first_law_closure = false;
    audit.complete_device_first_law_status = ...
        ['Modeled thermal control volume is audited separately. Full device ', ...
        'closure remains withheld until parasitic pump work/dissipation and ', ...
        'external accessory heat are assigned to measured boundaries.'];

    if isempty(output_json)
        output_json = fullfile(fileparts(result_path), ...
            'system_energy_audit.json');
    end
    parent = fileparts(output_json);
    if ~isempty(parent) && ~isfolder(parent)
        mkdir(parent);
    end
    fid = fopen(output_json, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:SystemEnergyAuditWriteFailed', ...
        'Cannot create audit JSON: %s.', output_json);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(audit, PrettyPrint = true));
    clear cleaner

    fprintf(['SYSTEM_ENERGY_RESULT_PASS=%d modeled_closure=%d ', ...
        'residual_W=%.12g relative=%.12g HHEX_KCL=%.12g ', ...
        'CHEX_KCL=%.12g mass_drift=%.12g\n'], ...
        audit.production_pass, audit.modeled_thermal_closure_pass, ...
        audit.modeled_thermal_residual_W, ...
        audit.modeled_thermal_residual_relative, ...
        audit.HHEX_node_kcl_rms_W, audit.CHEX_node_kcl_rms_W, ...
        audit.fluid_mass_drift_relative);
end

function [idx, local_time_s, duration_s] = final_complete_cycle(p, o)
    t = p.time_s(:);
    final_time_s = t(end);
    start_time_s = final_time_s - o.schedule.tau_cycle_s;
    tolerance_s = 10.0 * eps(max(abs(final_time_s), 1.0));
    idx = t >= start_time_s - tolerance_s & ...
        t <= final_time_s + tolerance_s;
    local_time_s = t(idx);
    assert(numel(local_time_s) >= 2, ...
        'HeatDriveECC:IncompleteSystemEnergyCycle', ...
        'Final system-energy cycle has fewer than two samples.');
    duration_s = local_time_s(end) - local_time_s(1);
    assert(duration_s >= o.schedule.tau_cycle_s - tolerance_s, ...
        'HeatDriveECC:IncompleteSystemEnergyCycle', ...
        'Final system-energy cycle covers %.12g of %.12g s.', ...
        duration_s, o.schedule.tau_cycle_s);
end

function value = cycle_mean(time_s, signal)
    value = trapz(time_s, signal) / (time_s(end) - time_s(1));
end

function value = endpoint_rate(signal, duration_s)
    value = (signal(end) - signal(1)) / duration_s;
end

function value = rms_value(signal)
    value = sqrt(mean(signal .^ 2));
end

function pass = read_mechanism_pass(result_dir)
    report_path = fullfile(result_dir, 'physical_validation_report.txt');
    assert(isfile(report_path), ...
        'HeatDriveECC:MissingSystemEnergyValidationReport', ...
        'Validation report is required beside the result.');
    text = fileread(report_path);
    token = regexp(text, ...
        'Physical Simscape validation passed:\s*([01])', 'tokens', 'once');
    assert(~isempty(token), ...
        'HeatDriveECC:UnreadableSystemEnergyValidationReport', ...
        'Cannot read mechanism status from %s.', report_path);
    pass = strcmp(token{1}, '1');
end

function record = Run_HeatDriveECC_RebuiltCyclePreflight(source_root, output_root)
% Rebuild a hash-bound cold model; compare one intact resumed cycle, not a production chain.
    assert(~isfolder(output_root) && ~isfile([output_root,'.rebuilt_config.json']), ...
        'Never overwrite a rebuilt-cycle experiment.');
    config=jsondecode(fileread([source_root,'.state_preflight_config.json']));
    prior=jsondecode(fileread(fullfile(source_root,'cold_chamber_execution.json')));
    assert(prior.state_restore_preflight_pass && ~prior.collection_pass && ...
        ~prior.production_recovery_allowed && ~prior.c200_state_imported && ...
        prior.cycle_count==2 && prior.stop_time_s==20 && ...
        isequal(prior.requested_arms,{'native'}) && ...
        strcmp(config.diagnostic_state_options.mode,'restore_preflight') && ...
        config.diagnostic_state_options.command_horizon_cycles==200, ...
        'Require the successful independent two-cycle state preflight.');
    repo=char(config.repo_root);workspace=fileparts(repo);
    [status,dirty]=system(sprintf('git -C "%s" status --porcelain',workspace));
    assert(status==0 && isempty(strtrim(dirty)),'Use the clean managed execution checkout.');
    assert(~isempty(regexp(prior.execution_commit,'^[0-9a-f]{40}$','once')), ...
        'Require exact producer identity.');
    physical={'Build_HeatDriveECC_EighthRound_Defaults.m','Build_HeatDriveECC_EighthRound_Simulink_Model.m', ...
        'Integrate_HeatDriveECC_Constitutive21_Interface.m','heatdrive_ecc_coupled_se21.slx', ...
        'verification/Configure_HeatDriveECC_DistributedPressureFeedforward.m', ...
        'verification/Build_HeatDriveECC_DistributedPressureEnvelope.m', ...
        'verification/Build_HeatDriveECC_IndependentColdBranchOverrides.m', ...
        'verification/Configure_HeatDriveECC_DiagnosticStateCapture.m', ...
        'Instrument_HeatDriveECC_PumpPressureProbes.m', ...
        'Instrument_HeatDriveECC_Stage4ControllerProbes.m', ...
        'Configure_HeatDriveECC_PressureCommandDomain.m','HeatDriveECC_PressureCommandInterval.m', ...
        'Audit_HeatDriveECC_PressureReferenceTopology.m', ...
        'verification/Run_HeatDriveECC_ColdChamberDiagnostic.m'};
    for k=1:numel(physical)
        [tracked,~]=system(sprintf('git -C "%s" ls-files --error-unmatch "gx101r1_R69_remote/%s"',workspace,physical{k}));
        assert(tracked==0,'Guarded implementation is not tracked: %s',physical{k});
    end
    if isfield(config,'pressure_command_reference_mode') && strcmp(config.pressure_command_reference_mode,'named_source_reference')
        mechanism=jsondecode(fileread(fullfile(source_root,'native','cold_mechanism_audit.json')));
        assert(mechanism.mechanism_pass && mechanism.directional_pressure_observation.pass);
    end
    paths=strjoin(cellfun(@(p) ['"gx101r1_R69_remote/',p,'"'],physical,'UniformOutput',false),' ');
    [status,~]=system(sprintf('git -C "%s" diff --quiet %s HEAD -- %s',workspace,prior.execution_commit,paths));
    assert(status==0,'Rebuilt experiment changed a physical, drive, probe, or state setting.');
    assert(strcmp(char(config.output_root),source_root),'Source config location changed.');
    config.output_root=output_root;
    config.diagnostic_state_options=struct('mode','rebuilt_cycle_preflight', ...
        'command_horizon_cycles',200,'restore_source_root',source_root);
    path=[output_root,'.rebuilt_config.json'];
    fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'Cannot save rebuilt config.');
    fprintf(fid,'%s\n',jsonencode(config,'PrettyPrint',true));fclose(fid);
    record=Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(path);
    assert(record.rebuilt_cycle_preflight_pass && ~record.collection_pass && ...
        ~record.production_recovery_allowed,'The state experiment must not grant physical authority.');
end

function result = Verify_HeatDriveECC_ManifoldInventoryDiagnostic()
    assert(isempty(fieldnames(Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct(),'diagnostic_resume',20,200,'native',true))));
    for factor=[1 0.1]
        result=Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',factor),'off',1,10,'native',true);
        assert(result.volume_factor==factor);
    end
    failures={ ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',0),'off',1,10,'native',true), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',NaN),'off',1,10,'native',true), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',0.2),'off',1,10,'native',true), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',1),'diagnostic_resume',1,10,'native',true), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',1),'off',20,200,'native',true), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',1),'off',1,10,'both',true), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',1),'off',1,10,'native',false), ...
        @() Resolve_HeatDriveECC_ManifoldInventoryDiagnostic(struct('volume_factor',1,'other',1),'off',1,10,'native',true)};
    for k=1:numel(failures)
        rejected=false;try, failures{k}();catch, rejected=true;end
        assert(rejected,'Invalid intervention was not rejected.');
    end
    result=struct('positive_cases',3,'negative_cases',numel(failures),'pass',true);
    fprintf('%s\n',jsonencode(result));
end

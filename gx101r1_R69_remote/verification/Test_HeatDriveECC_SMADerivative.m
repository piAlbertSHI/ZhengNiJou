function result=Test_HeatDriveECC_SMADerivative(repo,output_root)
% Executable kernel checks using coefficients from the rebuilt real model.
    assert(~isfolder(output_root),'Do not overwrite kernel evidence.');
    contract=fullfile(repo,'outputs_storage_audit','sma_derivative_contract_20260909_v3','sma_derivative_contract.json');
    r=jsondecode(fileread(contract));assert(r.collection_pass && ~r.simulation_run && ~r.production_recovery_allowed);
    assert(strcmp(r.producer_commit,'6d55b4e8bea82bb0024afa204c96592d38c8f2ec'),'Unexpected controller evidence producer.');
    lag=block(r,'SMAPressurePI_ErrorLag');kp=block(r,'SMAPressurePI_Kp');ki=block(r,'SMAPressurePI_Ki');
    integrator=block(r,'SMAPressurePI_Integrator');saturation=block(r,'SMAPressurePI_Saturation');
    assert(strcmp(lag.type,'TransferFcn') && lag.resolved.Numerator==1 && ...
        isequal(lag.resolved.Denominator(:),[.002;1]),'Existing lag differs.');
    p=[.002,kp.resolved.Gain,ki.resolved.Gain,integrator.resolved.LowerSaturationLimit, ...
        integrator.resolved.UpperSaturationLimit,saturation.resolved.LowerLimit,saturation.resolved.UpperLimit];
    assert(isequal(p,[.002,-.6,-10,-.14733718599999998,.1,-.35,.02]),'Actual controller coefficients changed.');
    % Columns: normalized error, lag, integral, enable, reset, bias, bias slope.
    u=[0,0,0,0,1,-1e-6,0; ...
        .01,.005,0,1,0,-.1,.4; ...
        .01,.005,0,0,1,-.1,.4; ...
        .01,.005,p(4),1,0,-.1,0; ...
        -.01,-.005,p(5),1,0,-.2,0; ...
        -.01,-.005,p(4),1,0,-.1,0; ...
        .01,.005,p(5),1,0,-.2,0; ...
        .01,.005,0,1,0,-1,0; ...
        -.01,-.005,0,1,0,1,0; ...
        .01,0,0,1,0,p(6),0; ...
        -.01,0,0,1,0,p(6),0; ...
        -.01,0,0,1,0,p(7),0; ...
        .01,0,0,1,0,p(7),0];
    expected=[0,-1.15,.4,-1.5,1.5,1.55,-1.55,0,0,0,3,0,-3];
    cases=cell(size(u,1),1);
    for k=1:size(u,1)
        v=num2cell(u(k,:));[d,value,dx,di]=Evaluate_HeatDriveECC_SMADerivative(v{:},p);
        assert(abs(d-expected(k))<1e-12,'Analytical derivative case failed.');
        cases{k}=struct('index',k,'inputs',u(k,:),'expected_dp_MPa_s',expected(k), ...
            'dp_MPa_s',d,'pressure_MPa',value,'dlag_per_s',dx,'dintegral_MPa_s',di);
    end
    % A smooth trajectory satisfies both original lag and integral ODEs.
    times=[.001,.01,.02];errors=zeros(size(times));h=1e-7;
    for k=1:numel(times)
        t=times(k);z=.005+.1*t;dz=.1;I=-10*(.005*t+.05*t*t);
        d=Evaluate_HeatDriveECC_SMADerivative(z+.002*dz,z,I,1,0,-.1+.4*t,.4,p);
        direct=@(s) -.6*(.005+.1*s)-10*(.005*s+.05*s*s)-.1+.4*s;
        fd=(direct(t+h)-direct(t-h))/(2*h);errors(k)=abs(d-fd);
    end
    assert(max(errors)<1e-8,'Independent smooth-trajectory finite difference failed.');
    [code,commit]=system('git rev-parse HEAD');assert(code==0);
    result=struct('schema','heatdrive_ecc_sma_derivative_kernel_test_v1','execution_commit',strtrim(commit), ...
        'kernel_test_pass',true,'actual_parameters',p,'cases',{cases}, ...
        'smooth_trajectory_max_derivative_error_MPa_s',max(errors), ...
        'coupled_model_tested',false,'jump_handling_verified',false,'production_recovery_allowed',false);
    mkdir(output_root);fid=fopen(fullfile(output_root,'kernel_tests.json'),'w','n','UTF-8');assert(fid>=0);c=onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(result,'PrettyPrint',true));
    fprintf('%s\n',jsonencode(struct('kernel_test_pass',true,'cases',numel(cases), ...
        'smooth_trajectory_max_derivative_error_MPa_s',max(errors),'coupled_model_tested',false)));
end

function b=block(r,name)
    idx=find(endsWith({r.blocks.path},['/' name]));assert(isscalar(idx),'Missing or duplicate controller block.');b=r.blocks(idx);
end

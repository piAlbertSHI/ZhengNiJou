function contract = Require_HeatDriveECC_StorageClosureColdSource(audit_path)
% Revalidate untouched C1 inputs before constructing the new C2 model.
    audit=jsondecode(fileread(audit_path));
    Evaluate_HeatDriveECC_StorageClosureColdQualification(audit);
    root=char(java.io.File(audit.source_root).getCanonicalPath());
    manifest_path=fullfile(root,'storage_closure_execution.json');
    manifest=jsondecode(fileread(manifest_path));
    assert(strcmp(file_hash(manifest_path),audit.manifest_sha256) && ...
        strcmp(manifest.status,'collected_requires_formulation_specific_physical_comparison') && ...
        ~manifest.existing_OP_imported && ~manifest.source_state_loaded, 'Changed C1 manifest.');
    candidate=char(java.io.File(manifest.candidate_root).getCanonicalPath());
    assert(strcmp(candidate,fullfile(root,'candidate')) && ...
        ~isfile(fullfile(candidate,'REJECTED_DO_NOT_RESUME.json')) && ...
        ~isfile(fullfile(candidate,'INCOMPLETE_DO_NOT_RESUME.json')), 'Never consume a failed C1 case.');
    files={'observations.mat','configuration.mat','inventory_metadata.json', ...
        'tl_connectivity.json','thermal_connectivity.json','public_inventory_targets.json'};
    names=cellfun(@matlab.lang.makeValidName,files,'UniformOutput',false);
    assert(isequal(sort(names(:)),sort(fieldnames(audit.cases(2).input_sha256))), ...
        'Require all six named C1 physical evidence files.');
    for k=1:numel(files)
        path=char(java.io.File(fullfile(candidate,'native',files{k})).getCanonicalPath());
        assert(startsWith(path,[candidate filesep], 'IgnoreCase',true) && ...
            strcmp(file_hash(path),audit.cases(2).input_sha256.(names{k})), 'Changed C1 physical evidence.');
    end
    component=fullfile(candidate,'component_build','+ecc_inventory_pressure_only','conservative_chamber.ssc');
    canonical=fullfile(fileparts(mfilename('fullpath')),'simscape_inventory_pressure_only', ...
        '+ecc_inventory_pressure_only','conservative_chamber.ssc');
    assert(strcmp(file_hash(component),audit.candidate_component_sha256) && ...
        strcmp(file_hash(component),file_hash(canonical)) && ...
        strcmp(file_hash(fullfile(candidate,'cold_chamber_execution.json')),manifest.candidate_execution_sha256) && ...
        strcmp(file_hash(fullfile(root,'candidate_config.json')),manifest.candidate_config_sha256), ...
        'A component, execution or config changed after C1 qualification.');
    contract=struct('schema','heatdrive_ecc_storage_closure_cold_c2_input_v1', ...
        'source_root',candidate,'candidate_config_path',fullfile(root,'candidate_config.json'), ...
        'source_audit_sha256',file_hash(audit_path),'component_sha256',audit.candidate_component_sha256, ...
        'new_cold_two_cycle_test_allowed',true,'state_import_allowed',false, ...
        'production_recovery_allowed',false,'outer_solve_eligible',false);
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

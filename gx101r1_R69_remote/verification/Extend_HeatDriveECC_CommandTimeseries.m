function [extended,record]=Extend_HeatDriveECC_CommandTimeseries(actual,generated,source_s,proof_stop_s)
% Keep actual past knots and their next interpolation knot; splice only future data.
    assert(isa(actual,'timeseries') && isa(generated,'timeseries') && actual.IsTimeFirst && generated.IsTimeFirst);
    a=double(actual.Time(:));b=double(generated.Time(:));x=actual.Data;y=generated.Data;
    assert(isa(x,'double') && isa(y,'double') && isreal(x) && isreal(y) && ismatrix(x) && ismatrix(y) && ...
        size(x,1)==numel(a) && size(y,1)==numel(b) && size(x,2)==size(y,2) && ...
        all(isfinite([a;b])) && all(diff(a)>0) && all(diff(b)>0) && ...
        all(isfinite(x),'all') && all(isfinite(y),'all') && a(1)==0 && b(1)==0 && b(end)>a(end));
    assert(strcmp(actual.TimeInfo.Units,generated.TimeInfo.Units) && ...
        isempty(actual.TimeInfo.StartDate) && isempty(generated.TimeInfo.StartDate) && ...
        strcmp(actual.DataInfo.Units,generated.DataInfo.Units) && ...
        strcmp(getinterpmethod(actual),getinterpmethod(generated)), 'Command metadata changed.');
    cut=a(end)-10;
    assert(source_s>=0 && proof_stop_s>source_s && proof_stop_s<cut, 'Future splice must follow the entire comparison window.');
    constant=all(x==x(1,:),'all') && all(y==x(1,:),'all');
    if constant
        t=[a;b(end)];v=[x;x(end,:)];first_possible_change=a(end);
    else
        clock_allowance=16*eps(max(1,abs(cut)));
        prefix=a<=cut+clock_allowance;tail=b>cut+clock_allowance;
        assert(any(prefix) && any(tail));
        t=[a(prefix);b(tail)];v=[x(prefix,:);y(tail,:)];
        first_possible_change=a(find(prefix,1,'last'));
    end
    assert(all(diff(t)>0) && t(end)==b(end) && first_possible_change>proof_stop_s);
    old_end=find(a>proof_stop_s,1,'first');new_end=find(t>proof_stop_s,1,'first');
    assert(~isempty(old_end) && old_end==new_end && isequal(a(1:old_end),t(1:new_end)) && ...
        isequal(typecast(reshape(x(1:old_end,:),[],1),'uint64'), ...
                typecast(reshape(v(1:new_end,:),[],1),'uint64')), ...
        'Executed prefix or its interpolation bracket changed.');
    extended=timeseries(v,t,'Name',actual.Name);
    extended.DataInfo.Units=actual.DataInfo.Units;extended.TimeInfo.Units=actual.TimeInfo.Units;
    extended=setinterpmethod(extended,getinterpmethod(actual));
    record=struct('source_snapshot_s',source_s,'proved_through_s',proof_stop_s, ...
        'old_end_s',a(end),'new_end_s',t(end),'first_possible_changed_interval_s',first_possible_change, ...
        'old_samples',numel(a),'new_samples',numel(t),'channels',size(x,2), ...
        'constant_profile',constant,'prefix_and_interpolation_bracket_bitwise_equal',true, ...
        'resampling_used',false,'interpolation_method',getinterpmethod(actual));
end

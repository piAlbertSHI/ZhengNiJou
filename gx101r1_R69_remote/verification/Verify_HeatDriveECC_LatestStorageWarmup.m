function result = Verify_HeatDriveECC_LatestStorageWarmup(source,verified,state_path,cycle_path,output_file)
% Load the exact latest vendor point with both typed storage-model ancestor proofs.
    assert(~isfile(output_file),'Never overwrite typed endpoint evidence.');
    options=struct('mode','diagnostic_resume','command_horizon_cycles',200, ...
        'restore_source_root',source,'restore_verification_root',verified, ...
        'storage_state_audit_path',state_path,'storage_complete_cycle_audit_path',cycle_path);
    options=Resolve_HeatDriveECC_DiagnosticStateOptions(options,20);
    [op,contract]=Load_HeatDriveECC_DiagnosticResumeSource(options);
    execution=jsondecode(fileread(fullfile(source,'cold_chamber_execution.json')));
    assert(op.snapshotTime==execution.stop_time_s && contract.snapshot_time_s==execution.stop_time_s && ...
        contract.ancestor_complete_cycle_restore_verified && contract.source_physical_gates_evaluated && ...
        ~contract.source_state_edited && ~contract.partial_state_restore_used && ...
        ~contract.production_recovery_allowed,'Latest storage-model endpoint changed or was promoted.');
    result=struct('schema','heatdrive_ecc_typed_latest_storage_warmup_guard_v1', ...
        'snapshot_time_s',op.snapshotTime,'total_cycles',execution.cycle_count,'actual_vendor_OP_loaded',true, ...
        'operating_point_sha256',contract.operating_point_sha256,'history_sha256',contract.history_sha256, ...
        'ancestor_storage_audit_sha256',contract.storage_complete_cycle_audit_sha256, ...
        'simulation_executed',false,'source_state_edited',false,'production_recovery_allowed',false);
    fid=fopen(output_file,'w','n','UTF-8');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));fprintf(fid,'%s\n',jsonencode(result,'PrettyPrint',true));
    fprintf('%s\n',jsonencode(result));
end

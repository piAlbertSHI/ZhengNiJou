function [op,manifest]=Load_HeatDriveECC_GatedObservationPacket(packet,require_boundary)
% Load complete vendor state only after the immutable native packet gate.
    manifest_file=fullfile(packet,'packet_manifest.json');manifest=jsondecode(fileread(manifest_file));
    gate=jsondecode(fileread(fullfile(packet,'packet_gate.json')));
    assert(~isfile(fullfile(packet,'REJECTED_DO_NOT_RESUME.json')) && ...
        strcmp(gate.input_sha256.manifest,file_hash(manifest_file)) && gate.gate_pass && ...
        gate.original_mechanism_count==73 && gate.original_mechanism_pass && ...
        numel(gate.six_local_inventory_gates)==6 && all(gate.six_local_inventory_gates) && ...
        gate.modeled_energy_balance.model_equation_energy_closure_pass && ...
        gate.modeled_energy_balance.energy_tolerance_J==1e-8 && ...
        abs(gate.modeled_energy_balance.external_heat_minus_total_storage_J)<=1e-8 && ...
        numel(gate.flow_gates)==6 && all([gate.flow_gates.selected_flow_gate]) && ...
        ~gate.production_recovery_allowed && ~gate.outer_solve_eligible && ...
        manifest.history_cap_cycles==2 && manifest.state_history_cap_cycles==11 && ...
        manifest.strict_vendor_restore && ~manifest.source_state_edited && ...
        manifest.window_s(2)<=720,'Incomplete or failed observation packet cannot propagate.');
    for k=1:numel(manifest.input_files)
        row=manifest.input_files(k);assert(strcmp(file_hash(fullfile(packet,row.path)),row.sha256));
    end
    if require_boundary
        boundary=jsondecode(fileread(fullfile(packet,'boundary_comparison.json')));
        assert(boundary.pass && boundary.retained_memories_bitwise_equal && ...
            strcmp(manifest.packet_role,'bounded_transient_observation') && ...
            strcmp(boundary.candidate_observation_sha256,file_hash(fullfile(packet,'native','observations.mat'))) && ...
            strcmp(boundary.candidate_state_sha256,file_hash(fullfile(packet,'observed_states.mat'))), ...
            'The next packet requires an intact recorded boundary.');
    end
    file=fullfile(packet,'comparison_only_complete_op.mat');
    assert(strcmp(file_hash(file),manifest.complete_OP_sha256));
    saved=load(file,'diagnostic_operating_point','production_recovery_allowed');op=saved.diagnostic_operating_point;
    assert(~saved.production_recovery_allowed && op.snapshotTime==manifest.window_s(2) && ...
        (isa(op,'Simulink.op.ModelOperatingPoint') || isa(op,'Simulink.SimulationOperatingPoint')));
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

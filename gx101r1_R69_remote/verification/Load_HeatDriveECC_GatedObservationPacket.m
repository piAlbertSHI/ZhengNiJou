function [op,manifest]=Load_HeatDriveECC_GatedObservationPacket(packet,require_boundary,expected_case_sha256)
% Load complete vendor state only after the immutable native packet gate.
    manifest_file=fullfile(packet,'packet_manifest.json');manifest=jsondecode(fileread(manifest_file));
    assert(~isfield(manifest,'packet_role') || ~strcmp(manifest.packet_role,'runtime_horizon_comparison'), ...
        'Command-horizon preflight states are comparison-only, never continuation authority.');
    if nargin<3,expected_case_sha256='';end
    sensitivity=isfield(manifest,'packet_role') && any(strcmp(manifest.packet_role,{'runtime_sensitivity_cold','runtime_sensitivity_transient'}));
    if sensitivity
        assert(~isempty(expected_case_sha256) && strcmp(manifest.sensitivity_case_contract_sha256,expected_case_sha256) && ...
            strcmp(file_hash(fullfile(packet,'native','sensitivity_case_contract.json')),expected_case_sha256) && ...
            manifest.sensitivity_case_scope_only && manifest.prescribed_Tc_K==276.95 && ...
            manifest.command_horizon_cycles==200 && manifest.window_s(2)<=200, ...
            'Sensitivity states require the exact same case; they are not old-family or mainline authority.');
    end
    gate=jsondecode(fileread(fullfile(packet,'packet_gate.json')));
    if isfield(manifest,'simulation_timing_sha256')
        assert(strcmp(file_hash(fullfile(packet,'simulation_timing.json')),manifest.simulation_timing_sha256));
    end
    flows=gate.flow_gates;if isstruct(flows),flows=num2cell(flows);end
    assert(iscell(flows) && numel(flows)==6,'Require the six original component/stage flow records.');
    flow_pass=cellfun(@(row) isstruct(row) && isfield(row,'selected_flow_gate') && ...
        islogical(row.selected_flow_gate) && isscalar(row.selected_flow_gate) && row.selected_flow_gate,flows);
    cold=isfield(manifest,'packet_role') && any(strcmp(manifest.packet_role,{'runtime_boundary_cold_baseline','runtime_sensitivity_cold'}));
    runtime=isfield(manifest,'packet_role') && strcmp(manifest.packet_role,'runtime_boundary_transient');
    candidate=isfield(manifest,'packet_role') && any(strcmp(manifest.packet_role,{'runtime_boundary_Tc_candidate','runtime_boundary_Tc_continuation'}));
    if candidate
        t=manifest.boundary_trial;
        Require_HeatDriveECC_RuntimeTcTrial(t);
        assert(strcmp(manifest.temperature_configurability,'runtime') && manifest.prescribed_Tc_K==t.candidate_Tc_K && ...
            manifest.command_horizon_cycles==200 && ...
            manifest.window_s(1)>=t.transition_time_s && manifest.window_s(2)<=2000 && ...
            t.minimum_transition_cycles==12 && ~t.source_state_edited && ~t.old_model_OP_imported && ...
            manifest.source_snapshot_s==manifest.window_s(1) && strcmp(manifest.checksum_policy,'error/error'));
    end
    if isfield(manifest,'packet_role') && strcmp(manifest.packet_role,'runtime_boundary_Tc_continuation')
        c=manifest.continuation;
        assert(c.temperature_unchanged && manifest.window_s(1)>=c.source_snapshot_s && ...
            manifest.window_s(2)<=c.budget_stop_s && c.budget_stop_s==c.source_snapshot_s+200 && ...
            c.source_snapshot_s>=400 && mod(c.source_snapshot_s,20)==0);
        if manifest.window_s(1)==c.source_snapshot_s,assert(strcmp(manifest.parent_complete_OP_sha256,c.source_OP_sha256));end
    end
    if runtime
        assert(strcmp(manifest.temperature_configurability,'runtime') && manifest.prescribed_Tc_K==276.95 && ...
            manifest.command_horizon_cycles==200 && manifest.window_s(1)>=20 && manifest.window_s(2)<=2000);
    end
    if cold
        assert(manifest.independent_cold_start && ~manifest.strict_vendor_restore && ...
            strcmp(manifest.checksum_policy,'error/error') && isequal(manifest.window_s(:),[0;20]) && ...
            manifest.source_snapshot_s==0 && isempty(manifest.parent_complete_OP_sha256));
    end
    assert(~isfile(fullfile(packet,'REJECTED_DO_NOT_RESUME.json')) && ...
        strcmp(gate.input_sha256.manifest,file_hash(manifest_file)) && gate.gate_pass && ...
        gate.original_mechanism_count==73 && gate.original_mechanism_pass && ...
        numel(gate.six_local_inventory_gates)==6 && all(gate.six_local_inventory_gates) && ...
        gate.modeled_energy_balance.model_equation_energy_closure_pass && ...
        gate.modeled_energy_balance.energy_tolerance_J==1e-8 && ...
        abs(gate.modeled_energy_balance.external_heat_minus_total_storage_J)<=1e-8 && ...
        all(flow_pass) && ...
        ~gate.production_recovery_allowed && ~gate.outer_solve_eligible && ...
        manifest.history_cap_cycles==2 && manifest.state_history_cap_cycles==11 && ...
        (manifest.strict_vendor_restore || cold) && ~manifest.source_state_edited && ...
        (manifest.window_s(2)<=720 || runtime || candidate || sensitivity),'Incomplete or failed observation packet cannot propagate.');
    for k=1:numel(manifest.input_files)
        row=manifest.input_files(k);assert(strcmp(file_hash(fullfile(packet,row.path)),row.sha256));
    end
    if require_boundary
        boundary=jsondecode(fileread(fullfile(packet,'boundary_comparison.json')));
        assert(boundary.pass && boundary.retained_memories_bitwise_equal && ...
            (strcmp(manifest.packet_role,'bounded_transient_observation') || runtime || candidate || sensitivity) && ...
            strcmp(boundary.candidate_observation_sha256,file_hash(fullfile(packet,'native','observations.mat'))) && ...
            strcmp(boundary.candidate_state_sha256,file_hash(fullfile(packet,'observed_states.mat'))), ...
            'The next packet requires an intact recorded boundary.');
    end
    file=fullfile(packet,'comparison_only_complete_op.mat');
    assert(strcmp(file_hash(file),manifest.complete_OP_sha256));
    saved=load(file,'diagnostic_operating_point','production_recovery_allowed');op=saved.diagnostic_operating_point;
    assert(~saved.production_recovery_allowed && op.snapshotTime==manifest.window_s(2) && ...
        (isa(op,'Simulink.op.ModelOperatingPoint') || isa(op,'Simulink.SimulationOperatingPoint')));
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

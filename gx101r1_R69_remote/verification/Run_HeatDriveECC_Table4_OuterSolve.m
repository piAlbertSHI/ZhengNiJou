function outer = Run_HeatDriveECC_Table4_OuterSolve(settings)
% Mechanism-gated fixed-Tc outer solve for a declared Table 4 endpoint.
%
% Each candidate starts from the current validated continuation authority.
% A candidate may enter bracketing/interpolation only after periodic steady
% state and the declared mechanism, flow, phase, energy, observability and
% modeled-system-energy gates all pass.

    if nargin < 1
        settings = struct();
    end
    repo_root = fileparts(fileparts(mfilename('fullpath')));
    defaults = struct( ...
        'output_root', fullfile(repo_root, 'outputs', ...
            'qian_table4_zero_load_outer_solve_20260822'), ...
        'Tc_candidates_K', [275.5, 278.5], ...
        'target_metric', 'eq10_SCP_W_per_g', ...
        'target_SCP_W_per_g', 0.0, ...
        'target_lift_K', 0.0, ...
        'root_SCP_tolerance_W_per_g', 0.01, ...
        'root_lift_tolerance_K', 0.1, ...
        'segment_cycles', 20, ...
        'minimum_boundary_transition_cycles', 11, ...
        'maximum_additional_cycles', 80, ...
        'generate_intermediate_figures', false, ...
        'resume_existing_candidates', true, ...
        'run_candidates', true, ...
        'model_overrides', struct(), ...
        'branch_overrides', struct(), ...
        'authority_settings', struct('contract_path', fullfile( ...
            repo_root, 'verification', ...
            'c200_mainline_recovery_reference_20260915.json')));
    settings = merge_structs(defaults, settings);
    validate_settings(settings);
    contract = jsondecode(fileread(settings.authority_settings.contract_path));
    if isfield(contract, 'steady_parameter_study_allowed') && ...
            ~isequal(contract.steady_parameter_study_allowed, true)
        error('HeatDriveECC:SteadyParameterStudyNotAuthorized', ...
            ['The authority permits only same-parameter state auditing. ', ...
            'Complete the inventory and PI periodicity audit first.']);
    end
    authority = Resolve_HeatDriveECC_MainlineAuthority( ...
        settings.authority_settings);
    if ~authority.outer_solve_authorized
        outer = write_unauthorized_guard(settings, authority);
        fprintf(['OUTER_SOLVE_GUARDED status=%s candidates_started=0 ', ...
            'reason=%s\n'], outer.status, outer.reason);
        return;
    end
    if ~exist(settings.output_root, 'dir')
        mkdir(settings.output_root);
    end

    records = frozen_baseline_record(authority);
    for idx = 1:numel(settings.Tc_candidates_K)
        Tc_K = settings.Tc_candidates_K(idx);
        if abs(Tc_K - records(1).Tc_K) <= 1.0e-12
            continue;
        end
        candidate_root = fullfile(settings.output_root, ...
            sprintf('Tc_%08.3fK', Tc_K));
        record_path = fullfile(candidate_root, 'outer_candidate_record.mat');
        state_path = fullfile(candidate_root, ...
            'steady_continuation_state.mat');
        if isfile(record_path)
            loaded = load(record_path, 'record');
            record = loaded.record;
        elseif isfile(state_path)
            loaded = load(state_path, 'state');
            if strcmp(loaded.state.status, 'running') && ...
                    logical(settings.run_candidates)
                state = run_candidate_with_recorded_failure(Tc_K, ...
                    candidate_root, authority, settings, state_path);
            else
                state = loaded.state;
            end
            record = evaluate_candidate(Tc_K, candidate_root, state);
            save(record_path, 'record', '-v7');
        elseif logical(settings.run_candidates)
            state = run_candidate_with_recorded_failure(Tc_K, ...
                candidate_root, authority, settings, state_path);
            record = evaluate_candidate(Tc_K, candidate_root, state);
            save(record_path, 'record', '-v7');
        else
            record = pending_record(Tc_K, candidate_root);
        end
        if ~record.admissible && ~strcmp(record.status, 'pending')
            write_rejection_marker(candidate_root, record, authority);
        end
        records(end + 1, 1) = record; %#ok<AGROW>
        write_outer_outputs(settings.output_root, records, settings, authority);
    end

    outer = build_outer_result(records, settings, authority);
    write_outer_outputs(settings.output_root, records, settings, authority);
    save(fullfile(settings.output_root, 'outer_solve_result.mat'), ...
        'outer', 'settings', '-v7');
    fprintf(['OUTER_SOLVE status=%s accepted=%d rejected=%d ', ...
        'root_bracketed=%d root_Tc_K=%.12g\n'], outer.status, ...
        outer.accepted_count, outer.rejected_count, ...
        outer.root_bracketed, outer.root_Tc_K);
end

function outer = write_unauthorized_guard(settings, authority)
% Persist a non-running guard result without creating candidate directories.
    if ~exist(settings.output_root, 'dir')
        mkdir(settings.output_root);
    end
    outer = struct( ...
        'schema', 'heatdrive_ecc_table4_outer_solve_guard_v1', ...
        'status', 'guarded_not_authorized', ...
        'reason', 'C200 authority contract has outer_solve_authorized=false.', ...
        'candidates_started', false, ...
        'candidate_count', 0, ...
        'authority_contract_path', authority.contract_path, ...
        'authority_result_path', authority.result_path, ...
        'authority_checkpoint_path', authority.checkpoint_path, ...
        'authority_completed_cycles', authority.completed_cycles, ...
        'mechanism_pass', authority.mechanism_pass, ...
        'periodic_steady_state', authority.periodic_steady_state, ...
        'strict_table4_reproduction', authority.strict_table4_reproduction, ...
        'claim_boundary', ['No fixed-Tc candidate, interpolation, endpoint ', ...
            'pairing, or Table 4 claim is authorized.']);
    json_path = fullfile(settings.output_root, 'outer_solve_guard.json');
    fid = fopen(json_path, 'w');
    assert(fid >= 0, 'HeatDriveECC:GuardWriteFailed', ...
        'Unable to write outer-solve guard JSON.');
    fprintf(fid, '%s\n', jsonencode(outer, PrettyPrint=true));
    fclose(fid);
    marker_path = fullfile(settings.output_root, ...
        'REJECTED_OUTER_SOLVE_NOT_AUTHORIZED.txt');
    fid_marker = fopen(marker_path, 'w');
    assert(fid_marker >= 0, 'HeatDriveECC:GuardWriteFailed', ...
        'Unable to write outer-solve guard marker.');
    fprintf(fid_marker, '%s\n', outer.reason);
    fclose(fid_marker);
    save(fullfile(settings.output_root, 'outer_solve_result.mat'), ...
        'outer', 'settings', '-v7');
end

function state = run_candidate_with_recorded_failure(Tc_K, candidate_root, ...
        authority, settings, state_path)
% Convert a continuation driver's recorded terminal error into an auditable
% rejected candidate. No result or checkpoint from the failed attempt is
% promoted; the authority paths in the state remain diagnostic references.
    try
        state = run_candidate(Tc_K, candidate_root, authority, settings);
    catch exception
        if ~isfile(state_path)
            rethrow(exception);
        end
        saved = load(state_path, 'state');
        state = saved.state;
        terminal = isfield(state, 'status') && ...
            strcmp(state.status, 'simulation_error');
        authority_preserved = isfield(state, 'current_cycles') && ...
            state.current_cycles == authority.completed_cycles && ...
            isfield(state, 'prior_result_path') && ...
            isfield(state, 'checkpoint_path') && ...
            strcmpi(canonical_path(state.prior_result_path), ...
                canonical_path(authority.result_path)) && ...
            strcmpi(canonical_path(state.checkpoint_path), ...
                canonical_path(authority.checkpoint_path));
        if ~(terminal && authority_preserved)
            rethrow(exception);
        end
        fprintf(2, ['OUTER_CANDIDATE_RECORDED_ERROR Tc_K=%.12g ', ...
            'cycles=%d id=%s; authority preserved without propagation\n'], ...
            Tc_K, state.current_cycles, exception.identifier);
    end
end

function state = run_candidate(Tc_K, candidate_root, authority, settings)
    [authority_model, frozen_controller, authority_Tc_K] = ...
        authority_state_overrides(authority);
    segment_cycles = settings.segment_cycles;
    if abs(Tc_K - authority_Tc_K) > 1.0e-12
        % Eq. 9/Eq. 10 and the fixed-CHEX authority gate use the final ten
        % complete cycles. One extra cycle keeps the transition boundary
        % sample and all pre-transition authority data outside that window.
        segment_cycles = max(segment_cycles, ...
            settings.minimum_boundary_transition_cycles);
    end
    model_overrides = merge_structs(authority_model, ...
        settings.model_overrides);
    branch_overrides = merge_structs(frozen_controller, ...
        settings.branch_overrides);
    candidate_settings = struct( ...
        'Tchex_K', Tc_K, ...
        'output_root', candidate_root, ...
        'segment_cycles', segment_cycles, ...
        'maximum_cycles', authority.completed_cycles + ...
            settings.maximum_additional_cycles, ...
        'required_consecutive_near_segments', intmax('int32'), ...
        'generate_intermediate_figures', ...
            settings.generate_intermediate_figures, ...
        'resume_existing_state', settings.resume_existing_candidates, ...
        'initial_prior_result_path', authority.result_path, ...
        'initial_checkpoint_path', authority.checkpoint_path, ...
        'initial_state_policy', 'validated_recovery_contract_only', ...
        'mainline_contract_path', authority.contract_path, ...
        'model_overrides', model_overrides, ...
        'checkpoint_transition_fields', {{ ...
            'system.Tchex_K', 'branch.boundary_T_se_chex_K'}}, ...
        'branch_overrides', branch_overrides);
    state = Run_HeatDriveECC_Table4_FixedReservoirPoint( ...
        candidate_settings);
end

function [model, branch, authority_Tc_K] = ...
        authority_state_overrides(authority)
% Preserve the controller/feedforward contract bound to the authority state.
    prior = load(authority.result_path, 'options');
    assert(isfield(prior, 'options') && isfield(prior.options, 'branch'), ...
        'HeatDriveECC:OuterMissingAuthorityOptions', ...
        'Continuation authority result does not contain its branch options.');
    source = prior.options.branch;
    authority_Tc_K = prior.options.system.Tchex_K;
    model = struct('system', struct( ...
        'cold_boundary_temperature_configurability', ...
        prior.options.system.cold_boundary_temperature_configurability));
    names = fieldnames(source);
    keep = contains(names, 'pressure_pi') | ...
        contains(names, 'pressure_feedforward') | ...
        contains(names, 'viscosity_blend') | ...
        contains(names, 'route_temperature_blend') | ...
        contains(names, 'pressure_integrator') | ...
        contains(names, 'pressure_bias') | ...
        contains(names, 'cold_design_dp') | ...
        contains(names, 'runtime_mu');
    names = names(keep);
    branch = struct();
    for idx = 1:numel(names)
        branch.(names{idx}) = source.(names{idx});
    end
    % These fields are part of the checkpoint contract. Preserve both the
    % physical mode and its provenance text so a documentation-only default
    % change cannot invalidate an otherwise identical authority state.
    pump_fields = {'pump_fluid_energy_model', ...
        'pump_fluid_energy_model_source'};
    for idx = 1:numel(pump_fields)
        name = pump_fields{idx};
        if isfield(source, name)
            branch.(name) = source.(name);
        end
    end
end

function record = frozen_baseline_record(authority)
    prior = load(authority.result_path, 'options');
    assert(isfield(prior, 'options'), ...
        'HeatDriveECC:OuterMissingAuthorityOptions', ...
        'Continuation authority result does not contain options.');
    progress = readtable(authority.progress_path, 'TextType', 'string');
    last = progress(end, :);
    report = fileread(authority.report_path);
    gates = required_gate_results(report);
    assert(~isempty(authority.audit_path), ...
        'HeatDriveECC:OuterMissingAuthoritySystemEnergyAudit', ...
        'Continuation authority must declare a system-energy audit.');
    system_energy = jsondecode(fileread(authority.audit_path));
    record = record_template();
    record.Tc_K = prior.options.system.Tchex_K;
    record.status = 'accepted_continuation_authority';
    record.source = 'validated_recovery_contract';
    record.attempted_cycles = authority.completed_cycles;
    record.validated_cycles = authority.completed_cycles;
    record.mechanism_pass = authority.mechanism_pass;
    record.periodic_steady_state = authority.periodic_steady_state;
    record.flow_gates_pass = gates.flow;
    record.phase_gates_pass = gates.phase;
    record.energy_gates_pass = gates.energy;
    record.observability_gates_pass = gates.observability;
    record.system_energy_gates_pass = logical(system_energy.production_pass);
    record.system_energy_residual_relative = ...
        system_energy.modeled_thermal_residual_relative;
    record.fluid_mass_drift_relative = ...
        system_energy.fluid_mass_drift_relative;
    record.system_energy_audit_path = authority.audit_path;
    record.admissible = all([record.mechanism_pass, ...
        record.periodic_steady_state, record.flow_gates_pass, ...
        record.phase_gates_pass, record.energy_gates_pass, ...
        record.observability_gates_pass, ...
        record.system_energy_gates_pass]);
    record.eq9_lift_K = last.eq9_lift_K;
    record.eq10_SCP_W_per_g = last.eq10_SCP_W_per_g;
    record.endpoint_drift_K = last.endpoint_drift_K;
    record.same_phase_temperature_drift_K = ...
        last.same_phase_temperature_drift_K;
    record.same_phase_phase_drift = last.same_phase_phase_drift;
    record.result_path = authority.result_path;
    record.checkpoint_path = authority.checkpoint_path;
    record.report_path = authority.report_path;
    record.output_root = fileparts(authority.progress_path);
end

function record = evaluate_candidate(Tc_K, candidate_root, state)
    record = record_template();
    record.Tc_K = Tc_K;
    record.status = char(string(state.status));
    record.source = 'validated_recovery_continuation_candidate';
    record.output_root = candidate_root;
    record.validated_cycles = state.current_cycles;
    record.attempted_cycles = get_field(state, 'last_attempt_cycles', ...
        state.current_cycles);
    record.failure_reason = char(string(get_field(state, 'stop_reason', '')));
    if isempty(state.rows)
        return;
    end
    row = state.rows(end, :);
    record.mechanism_pass = logical(row.mechanism_pass);
    record.periodic_steady_state = logical(row.periodic_steady_state);
    record.eq9_lift_K = row.eq9_lift_K;
    record.eq10_SCP_W_per_g = row.eq10_SCP_W_per_g;
    record.endpoint_drift_K = row.endpoint_drift_K;
    record.same_phase_temperature_drift_K = ...
        row.same_phase_temperature_drift_K;
    record.same_phase_phase_drift = row.same_phase_phase_drift;
    record.result_path = char(string(row.output_mat));
    record.checkpoint_path = char(string(row.checkpoint_path));
    record.report_path = fullfile(char(string(row.output_dir)), ...
        'physical_validation_report.txt');
    if isfile(record.report_path)
        gates = required_gate_results(fileread(record.report_path));
        record.flow_gates_pass = gates.flow;
        record.phase_gates_pass = gates.phase;
        record.energy_gates_pass = gates.energy;
        record.observability_gates_pass = gates.observability;
    end
    if isfile(record.result_path)
        record.system_energy_audit_path = fullfile(candidate_root, ...
            'system_energy_audit.json');
        try
            system_energy = Audit_HeatDriveECC_SystemEnergyResult( ...
                record.result_path, record.system_energy_audit_path);
            record.system_energy_gates_pass = ...
                logical(system_energy.production_pass);
            record.system_energy_residual_relative = ...
                system_energy.modeled_thermal_residual_relative;
            record.fluid_mass_drift_relative = ...
                system_energy.fluid_mass_drift_relative;
        catch exception
            record.system_energy_audit_error = exception.message;
        end
    end
    record.admissible = strcmp(state.status, 'periodic_steady_state') && ...
        all([record.mechanism_pass, record.periodic_steady_state, ...
        record.flow_gates_pass, record.phase_gates_pass, ...
        record.energy_gates_pass, record.observability_gates_pass, ...
        record.system_energy_gates_pass]);
    if ~record.admissible
        record.checkpoint_path = '';
    end
end

function gates = required_gate_results(report)
    flow_names = {'SMA_settled_instantaneous_flow_target', ...
        'SE_last_cycle_settled_flow_no_reversal', ...
        'SE_last_cycle_settled_instantaneous_flow_target', ...
        'SE_last_cycle_settled_flow_RMS_target', ...
        'qian_active_flow_targets', 'route_flow_direction'};
    phase_names = {'constitutive_phase_direction', 'SMA_phase_swing', ...
        'SE_phase_swing', 'qian_table4_half_cycle_phase_completion', ...
        'qian_table4_compatibility_stress'};
    energy_names = {'pump_work_nonnegative', 'SMA_solid_energy_balance', ...
        'SE_solid_energy_balance', ...
        'stage_constitutive_energy_decomposition', ...
        'internal_mechanical_work_transfer'};
    observability_names = {'qian_eq9_eq10_observability', ...
        'fixed_chex_temperature_authority'};
    gates = struct( ...
        'flow', report_checks_pass(report, flow_names), ...
        'phase', report_checks_pass(report, phase_names), ...
        'energy', report_checks_pass(report, energy_names), ...
        'observability', report_checks_pass(report, observability_names));
end

function tf = report_checks_pass(report, names)
    tf = true;
    for idx = 1:numel(names)
        pattern = sprintf('(?m)^\\s*%s\\s+1\\s*$', ...
            regexptranslate('escape', names{idx}));
        tf = tf && ~isempty(regexp(report, pattern, 'once'));
    end
end

function outer = build_outer_result(records, settings, authority)
    admitted = records([records.admissible]);
    [~, order] = sort([admitted.Tc_K]);
    admitted = admitted(order);
    [values, target, tolerance, endpoint_name] = ...
        endpoint_response(admitted, settings);
    response = values - target;
    bracket = [];
    for idx = 1:(numel(admitted) - 1)
        if response(idx) == 0 || response(idx) * response(idx + 1) <= 0
            bracket = idx:(idx + 1);
            break;
        end
    end
    root_Tc_K = NaN;
    root_bracketed = ~isempty(bracket);
    if root_bracketed
        x = [admitted(bracket).Tc_K];
        y = response(bracket);
        if abs(diff(y)) > eps
            root_Tc_K = x(1) - y(1) * diff(x) / diff(y);
        else
            root_Tc_K = mean(x);
        end
    end
    root_records = admitted(abs(response) <= tolerance);
    if ~isempty(root_records)
        [root_values, ~, ~, ~] = endpoint_response(root_records, settings);
        [~, best] = min(abs(root_values - target));
        root_Tc_K = root_records(best).Tc_K;
        status = ['accepted_' endpoint_name '_root'];
    elseif root_bracketed
        status = 'valid_bracket_requires_next_candidate';
    else
        status = 'no_valid_bracket';
    end
    outer = struct();
    outer.schema = 'heatdrive_ecc_mechanism_gated_outer_solve_v3';
    outer.generated_at = char(datetime('now', 'TimeZone', 'local'));
    outer.status = status;
    outer.endpoint_name = endpoint_name;
    outer.target_metric = settings.target_metric;
    outer.target_value = target;
    outer.root_tolerance = tolerance;
    outer.root_bracketed = root_bracketed;
    outer.root_Tc_K = root_Tc_K;
    outer.accepted_count = nnz([records.admissible]);
    outer.rejected_count = nnz(~[records.admissible] & ...
        ~strcmp({records.status}, 'pending'));
    outer.pending_count = nnz(strcmp({records.status}, 'pending'));
    outer.records = records;
    outer.authority_contract_path = authority.contract_path;
    outer.interpolation_policy = [ ...
        'Only periodic candidates passing mechanism, flow, phase, energy, ', ...
        'observability and modeled-system-energy gates are admitted.'];
    outer.minimum_boundary_transition_cycles = ...
        settings.minimum_boundary_transition_cycles;
    outer.boundary_transition_window_policy = [ ...
        'A changed Tc must run at least eleven new cycles so the final ', ...
        'ten-cycle Eq. 9/Eq. 10 and boundary-authority window excludes ', ...
        'the transition sample and all authority-history cycles.'];
end

function [values, target, tolerance, endpoint_name] = ...
        endpoint_response(records, settings)
    switch settings.target_metric
        case 'eq10_SCP_W_per_g'
            values = [records.eq10_SCP_W_per_g];
            target = settings.target_SCP_W_per_g;
            tolerance = settings.root_SCP_tolerance_W_per_g;
            endpoint_name = 'zero_load';
        case 'eq9_lift_K'
            values = [records.eq9_lift_K];
            target = settings.target_lift_K;
            tolerance = settings.root_lift_tolerance_K;
            endpoint_name = 'zero_lift';
        otherwise
            error('HeatDriveECC:OuterInvalidTargetMetric', ...
                'Unsupported target metric: %s', settings.target_metric);
    end
end

function write_outer_outputs(output_root, records, settings, authority)
    summary = struct2table(records);
    writetable(summary, fullfile(output_root, 'outer_candidate_summary.csv'));
    outer = build_outer_result(records, settings, authority);
    json_path = fullfile(output_root, 'outer_solve_summary.json');
    fid = fopen(json_path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:OuterSummaryOpenFailed', ...
        'Cannot write %s.', json_path);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(outer, 'PrettyPrint', true));
    clear cleaner
end

function write_rejection_marker(candidate_root, record, authority)
    if ~exist(candidate_root, 'dir')
        mkdir(candidate_root);
    end
    path = fullfile(candidate_root, 'REJECTED_DO_NOT_RESUME.txt');
    fid = fopen(path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:OuterRejectMarkerOpenFailed', ...
        'Cannot write %s.', path);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, 'status=rejected_not_admissible_for_outer_solve\n');
    fprintf(fid, 'Tc_K=%.12g\n', record.Tc_K);
    fprintf(fid, 'attempt_status=%s\n', record.status);
    fprintf(fid, 'failure_reason=%s\n', record.failure_reason);
    fprintf(fid, 'mechanism_pass=%d\n', record.mechanism_pass);
    fprintf(fid, 'periodic_steady_state=%d\n', record.periodic_steady_state);
    fprintf(fid, 'flow_gates_pass=%d\n', record.flow_gates_pass);
    fprintf(fid, 'phase_gates_pass=%d\n', record.phase_gates_pass);
    fprintf(fid, 'energy_gates_pass=%d\n', record.energy_gates_pass);
    fprintf(fid, 'observability_gates_pass=%d\n', ...
        record.observability_gates_pass);
    fprintf(fid, 'system_energy_gates_pass=%d\n', ...
        record.system_energy_gates_pass);
    fprintf(fid, 'system_energy_residual_relative=%.12g\n', ...
        record.system_energy_residual_relative);
    fprintf(fid, 'fluid_mass_drift_relative=%.12g\n', ...
        record.fluid_mass_drift_relative);
    if ~isempty(record.system_energy_audit_error)
        fprintf(fid, 'system_energy_audit_error=%s\n', ...
            record.system_energy_audit_error);
    end
    fprintf(fid, 'failed_result_may_resume=0\n');
    fprintf(fid, 'failed_result_may_interpolate=0\n');
    fprintf(fid, 'sole_recovery_path=%s\n', authority.checkpoint_path);
    clear cleaner
end

function record = pending_record(Tc_K, candidate_root)
    record = record_template();
    record.Tc_K = Tc_K;
    record.status = 'pending';
    record.source = 'not_run';
    record.output_root = candidate_root;
end

function record = record_template()
    record = struct( ...
        'Tc_K', NaN, 'status', '', 'source', '', ...
        'attempted_cycles', 0, 'validated_cycles', 0, ...
        'mechanism_pass', false, 'periodic_steady_state', false, ...
        'flow_gates_pass', false, 'phase_gates_pass', false, ...
        'energy_gates_pass', false, ...
        'observability_gates_pass', false, ...
        'system_energy_gates_pass', false, ...
        'system_energy_residual_relative', NaN, ...
        'fluid_mass_drift_relative', NaN, ...
        'system_energy_audit_path', '', ...
        'system_energy_audit_error', '', 'failure_reason', '', ...
        'admissible', false, ...
        'eq9_lift_K', NaN, 'eq10_SCP_W_per_g', NaN, ...
        'endpoint_drift_K', NaN, ...
        'same_phase_temperature_drift_K', NaN, ...
        'same_phase_phase_drift', NaN, 'result_path', '', ...
        'checkpoint_path', '', 'report_path', '', 'output_root', '');
end

function value = get_field(s, name, fallback)
    if isfield(s, name)
        value = s.(name);
    else
        value = fallback;
    end
end

function path = canonical_path(path)
    path = char(java.io.File(char(string(path))).getCanonicalPath());
end

function validate_settings(settings)
    candidates = settings.Tc_candidates_K;
    assert(isnumeric(candidates) && isvector(candidates) && ...
        all(isfinite(candidates)) && all(candidates >= 255.05) && ...
        all(candidates <= 303.15), ...
        'HeatDriveECC:OuterInvalidCandidates', ...
        'Tc candidates must remain inside the declared SE-fluid range.');
    assert(settings.maximum_additional_cycles > 0 && ...
        settings.maximum_additional_cycles == ...
        round(settings.maximum_additional_cycles), ...
        'HeatDriveECC:OuterInvalidMaximumCycles', ...
        'maximum_additional_cycles must be a positive integer.');
    assert(settings.segment_cycles > 0 && ...
        settings.segment_cycles == round(settings.segment_cycles), ...
        'HeatDriveECC:OuterInvalidSegmentCycles', ...
        'segment_cycles must be a positive integer.');
    assert(settings.minimum_boundary_transition_cycles >= 11 && ...
        settings.minimum_boundary_transition_cycles == ...
        round(settings.minimum_boundary_transition_cycles) && ...
        settings.maximum_additional_cycles >= ...
        settings.minimum_boundary_transition_cycles, ...
        'HeatDriveECC:OuterInvalidTransitionWindow', ...
        ['The boundary-transition segment must provide at least eleven ', ...
        'new cycles and fit inside maximum_additional_cycles.']);
    assert(any(strcmp(settings.target_metric, ...
        {'eq10_SCP_W_per_g', 'eq9_lift_K'})), ...
        'HeatDriveECC:OuterInvalidTargetMetric', ...
        'target_metric must be eq10_SCP_W_per_g or eq9_lift_K.');
    assert(isfinite(settings.root_SCP_tolerance_W_per_g) && ...
        settings.root_SCP_tolerance_W_per_g > 0 && ...
        isfinite(settings.root_lift_tolerance_K) && ...
        settings.root_lift_tolerance_K > 0, ...
        'HeatDriveECC:OuterInvalidTolerance', ...
        'Endpoint tolerances must be finite and positive.');
end

function out = merge_structs(out, overrides)
    names = fieldnames(overrides);
    for idx = 1:numel(names)
        name = names{idx};
        if isfield(out, name) && isstruct(out.(name)) && ...
                isstruct(overrides.(name))
            out.(name) = merge_structs(out.(name), overrides.(name));
        else
            out.(name) = overrides.(name);
        end
    end
end

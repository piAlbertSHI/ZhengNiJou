function authority = Resolve_HeatDriveECC_SourceHeatFlowRecovery(settings)
% Resolve one mechanism-valid source heat-flow intermediate recovery state.

    if nargin < 1
        settings = struct();
    end
    verification_dir = fileparts(mfilename('fullpath'));
    repo_root = fileparts(verification_dir);
    assert(isfield(settings, 'contract_path'), ...
        'HeatDriveECC:MissingSourceRecoveryContractPath', ...
        'Source heat-flow recovery requires an explicit contract path.');
    contract_path = char(string(settings.contract_path));
    assert(isfile(contract_path), 'HeatDriveECC:MissingSourceRecoveryContract', ...
        'Source heat-flow recovery contract is missing: %s', contract_path);
    contract = jsondecode(fileread(contract_path));
    assert(strcmp(contract.schema, ...
        'heatdrive_ecc_source_heatflow_recovery_v1'), ...
        'HeatDriveECC:UnsupportedSourceRecoveryContract', ...
        'Unsupported source heat-flow recovery schema: %s', contract.schema);
    assert(logical(contract.mechanism_pass) && ...
        logical(contract.periodic_steady_state) && ~logical(contract.state_reset), ...
        'HeatDriveECC:InvalidSourceRecoveryGate', ...
        'Source heat-flow recovery must be periodic, mechanism-valid without state reset.');
    if isfield(contract, 'recovery_policy')
        policy = contract.recovery_policy;
        assert(logical(policy.state_recovery_allowed) && ...
            logical(policy.preserve_final_operating_point) && ...
            ~logical(policy.failed_results_may_resume), ...
            'HeatDriveECC:DisabledSourceRecoveryContract', ...
            'The recovery contract is superseded or does not authorize continuation.');
        assert(isfield(policy, 'complete_operating_point_restore_verified') && ...
            logical(policy.complete_operating_point_restore_verified), ...
            'HeatDriveECC:UnverifiedOperatingPointRestore', ...
            ['Continuation is disabled until an exact ModelOperatingPoint ', ...
            'contents/interface checksum restore has been demonstrated.']);
    end

    result_path = resolve_inside_repo(repo_root, contract.result_relative_path);
    checkpoint_path = resolve_inside_repo(repo_root, ...
        contract.checkpoint_relative_path);
    report_path = resolve_inside_repo(repo_root, ...
        contract.validation_report_relative_path);
    progress_path = fullfile(fileparts(fileparts(result_path)), ...
        'steady_continuation_progress.csv');
    assert(all(cellfun(@isfile, ...
        {result_path, checkpoint_path, report_path, progress_path})), ...
        'HeatDriveECC:MissingSourceRecoveryArtifact', ...
        'One or more source heat-flow recovery artifacts are missing.');
    report = fileread(report_path);
    assert(~isempty(regexp(report, ...
        '(?m)^coupled_mechanism_pass:\s*1\s*$', 'once')) && ...
        ~isempty(regexp(report, ...
        '(?m)^\s*SHEX source heat flow positive/negative fraction:.*direction pass:\s*1\s*$', ...
        'once')), 'HeatDriveECC:SourceRecoveryReportMismatch', ...
        'Source heat-flow recovery report does not satisfy its contract.');
    checkpoint = load(checkpoint_path, 'checkpoint_meta');
    assert(isfield(checkpoint, 'checkpoint_meta') && ...
        checkpoint.checkpoint_meta.cycle_count == contract.completed_cycles, ...
        'HeatDriveECC:SourceRecoveryCheckpointCycleMismatch', ...
        'Source heat-flow Operating Point cycle count differs from its contract.');

    actual_checkpoint_hash = powershell_sha256(checkpoint_path);
    assert(strcmpi(actual_checkpoint_hash, contract.checkpoint_sha256), ...
        'HeatDriveECC:SourceRecoveryCheckpointHashMismatch', ...
        'Source heat-flow Operating Point SHA-256 differs from its contract.');
    if isfield(settings, 'verify_large_result_hash') && ...
            logical(settings.verify_large_result_hash)
        actual_result_hash = powershell_sha256(result_path);
        assert(strcmpi(actual_result_hash, contract.result_sha256), ...
            'HeatDriveECC:SourceRecoveryResultHashMismatch', ...
            'Source heat-flow result SHA-256 differs from its contract.');
    end

    if isfield(contract, 'system_energy_audit_relative_path')
        audit_path = resolve_inside_repo(repo_root, ...
            contract.system_energy_audit_relative_path);
        assert(isfile(audit_path), ...
            'HeatDriveECC:MissingSystemEnergyRecoveryAudit', ...
            'System-energy recovery audit is missing: %s', audit_path);
        audit = jsondecode(fileread(audit_path));
        assert(logical(audit.production_pass) && ...
            logical(audit.modeled_thermal_closure_pass) && ...
            logical(audit.fluid_mass_conservation_pass), ...
            'HeatDriveECC:SystemEnergyRecoveryGateMismatch', ...
            'System-energy authority does not satisfy its production gates.');
    else
        audit_path = '';
    end

    authority = struct( ...
        'schema', contract.schema, ...
        'contract_path', contract_path, ...
        'result_path', result_path, ...
        'checkpoint_path', checkpoint_path, ...
        'report_path', report_path, ...
        'progress_path', progress_path, ...
        'audit_path', audit_path, ...
        'result_sha256', contract.result_sha256, ...
        'checkpoint_sha256', contract.checkpoint_sha256, ...
        'completed_cycles', contract.completed_cycles, ...
        'mechanism_pass', true, ...
        'periodic_steady_state', logical(contract.periodic_steady_state));
end

function hash = powershell_sha256(path)
    escaped = strrep(path, '''', '''''');
    script = sprintf([ ...
        '$s=[IO.File]::OpenRead(''%s'');try{', ...
        '$h=[Security.Cryptography.SHA256]::Create();', ...
        '[BitConverter]::ToString($h.ComputeHash($s)).Replace(''-'','''')', ...
        '}finally{$s.Dispose()}'], escaped);
    encoded = matlab.net.base64encode(unicode2native(script, 'UTF-16LE'));
    command = sprintf( ...
        'powershell -NoProfile -NonInteractive -EncodedCommand %s', encoded);
    [status, output] = system(command);
    assert(status == 0, 'HeatDriveECC:SourceRecoveryHashCommandFailed', ...
        'Unable to compute SHA-256 for %s.', path);
    hash = upper(strtrim(output));
end

function path = resolve_inside_repo(repo_root, relative_path)
    relative_path = strrep(char(string(relative_path)), '/', filesep);
    path = char(java.io.File(fullfile(repo_root, relative_path)).getCanonicalPath());
    canonical_root = char(java.io.File(repo_root).getCanonicalPath());
    assert(startsWith(lower(path), [lower(canonical_root), filesep]), ...
        'HeatDriveECC:SourceRecoveryPathEscape', ...
        'Source recovery path escapes the repository: %s', relative_path);
end

function audit = Audit_HeatDriveECC_OperatingPointRestore( ...
        result_path, checkpoint_path, output_path, diagnose_mismatch)
% Verify that a saved ModelOperatingPoint restores with strict checksums.

    if nargin < 3 || isempty(output_path)
        output_path = fullfile(fileparts(checkpoint_path), ...
            'operating_point_strict_restore_audit.json');
    end
    if nargin < 4
        diagnose_mismatch = false;
    end
    result_path = char(string(result_path));
    checkpoint_path = char(string(checkpoint_path));
    output_path = char(string(output_path));
    assert(isfile(result_path) && isfile(checkpoint_path), ...
        'HeatDriveECC:OperatingPointAuditInputMissing', ...
        'Result or checkpoint is missing.');

    prior = load(result_path, 'options', 'physical');
    checkpoint = load(checkpoint_path, 'operating_point', 'checkpoint_meta');
    assert(all(isfield(prior, {'options','physical'})) && ...
        all(isfield(checkpoint, {'operating_point','checkpoint_meta'})), ...
        'HeatDriveECC:OperatingPointAuditInputInvalid', ...
        'Result or checkpoint does not contain the required variables.');

    audit = audit_template(result_path, checkpoint_path, prior, checkpoint);
    try
        [model_name, options] = ...
            Build_HeatDriveECC_EighthRound_Simulink_Model(prior.options);
        cleanup = onCleanup(@() close_without_saving(model_name));
        assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
        stop_time_s = checkpoint.checkpoint_meta.time_s + ...
            options.simulation.fixed_step_s;
        sim_in = Simulink.SimulationInput(model_name);
        sim_in = sim_in.setModelParameter( ...
            'StartTime', '0', ...
            'StopTime', num2str(stop_time_s, '%.15g'), ...
            'Solver', options.simulation.solver, ...
            'FixedStep', num2str(options.simulation.fixed_step_s, '%.15g'), ...
            'SimulationMode', options.simulation.mode, ...
            'CaptureErrors', 'on', ...
            'ReturnWorkspaceOutputs', 'on', ...
            'SaveTime', 'off', ...
            'SaveOutput', 'off', ...
            'SignalLogging', 'off', ...
            'SimscapeLogLimitData', 'on', ...
            'SimscapeLogDataHistory', max(2, ceil(options.schedule.tau_cycle_s / ...
                options.simulation.fixed_step_s) + 2), ...
            'SaveFinalState', 'on', 'FinalStateName', 'xFinal', ...
            'SaveOperatingPoint', 'on', ...
            'OperatingPointContentsChecksumMismatchMsg', 'error', ...
            'OperatingPointInterfaceChecksumMismatchMsg', 'error');
        sim_in = sim_in.setVariable('EIGHTH_ROUND_OPTIONS', options);
        sim_in = sim_in.setInitialState(checkpoint.operating_point);
        sim_out = sim(sim_in);
        audit.error_message = char(string(sim_out.ErrorMessage));
        audit.strict_restore_pass = isempty(audit.error_message);
        audit.complete_operating_point_restore_verified = ...
            audit.strict_restore_pass;
        if ~audit.strict_restore_pass && diagnose_mismatch
            % A one-step diagnostic may identify differences. Its state is
            % discarded and can never turn a failed strict audit into a pass.
            probe = sim_in.setModelParameter( ...
                'OperatingPointContentsChecksumMismatchMsg', 'warning', ...
                'OperatingPointInterfaceChecksumMismatchMsg', 'warning');
            probe_out = sim(probe);
            audit.partial_diagnostic_executed = true;
            audit.partial_diagnostic_error = char(string(probe_out.ErrorMessage));
            info = probe_out.SimulationMetadata.ModelInfo;
            if isfield(info, 'OperatingPointMismatches')
                audit.partial_diagnostic_mismatches = ...
                    evalc('disp(info.OperatingPointMismatches)');
            end
            clear probe_out
        end
        clear cleanup
    catch exception
        audit.error_identifier = exception.identifier;
        audit.error_message = exception.message;
    end
    audit.contents_checksum_mismatch_detected = any(contains(lower( ...
        audit.error_message), {'checksum','校验和'})) || contains( ...
        audit.error_message, '不同于生成工作点');
    audit.failed_result_may_resume = false;
    write_json(output_path, audit);
    fprintf(['OPERATING_POINT_STRICT_RESTORE_PASS=%d ', ...
        'contents_mismatch=%d output=%s\n'], ...
        audit.strict_restore_pass, ...
        audit.contents_checksum_mismatch_detected, output_path);
end

function audit = audit_template(result_path, checkpoint_path, prior, checkpoint)
    audit = struct( ...
        'schema', 'heatdrive_ecc_operating_point_restore_audit_v2', ...
        'generated_at', char(datetime('now', 'TimeZone', 'local')), ...
        'result_path', result_path, ...
        'checkpoint_path', checkpoint_path, ...
        'result_cycles', prior.options.cycle_count, ...
        'result_end_time_s', prior.physical.time_s(end), ...
        'checkpoint_time_s', checkpoint.checkpoint_meta.time_s, ...
        'diagnostic_policy', 'contents=error; interface=error', ...
        'production_logging_and_final_state_settings_matched', true, ...
        'partial_diagnostic_executed', false, ...
        'partial_diagnostic_error', '', 'partial_diagnostic_mismatches', '', ...
        'strict_restore_pass', false, ...
        'complete_operating_point_restore_verified', false, ...
        'contents_checksum_mismatch_detected', false, ...
        'error_identifier', '', 'error_message', '', ...
        'failed_result_may_resume', false);
end

function write_json(path, value)
    parent = fileparts(path);
    if ~isempty(parent) && ~isfolder(parent)
        mkdir(parent);
    end
    fid = fopen(path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:OperatingPointAuditWriteFailed', ...
        'Cannot write %s.', path);
    cleanup = onCleanup(@() fclose(fid));
    fwrite(fid, jsonencode(value, 'PrettyPrint', true), 'char');
    fwrite(fid, newline, 'char');
    clear cleanup
end

function close_without_saving(model_name)
    if ~isempty(model_name) && bdIsLoaded(model_name)
        set_param(model_name, 'Dirty', 'off');
        close_system(model_name, 0);
    end
end

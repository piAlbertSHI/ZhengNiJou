function record=Run_HeatDriveECC_C62ObservationPreflight(output_root,contract_path,python)
% Prepare the original C62 model, then execute only the explicit split comparison.
    repo=fileparts(fileparts(mfilename('fullpath')));workspace=fileparts(repo);
    assert(~isfolder(output_root) && ~isfile([output_root,'.preflight_config.json']),'Never overwrite preflight evidence.');
    [status,dirty]=system(sprintf('git -C "%s" status --porcelain',workspace));
    assert(status==0 && isempty(strtrim(dirty)),'Run only the clean managed execution checkout.');
    pointer=jsondecode(fileread(contract_path));source=fullfile(pointer.execution_repo,pointer.source_root_relative);
    assert(pointer.total_cycles==62 && pointer.snapshot_time_s==620 && pointer.model_native_history_cap_cycles==2 && ...
        ~pointer.native_history_cap_change_allowed && ~pointer.production_recovery_allowed && ...
        ~pointer.outer_solve_eligible,'Only the unchanged C62 diagnostic may enter this experiment.');
    main_repo=fileparts(fileparts(contract_path));
    verified=fullfile(main_repo,pointer.qualification_root_relative_to_main_repo);
    Load_HeatDriveECC_LatestDiagnosticEndpoint(struct('restore_source_root',source,'restore_verification_root',verified));
    config=jsondecode(fileread([source,'.resumed_config.json']));
    physical={'Build_HeatDriveECC_EighthRound_Defaults.m','Build_HeatDriveECC_EighthRound_Simulink_Model.m', ...
        'heatdrive_ecc_coupled_se21.slx','Integrate_HeatDriveECC_Constitutive21_Interface.m', ...
        'HeatDriveECC_ConstitutiveStateVectorStep21.m','HeatDriveECC_ConstitutiveCompatibilityStep51.m', ...
        'HeatDriveECC_ConstitutiveStateVectorStep21_StableDiagnostic.m', ...
        'Initialize_HeatDriveECC_ConstitutiveVector21.m','Initialize_HeatDriveECC_EighthRound_State.m', ...
        'Instrument_HeatDriveECC_PumpPressureProbes.m','Instrument_HeatDriveECC_Stage4ControllerProbes.m', ...
        'Configure_HeatDriveECC_PressureCommandDomain.m','HeatDriveECC_PressureCommandInterval.m', ...
        'verification/Configure_HeatDriveECC_DistributedPressureFeedforward.m', ...
        'verification/Build_HeatDriveECC_DistributedPressureEnvelope.m', ...
        'verification/Build_HeatDriveECC_IndependentColdBranchOverrides.m', ...
        'verification/Configure_HeatDriveECC_DiagnosticStateCapture.m', ...
        'verification/Configure_HeatDriveECC_SEReferenceClosure.m', ...
        'verification/Configure_HeatDriveECC_PressureOnlyInventoryMap.m', ...
        'verification/simscape_inventory_pressure_only/+ecc_inventory_pressure_only/conservative_chamber.ssc', ...
        'verification/simscape_buffer_coupled_offset/+ecc_buffer_coupled_offset/conservative_buffer.ssc', ...
        'verification/Build_HeatDriveECC_ColdInitialFluxCompensation.m', ...
        'verification/Build_HeatDriveECC_ColdInventoryTargets.m'};
    paths=strjoin(cellfun(@(p) ['"gx101r1_R69_remote/',p,'"'],physical,'UniformOutput',false),' ');
    [status,~]=system(sprintf('git -C "%s" diff --quiet %s HEAD -- %s',workspace,pointer.source_producer,paths));
    assert(status==0,'A plant/command/state equation changed; the observation preflight must not disguise it.');
    config.repo_root=repo;config.output_root=output_root;
    config.duration_s=200;config.cycle_count=20;config.diagnostic_arm='native';
    config.diagnostic_state_options.restore_source_root=source;
    config.diagnostic_state_options.restore_verification_root=verified;
    assert(~isfield(config,'diagnostic_buffer_factor_options'),'No geometry experiment may enter C62.');
    config.diagnostic_observation_options=struct('mode','split_preflight','python_executable',python, ...
        'source_contract_path',contract_path);
    path=[output_root,'.preflight_config.json'];fid=fopen(path,'w','n','UTF-8');assert(fid>=0);
    fprintf(fid,'%s\n',jsonencode(config,'PrettyPrint',true));fclose(fid);
    record=Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(path);
    assert(record.observation_preflight_pass && ~record.requested_arm_collection_pass && ...
        ~record.checkpoint_saved && ~record.production_recovery_allowed, ...
        'A comparison must not masquerade as a twenty-cycle continuation.');
    fprintf('FINAL_JSON=%s\n',jsonencode(record.observation_preflight));
end

function record = Audit_HeatDriveECC_SavedPeriodicity(mechanism_root, output_root)
% Exact original production statistics on the saved pair, never a ten-cycle claim.
    assert(~isfolder(output_root), 'Never overwrite a periodicity decision.');
    receipt_file = fullfile(mechanism_root, 'saved_mechanism_audit.json');
    receipt = jsondecode(fileread(receipt_file));
    assert(receipt.original_production_predicates_evaluated && receipt.exact_saved_window_pass && ...
        receipt.mechanism_pass && ~receipt.simulation_executed && ~receipt.operating_point_loaded, ...
        'Require a passed read-only original mechanism audit.');
    source = receipt.source_root;
    assert(strcmp(file_hash(fullfile(source,'cold_chamber_execution.json')),receipt.source_execution_sha256) && ...
        strcmp(file_hash(fullfile(source,'native','observations.mat')),receipt.source_observation_sha256) && ...
        strcmp(file_hash(fullfile(source,'native','configuration.mat')),receipt.source_configuration_sha256), ...
        'Changed source trajectory.');
    view_file = fullfile(mechanism_root, 'mechanism_view.mat');
    saved = load(view_file, 'physical', 'options', 'provenance');
    configured = load(fullfile(source,'native','configuration.mat'),'options');
    assert(isequaln(saved.options,configured.options), 'Changed saved analysis options.');
    raw = load(fullfile(source,'native','observations.mat'),'signals','thermal_boundary_signals');
    observation = Slice_HeatDriveECC_SavedMechanismObservation(raw, ...
        receipt.analysis_window.absolute_start_s,receipt.analysis_window.absolute_stop_s, ...
        configured.options.simulation.fixed_step_s);
    expected = Extract_HeatDriveECC_PhysicalLogs(observation,configured.options,'',false);
    expected.authority = 'physical_simscape_to_workspace_logs';
    expected.legacy_surrogate_used_for_results = false;
    expected.sim_call_count = 1;
    expected.walltime_s = NaN;
    assert(isequaln(saved.physical,expected), 'Saved view differs from immutable source extraction.');
    view = Make_HeatDriveECC_MechanismWindow(saved.physical, saved.options, saved.provenance, output_root);
    assert(view.options.cycle_count == 2 && ...
        isequaln(view.analysis_window, receipt.analysis_window), 'Wrong saved analysis window.');
    summary = Summarize_HeatDriveECC_EighthRound_Output(view.physical, view.options);
    p = summary.performance;
    values = [p.last_cycle_endpoint_drift_K, ...
        p.last_cycle_same_phase_temperature_p99_drift_K, p.last_cycle_same_phase_temperature_rms_drift_K, ...
        p.last_cycle_phase_drift, p.last_cycle_same_phase_phase_p99_drift, p.last_cycle_same_phase_phase_rms_drift];
    limits = [p.periodic_endpoint_limit_K, p.periodic_same_phase_temperature_p99_limit_K, ...
        p.periodic_same_phase_temperature_rms_limit_K, p.periodic_phase_limit, ...
        p.periodic_same_phase_phase_p99_limit, p.periodic_same_phase_phase_rms_limit];
    names = {'temperature_endpoint','temperature_p99','temperature_rms','phase_extrema','phase_p99','phase_rms'};
    predicates = struct();
    for k = 1:numel(names)
        predicates.(names{k}) = struct('value',values(k),'limit',limits(k),'pass_gate',values(k)<=limits(k));
    end
    assert(~p.periodic_steady_state && p.periodic_window_cycles == 2, ...
        'A two-cycle view cannot qualify the production ten-cycle window.');
    record = struct('schema','heatdrive_ecc_saved_production_periodicity_v1', ...
        'source_execution_commit',receipt.source_execution_commit, ...
        'source_execution_sha256',receipt.source_execution_sha256, ...
        'source_observation_sha256',receipt.source_observation_sha256, ...
        'source_configuration_sha256',receipt.source_configuration_sha256, ...
        'mechanism_receipt_sha256',file_hash(receipt_file), 'mechanism_view_sha256',file_hash(view_file), ...
        'original_summarizer_sha256',file_hash(which('Summarize_HeatDriveECC_EighthRound_Output')), ...
        'original_summarizer_used',true,'physical_tolerances_changed',false, ...
        'simulation_executed',false,'operating_point_loaded',false,'analysis_window',view.analysis_window, ...
        'periodic_window_cycles',p.periodic_window_cycles,'predicates',predicates, ...
        'last_pair_predicates_pass',all(values<=limits), ...
        'diagnostic_temperature_peak_K',p.last_cycle_same_phase_temperature_drift_K, ...
        'diagnostic_phase_peak',p.last_cycle_same_phase_phase_drift, ...
        'ten_cycle_production_window_verified',false,'periodic_steady_state_verified',false, ...
        'production_recovery_allowed',false,'table4_reproduction_claim',false, ...
        'interpretation','Exact original mean-endpoint / cycle-phase-extrema / nearest-rank p99 statistics; two-cycle diagnostic only.');
    mkdir(output_root);
    fid=fopen(fullfile(output_root,'saved_periodicity_audit.json'),'w','n','UTF-8');
    assert(fid>=0,'Cannot save periodicity receipt.');
    cleanup=onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(record,'PrettyPrint',true));
    fprintf('FINAL_JSON=%s\n',jsonencode(record));
end

function result = file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');
    fid=fopen(file,'rb'); assert(fid>=0,'Missing immutable evidence.');
    cleanup=onCleanup(@() fclose(fid));
    while ~feof(fid), digest.update(fread(fid,8*1024*1024,'*uint8')); end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

function record=Audit_HeatDriveECC_NativeLedgerPersistence(file,native,source_traces,boundary_metadata)
% Exact public numerical evidence roundtrip, not vendor-object serialization.
    persisted=load(file,'native','source_traces','boundary_metadata');
    assert(isequaln(persisted.native,native) && ...
        isequaln(persisted.source_traces,source_traces) && ...
        isequaln(persisted.boundary_metadata,boundary_metadata), ...
        'Actual native/source numerical evidence changed during MAT roundtrip.');
    assert(numel(native)>0 && numel(source_traces)>0);
    record=struct('schema','heatdrive_ecc_native_ledger_persistence_v1', ...
        'method','public named native series to numeric MAT save/load', ...
        'native_trace_count',numel(native),'source_trace_count',numel(source_traces), ...
        'all_trace_values_clock_units_metadata_exact',true, ...
        'native_object_archive_required',false,'scientific_ledger_pass_claimed',false, ...
        'production_recovery_allowed',false);
end

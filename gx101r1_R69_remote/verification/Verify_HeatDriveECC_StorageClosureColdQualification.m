function result = Verify_HeatDriveECC_StorageClosureColdQualification(audit_path)
    original=jsondecode(fileread(audit_path));
    assert(Evaluate_HeatDriveECC_StorageClosureColdQualification(original));
    contract=Require_HeatDriveECC_StorageClosureColdSource(audit_path);
    assert(contract.new_cold_two_cycle_test_allowed && ~contract.state_import_allowed);
    changes={ ...
        @(a) setfield(a,'production_recovery_allowed',true), ...
        @(a) setfield(a,'outer_solve_eligible',true), ...
        @(a) setfield(a,'initial_coordinates','strict_coordinate_match_count',203), ...
        @(a) setfield(a,'initial_coordinates','own_actual_coordinates_match_targets',false), ...
        @(a) setfield(a,'cases',{2},'local_inventory_gates',false(1,6)), ...
        @(a) setfield(a,'cases',{2},'model_energy_balance','model_equation_energy_closure_pass',false), ...
        @(a) setfield(a,'cases',{2},'runtime_mechanism_subset','selected_flow_gates_pass',false), ...
        @(a) setfield(a,'cases',{2},'runtime_mechanism_subset','pressure_boundary','pressure_range_gate',false), ...
        @(a) setfield(a,'cases',{2},'compiled_chamber_state_tags',{1},'isDifferential',false)};
    for k=1:numel(changes)
        rejected=false;
        try,Evaluate_HeatDriveECC_StorageClosureColdQualification(changes{k}(original));catch,rejected=true;end
        assert(rejected,'Failed or overstated C1 physical evidence was accepted.');
    end
    result=struct('positive_cases',2,'negative_cases',numel(changes),'pass',true);
    fprintf('%s\n',jsonencode(result));
end

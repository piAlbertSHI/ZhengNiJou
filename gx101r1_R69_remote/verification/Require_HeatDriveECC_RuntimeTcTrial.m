function Require_HeatDriveECC_RuntimeTcTrial(t)
% Keep the compatibility probe distinct from the bounded physical search.
    if strcmp(t.schema,'heatdrive_ecc_runtime_Tc_intervention_v1')
        assert(t.source_Tc_K==276.95 && abs(t.candidate_Tc_K-276.95)<=.1+1e-12);
    else
        assert(strcmp(t.schema,'heatdrive_ecc_runtime_Tc_intervention_v2'));
        p=t.search_policy;
        assert(strcmp(p.schema,'heatdrive_ecc_runtime_Tc_bounded_search_v1') && ...
            p.minimum_Tc_K==255.05 && p.maximum_Tc_K==393.15 && p.maximum_step_K==2 && ...
            p.fluid_minimum_K==255.05 && p.fluid_maximum_K==393.15 && ...
            t.source_Tc_K>=p.minimum_Tc_K && t.source_Tc_K<=p.maximum_Tc_K && ...
            t.candidate_Tc_K>=p.minimum_Tc_K && t.candidate_Tc_K<=p.maximum_Tc_K && ...
            abs(t.candidate_Tc_K-t.source_Tc_K)<=p.maximum_step_K+1e-12 && ...
            t.transition_time_s>=520 && p.source_public_periodic_pass && p.source_target_precision_pass);
    end
    assert(isscalar(t.candidate_Tc_K) && isfinite(t.candidate_Tc_K) && ...
        isscalar(t.source_Tc_K) && isfinite(t.source_Tc_K) && ...
        abs(t.candidate_Tc_K-t.source_Tc_K)>.001 && t.minimum_transition_cycles==12 && ...
        t.only_runtime_temperature_variable_changed && ~t.source_state_edited && ~t.old_model_OP_imported);
end

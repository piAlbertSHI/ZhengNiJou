function record=Run_HeatDriveECC_BoundedRebuiltPreflight(source_root,output_root)
% Use the passed C2 OP for state-interface diagnosis, not a repeated cold seed run.
    assert(~isfolder(output_root));
    candidate=Require_HeatDriveECC_BoundedStateCandidate(source_root);
    config=jsondecode(fileread([source_root,'.state_preflight_config.json']));
    execution=jsondecode(fileread(fullfile(source_root,'cold_chamber_execution.json')));
    workspace=fileparts(config.repo_root);
    [status,dirty]=system(sprintf('git -C "%s" status --porcelain',workspace));
    assert(status==0 && isempty(strtrim(dirty)));
    physical={'Build_HeatDriveECC_EighthRound_Defaults.m','Build_HeatDriveECC_EighthRound_Simulink_Model.m', ...
        'Integrate_HeatDriveECC_Constitutive21_Interface.m','heatdrive_ecc_coupled_se21.slx', ...
        'Audit_HeatDriveECC_ManifoldMask.m','Configure_HeatDriveECC_PressureCommandDomain.m', ...
        'HeatDriveECC_PressureCommandInterval.m', ...
        'verification/Configure_HeatDriveECC_DistributedPressureFeedforward.m', ...
        'verification/Build_HeatDriveECC_DistributedPressureEnvelope.m', ...
        'verification/Build_HeatDriveECC_IndependentColdBranchOverrides.m', ...
        'verification/Configure_HeatDriveECC_DiagnosticStateCapture.m', ...
        'Instrument_HeatDriveECC_PumpPressureProbes.m','Instrument_HeatDriveECC_Stage4ControllerProbes.m'};
    paths=strjoin(cellfun(@(p) ['"gx101r1_R69_remote/',p,'"'],physical,'UniformOutput',false),' ');
    [status,~]=system(sprintf('git -C "%s" diff --quiet %s HEAD -- %s',workspace,execution.execution_commit,paths));
    assert(status==0,'Only observation/persistence repairs may differ from the candidate model.');
    config.output_root=output_root;
    config.diagnostic_state_options=struct('mode','rebuilt_cycle_preflight', ...
        'command_horizon_cycles',200,'restore_source_root',source_root);
    path=[output_root,'.rebuilt_config.json'];assert(~isfile(path));
    fid=fopen(path,'w','n','UTF-8');assert(fid>=0);
    fprintf(fid,'%s\n',jsonencode(config,'PrettyPrint',true));fclose(fid);
    record=Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(path);
    assert(record.rebuilt_cycle_preflight_pass && ~record.production_recovery_allowed);
    fprintf('%s\n',jsonencode(struct('bounded_full_cycle_restore_pass',true, ...
        'candidate_contract',candidate,'production_recovery_allowed',false)));
end

function Assert_HeatDriveECC_InventoryRecoveryUse(contract, settings)
% An unresolved inventory equation audit permits diagnostics, not production.
    if ~isfield(contract, 'control_volume_basis_review'), return; end
    review = contract.control_volume_basis_review;
    assert(isfield(review, 'production_continuation_allowed') && ...
        islogical(review.production_continuation_allowed) && ...
        isscalar(review.production_continuation_allowed), ...
        'HeatDriveECC:InvalidInventoryRecoveryPolicy', ...
        'Inventory review must declare a scalar production permission.');
    if review.production_continuation_allowed, return; end
    diagnostic = isfield(settings, 'recovery_use') && ...
        strcmp(settings.recovery_use, 'inventory_diagnostic') && ...
        isfield(review, 'strict_inventory_diagnostic_allowed') && ...
        isequal(review.strict_inventory_diagnostic_allowed, true);
    assert(diagnostic, 'HeatDriveECC:InventoryBasisUnderReview', ...
        ['Production continuation is suspended pending equation-matched ', ...
        'inventory accounting. Only an explicit strict inventory diagnostic ', ...
        'may use this source; it cannot promote its Operating Point.']);
end

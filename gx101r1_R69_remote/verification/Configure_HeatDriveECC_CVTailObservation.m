function record=Configure_HeatDriveECC_CVTailObservation(model,stop,retained)
% Passive bounded sinks only: no sample-time, equation, controller or IC change.
    assert(ismember(stop,[20 200]) && ismember(retained,[10 20]) && stop>retained);
    native_points=round(retained/.001)+2;
    set_param(model,'SimscapeLogLimitData','on','SimscapeLogDataHistory',native_points);
    sinks=find_system(model,'LookUnderMasks','all','FollowLinks','on','Type','Block','BlockType','ToWorkspace');
    names=cellfun(@(p)get_param(p,'VariableName'),sinks,'UniformOutput',false);
    coarse={'ECC_constitutive21_output','SMA_Tx21_internal','SE_Tx21_internal', ...
        'cv_PI_sma_state','cv_PI_se_stage2_state','stage4_integrator_state', ...
        'mass_flow_sma_stage13_kgps','mass_flow_v1_cold_inlet_kgps','mass_flow_v4_hot_inlet_kgps', ...
        'Qdot_cold_sink_mass_to_hx_pipe_W','shex_source_heat_flow_W', ...
        'sma_hold_pipe_node01_fluid_temp_out','sma_hold_pipe_node11_fluid_temp_out','sma_hold_pipe_node21_fluid_temp_out'};
    assert(isempty(setdiff(coarse,names)) && numel(unique(names))==numel(names));
    records=cell(size(sinks));coarse_records=cell(size(coarse));
    % Event duplicates are retained too; the final native-grid coverage check
    % rejects an insufficient sink history rather than inventing held values.
    workspace_points=2*round(retained/.001)+2;
    for k=1:numel(sinks)
        p=sinks{k};sample=get_param(p,'SampleTime');decimation=get_param(p,'Decimation');
        records{k}=struct('block_path',p,'workspace_variable',names{k}, ...
            'prior_MaxDataPoints',get_param(p,'MaxDataPoints'),'sample_time',sample,'decimation',decimation);
        set_param(p,'MaxDataPoints',num2str(workspace_points));
        assert(strcmp(get_param(p,'SampleTime'),sample) && strcmp(get_param(p,'Decimation'),decimation));
    end
    for k=1:numel(coarse)
        old=sinks(strcmp(names,coarse{k}));assert(isscalar(old));old=old{1};
        parent=get_param(old,'Parent');name=['coarse_' coarse{k}];p=[parent '/ToWorkspace_' name];
        assert(getSimulinkBlockHandle(p)<0);
        add_block('simulink/Sinks/To Workspace',p,'VariableName',name, ...
            'SaveFormat','Structure With Time','SampleTime',get_param(old,'SampleTime'), ...
            'Decimation','1000','MaxDataPoints','inf');
        a=get_param(old,'PortHandles');line=get_param(a.Inport(1),'Line');assert(line>=0);
        source=get_param(line,'SrcPortHandle');b=get_param(p,'PortHandles');
        add_line(parent,source,b.Inport(1),'autorouting','on');
        coarse_records{k}=struct('source_sink',old,'workspace_variable',name,'source_variable',coarse{k}, ...
            'decimation',1000,'actual_time_stamps_not_uniform_seconds',true);
    end
    record=struct('schema','heatdrive_ecc_passive_CV_tail_observation_v1', ...
        'start_s',stop-retained,'stop_s',stop,'retained_duration_s',retained, ...
        'native_history_points',native_points,'workspace_history_points',workspace_points, ...
        'workspace_sink_changes',{records},'coarse_probes',{coarse_records}, ...
        'coarse_workspace_variables',{cellfun(@(r)r.workspace_variable,coarse_records,'UniformOutput',false)}, ...
        'equations_sample_times_controllers_or_initial_targets_modified',false, ...
        'full_early_cycle_mechanism_coverage_claimed',false,'time_interpolation_performed',false);
end

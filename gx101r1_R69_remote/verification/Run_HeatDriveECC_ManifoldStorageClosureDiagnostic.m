function study = Run_HeatDriveECC_ManifoldStorageClosureDiagnostic(baseline_config_path, reference_audit_path, output_root)
% Reuse the coherent C1 baseline; change only the manifold stored-density law.
    baseline_config_path=char(java.io.File(baseline_config_path).getCanonicalPath());
    output_root=char(java.io.File(output_root).getCanonicalPath());
    assert(~isfolder(output_root),'Never overwrite a storage-closure experiment.');
    config=jsondecode(fileread(baseline_config_path));
    baseline_root=config.output_root;
    baseline=jsondecode(fileread(fullfile(baseline_root,'cold_chamber_execution.json')));
    audit=jsondecode(fileread(reference_audit_path));
    manifest=jsondecode(fileread(fullfile(audit.source_root,'reference_execution.json')));
    assert(audit.two_cycle_cold_followup_allowed && ~audit.production_recovery_allowed && ...
        strcmp(manifest.candidate_root,baseline_root) && ...
        strcmp(file_hash(baseline_config_path),manifest.candidate_config_sha256) && ...
        strcmp(file_hash(fullfile(baseline_root,'native','observations.mat')),audit.cases(2).input_sha256.observations_mat), ...
        'Require the existing physically passing coherent C1 baseline.');
    assert(baseline.requested_arm_collection_pass && isempty(baseline.error_message) && ...
        baseline.start_time_s==0 && baseline.stop_time_s==10 && ~baseline.checkpoint_saved && ...
        ~baseline.production_recovery_allowed && ~baseline.c200_state_imported && ...
        strcmp(config.diagnostic_state_options.mode,'off') && config.cycle_count==1 && ...
        config.diagnostic_inventory_options.volume_factor==1 && ...
        strcmp(config.diagnostic_se_reference_options.mode,'coherent_envelope'), ...
        'Only a state-free nominal-volume common-reference cold baseline can be reused.');
    mkdir(output_root);
    config.output_root=fullfile(output_root,'candidate');
    config.diagnostic_inventory_options=struct('storage_closure','pressure_only_density');
    path=fullfile(output_root,'candidate_config.json');write_json(path,config);
    study=struct('schema','heatdrive_ecc_manifold_storage_closure_experiment_v1','status','running', ...
        'baseline_root',baseline_root,'baseline_config_path',baseline_config_path, ...
        'baseline_config_sha256',file_hash(baseline_config_path), ...
        'baseline_execution_sha256',file_hash(fullfile(baseline_root,'cold_chamber_execution.json')), ...
        'baseline_reused',true,'candidate_root',config.output_root,'candidate_config_sha256',file_hash(path), ...
        'reference_audit_sha256',file_hash(reference_audit_path), ...
        'geometry_changed',false,'property_tables_changed',false,'controls_changed',false, ...
        'source_state_loaded',false,'existing_OP_imported',false,'production_recovery_allowed',false, ...
        'real_fluid_EOS_claim',false,'paper_exact_accessory_model_claim',false);
    try
        result=Run_HeatDriveECC_IndependentColdDiagnosticFromConfig(path);
        assert(result.requested_arm_collection_pass && isempty(result.error_message),'Storage-closure collection failed.');
        study.status='collected_requires_formulation_specific_physical_comparison';
        study.candidate_execution_sha256=file_hash(fullfile(config.output_root,'cold_chamber_execution.json'));
    catch exception
        study.status='failed_requires_diagnosis';study.error_message=getReport(exception,'extended','hyperlinks','off');
        write_json(fullfile(output_root,'storage_closure_execution.json'),study);rethrow(exception);
    end
    write_json(fullfile(output_root,'storage_closure_execution.json'),study);
    fprintf('%s\n',jsonencode(study));
end

function write_json(path,record)
    fid=fopen(path,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@() fclose(fid));
    fprintf(fid,'%s\n',jsonencode(record,'PrettyPrint',true));
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

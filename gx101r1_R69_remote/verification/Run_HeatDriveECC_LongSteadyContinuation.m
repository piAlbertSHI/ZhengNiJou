function state = Run_HeatDriveECC_LongSteadyContinuation(settings)
% Run checkpointed physical Simscape segments until steady or near steady.

    if nargin < 1
        settings = struct();
    end
    root_dir = fileparts(fileparts(mfilename('fullpath')));
    defaults = struct( ...
        'output_root', fullfile(root_dir, 'outputs', ...
            'qian_coupled_long_steady'), ...
        'segment_cycles', 20, ...
        'maximum_cycles', 200, ...
        'initial_prior_result_path', '', ...
        'initial_checkpoint_path', '', ...
        'near_endpoint_drift_K', 0.10, ...
        'near_same_phase_temperature_drift_K', 0.10, ...
        'near_same_phase_phase_drift', 2.0e-4, ...
        'required_consecutive_near_segments', 2, ...
        'generate_intermediate_figures', false, ...
        'capture_internal_states', false, ...
        'compact_superseded_segments', false, ...
        'resume_existing_state', true, ...
        'initial_state_policy', 'unrestricted', ...
        'mainline_contract_path', '', ...
        'model_overrides', struct(), ...
        'checkpoint_transition_fields', {{}}, ...
        'checkpoint_append_signal_fields', {{}}, ...
        'system_overrides', struct(), ...
        'branch_overrides', struct());
    settings = merge_structs(defaults, settings);
    validate_settings(settings);
    if ~exist(settings.output_root, 'dir')
        mkdir(settings.output_root);
    end

    progress_path = fullfile(settings.output_root, ...
        'steady_continuation_progress.csv');
    state_path = fullfile(settings.output_root, ...
        'steady_continuation_state.mat');
    if logical(settings.resume_existing_state) && exist(state_path, 'file')
        [state, current_cycles, prior_result_path, checkpoint_path] = ...
            restore_existing_state(state_path, settings, root_dir, ...
            progress_path);
        fprintf(['STEADY_CONTINUATION_RESUME current=%d ', ...
            'prior=%s checkpoint=%s\n'], current_cycles, ...
            prior_result_path, checkpoint_path);
    else
        [current_cycles, prior_result_path, checkpoint_path] = ...
            resolve_initial_state(settings);
        state = struct( ...
            'status', 'running', ...
            'stop_reason', '', ...
            'current_cycles', current_cycles, ...
            'prior_result_path', prior_result_path, ...
            'checkpoint_path', checkpoint_path, ...
            'progress_path', progress_path, ...
            'state_path', state_path, ...
            'code_commit', git_head(root_dir), ...
            'started_at', char(datetime('now', 'Format', ...
                'yyyy-MM-dd HH:mm:ss')), ...
            'updated_at', '', ...
            'near_segment_count', 0, ...
            'rows', empty_progress_table());
    end
    persist_state(state_path, state, settings);

    while current_cycles < settings.maximum_cycles
        target_cycles = min(current_cycles + settings.segment_cycles, ...
            settings.maximum_cycles);
        superseded_result_path = prior_result_path;
        superseded_checkpoint_path = checkpoint_path;
        fprintf(['STEADY_SEGMENT_START prior=%d target=%d ', ...
            'time=%s\n'], current_cycles, target_cycles, ...
            char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss')));

        overrides = build_overrides(settings, target_cycles, ...
            prior_result_path, checkpoint_path);
        try
            audit = Validate_HeatDriveECC_EighthRound_Physics(overrides);
        catch ME
            state.status = 'simulation_error';
            state.stop_reason = sprintf('%s: %s', ME.identifier, ME.message);
            state.updated_at = char(datetime('now', 'Format', ...
                'yyyy-MM-dd HH:mm:ss'));
            persist_state(state_path, state, settings);
            fprintf(2, 'STEADY_SEGMENT_ERROR target=%d id=%s message=%s\n', ...
                target_cycles, ME.identifier, ME.message);
            rethrow(ME);
        end

        row = progress_row(audit, settings, current_cycles, target_cycles);
        state.rows = [state.rows; struct2table(row)];
        writetable(state.rows, progress_path);
        fprintf(['STEADY_PROGRESS total=%d segment_wall_s=%.6f ', ...
            'mechanism=%d periodic=%d near=%d endpoint_K=%.9g ', ...
            'same_phase_T_K=%.9g phase=%.9g Eq9_K=%.9g ', ...
            'SCP_W_per_g=%.9g output=%s\n'], ...
            target_cycles, row.segment_walltime_s, row.mechanism_pass, ...
            row.periodic_steady_state, row.near_steady_state, ...
            row.endpoint_drift_K, row.same_phase_temperature_drift_K, ...
            row.same_phase_phase_drift, row.eq9_lift_K, ...
            row.eq10_SCP_W_per_g, row.output_dir{1});

        state.last_attempt_cycles = target_cycles;
        state.last_attempt_result_path = audit.result.output_mat;
        state.last_attempt_checkpoint_path = audit.result.checkpoint_path;
        state.updated_at = char(datetime('now', 'Format', ...
            'yyyy-MM-dd HH:mm:ss'));

        if ~audit.passed
            state.status = 'mechanism_failure';
            state.stop_reason = ...
                ['A required physical mechanism gate failed. The attempt ', ...
                'was recorded but was not promoted to a recovery state.'];
        else
            current_cycles = target_cycles;
            prior_result_path = audit.result.output_mat;
            checkpoint_path = audit.result.checkpoint_path;
            state.current_cycles = current_cycles;
            state.prior_result_path = prior_result_path;
            state.checkpoint_path = checkpoint_path;
        end
        if audit.passed && row.periodic_steady_state
            state.status = 'periodic_steady_state';
            state.stop_reason = ...
                'All declared periodic-state drift gates passed.';
        elseif audit.passed
            if row.near_steady_state
                state.near_segment_count = state.near_segment_count + 1;
            else
                state.near_segment_count = 0;
            end
            if state.near_segment_count >= ...
                    settings.required_consecutive_near_segments
                state.status = 'near_steady_state';
                state.stop_reason = sprintf( ...
                    'Near-steady limits passed in %d consecutive segments.', ...
                    state.near_segment_count);
            end
        end
        persist_state(state_path, state, settings);
        if audit.passed && logical(settings.compact_superseded_segments)
            compact_superseded_segment(superseded_result_path, ...
                superseded_checkpoint_path, prior_result_path, ...
                checkpoint_path, settings.output_root);
        end
        clear audit

        if ~strcmp(state.status, 'running')
            break;
        end
    end

    if strcmp(state.status, 'running') && ...
            current_cycles >= settings.maximum_cycles
        state.status = 'maximum_cycles_reached';
        state.stop_reason = sprintf( ...
            'Reached the configured maximum of %d cycles.', ...
            settings.maximum_cycles);
    end
    state.updated_at = char(datetime('now', 'Format', ...
        'yyyy-MM-dd HH:mm:ss'));
    persist_state(state_path, state, settings);
    fprintf('STEADY_CONTINUATION_STOP status=%s cycles=%d reason=%s\n', ...
        state.status, state.current_cycles, state.stop_reason);
end

function [state, cycles, prior_result_path, checkpoint_path] = ...
        restore_existing_state(state_path, settings, root_dir, progress_path)
    saved = load(state_path, 'state', 'settings');
    if ~isfield(saved, 'state') || ~isfield(saved, 'settings')
        error('HeatDriveECC:LongRunInvalidExistingState', ...
            'The existing continuation state is incomplete.');
    end
    if ~isfield(saved.settings, 'capture_internal_states')
        saved.settings.capture_internal_states = false;
    end
    state = saved.state;
    required = {'status','current_cycles','prior_result_path', ...
        'checkpoint_path','rows','near_segment_count'};
    if ~all(isfield(state, required)) || ~strcmp(state.status, 'running')
        error('HeatDriveECC:LongRunExistingStateNotResumable', ...
            'Only an interrupted state with status=running may auto-resume.');
    end
    setting_names = {'segment_cycles','near_endpoint_drift_K', ...
        'near_same_phase_temperature_drift_K', ...
        'near_same_phase_phase_drift', ...
        'required_consecutive_near_segments', 'initial_state_policy', ...
        'compact_superseded_segments', ...
        'capture_internal_states', ...
        'mainline_contract_path', 'model_overrides', ...
        'checkpoint_transition_fields', ...
        'checkpoint_append_signal_fields', ...
        'system_overrides', ...
        'branch_overrides'};
    for idx = 1:numel(setting_names)
        name = setting_names{idx};
        if ~isfield(saved.settings, name) || ...
                ~isequaln(saved.settings.(name), settings.(name))
            error('HeatDriveECC:LongRunExistingSettingsMismatch', ...
                'Existing continuation setting differs: %s.', name);
        end
    end
    cycles = state.current_cycles;
    if settings.maximum_cycles < cycles
        error('HeatDriveECC:LongRunMaximumBelowCurrent', ...
            'maximum_cycles cannot be below the resumed cycle count.');
    end
    prior_result_path = char(string(state.prior_result_path));
    checkpoint_path = char(string(state.checkpoint_path));
    if ~exist(prior_result_path, 'file') || ~exist(checkpoint_path, 'file')
        error('HeatDriveECC:LongRunMissingResumeCheckpoint', ...
            'The last validated result or Operating Point is missing.');
    end
    checkpoint = load(checkpoint_path, 'checkpoint_meta');
    if ~isfield(checkpoint, 'checkpoint_meta') || ...
            checkpoint.checkpoint_meta.cycle_count ~= cycles
        error('HeatDriveECC:LongRunResumeCycleMismatch', ...
            'Existing state and Operating Point cycle counts differ.');
    end
    state.status = 'running';
    state.stop_reason = '';
    state.progress_path = progress_path;
    state.state_path = state_path;
    state.code_commit = git_head(root_dir);
    state.updated_at = char(datetime('now', 'Format', ...
        'yyyy-MM-dd HH:mm:ss'));
    if ~isempty(state.rows)
        writetable(state.rows, progress_path);
    end
end

function overrides = build_overrides(settings, target_cycles, ...
        prior_result_path, checkpoint_path)
    overrides = settings.model_overrides;
    overrides.cycle_count = target_cycles;
    overrides.outputs_dir = settings.output_root;
    overrides.simulation = struct( ...
        'mode', 'accelerator', ...
        'disable_redundant_model_logging', true, ...
        'save_final_operating_point', true, ...
        'prior_result_path', prior_result_path, ...
        'resume_checkpoint_path', checkpoint_path, ...
        'checkpoint_transition_fields', ...
            {settings.checkpoint_transition_fields}, ...
        'checkpoint_append_signal_fields', ...
            {settings.checkpoint_append_signal_fields});
    overrides.output = struct( ...
        'generate_figures', settings.generate_intermediate_figures, ...
        'capture_internal_states', settings.capture_internal_states);
    if isfield(settings, 'system_overrides') && ...
            ~isempty(fieldnames(settings.system_overrides))
        if isfield(overrides, 'system') && isstruct(overrides.system)
            overrides.system = merge_structs(overrides.system, ...
                settings.system_overrides);
        else
            overrides.system = settings.system_overrides;
        end
    end
    if isfield(settings, 'branch_overrides') && ...
            ~isempty(fieldnames(settings.branch_overrides))
        if isfield(overrides, 'branch') && isstruct(overrides.branch)
            overrides.branch = merge_structs(overrides.branch, ...
                settings.branch_overrides);
        else
            overrides.branch = settings.branch_overrides;
        end
    end
    if isfield(overrides, 'validation') && ...
            isstruct(overrides.validation)
        overrides.validation = merge_structs(overrides.validation, ...
            struct('error_on_mechanism_failure', false));
    else
        overrides.validation = struct('error_on_mechanism_failure', false);
    end
end

function row = progress_row(audit, settings, prior_cycles, target_cycles)
    p = audit.result.summary.performance;
    row = struct();
    row.prior_cycles = prior_cycles;
    row.total_cycles = target_cycles;
    row.segment_walltime_s = audit.result.physical.segment_walltime_s;
    row.cumulative_walltime_s = audit.result.physical.walltime_s;
    row.sim_call_count = audit.result.physical.sim_call_count;
    row.mechanism_pass = logical(audit.passed);
    row.all_required_pass = logical(audit.all_required_pass);
    row.periodic_steady_state = logical(p.periodic_steady_state);
    row.endpoint_drift_K = p.last_cycle_endpoint_drift_K;
    row.same_phase_temperature_drift_K = ...
        p.last_cycle_same_phase_temperature_drift_K;
    row.same_phase_phase_drift = p.last_cycle_same_phase_phase_drift;
    row.eq9_lift_K = p.temperature_lift_eq9_K;
    row.eq10_SCP_W_per_g = p.specific_cooling_eq10_W_per_g;
    row.SE_phase_swing = ...
        audit.result.summary.cycle(end).xM_SE_swing;
    row.near_steady_state = logical( ...
        row.endpoint_drift_K <= settings.near_endpoint_drift_K && ...
        row.same_phase_temperature_drift_K <= ...
            settings.near_same_phase_temperature_drift_K && ...
        row.same_phase_phase_drift <= ...
            settings.near_same_phase_phase_drift);
    row.output_dir = {audit.result.output_dir};
    row.output_mat = {audit.result.output_mat};
    row.checkpoint_path = {audit.result.checkpoint_path};
    row.completed_at = {char(datetime('now', 'Format', ...
        'yyyy-MM-dd HH:mm:ss'))};
end

function [cycles, prior_result_path, checkpoint_path] = ...
        resolve_initial_state(settings)
    prior_result_path = char(string(settings.initial_prior_result_path));
    checkpoint_path = char(string(settings.initial_checkpoint_path));
    if isempty(strtrim(prior_result_path)) && isempty(strtrim(checkpoint_path))
        policy = lower(strtrim(char(string(settings.initial_state_policy))));
        if ~ismember(policy, {'unrestricted','cold_start_no_checkpoint'})
            error('HeatDriveECC:ColdStartPolicyMismatch', ...
                ['An empty initial state is allowed only for unrestricted or ', ...
                'cold_start_no_checkpoint policy.']);
        end
        cycles = 0;
        return;
    end
    if isempty(strtrim(prior_result_path)) || isempty(strtrim(checkpoint_path))
        error('HeatDriveECC:LongRunIncompleteInitialCheckpoint', ...
            'Both initial prior result and checkpoint paths are required.');
    end
    if strcmpi(char(string(settings.initial_state_policy)), ...
            'frozen_c200_only')
        authority_settings = struct();
        if ~isempty(strtrim(char(string(settings.mainline_contract_path))))
            authority_settings.contract_path = settings.mainline_contract_path;
        end
        authority = Resolve_HeatDriveECC_MainlineAuthority( ...
            authority_settings);
        if ~same_path(prior_result_path, authority.result_path) || ...
                ~same_path(checkpoint_path, authority.checkpoint_path)
            error('HeatDriveECC:UnauthorizedInitialState', [ ...
                'This continuation requires the frozen C200 result and ', ...
                'Operating Point as its sole initial authority.']);
        end
    elseif strcmpi(char(string(settings.initial_state_policy)), ...
            'validated_recovery_contract_only')
        authority = Resolve_HeatDriveECC_SourceHeatFlowRecovery(struct( ...
            'contract_path', settings.mainline_contract_path));
        if ~same_path(prior_result_path, authority.result_path) || ...
                ~same_path(checkpoint_path, authority.checkpoint_path)
            error('HeatDriveECC:UnauthorizedSourceRecoveryState', [ ...
                'This continuation requires the source heat-flow result ', ...
                'and Operating Point named by its recovery contract.']);
        end
    elseif ~strcmpi(char(string(settings.initial_state_policy)), ...
            'unrestricted')
        error('HeatDriveECC:UnknownInitialStatePolicy', ...
            'Unsupported initial_state_policy: %s', ...
            char(string(settings.initial_state_policy)));
    end
    if ~exist(prior_result_path, 'file') || ~exist(checkpoint_path, 'file')
        error('HeatDriveECC:LongRunMissingInitialCheckpoint', ...
            'The initial prior result or checkpoint file is missing.');
    end
    checkpoint = load(checkpoint_path, 'checkpoint_meta');
    if ~isfield(checkpoint, 'checkpoint_meta') || ...
            ~isfield(checkpoint.checkpoint_meta, 'cycle_count')
        error('HeatDriveECC:LongRunInvalidInitialCheckpoint', ...
            'The initial checkpoint metadata is invalid.');
    end
    cycles = checkpoint.checkpoint_meta.cycle_count;
end

function compact_superseded_segment(result_path, checkpoint_path, ...
        replacement_result_path, replacement_checkpoint_path, output_root)
    if isempty(strtrim(char(string(result_path)))) && ...
            isempty(strtrim(char(string(checkpoint_path))))
        return
    end
    try
        root = canonical_path(output_root);
        result = canonical_path(result_path);
        checkpoint = canonical_path(checkpoint_path);
        replacement_result = canonical_path(replacement_result_path);
        replacement_checkpoint = canonical_path(replacement_checkpoint_path);
        assert(startsWith(lower(result), [lower(root), filesep]) && ...
            startsWith(lower(checkpoint), [lower(root), filesep]), ...
            'HeatDriveECC:CompactionPathEscape', ...
            'Superseded raw files must remain inside the run output root.');
        assert(~strcmpi(result, replacement_result) && ...
            ~strcmpi(checkpoint, replacement_checkpoint), ...
            'HeatDriveECC:CompactionReplacementCollision', ...
            'Refusing to compact the active result or checkpoint.');
        assert(strcmpi(string(java.io.File(result).getName()), ...
                'physical_simscape_result.mat') && ...
            strcmpi(string(java.io.File(checkpoint).getName()), ...
                'final_operating_point.mat'), ...
            'HeatDriveECC:CompactionUnexpectedFile', ...
            'Only the known result and Operating Point filenames may be removed.');
        result_bytes = file_bytes(result);
        checkpoint_bytes = file_bytes(checkpoint);
        if isfile(result)
            delete(result);
        end
        if isfile(checkpoint)
            delete(checkpoint);
        end
        marker_path = fullfile(fileparts(result), ...
            'SUPERSEDED_RAW_COMPACTED.txt');
        fid = fopen(marker_path, 'w', 'n', 'UTF-8');
        assert(fid >= 0, 'HeatDriveECC:CompactionMarkerOpenFailed', ...
            'Cannot write %s.', marker_path);
        cleanup = onCleanup(@() fclose(fid));
        fprintf(fid, 'schema=heatdrive_ecc_superseded_segment_compaction_v1\n');
        fprintf(fid, 'compacted_at=%s\n', char(datetime('now', ...
            'TimeZone', 'local')));
        fprintf(fid, 'removed_result_bytes=%.0f\n', result_bytes);
        fprintf(fid, 'removed_checkpoint_bytes=%.0f\n', checkpoint_bytes);
        fprintf(fid, 'replacement_result=%s\n', replacement_result);
        fprintf(fid, 'replacement_checkpoint=%s\n', replacement_checkpoint);
        fprintf(fid, 'failed_result_may_resume=0\n');
        clear cleanup
        fprintf(['SUPERSEDED_SEGMENT_COMPACTED bytes=%.0f ', ...
            'replacement=%s\n'], result_bytes + checkpoint_bytes, ...
            replacement_result);
    catch exception
        warning('HeatDriveECC:SupersededSegmentCompactionFailed', ...
            'Validated state was retained, but old raw compaction failed: %s', ...
            exception.message);
    end
end

function bytes = file_bytes(path)
    if isfile(path)
        info = dir(path);
        bytes = info.bytes;
    else
        bytes = 0;
    end
end

function path = canonical_path(path)
    path = char(java.io.File(char(string(path))).getCanonicalPath());
end

function tf = same_path(a, b)
    a = char(java.io.File(char(string(a))).getCanonicalPath());
    b = char(java.io.File(char(string(b))).getCanonicalPath());
    tf = strcmpi(a, b);
end

function validate_settings(settings)
    Resolve_HeatDriveECC_StateLoggingPolicy(struct('output', ...
        struct('capture_internal_states', settings.capture_internal_states)));
    integer_fields = {'segment_cycles','maximum_cycles', ...
        'required_consecutive_near_segments'};
    for idx = 1:numel(integer_fields)
        value = settings.(integer_fields{idx});
        if ~isscalar(value) || value <= 0 || value ~= round(value)
            error('HeatDriveECC:LongRunInvalidIntegerSetting', ...
                '%s must be a positive integer.', integer_fields{idx});
        end
    end
    positive_fields = {'near_endpoint_drift_K', ...
        'near_same_phase_temperature_drift_K', ...
        'near_same_phase_phase_drift'};
    for idx = 1:numel(positive_fields)
        value = settings.(positive_fields{idx});
        if ~isscalar(value) || ~isfinite(value) || value <= 0
            error('HeatDriveECC:LongRunInvalidPositiveSetting', ...
                '%s must be positive and finite.', positive_fields{idx});
        end
    end
end

function table_value = empty_progress_table()
    names = {'prior_cycles','total_cycles','segment_walltime_s', ...
        'cumulative_walltime_s','sim_call_count','mechanism_pass', ...
        'all_required_pass','periodic_steady_state','endpoint_drift_K', ...
        'same_phase_temperature_drift_K','same_phase_phase_drift', ...
        'eq9_lift_K','eq10_SCP_W_per_g','SE_phase_swing', ...
        'near_steady_state','output_dir','output_mat','checkpoint_path', ...
        'completed_at'};
    types = {'double','double','double','double','double','logical', ...
        'logical','logical','double','double','double','double','double', ...
        'double','logical','cell','cell','cell','cell'};
    table_value = table('Size', [0 numel(names)], ...
        'VariableTypes', types, 'VariableNames', names);
end

function persist_state(path, state, settings)
    save(path, 'state', 'settings', '-v7.3');
end

function value = git_head(root_dir)
    [status, text_value] = system(sprintf( ...
        'git -C "%s" rev-parse HEAD', fileparts(root_dir)));
    if status == 0
        value = strtrim(text_value);
    else
        value = 'unavailable';
    end
end

function out = merge_structs(out, overrides)
    names = fieldnames(overrides);
    for idx = 1:numel(names)
        out.(names{idx}) = overrides.(names{idx});
    end
end

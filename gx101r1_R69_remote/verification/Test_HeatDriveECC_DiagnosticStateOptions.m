function record = Test_HeatDriveECC_DiagnosticStateOptions()
    defaults=Resolve_HeatDriveECC_DiagnosticStateOptions(struct(),20);
    assert(strcmp(defaults.mode,'off') && defaults.command_horizon_cycles==20,'Default policy changed.');
    preflight=Resolve_HeatDriveECC_DiagnosticStateOptions( ...
        struct('mode','restore_preflight','command_horizon_cycles',200),2);
    assert(preflight.command_horizon_cycles==200,'Fixed command horizon lost.');
    rebuilt=Resolve_HeatDriveECC_DiagnosticStateOptions(struct('mode','rebuilt_cycle_preflight', ...
        'command_horizon_cycles',200,'restore_source_root','fixture'),2);
    assert(strcmp(rebuilt.restore_source_root,'fixture'),'Rebuilt source lost.');
    resumed=Resolve_HeatDriveECC_DiagnosticStateOptions(struct('mode','diagnostic_resume', ...
        'command_horizon_cycles',200,'restore_source_root','fixture','restore_verification_root','proof'),20);
    assert(strcmp(resumed.restore_verification_root,'proof'),'Complete-cycle proof lost.');
    bad={struct('mode','capture'),struct('mode','off','command_horizon_cycles',200), ...
        struct('mode','restore_preflight'),struct('unknown',1), ...
        struct('mode','rebuilt_cycle_preflight'), ...
        struct('mode','capture','restore_source_root','fixture'), ...
        struct('mode','rebuilt_cycle_preflight','restore_source_root','fixture'), ...
        struct('mode','diagnostic_resume','command_horizon_cycles',200), ...
        struct('mode','diagnostic_resume','restore_source_root','fixture','restore_verification_root','proof'), ...
        struct('mode','capture','restore_verification_root','proof')};
    counts=[1,20,20,20,2,20,20,20,20,20];
    for k=1:numel(bad)
        rejected=false;
        try,Resolve_HeatDriveECC_DiagnosticStateOptions(bad{k},counts(k));
        catch,rejected=true;end
        assert(rejected,'Invalid diagnostic state policy accepted.');
    end
    record=struct('default_off_pass',true,'fixed_horizon_pass',true,'rebuilt_source_pass',true, ...
        'diagnostic_resume_policy_pass',true,'rejected_invalid_cases',10);
    fprintf('%s\n',jsonencode(record));
end

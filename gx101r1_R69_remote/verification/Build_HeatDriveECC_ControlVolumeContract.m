        "Qcool_mean / integral(max(Q_SHEX_source_to_sink_W,0)) dt / Delta t"; ...
        "integral(Tout_HHEX-Tout_CHEX) dt / Delta t"; ...
        "integral(I_stage4*abs(mdot_SE)*cp*(Tout_CHEX-Tin_CHEX)) dt / Delta t"; ...
        "Qcool_mean / (1000*m_SE_kg)"; ...
        "integral(Q_CHEX_reservoir_to_hx_W) dt / Delta t"; ...
        "integral(pump_power_SMA_W+pump_power_SE_W) dt / Delta t"; ...
        "Qcool_mean / Ppump_mean"];

    mass_basis = ["not applicable"; "not applicable"; "SE glycol-water stream"; ...
        sprintf('active SE solid only: %.12g kg = %.12g g', o.equilibrium.m_r_kg, o.equilibrium.m_r_kg*1.0e3); ...
        "not applicable"; "not applicable"; "not applicable"];
    inclusion = ["positive SHEX source heat-flow input and Eq.10 cooling power"; ...
        "HHEX/CHEX SE-fluid outlet temperatures"; ...

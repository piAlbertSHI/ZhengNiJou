function write_markdown(path, rows, equations, o)
    fid = fopen(path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:ControlVolumeMarkdownOpenFailed', ...
        'Cannot write %s.', path);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '# SMA-SE control-volume and performance contract\n\n');
    fprintf(fid, '- Cold boundary: `%s`, `Tc = %.12g K`.\n', ...
        o.system.cold_boundary_mode, o.system.Tchex_K);
    fprintf(fid, '- Cycle period: `%.12g s`; Eq.9/10 window: last `min(N,10)` complete cycles.\n', ...
        o.schedule.tau_cycle_s);
    fprintf(fid, '- SCP mass basis: active SE solid only, `%.12g kg = %.12g g`.\n\n', ...
        o.equilibrium.m_r_kg, o.equilibrium.m_r_kg * 1.0e3);
    write_table(fid, rows);
    fprintf(fid, '\n## Eq.9/Eq.10 and work definitions\n\n');
    write_table(fid, equations);
    fprintf(fid, ['\nThe contract is a model-boundary declaration, not an ', ...
        'experimental validation claim. Pump dissipation is observed but ', ...
        'is not injected into the thermal-liquid energy balance.\n']);
    clear cleaner
end

function write_table(fid, values)
    names = values.Properties.VariableNames;
    fprintf(fid, '| %s |\n', strjoin(names, ' | '));
    fprintf(fid, '|%s\n', repmat('---|', 1, numel(names)));
    for row = 1:height(values)
        cells = cell(1, numel(names));
        for col = 1:numel(names)
            value = values{row, col};
            if iscell(value)
                value = value{1};
            end
            cells{col} = strrep(char(string(value)), '|', '\|');
        end
        fprintf(fid, '| %s |\n', strjoin(cells, ' | '));
    end
end

function out = merge_structs(out, overrides)
    names = fieldnames(overrides);
    for idx = 1:numel(names)
        name = names{idx};
        if isfield(out, name) && isstruct(out.(name)) && ...
                isstruct(overrides.(name))
            out.(name) = merge_structs(out.(name), overrides.(name));
        else
            out.(name) = overrides.(name);
        end
    end
end

function contract = Build_HeatDriveECC_ControlVolumeContract(output_dir, overrides)
% Write explicit mass/energy boundaries and Qian Eq.9/Eq.10 definitions.

    if nargin < 1 || isempty(output_dir)
        root_dir = fileparts(fileparts(mfilename('fullpath')));
        output_dir = fullfile(root_dir, 'outputs_storage_audit', ...
            'control_volume_contract');
    end
    if nargin < 2
        overrides = struct();
    end
    contract_defaults = struct( ...
        'cycle_count', 200, ...
        'system', struct( ...
            'Tchex_K', 276.95, ...
            'cold_boundary_mode', 'fixed_reservoir_temperature', ...
            'cold_load_mode', 'no_load', ...
            'cold_load_heat_W', 0.0));
    overrides = merge_structs(contract_defaults, overrides);
    options = Build_HeatDriveECC_EighthRound_Defaults(overrides);
    if ~exist(output_dir, 'dir')
        mkdir(output_dir);
    end

    rows = control_volume_rows(options);
    equations = equation_rows(options);
    table_path = fullfile(output_dir, 'control_volume_contract.csv');
    equation_path = fullfile(output_dir, 'qian_eq9_eq10_contract.csv');
    markdown_path = fullfile(output_dir, 'control_volume_contract.md');
    json_path = fullfile(output_dir, 'control_volume_contract.json');
    writetable(rows, table_path);
    writetable(equations, equation_path);
    write_markdown(markdown_path, rows, equations, options);

    contract = struct();
    contract.schema = 'heatdrive_ecc_control_volume_contract_v1';
    contract.generated_at = char(datetime('now', 'TimeZone', 'local'));
    contract.cold_boundary_mode = options.system.cold_boundary_mode;
    contract.cycle_period_s = options.schedule.tau_cycle_s;
    contract.qian_window_cycles = min(options.cycle_count, 10);
    contract.SE_active_mass_kg = options.equilibrium.m_r_kg;
    contract.SE_active_mass_g = options.equilibrium.m_r_kg * 1.0e3;
    contract.rows = table2struct(rows);
    contract.equations = table2struct(equations);
    contract.outputs = struct('table_csv', table_path, ...
        'equation_csv', equation_path, 'markdown', markdown_path, ...
        'json', json_path);
    fid = fopen(json_path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:ControlVolumeJsonOpenFailed', ...
        'Cannot write %s.', json_path);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(contract, 'PrettyPrint', true));
    clear cleaner
end


function audit = Audit_HeatDriveECC_SourceHeatFlowResult(result_path)
% Audit one completed production result containing the SHEX source heat sensor.

    assert(isfile(result_path), 'HeatDriveECC:MissingSourceHeatFlowResult', ...
        'Production result is missing: %s', result_path);
    loaded = load(result_path, 'summary', 'options', 'provenance');
    required = {'summary','options','provenance'};
    assert(all(isfield(loaded, required)), ...
        'HeatDriveECC:IncompleteSourceHeatFlowResult', ...
        'Production result package is incomplete.');
    performance = loaded.summary.performance;
    signal_present = isfield(performance, ...
        'SHEX_source_heat_flow_direction_pass');
    signal_finite = signal_present && ...
        isfinite(performance.SHEX_source_heat_input_W) && ...
        isfinite(performance.SHEX_source_heat_flow_mean_W);

    audit = struct();
    audit.schema = 'heatdrive_ecc_source_heat_flow_result_audit_v1';
    audit.result_path = result_path;
    audit.signal_present = signal_present;
    audit.signal_finite = signal_finite;
    audit.source_direction_pass = logical( ...
        performance.SHEX_source_heat_flow_direction_pass);
    audit.energy_closure_pass = ...
        isfinite(loaded.summary.max_SMA_solid_energy_residual_fraction) && ...
        isfinite(loaded.summary.max_SE_solid_energy_residual_fraction) && ...
        loaded.summary.max_SMA_solid_energy_residual_fraction <= ...
            loaded.options.validation.max_energy_residual_fraction && ...
        loaded.summary.max_SE_solid_energy_residual_fraction <= ...
            loaded.options.validation.max_energy_residual_fraction;
    audit.energy_closure_relative = max( ...
        loaded.summary.max_SMA_solid_energy_residual_fraction, ...
        loaded.summary.max_SE_solid_energy_residual_fraction);
    audit.source_heat_input_W = performance.SHEX_source_heat_input_W;
    audit.cooling_power_W = performance.cooling_power_eq10_W;
    audit.heat_driven_system_COP = performance.heat_driven_system_COP;
    audit.heat_driven_system_COP_available = logical( ...
        performance.heat_driven_system_COP_available);
    audit.periodic_steady_state = logical( ...
        performance.periodic_steady_state);
    audit.checkpoint_restart_used = logical( ...
        loaded.provenance.checkpoint_restart_used);
    audit.checkpoint_chain_verified = logical( ...
        loaded.provenance.checkpoint_chain_verified);
    audit.system_energy_closure_complete = false;
    audit.system_energy_closure_status = ...
        'solid SMA/SE gates pass; downstream SHEX transfer is not measured';
    audit.production_pass = audit.signal_present && audit.signal_finite && ...
        audit.source_direction_pass && audit.energy_closure_pass && ...
        audit.periodic_steady_state && ...
        audit.checkpoint_restart_used && audit.checkpoint_chain_verified && ...
        audit.heat_driven_system_COP_available && ...
        isfinite(audit.heat_driven_system_COP) && ...
        audit.heat_driven_system_COP > 0.0;

    fprintf(['SOURCE_HEAT_FLOW_RESULT_PASS=%d source_W=%.12g ', ...
        'solid_energy_residual=%.12g COP=%.12g periodic=%d\n'], ...
        audit.production_pass, audit.source_heat_input_W, ...
        audit.energy_closure_relative, ...
        audit.heat_driven_system_COP, audit.periodic_steady_state);
end

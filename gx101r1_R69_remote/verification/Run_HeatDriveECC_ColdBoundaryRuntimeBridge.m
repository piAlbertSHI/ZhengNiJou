function bridge = Run_HeatDriveECC_ColdBoundaryRuntimeBridge(settings)
% Migrate the fixed CHEX temperature parameter to run-time configurability.
%
% The bridge holds Tc fixed at the validated authority value. It restores
% the complete authority Operating Point and changes only the Simscape
% parameter configurability, so later Tc sweeps do not rely on incomplete
% ModelOperatingPoint restoration after a compile-time parameter change.

    if nargin < 1
        settings = struct();
    end
    repo_root = fileparts(fileparts(mfilename('fullpath')));
    defaults = struct( ...
        'output_root', fullfile(repo_root, 'outputs', ...
            'qian_cold_boundary_runtime_bridge_from_c243_20260904'), ...
        'segment_cycles', 3, ...
        'maximum_additional_cycles', 12, ...
        'generate_intermediate_figures', false, ...
        'authority_settings', struct('contract_path', fullfile( ...
            repo_root, 'verification', ...
            'system_energy_c243_recovery_contract.json')));
    settings = merge_structs(defaults, settings);
    authority = Resolve_HeatDriveECC_SourceHeatFlowRecovery( ...
        settings.authority_settings);
    if ~isfolder(settings.output_root)
        mkdir(settings.output_root);
    end

    prior = load(authority.result_path, 'options');
    assert(isfield(prior, 'options'), ...
        'HeatDriveECC:BridgeMissingAuthorityOptions', ...
        'Continuation authority result does not contain options.');
    baseline_Tc_K = prior.options.system.Tchex_K;
    branch_overrides = authority_branch_overrides(prior.options.branch);
    candidate_settings = struct( ...
        'Tchex_K', baseline_Tc_K, ...
        'output_root', settings.output_root, ...
        'segment_cycles', settings.segment_cycles, ...
        'maximum_cycles', authority.completed_cycles + ...
            settings.maximum_additional_cycles, ...
        'required_consecutive_near_segments', intmax('int32'), ...
        'generate_intermediate_figures', ...
            settings.generate_intermediate_figures, ...
        'resume_existing_state', true, ...
        'initial_prior_result_path', authority.result_path, ...
        'initial_checkpoint_path', authority.checkpoint_path, ...
        'initial_state_policy', 'validated_recovery_contract_only', ...
        'mainline_contract_path', authority.contract_path, ...
        'model_overrides', struct('system', struct( ...
            'cold_boundary_temperature_configurability', 'runtime')), ...
        'checkpoint_transition_fields', {{ ...
            'system.cold_boundary_temperature_configurability'}}, ...
        'branch_overrides', branch_overrides);

    state_path = fullfile(settings.output_root, ...
        'steady_continuation_state.mat');
    try
        state = Run_HeatDriveECC_Table4_FixedReservoirPoint( ...
            candidate_settings);
    catch exception
        if ~isfile(state_path)
            rethrow(exception);
        end
        saved = load(state_path, 'state');
        state = saved.state;
        if ~recorded_authority_preserving_error(state, authority)
            rethrow(exception);
        end
    end

    bridge = bridge_template();
    bridge.generated_at = char(datetime('now', 'TimeZone', 'local'));
    bridge.authority_contract_path = authority.contract_path;
    bridge.authority_cycles = authority.completed_cycles;
    bridge.authority_result_path = authority.result_path;
    bridge.authority_checkpoint_path = authority.checkpoint_path;
    bridge.baseline_Tc_K = baseline_Tc_K;
    bridge.status = char(string(state.status));
    bridge.stop_reason = char(string(state.stop_reason));
    bridge.completed_cycles = state.current_cycles;

    if strcmp(state.status, 'periodic_steady_state') && ...
            isfile(state.prior_result_path) && isfile(state.checkpoint_path)
        data = load(state.prior_result_path, 'options', 'provenance');
        bridge.result_path = state.prior_result_path;
        bridge.checkpoint_path = state.checkpoint_path;
        bridge.Tc_unchanged = abs(data.options.system.Tchex_K - ...
            baseline_Tc_K) <= 1.0e-12;
        bridge.runtime_configurability = strcmp( ...
            data.options.system. ...
            cold_boundary_temperature_configurability, 'runtime');
        bridge.checkpoint_restart_used = logical( ...
            data.provenance.checkpoint_restart_used);
        bridge.checkpoint_chain_verified = logical( ...
            data.provenance.checkpoint_chain_verified);
        bridge.time_continuity_verified = logical( ...
            data.provenance.checkpoint_time_continuity_verified);
        bridge.complete_operating_point_restore_verified = ...
            isfield(data.provenance, 'checkpoint_complete_restore_verified') && ...
            logical(data.provenance.checkpoint_complete_restore_verified);
        bridge.segment_start_time_s = ...
            data.provenance.segment_start_time_s;
        bridge.expected_segment_start_time_s = ...
            authority.completed_cycles * data.options.schedule.tau_cycle_s;
        bridge.segment_start_matches_authority = abs( ...
            bridge.segment_start_time_s - ...
            bridge.expected_segment_start_time_s) <= 1.0e-9;
        bridge.system_energy_audit_path = fullfile( ...
            settings.output_root, 'system_energy_bridge_audit.json');
        energy = Audit_HeatDriveECC_SystemEnergyResult( ...
            bridge.result_path, bridge.system_energy_audit_path);
        bridge.mechanism_pass = logical(energy.mechanism_pass);
        bridge.periodic_steady_state = logical( ...
            energy.periodic_steady_state);
        bridge.system_energy_production_pass = logical( ...
            energy.production_pass);
        bridge.modeled_thermal_residual_relative = ...
            energy.modeled_thermal_residual_relative;
        bridge.fluid_mass_drift_relative = ...
            energy.fluid_mass_drift_relative;
    end

    bridge.accepted = all([bridge.Tc_unchanged, ...
        bridge.runtime_configurability, bridge.checkpoint_restart_used, ...
        bridge.checkpoint_chain_verified, bridge.time_continuity_verified, ...
        bridge.complete_operating_point_restore_verified, ...
        bridge.segment_start_matches_authority, bridge.mechanism_pass, ...
        bridge.periodic_steady_state, ...
        bridge.system_energy_production_pass]);
    bridge.state_reset = ~bridge.complete_operating_point_restore_verified;
    if bridge.complete_operating_point_restore_verified
        bridge.preserved_state_classes = { ...
            'thermal_capacity','buffer','constitutive','temperature', ...
            'phase_fraction','independent_route_PI_memory', ...
            'simscape_solver_internal_state'};
    end
    bridge.failed_result_may_resume = false;
    bridge.accepted_result_may_resume = bridge.accepted;

    save(fullfile(settings.output_root, 'runtime_bridge_result.mat'), ...
        'bridge', 'settings', 'candidate_settings', '-v7');
    write_json(fullfile(settings.output_root, ...
        'runtime_bridge_summary.json'), bridge);
    write_marker(settings.output_root, bridge);
    fprintf(['COLD_BOUNDARY_RUNTIME_BRIDGE_PASS=%d status=%s cycles=%d ', ...
        'Tc_K=%.12g mechanism=%d periodic=%d system_energy=%d\n'], ...
        bridge.accepted, bridge.status, bridge.completed_cycles, ...
        bridge.baseline_Tc_K, bridge.mechanism_pass, ...
        bridge.periodic_steady_state, ...
        bridge.system_energy_production_pass);
end

function branch = authority_branch_overrides(source)
    names = fieldnames(source);
    keep = contains(names, 'pressure_pi') | ...
        contains(names, 'pressure_feedforward') | ...
        contains(names, 'viscosity_blend') | ...
        contains(names, 'route_temperature_blend') | ...
        contains(names, 'pressure_integrator') | ...
        contains(names, 'pressure_bias') | ...
        contains(names, 'cold_design_dp') | ...
        contains(names, 'runtime_mu');
    names = names(keep);
    branch = struct();
    for idx = 1:numel(names)
        branch.(names{idx}) = source.(names{idx});
    end
    pump_fields = {'pump_fluid_energy_model', ...
        'pump_fluid_energy_model_source'};
    for idx = 1:numel(pump_fields)
        name = pump_fields{idx};
        if isfield(source, name)
            branch.(name) = source.(name);
        end
    end
end

function tf = recorded_authority_preserving_error(state, authority)
    tf = isfield(state, 'status') && ...
        strcmp(state.status, 'simulation_error') && ...
        isfield(state, 'current_cycles') && ...
        state.current_cycles == authority.completed_cycles && ...
        isfield(state, 'prior_result_path') && ...
        isfield(state, 'checkpoint_path') && ...
        strcmpi(canonical_path(state.prior_result_path), ...
            canonical_path(authority.result_path)) && ...
        strcmpi(canonical_path(state.checkpoint_path), ...
            canonical_path(authority.checkpoint_path));
end

function bridge = bridge_template()
    bridge = struct( ...
        'schema', 'heatdrive_ecc_cold_boundary_runtime_bridge_v1', ...
        'generated_at', '', 'accepted', false, 'status', '', ...
        'stop_reason', '', 'authority_contract_path', '', ...
        'authority_cycles', 0, 'authority_result_path', '', ...
        'authority_checkpoint_path', '', 'baseline_Tc_K', NaN, ...
        'completed_cycles', 0, 'result_path', '', ...
        'checkpoint_path', '', 'Tc_unchanged', false, ...
        'runtime_configurability', false, ...
        'checkpoint_restart_used', false, ...
        'checkpoint_chain_verified', false, ...
        'time_continuity_verified', false, ...
        'complete_operating_point_restore_verified', false, ...
        'segment_start_time_s', NaN, ...
        'expected_segment_start_time_s', NaN, ...
        'segment_start_matches_authority', false, ...
        'mechanism_pass', false, 'periodic_steady_state', false, ...
        'system_energy_production_pass', false, ...
        'modeled_thermal_residual_relative', NaN, ...
        'fluid_mass_drift_relative', NaN, ...
        'system_energy_audit_path', '', 'state_reset', false, ...
        'preserved_state_classes', {{}}, ...
        'failed_result_may_resume', false, ...
        'accepted_result_may_resume', false);
end

function write_marker(output_root, bridge)
    if bridge.accepted
        name = 'RUNTIME_BRIDGE_ACCEPTED.txt';
    else
        name = 'REJECTED_DO_NOT_RESUME.txt';
    end
    path = fullfile(output_root, name);
    fid = fopen(path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:BridgeMarkerOpenFailed', ...
        'Cannot create %s.', path);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, 'accepted=%d\n', bridge.accepted);
    fprintf(fid, 'status=%s\n', bridge.status);
    fprintf(fid, 'stop_reason=%s\n', bridge.stop_reason);
    fprintf(fid, 'Tc_K=%.12g\n', bridge.baseline_Tc_K);
    fprintf(fid, 'completed_cycles=%d\n', bridge.completed_cycles);
    fprintf(fid, 'mechanism_pass=%d\n', bridge.mechanism_pass);
    fprintf(fid, 'periodic_steady_state=%d\n', ...
        bridge.periodic_steady_state);
    fprintf(fid, 'system_energy_production_pass=%d\n', ...
        bridge.system_energy_production_pass);
    fprintf(fid, 'state_reset=%d\n', bridge.state_reset);
    fprintf(fid, 'failed_result_may_resume=%d\n', ...
        bridge.failed_result_may_resume);
    fprintf(fid, 'accepted_result_may_resume=%d\n', ...
        bridge.accepted_result_may_resume);
    fprintf(fid, 'authority_checkpoint_path=%s\n', ...
        bridge.authority_checkpoint_path);
    if bridge.accepted
        fprintf(fid, 'accepted_checkpoint_path=%s\n', ...
            bridge.checkpoint_path);
    end
    clear cleaner
end

function write_json(path, value)
    fid = fopen(path, 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'HeatDriveECC:BridgeSummaryOpenFailed', ...
        'Cannot create %s.', path);
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(value, PrettyPrint = true));
    clear cleaner
end

function path = canonical_path(path)
    path = char(java.io.File(char(string(path))).getCanonicalPath());
end

function out = merge_structs(out, overrides)
    names = fieldnames(overrides);
    for idx = 1:numel(names)
        name = names{idx};
        if isfield(out, name) && isstruct(out.(name)) && ...
                isstruct(overrides.(name))
            out.(name) = merge_structs(out.(name), overrides.(name));
        else
            out.(name) = overrides.(name);
        end
    end
end

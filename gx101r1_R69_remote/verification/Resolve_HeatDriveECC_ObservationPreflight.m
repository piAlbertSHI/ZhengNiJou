function options=Resolve_HeatDriveECC_ObservationPreflight(options,state,cycles,duration,arm,endpoint_all,factors)
% Execution-only comparison; the configured model and native history stay unchanged.
    assert(isstruct(options) && isscalar(options),'Require scalar observation options.');
    if isempty(fieldnames(options)),return;end
    if isfield(options,'mode') && any(strcmp(options.mode,{'runtime_sensitivity_cold','runtime_sensitivity_continuation','runtime_sensitivity_kernel_cold_comparison'}))
        required={'mode';'python_executable';'source_contract_path';'candidate_qualification_path';'case_index';'probe_only'};
        continuation=strcmp(options.mode,'runtime_sensitivity_continuation');
        kernel_comparison=strcmp(options.mode,'runtime_sensitivity_kernel_cold_comparison');
        if continuation,required=[required;{'source_closeout_path';'collection_root';'resume_collection';'collection_stop_s'}];end
        if kernel_comparison,required=[required;{'source_closeout_path';'kernel_qualification_path'}];end
        assert(isequal(sort(fieldnames(options)),sort(required)) && strcmp(state.mode,'capture') && ...
            state.command_horizon_cycles==200 && cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)));
        validateattributes(options.case_index,{'numeric'},{'scalar','finite','integer','>=',0,'<=',8});
        assert(islogical(options.probe_only) && isscalar(options.probe_only));
        if kernel_comparison
            assert(options.probe_only && ismember(options.case_index,[0 1]));
            source=Read_HeatDriveECC_SensitivityColdSource(options.source_closeout_path,options.case_index);
            assert(strcmp(source.case_contract.source_qualification_path,options.candidate_qualification_path));
            Read_HeatDriveECC_KernelQualification(options.kernel_qualification_path);
        end
        if continuation
            assert(~options.probe_only && islogical(options.resume_collection) && isscalar(options.resume_collection));
            validateattributes(options.collection_stop_s,{'numeric'},{'scalar','finite','integer','>=',220,'<=',2000});
            assert(mod(options.collection_stop_s,20)==0);
            source=Read_HeatDriveECC_SensitivityColdSource(options.source_closeout_path,options.case_index);
            assert(strcmp(source.case_contract.source_qualification_path,options.candidate_qualification_path));
            repo=fileparts(fileparts(mfilename('fullpath')));
            collection=char(java.io.File(options.collection_root).getCanonicalPath());
            prefix=[char(java.io.File(fullfile(repo,'outputs')).getCanonicalPath()) filesep];
            assert(startsWith(collection,prefix) && ~strcmp(collection,source.root));
        end
        for key={'python_executable','source_contract_path','candidate_qualification_path'},assert(isfile(options.(key{1})));end
        q=jsondecode(fileread(options.candidate_qualification_path));
        assert(strcmp(q.schema,'heatdrive_ecc_runtime_Tc_candidate_endpoint_v1') && ...
            q.all_original_packet_mechanism_flow_phase_energy_gates_pass && q.original_public_thermal_periodic_pass && ...
            q.current_target_window_stability.precision_pass && ~q.source_state_edited && ~q.production_recovery_allowed);
        return;
    end
    if isfield(options,'mode') && strcmp(options.mode,'runtime_boundary_horizon_preflight')
        required={'mode';'python_executable';'source_contract_path';'candidate_qualification_path'};
        assert(isequal(sort(fieldnames(options)),sort(required)) && strcmp(state.mode,'capture') && ...
            state.command_horizon_cycles==200 && cycles==20 && duration==200 && ...
            strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)));
        for key={'python_executable','source_contract_path','candidate_qualification_path'}
            assert(isfile(options.(key{1})),'Missing command-horizon source.');
        end
        q=jsondecode(fileread(options.candidate_qualification_path));
        assert(strcmp(q.schema,'heatdrive_ecc_runtime_Tc_candidate_endpoint_v1') && ...
            q.snapshot_time_s>=400 && q.snapshot_time_s+20<1990 && mod(q.snapshot_time_s,20)==0 && ...
            q.all_original_packet_mechanism_flow_phase_energy_gates_pass && q.all_four_memories_bitwise_preserved && ...
            q.original_public_thermal_periodic_pass && q.current_target_window_stability.precision_pass && ...
            ~q.production_recovery_allowed && ~q.source_state_edited);
        return;
    end
    if isfield(options,'mode') && any(strcmp(options.mode,{'runtime_boundary_Tc_continuation','runtime_boundary_Tc_step'}))
        stepping=strcmp(options.mode,'runtime_boundary_Tc_step');
        required={'mode';'python_executable';'source_contract_path';'candidate_qualification_path'; ...
            'collection_root';'resume_collection';'collection_stop_s';'candidate_Tc_K'; ...
            'target_lift_span_K';'target_SCP_span_W_per_g'};
        if isfield(options,'minimum_stop_time_s'),required{end+1}='minimum_stop_time_s';end
        assert(isequal(sort(fieldnames(options)),sort(required)) && strcmp(state.mode,'capture') && ...
            state.command_horizon_cycles==200 && isequal(sort(fieldnames(state)),sort({'mode';'command_horizon_cycles'})) && ...
            cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)) && ...
            islogical(options.resume_collection) && isscalar(options.resume_collection));
        for key={'python_executable','source_contract_path','candidate_qualification_path'}
            assert(isfile(options.(key{1})),'Missing intact same-Tc continuation prerequisite.');
        end
        q=jsondecode(fileread(options.candidate_qualification_path));
        if stepping
            assert(~isfield(options,'minimum_stop_time_s') && q.snapshot_time_s>=520 && ...
                q.original_public_thermal_periodic_pass && q.bounded_outer_metric_sampling_allowed && ...
                q.current_target_window_stability.precision_pass && ...
                isnumeric(options.candidate_Tc_K) && isscalar(options.candidate_Tc_K) && isfinite(options.candidate_Tc_K) && ...
                options.candidate_Tc_K>=255.05 && options.candidate_Tc_K<=393.15 && ...
                abs(options.candidate_Tc_K-q.temperature_K)>.001 && abs(options.candidate_Tc_K-q.temperature_K)<=2+1e-12);
        else
            assert(options.candidate_Tc_K==q.temperature_K);
        end
        if isfield(options,'minimum_stop_time_s')
            assert(isnumeric(options.minimum_stop_time_s) && isscalar(options.minimum_stop_time_s) && ...
                isfinite(options.minimum_stop_time_s) && mod(options.minimum_stop_time_s,20)==0 && ...
                options.minimum_stop_time_s>q.snapshot_time_s && options.minimum_stop_time_s<=options.collection_stop_s);
        end
        assert(options.collection_stop_s==q.snapshot_time_s+200 && options.collection_stop_s<=2000 && ...
            options.target_lift_span_K==.1 && ...
            options.target_SCP_span_W_per_g==.01, ...
            'Same-Tc continuation uses the existing outer target precision, never relaxed physical gates.');
        return;
    end
    if isfield(options,'mode') && strcmp(options.mode,'runtime_boundary_Tc_candidate')
        required={'mode';'python_executable';'source_contract_path';'recording_contract_path'; ...
            'collection_root';'resume_collection';'collection_stop_s';'candidate_Tc_K';'minimum_transition_cycles'};
        assert(isequal(sort(fieldnames(options)),sort(required)) && strcmp(state.mode,'capture') && ...
            state.command_horizon_cycles==200 && isequal(sort(fieldnames(state)),sort({'mode';'command_horizon_cycles'})) && ...
            cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)) && ...
            islogical(options.resume_collection) && isscalar(options.resume_collection));
        for key={'python_executable','source_contract_path','recording_contract_path'}
            assert(isfile(options.(key{1})),'Missing fixed-Tc prerequisite.');
        end
        p=jsondecode(fileread(options.recording_contract_path));
        assert(isnumeric(options.candidate_Tc_K) && isscalar(options.candidate_Tc_K) && ...
            isfinite(options.candidate_Tc_K) && abs(options.candidate_Tc_K-276.95)>.001 && ...
            abs(options.candidate_Tc_K-276.95)<=.1+1e-12 && options.minimum_transition_cycles==12 && ...
            options.collection_stop_s==p.snapshot_time_s+200 && options.collection_stop_s<=2000 && ...
            mod(p.snapshot_time_s,20)==0 && p.snapshot_time_s>=120 && ...
            strcmp(p.schema,'heatdrive_ecc_runtime_boundary_warmup_endpoint_v1') && ...
            ~p.production_recovery_allowed && ~p.outer_solve_eligible, ...
            'A declared small runtime Tc intervention needs twelve post-transition cycles before any ten-cycle score.');
        return;
    end
    if isfield(options,'mode') && strcmp(options.mode,'runtime_boundary_warmup')
        required={'mode';'python_executable';'source_contract_path';'recording_contract_path'; ...
            'collection_root';'resume_collection';'collection_stop_s'};
        if isfield(options,'stop_on_public_periodicity')
            assert(islogical(options.stop_on_public_periodicity) && isscalar(options.stop_on_public_periodicity) && ...
                options.stop_on_public_periodicity,'Explicit convergence only; never a changed physical tolerance.');
            required{end+1}='stop_on_public_periodicity';
        end
        assert(isequal(sort(fieldnames(options)),sort(required)) && ...
            strcmp(state.mode,'capture') && state.command_horizon_cycles==200 && ...
            isequal(sort(fieldnames(state)),sort({'mode';'command_horizon_cycles'})) && ...
            cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)) && ...
            islogical(options.resume_collection) && isscalar(options.resume_collection));
        for key={'python_executable','source_contract_path','recording_contract_path'}
            assert(isfile(options.(key{1})),'Missing runtime warmup prerequisite.');
        end
        pointer=jsondecode(fileread(options.recording_contract_path));
        assert(isscalar(options.collection_stop_s) && isnumeric(options.collection_stop_s) && ...
            isfinite(options.collection_stop_s) && options.collection_stop_s-pointer.snapshot_time_s==200 && ...
            options.collection_stop_s<=2000 && pointer.snapshot_time_s>=20 && ...
            mod(pointer.snapshot_time_s,20)==0 && ~pointer.production_recovery_allowed && ~pointer.outer_solve_eligible, ...
            'Runtime warmup is an explicit twenty-cycle segment within the unchanged command horizon.');
        return;
    end
    if isfield(options,'mode') && strcmp(options.mode,'runtime_boundary_cold_family')
        assert(isequal(sort(fieldnames(options)),sort({'mode';'python_executable';'source_contract_path';'boundary_probe_path'})) && ...
            strcmp(state.mode,'capture') && state.command_horizon_cycles==200 && ...
            isequal(sort(fieldnames(state)),sort({'mode';'command_horizon_cycles'})) && ...
            cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)), ...
            'The runtime family is an independent cold capture, never a migrated or partial OP.');
        for key={'python_executable','source_contract_path','boundary_probe_path'}
            assert(isfile(options.(key{1})),'Missing runtime-family prerequisite.');
        end
        probe=jsondecode(fileread(options.boundary_probe_path));
        cases=probe.cases;if isstruct(cases),cases=num2cell(cases);end
        assert(iscell(cases) && numel(cases)==2);
        assert(probe.experiment_completed && ~probe.candidate_compatible && ...
            strcmp(probe.checksum_policy,'error/error') && ~probe.source_state_edited && ...
            ~probe.new_OP_saved && cases{1}.strict_vendor_restore_pass && ...
            cases{1}.all_logged_initial_states_bitwise_equal && ...
            cases{1}.all_native_initial_values_bitwise_equal && ...
            ~cases{2}.simulation_returned_without_error && ~isempty(cases{2}.error_message));
        return;
    end
    required={'mode';'python_executable';'source_contract_path'};
    assert(all(ismember(required,fieldnames(options))) && ...
        all(ismember(fieldnames(options),[required;{'reference_review_path';'recording_contract_path';'collection_root';'resume_collection';'endpoint_contract_path';'candidate_Tc_K'}])) && ...
        any(strcmp(options.mode,{'split_preflight','packet_collection','boundary_parameter_probe'})) && strcmp(state.mode,'diagnostic_resume') && ...
        cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && ...
        isempty(fieldnames(factors)) && ~isfield(state,'native_inventory_window_cycles'), ...
        'Observation preflight requires the unchanged qualified native resume recipe, no geometry or log-cap override.');
    for key={'python_executable','source_contract_path'}
        options.(key{1})=char(string(options.(key{1})));
        assert(isfile(options.(key{1})),'Missing observation prerequisite: %s',key{1});
    end
    if isfield(options,'reference_review_path')
        assert(strcmp(options.mode,'split_preflight') && isfile(options.reference_review_path),'Missing immutable reference review.');
    end
    extra={'recording_contract_path','collection_root','resume_collection'};
    boundary_fields={'endpoint_contract_path','candidate_Tc_K'};
    if strcmp(options.mode,'boundary_parameter_probe')
        assert(all(isfield(options,boundary_fields)) && ~any(isfield(options,[extra,{'reference_review_path'}])) && ...
            isfile(options.endpoint_contract_path) && isnumeric(options.candidate_Tc_K) && ...
            isscalar(options.candidate_Tc_K) && isfinite(options.candidate_Tc_K) && ...
            abs(options.candidate_Tc_K-276.95)<=.1+1e-12 && abs(options.candidate_Tc_K-276.95)>.001, ...
            'Only a source-bound C72 boundary probe within 0.1 K is permitted.');
    elseif strcmp(options.mode,'packet_collection')
        assert(~any(isfield(options,boundary_fields)));
        assert(all(isfield(options,extra)) && ~isfield(options,'reference_review_path') && ...
            isfile(options.recording_contract_path) && ...
            islogical(options.resume_collection) && isscalar(options.resume_collection), ...
            'Bounded collection needs its sealed source and explicit restart policy.');
    else
        assert(~any(isfield(options,[extra,boundary_fields])),'Split tests cannot accept collection overrides.');
    end
end

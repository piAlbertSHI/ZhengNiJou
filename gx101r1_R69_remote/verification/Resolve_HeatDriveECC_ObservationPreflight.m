function options=Resolve_HeatDriveECC_ObservationPreflight(options,state,cycles,duration,arm,endpoint_all,factors)
% Execution-only comparison; the configured model and native history stay unchanged.
    assert(isstruct(options) && isscalar(options),'Require scalar observation options.');
    if isempty(fieldnames(options)),return;end
    if isfield(options,'mode') && strcmp(options.mode,'runtime_boundary_warmup')
        required={'mode';'python_executable';'source_contract_path';'recording_contract_path'; ...
            'collection_root';'resume_collection';'collection_stop_s'};
        assert(isequal(sort(fieldnames(options)),sort(required)) && ...
            strcmp(state.mode,'capture') && state.command_horizon_cycles==200 && ...
            isequal(sort(fieldnames(state)),sort({'mode';'command_horizon_cycles'})) && ...
            cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)) && ...
            islogical(options.resume_collection) && isscalar(options.resume_collection));
        for key={'python_executable','source_contract_path','recording_contract_path'}
            assert(isfile(options.(key{1})),'Missing runtime warmup prerequisite.');
        end
        pointer=jsondecode(fileread(options.recording_contract_path));
        assert(isscalar(options.collection_stop_s) && isnumeric(options.collection_stop_s) && ...
            isfinite(options.collection_stop_s) && options.collection_stop_s-pointer.snapshot_time_s==200 && ...
            options.collection_stop_s<=2000 && pointer.snapshot_time_s>=20 && ...
            mod(pointer.snapshot_time_s,20)==0 && ~pointer.production_recovery_allowed && ~pointer.outer_solve_eligible, ...
            'Runtime warmup is an explicit twenty-cycle segment within the unchanged command horizon.');
        return;
    end
    if isfield(options,'mode') && strcmp(options.mode,'runtime_boundary_cold_family')
        assert(isequal(sort(fieldnames(options)),sort({'mode';'python_executable';'source_contract_path';'boundary_probe_path'})) && ...
            strcmp(state.mode,'capture') && state.command_horizon_cycles==200 && ...
            isequal(sort(fieldnames(state)),sort({'mode';'command_horizon_cycles'})) && ...
            cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && isempty(fieldnames(factors)), ...
            'The runtime family is an independent cold capture, never a migrated or partial OP.');
        for key={'python_executable','source_contract_path','boundary_probe_path'}
            assert(isfile(options.(key{1})),'Missing runtime-family prerequisite.');
        end
        probe=jsondecode(fileread(options.boundary_probe_path));
        cases=probe.cases;if isstruct(cases),cases=num2cell(cases);end
        assert(iscell(cases) && numel(cases)==2);
        assert(probe.experiment_completed && ~probe.candidate_compatible && ...
            strcmp(probe.checksum_policy,'error/error') && ~probe.source_state_edited && ...
            ~probe.new_OP_saved && cases{1}.strict_vendor_restore_pass && ...
            cases{1}.all_logged_initial_states_bitwise_equal && ...
            cases{1}.all_native_initial_values_bitwise_equal && ...
            ~cases{2}.simulation_returned_without_error && ~isempty(cases{2}.error_message));
        return;
    end
    required={'mode';'python_executable';'source_contract_path'};
    assert(all(ismember(required,fieldnames(options))) && ...
        all(ismember(fieldnames(options),[required;{'reference_review_path';'recording_contract_path';'collection_root';'resume_collection';'endpoint_contract_path';'candidate_Tc_K'}])) && ...
        any(strcmp(options.mode,{'split_preflight','packet_collection','boundary_parameter_probe'})) && strcmp(state.mode,'diagnostic_resume') && ...
        cycles==20 && duration==200 && strcmp(arm,'native') && endpoint_all && ...
        isempty(fieldnames(factors)) && ~isfield(state,'native_inventory_window_cycles'), ...
        'Observation preflight requires the unchanged qualified native resume recipe, no geometry or log-cap override.');
    for key={'python_executable','source_contract_path'}
        options.(key{1})=char(string(options.(key{1})));
        assert(isfile(options.(key{1})),'Missing observation prerequisite: %s',key{1});
    end
    if isfield(options,'reference_review_path')
        assert(strcmp(options.mode,'split_preflight') && isfile(options.reference_review_path),'Missing immutable reference review.');
    end
    extra={'recording_contract_path','collection_root','resume_collection'};
    boundary_fields={'endpoint_contract_path','candidate_Tc_K'};
    if strcmp(options.mode,'boundary_parameter_probe')
        assert(all(isfield(options,boundary_fields)) && ~any(isfield(options,[extra,{'reference_review_path'}])) && ...
            isfile(options.endpoint_contract_path) && isnumeric(options.candidate_Tc_K) && ...
            isscalar(options.candidate_Tc_K) && isfinite(options.candidate_Tc_K) && ...
            abs(options.candidate_Tc_K-276.95)<=.1+1e-12 && abs(options.candidate_Tc_K-276.95)>.001, ...
            'Only a source-bound C72 boundary probe within 0.1 K is permitted.');
    elseif strcmp(options.mode,'packet_collection')
        assert(~any(isfield(options,boundary_fields)));
        assert(all(isfield(options,extra)) && ~isfield(options,'reference_review_path') && ...
            isfile(options.recording_contract_path) && ...
            islogical(options.resume_collection) && isscalar(options.resume_collection), ...
            'Bounded collection needs its sealed source and explicit restart policy.');
    else
        assert(~any(isfield(options,[extra,boundary_fields])),'Split tests cannot accept collection overrides.');
    end
end

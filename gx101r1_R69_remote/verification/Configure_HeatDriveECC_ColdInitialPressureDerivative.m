function contract=Configure_HeatDriveECC_ColdInitialPressureDerivative(model)
% Supply the verified right derivative only for an initial-point diagnostic.
    assert(strcmp(get_param(model,'StartTime'),'0') && strcmp(get_param(model,'StopTime'),'0'), ...
        'A constant initial derivative is forbidden for a trajectory.');
    assert(strcmp(get_param(model,'LoadInitialState'),'off') && ...
        strcmp(get_param(model,'SaveOperatingPoint'),'off'),'Cold diagnostic only.');
    blocks={'SMAPressureBiasFromWorkspace','SMAPressureFeedbackEnableFromWorkspace','SMAPressureFeedbackResetFromWorkspace'};
    variables={'SMA_pressure_bias_command','SMA_pressure_feedback_enable_command','SMA_pressure_feedback_reset_command'};
    interpolation={'on','off','off'};samples=cell(1,3);until=Inf;
    for k=1:3
        b=[model '/' blocks{k}];
        assert(strcmp(get_param(b,'VariableName'),variables{k}) && ...
            strcmp(get_param(b,'Interpolate'),interpolation{k}),'Unexpected command source.');
        v=slResolve(variables{k},b);
        assert(isa(v,'timeseries') && numel(v.Time)>=2 && v.Time(1)==0 && ...
            v.Time(2)>0 && isvector(v.Data) && all(isfinite(v.Data(1:2))) && ...
            v.Data(1)==v.Data(2),'Require a constant initial command interval.');
        samples{k}=struct('block',b,'variable',variables{k},'interpolate',interpolation{k}, ...
            'time_s',v.Time(1:2),'values',v.Data(1:2));
        until=min(until,v.Time(2));
    end
    assert(samples{2}.values(1)==0 && samples{3}.values(1)==1,'Feedback must be disabled and reset held.');
    integrator=[model '/SMAPressurePI_Integrator'];
    assert(strcmp(get_param(integrator,'ExternalReset'),'level') && ...
        strcmp(get_param(integrator,'InitialConditionSource'),'internal') && ...
        strcmp(get_param(integrator,'InitialCondition'),'0'),'Integrator must remain reset at zero.');
    assert(strcmp(get_param([model '/SMAPressurePEnableProduct'],'Inputs'),'**') && ...
        strcmp(get_param([model '/SMAPressurePI_BiasSum'],'Inputs'),'+++'),'Unexpected PI algebra.');
    connections={ 'SMAPressurePEnableProduct',2,'SMAPressureFeedbackEnableFromWorkspace'; ...
        'SMAPressurePI_Integrator',2,'SMAPressureFeedbackResetFromWorkspace'; ...
        'SMAPressurePI_BiasSum',1,'SMAPressurePEnableProduct'; ...
        'SMAPressurePI_BiasSum',2,'SMAPressurePI_Integrator'; ...
        'SMAPressurePI_BiasSum',3,'SMAPressureBiasFromWorkspace'; ...
        'SMAPressurePI_Saturation',1,'SMAPressurePI_BiasSum'; ...
        'SMAPressurePI_SimulinkPS',1,'SMAPressurePI_Saturation'};
    for k=1:size(connections,1)
        assert(strcmp(input_source([model '/' connections{k,1}],connections{k,2}), ...
            [model '/' connections{k,3}]),'Pressure PI wiring differs.');
    end
    converter=[model '/SMAPressurePI_SimulinkPS'];
    assert(strcmp(get_param(converter,'Unit'),'MPa') && ...
        strcmp(get_param(converter,'FilteringAndDerivatives'),'provide') && ...
        strcmp(get_param(converter,'UdotUserProvided'),'0'),'Require unfiltered input-only baseline.');
    value_source=input_source(converter,1);
    set_param(converter,'UdotUserProvided','1');
    ports=get_param(converter,'PortHandles');assert(numel(ports.Inport)==2,'Require value and first derivative ports.');
    derivative=[model '/ColdInitialPressureDerivativeOnly'];
    add_block('simulink/Sources/Constant',derivative,'Value','0','SampleTime','inf');
    p=get_param(derivative,'PortHandles');add_line(model,p.Outport(1),ports.Inport(2));
    assert(strcmp(input_source(converter,1),value_source) && ...
        strcmp(input_source(converter,2),derivative),'Do not alter the pressure value path.');
    contract=struct('initialization_only',true,'allowed_stop_time_s',0, ...
        'constant_interval_start_s',0,'constant_interval_end_exclusive_s',until, ...
        'first_derivative_MPa_per_s',0,'command_samples',{samples}, ...
        'value_source',value_source,'derivative_source',derivative,'connections',{connections}, ...
        'filtering','provide','provided_derivatives_before','0','provided_derivatives_after','1', ...
        'production_recovery_allowed',false,'full_cycle_derivative_verified',false);
end

function source=input_source(block,index)
    p=get_param(block,'PortHandles');line=get_param(p.Inport(index),'Line');
    assert(line~=-1,'Missing pressure command connection.');
    source=getfullname(get_param(line,'SrcBlockHandle'));
end

function record = Audit_HeatDriveECC_SavedMechanism(source_root, output_root, controller_root)
% Run original production predicates on the last pair of an immutable qualified segment.
    assert(~isfolder(output_root), 'Never overwrite a mechanism audit.');
    completion = jsondecode(fileread(fullfile(source_root, 'native', 'arm_completion.json')));
    execution = jsondecode(fileread(fullfile(source_root, 'cold_chamber_execution.json')));
    source_file = fullfile(source_root, 'native', 'observations.mat');
    contract=execution.diagnostic_resume_contract;
    original=strcmp(contract.schema,'heatdrive_ecc_state_qualified_diagnostic_resume_v1') && ...
        execution.start_time_s==20 && execution.stop_time_s==220 && contract.full_cycle_state_restore_verified;
    latest=strcmp(contract.schema,'heatdrive_ecc_latest_qualified_diagnostic_resume_v2') && ...
        contract.ancestor_complete_cycle_restore_verified && contract.source_physical_gates_evaluated && ...
        ~contract.latest_endpoint_complete_cycle_reference_compared && ...
        contract.snapshot_time_s==execution.start_time_s && execution.start_time_s>=220;
    if latest
        qualification=fullfile(contract.verification_root,'diagnostic_resume_qualification.json');
        assert(strcmp(file_hash(qualification),contract.qualification_sha256), ...
            'Changed latest-endpoint qualification.');
    end
    assert(execution.requested_arm_collection_pass && isempty(execution.error_message) && ...
        (original || latest) && strcmp(execution.diagnostic_state_options.mode,'diagnostic_resume') && ...
        execution.segment_cycle_count==20 && execution.stop_time_s-execution.start_time_s==200 && ...
        execution.cycle_count*10==execution.stop_time_s && execution.stop_time_s<=2000 && ...
        ~execution.c200_state_imported && ~contract.failed_state_propagated && ...
        ~contract.source_state_edited && ~contract.partial_state_restore_used && ...
        ~execution.production_recovery_allowed && ...
        strcmp(completion.observation_sha256, file_hash(source_file)), ...
        'Require complete, hash-bound actual diagnostic segment evidence.');
    configured = load(fullfile(source_root, 'native', 'configuration.mat'), 'options');
    options = configured.options;
    controller_receipt_sha256 = '';
    if nargin >= 3 && ~isempty(controller_root)
        receipt_file = fullfile(controller_root, 'controller_contract_verification.json');
        proof = jsondecode(fileread(receipt_file));
        assert(strcmp(proof.source_root, source_root) && ...
            strcmp(proof.source_producer, execution.execution_commit) && ...
            proof.audit_expression_only_change_verified && proof.source_model_control_unchanged && ...
            proof.physical_audit_sections_unchanged && ...
            proof.route_memory_before_distributed.pass && proof.route_memory_after_distributed.pass && ...
            ~proof.simulation_executed && ~proof.operating_point_loaded && ...
            ~proof.production_recovery_allowed && ...
            isequaln(jsondecode(jsonencode(options.validation.article_component_pipe_UA_audit)), ...
                proof.original_article_audit), 'Controller correction evidence does not match saved source.');
        options.validation.article_component_pipe_UA_audit = proof.corrected_article_audit;
        options.validation.article_component_pipe_UA_implemented = proof.corrected_article_audit.ok;
        controller_receipt_sha256 = file_hash(receipt_file);
    end
    saved = load(source_file, 'signals', 'thermal_boundary_signals');
    observation = Slice_HeatDriveECC_SavedMechanismObservation(saved, ...
        execution.stop_time_s-20, execution.stop_time_s, ...
        options.simulation.fixed_step_s);
    physical = Extract_HeatDriveECC_PhysicalLogs(observation, options, '', false);
    % Direct workspace channels must survive the shared extractor unchanged.
    assert(isequaln(physical.SMA_T_21_K, observation.signals.SMA_Tx21_internal.values) && ...
        isequaln(physical.SE_T_21_K, observation.signals.SE_Tx21_internal.values) && ...
        isequaln(physical.xM_SMA_21, observation.signals.ECC_constitutive21_output.values(:,43:63)) && ...
        isequaln(physical.xM_SE_21, observation.signals.ECC_constitutive21_output.values(:,64:84)), ...
        'Shared extraction changed saved material coordinates.');
    temperature_mask = HeatDriveECC_IsTemperatureSignal(fieldnames(observation.signals));
    names = fieldnames(observation.signals);
    expected_probes = names(temperature_mask);
    for k = 1:numel(expected_probes)
        name = expected_probes{k};
        if size(observation.signals.(name).values, 2) ~= 1, continue; end
        assert(isfield(physical.probes, name) && ...
            isequaln(physical.probes.(name), observation.signals.(name).values), ...
            'Temperature probe missing or changed: %s', name);
    end
    legacy_mask = contains(names, 'temp', 'IgnoreCase', true) | contains(names, 'probe_', 'IgnoreCase', true);
    excluded = names(legacy_mask & ~temperature_mask);
    physical.authority = 'physical_simscape_to_workspace_logs';
    physical.legacy_surrogate_used_for_results = false;
    physical.sim_call_count = 1; % One documented actual sim() for the saved segment.
    physical.walltime_s = NaN; % Historical total wall time is not the simulation time.
    provenance = struct('checkpoint_chain_verified', true, 'checkpoint_restart_used', true, ...
        'sim_call_count', 1, 'solver', options.simulation.solver, ...
        'fixed_step_s', options.simulation.fixed_step_s, 'simulation_mode', options.simulation.mode, ...
        'execution_commit', execution.execution_commit, ...
        'observation_sha256', completion.observation_sha256, ...
        'simulation_executed_by_this_audit', false, 'production_recovery_allowed', false);
    mkdir(output_root);
    view = Make_HeatDriveECC_MechanismWindow(physical, options, provenance, output_root);
    audit = Validate_HeatDriveECC_EighthRound_Physics(view);
    checks = fieldnames(audit.checks);
    failed = checks(~cellfun(@(name) logical(audit.checks.(name)), checks));
    [status, commit] = system('git rev-parse HEAD');
    assert(status == 0, 'Missing audit provenance.');
    record = struct('schema', 'heatdrive_ecc_saved_production_mechanism_audit_v1', ...
        'source_root', source_root, 'source_observation_sha256', completion.observation_sha256, ...
        'source_execution_sha256', file_hash(fullfile(source_root, 'cold_chamber_execution.json')), ...
        'source_configuration_sha256', file_hash(fullfile(source_root, 'native', 'configuration.mat')), ...
        'audit_execution_commit', strtrim(commit), 'source_execution_commit', execution.execution_commit, ...
        'controller_correction_receipt_sha256', controller_receipt_sha256, ...
        'simulation_executed', false, 'operating_point_loaded', false, ...
        'exact_saved_window_pass', true, 'direct_material_coordinates_equal', true, ...
        'temperature_probes_exact', true, 'non_temperature_probes_excluded', {excluded}, ...
        'analysis_window', view.analysis_window, 'original_production_predicates_evaluated', true, ...
        'checks', audit.checks, 'failed_checks', {failed}, 'diagnostics', audit.diagnostics, ...
        'mechanism_pass', audit.passed, 'full_device_first_law_verified', false, ...
        'periodic_steady_state_verified', false, 'strict_table4_reproduction_pass', false, ...
        'production_recovery_allowed', false);
    save(fullfile(output_root, 'mechanism_view.mat'), 'physical', 'options', 'provenance', '-v7.3');
    fid = fopen(fullfile(output_root, 'saved_mechanism_audit.json'), 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'Cannot save mechanism receipt.');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(record, 'PrettyPrint', true));
    fprintf('%s\n', jsonencode(record));
end

function result = file_hash(file)
    digest = java.security.MessageDigest.getInstance('SHA-256');
    fid = fopen(file, 'rb'); assert(fid >= 0, 'Missing immutable evidence.');
    cleanup = onCleanup(@() fclose(fid));
    while ~feof(fid), digest.update(fread(fid, 8*1024*1024, '*uint8')); end
    result = upper(reshape(dec2hex(typecast(digest.digest(), 'uint8'), 2).', 1, []));
end

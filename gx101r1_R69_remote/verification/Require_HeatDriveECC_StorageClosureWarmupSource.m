function contract = Require_HeatDriveECC_StorageClosureWarmupSource(source_root, state_audit_path, cycle_audit_path)
% Exact C2 state plus full C3 proof admit unchanged-model transient continuation only.
    state=Require_HeatDriveECC_StorageClosureCheckpoint(source_root,state_audit_path);
    audit=jsondecode(fileread(cycle_audit_path));
    assert(strcmp(audit.schema,'heatdrive_ecc_storage_closure_complete_cycle_restore_v1') && ...
        strcmp(canonical(audit.source_root),canonical(source_root)) && ...
        strcmp(audit.C2_audit_sha256,file_hash(state_audit_path)) && ...
        strcmp(audit.source_operating_point_sha256,state.operating_point_sha256) && ...
        strcmp(audit.source_history_sha256,state.history_sha256) && ...
        audit.complete_cycle_restore_verified && audit.diagnostic_warmup_continuation_allowed && ...
        audit.full_mechanism_checks_passed==73 && audit.local_inventory_pass && ...
        audit.modeled_energy_balance.model_equation_energy_closure_pass && ...
        isequal(audit.actual_restored_window_s(:),[20;30]) && ...
        audit.state_groups_exact==74 && audit.signals_exact==201 && audit.samples_per_comparison==10001 && ...
        strcmp(audit.checksum_policy,'error/error') && ~audit.source_state_edited && ...
        ~audit.failed_state_propagated && ~audit.production_recovery_allowed && ...
        ~audit.outer_solve_eligible && ~audit.periodic_steady_state && ...
        ~audit.real_fluid_EOS_claim && ~audit.table4_reproduction_claim, ...
        'Require source-bound complete-cycle storage-model proof, not production authority.');
    files={'native/rebuilt_cycle_restore.json','native/rebuilt_cycle_comparison.mat', ...
        'native/restored_native_ledger_observation.mat','native/restored_physical_observation.mat', ...
        'native/configuration.mat','cold_chamber_execution.json'};
    names=cellfun(@matlab.lang.makeValidName,files,'UniformOutput',false);
    assert(isequal(sort(names(:)),sort(fieldnames(audit.input_sha256))), 'Incomplete C3 evidence inventory.');
    for k=1:numel(files)
        assert(strcmp(file_hash(fullfile(audit.restored_root,files{k})),audit.input_sha256.(names{k})), ...
            'Complete-cycle evidence changed: %s',files{k});
    end
    for marker={'REJECTED_DO_NOT_RESUME.json','REJECTED_DO_NOT_RESUME.txt','INCOMPLETE_DO_NOT_RESUME.json'}
        assert(~isfile(fullfile(source_root,marker{1})) && ...
            ~isfile(fullfile(audit.restored_root,marker{1})), 'Rejected evidence cannot propagate.');
    end
    proof=jsondecode(fileread(fullfile(audit.restored_root,files{1})));
    assert(proof.rebuilt_complete_cycle_pass && proof.strict_restore_completed && ...
        proof.continuous_reference_pass && isempty(proof.error_message) && ...
        proof.bounded_restored_cycle_mechanism_pass && ...
        numel(fieldnames(proof.bounded_restored_cycle_mechanism_checks))==73 && ...
        all(structfun(@logical,proof.bounded_restored_cycle_mechanism_checks)), 'Original mechanism predicates failed.');
    contract=state;
    contract.schema='heatdrive_ecc_storage_closure_warmup_source_v1';
    contract.verification_root=canonical(audit.restored_root);
    contract.complete_cycle_audit_sha256=file_hash(cycle_audit_path);
    contract.complete_cycle_restore_verified=true;
    contract.diagnostic_warmup_continuation_allowed=true;
end

function result=canonical(path)
    result=char(java.io.File(path).getCanonicalPath());
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

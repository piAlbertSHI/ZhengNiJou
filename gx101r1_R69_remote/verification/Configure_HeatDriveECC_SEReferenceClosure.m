function contract = Configure_HeatDriveECC_SEReferenceClosure(model, options, feedforward, start_time, stop_time)
% Use one physical stroke envelope; route memories remain differential states.
    assert(bdIsLoaded(model) && strcmp(feedforward.schema,'heatdrive_ecc_distributed_pressure_ff_v2'), ...
        'Require the actual distributed-feedforward model.');
    envelope=evalin('base','SE_distributed_pressure_envelope_command');
    original=evalin('base','SE_mdot_target_command');
    if nargin<4,start_time=envelope.Time(1);stop_time=envelope.Time(end);end
    scope=envelope.Time>=start_time-1e-9 & envelope.Time<=stop_time+1e-9;
    assert(isa(envelope,'timeseries') && isequal(envelope.Time,original.Time) && ...
        all(envelope.Data>=0 & envelope.Data<=1) && ...
        strcmp(get_param([model '/SEFlowTargetFromWorkspace'],'VariableName'),'SE_mdot_target_command') && ...
        strcmp(get_param([model '/SEFlowTargetFromWorkspace'],'Interpolate'),'on'), ...
        'Flow reference must bind to the actual common pressure-envelope clock.');
    nominal=options.branch.m_dot_se_the_kg_per_s;
    assert(nominal>0 && nominal==options.branch.m_dot_se_chex_kg_per_s, ...
        'One double-acting piston requires the same nominal stroke mass flow.');
    target=Build_HeatDriveECC_CoherentReferenceCommand(envelope,original,nominal);
    assignin('base','SE_mdot_target_command',target);
    assignin('base','SE_mdot_target_command_time_s',target.Time);
    assignin('base','SE_mdot_target_command_values',target.Data);
    gates=cell(1,2);
    for index=1:2
        stage=[2 4];route=stage(index);
        variable=sprintf('SE_stage%d_pressure_integrator_output_enable_command',route);
        before=evalin('base',variable);
        after=Build_HeatDriveECC_CoherentReferenceCommand(envelope,before);
        assignin('base',variable,after);
        assignin('base',[variable '_time_s'],after.Time);
        assignin('base',[variable '_values'],after.Data);
        gate_scope=before.Time>=start_time-1e-9 & before.Time<=stop_time+1e-9;
        gates{index}=struct('stage',route,'time_s',double(before.Time(gate_scope)), ...
            'original_output_enable',double(before.Data(gate_scope)), ...
            'coherent_output_enable',double(after.Data(gate_scope)));
    end
    contract=struct('schema','heatdrive_ecc_se_coherent_reference_v1', ...
        'nominal_mass_flow_kgps',nominal,'time_s',double(target.Time(scope)), ...
        'original_PI_target_kgps',double(original.Data(scope)), ...
        'coherent_PI_target_kgps',double(target.Data(scope)),'stroke_envelope',double(envelope.Data(scope)), ...
        'observed_contract_window_s',[start_time stop_time], ...
        'complete_generated_command_horizon_s',double(target.Time(end)), ...
        'route_output_gates',{gates},'original_ff_pressure_envelope_unchanged',true, ...
        'PI_reference_changed',true,'integrator_update_gates_changed',false, ...
        'integrator_memory_reset',false,'gains_changed',false,'geometry_changed',false, ...
        'source_state_loaded',false,'production_recovery_allowed',false, ...
        'interpretation','Common envelope on FF, PI target and remembered-I output; not an integral-state reset.');
end

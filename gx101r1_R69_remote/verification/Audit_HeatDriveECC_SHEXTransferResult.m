function audit = Audit_HeatDriveECC_SHEXTransferResult(result_path)
% Audit source and downstream SHEX thermal-transfer signals in one result.

    assert(isfile(result_path), 'HeatDriveECC:MissingSHEXTransferResult', ...
        'Production result is missing: %s', result_path);
    loaded = load(result_path, 'summary', 'options', 'provenance');
    required = {'summary','options','provenance'};
    assert(all(isfield(loaded, required)), ...
        'HeatDriveECC:IncompleteSHEXTransferResult', ...
        'Production result package is incomplete.');
    p = loaded.summary.performance;
    names = {'SHEX_source_heat_flow_mean_W', ...
        'SHEX_source_heat_input_W', ...
        'SHEX_source_heat_flow_direction_pass', ...
        'SHEX_sink_to_fluid_heat_flow_mean_W', ...
        'SHEX_sink_to_fluid_heat_input_W', ...
        'SHEX_sink_to_fluid_heat_flow_direction_pass', ...
        'periodic_steady_state'};
    present = all(cellfun(@(name) isfield(p, name), names));
    assert(present, 'HeatDriveECC:MissingSHEXTransferMetrics', ...
        'Production result lacks required SHEX transfer metrics.');
    finite = isfinite(p.SHEX_source_heat_flow_mean_W) && ...
        isfinite(p.SHEX_source_heat_input_W) && ...
        isfinite(p.SHEX_sink_to_fluid_heat_flow_mean_W) && ...
        isfinite(p.SHEX_sink_to_fluid_heat_input_W);

    audit = struct();
    audit.schema = 'heatdrive_ecc_shex_transfer_result_audit_v1';
    audit.result_path = result_path;
    audit.signals_present = present;
    audit.signals_finite = finite;
    audit.source_direction_pass = present && logical( ...
        p.SHEX_source_heat_flow_direction_pass);
    audit.sink_to_fluid_direction_pass = present && logical( ...
        p.SHEX_sink_to_fluid_heat_flow_direction_pass);
    audit.periodic_steady_state = present && logical(p.periodic_steady_state);
    audit.source_heat_input_W = p.SHEX_source_heat_input_W;
    audit.sink_to_fluid_heat_input_W = p.SHEX_sink_to_fluid_heat_input_W;
    audit.transfer_ratio = audit.sink_to_fluid_heat_input_W / ...
        max(audit.source_heat_input_W, eps);
    audit.positive_heat_input_difference_W = ...
        audit.source_heat_input_W - audit.sink_to_fluid_heat_input_W;
    audit.system_energy_closure_complete = false;
    audit.system_energy_closure_status = ...
        ['SHEX source and sink-to-fluid branches measured; complete ', ...
        'coupled-system closure still requires HHEX/CHEX/buffer/pipe ', ...
        'thermal-flow boundaries'];
    audit.production_pass = audit.signals_present && audit.signals_finite && ...
        audit.source_direction_pass && audit.sink_to_fluid_direction_pass && ...
        audit.periodic_steady_state && audit.transfer_ratio > 0.0 && ...
        audit.transfer_ratio <= 1.5 && ...
        loaded.provenance.checkpoint_restart_used && ...
        loaded.provenance.checkpoint_chain_verified;
    fprintf(['SHEX_TRANSFER_RESULT_PASS=%d source_W=%.12g ', ...
        'sink_to_fluid_W=%.12g ratio=%.12g periodic=%d\n'], ...
        audit.production_pass, audit.source_heat_input_W, ...
        audit.sink_to_fluid_heat_input_W, audit.transfer_ratio, ...
        audit.periodic_steady_state);
end

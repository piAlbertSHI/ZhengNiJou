function record = Verify_HeatDriveECC_StableConstitutivePrototype(input_root, stiffness_root, output_root)
% Local refinement evidence is necessary, never sufficient for a coupled production promotion.
    assert(~isfolder(output_root),'Never overwrite numerical prototype evidence.');
    contract=jsondecode(fileread(fullfile(input_root,'replay_input_contract.json')));
    evidence=jsondecode(fileread(fullfile(stiffness_root,'constitutive_replay_stiffness.json')));
    assert(evidence.all_252_output_coordinates_exact && evidence.local_stability_evaluated && ...
        strcmp(evidence.source_fixture_sha256,contract.replay_fixture_sha256), 'Require exact original replay.');
    configured=load(fullfile(contract.source_root,'native','configuration.mat'),'options');options=configured.options;
    input=load(fullfile(input_root,'constitutive_replay_inputs.mat'));dt=.001;
    assert(strcmp(file_hash(fullfile(input_root,'constitutive_replay_inputs.mat')),contract.replay_fixture_sha256));
    rows=cell(numel(evidence.selected_frames),1);
    for k=1:numel(rows)
        frame=evidence.selected_frames(k);idx=find(abs(input.time_s-frame.time_s)<1e-9);
        assert(isscalar(idx));state=Initialize_HeatDriveECC_EighthRound_State(options);
        state.Ta_21=input.temperature_sma(idx,:).';state.Tr_21=input.temperature_se(idx,:).';
        fields={'xM_a_21','xM_r_21','sigma_a_21','sigma_r_21','epsilon_a_21','epsilon_r_21', ...
            'pai_a_21','pai_r_21','r_xi_a_21','r_xi_r_21'};
        for j=1:10,state.(fields{j})=input.memory(idx,(j-1)*21+(1:21)).';end
        [next,audit,numerical]=Integrate_HeatDriveECC_StableConstitutiveSample(state,options,dt,frame.stage_id);
        reference=state;reference_energy=zeros(21,4);
        names={'latentA_J_21','latentR_J_21','mechanicalA_J_21','mechanicalR_J_21'};
        for sub=1:4*numerical.substeps
            [reference,detail]=HeatDriveECC_ConstitutiveCompatibilityStep51(reference,options,dt/(4*numerical.substeps),frame.stage_id);
            for j=1:4,reference_energy(:,j)=reference_energy(:,j)+detail.(names{j});end
        end
        phase_error=max(abs([next.xM_a_21;next.xM_r_21]-[reference.xM_a_21;reference.xM_r_21]));
        final_phase=[next.xM_a_21;next.xM_r_21];
        g=options.geometry;a=options.material.SMA;r=options.material.SE;
        massA=a.rho_kg_per_m3*g.S_a_m2*g.L_a_m/21;massR=r.rho_kg_per_m3*g.S_r_m2*g.L_r_m/21;
        latent_residual=max(abs([audit.latentA_J_21+massA*a.Delta_h_J_per_kg*(next.xM_a_21-state.xM_a_21); ...
            audit.latentR_J_21+massR*r.Delta_h_J_per_kg*(next.xM_r_21-state.xM_r_21)]));
        accumulated=[audit.latentA_J_21,audit.latentR_J_21,audit.mechanicalA_J_21,audit.mechanicalR_J_21];
        aliases_equal=isequaln(audit.latentA_W_21,audit.latentA_W_51) && ...
            isequaln(audit.mechanicalR_W_21,audit.mechanicalR_W_51);
        rows{k}=struct('time_s',frame.time_s,'stage_id',frame.stage_id,'substeps',numerical.substeps, ...
            'bound_per_s',numerical.phase_jacobian_norm_bound_per_s, ...
            'internal_step_times_bound',numerical.internal_step_times_bound, ...
            'reference_substeps',4*numerical.substeps,'phase_difference_from_reference',phase_error, ...
            'energy_difference_from_reference_J',max(abs(accumulated-reference_energy),[],1), ...
            'latent_telescoping_residual_J',latent_residual, ...
            'phase_bounds_pass',all(final_phase>=0 & final_phase<=1), ...
            'force_residual_N',audit.force_residual_N,'displacement_residual_m',audit.disp_residual_m, ...
            'legacy_energy_aliases_equal',aliases_equal);
    end
    all_rows=vertcat(rows{:});
    record=struct('schema','heatdrive_ecc_stable_constitutive_prototype_v1', ...
        'source_producer',contract.producer,'source_fixture_sha256',contract.replay_fixture_sha256, ...
        'original_replay_receipt_sha256',file_hash(fullfile(stiffness_root,'constitutive_replay_stiffness.json')), ...
        'local_phase_accuracy_target',1e-6,'maximum_phase_difference',max([all_rows.phase_difference_from_reference]), ...
        'phase_accuracy_pass',all([all_rows.phase_difference_from_reference]<=1e-6), ...
        'all_phase_bounds_pass',all([all_rows.phase_bounds_pass]), ...
        'all_energy_aliases_equal',all([all_rows.legacy_energy_aliases_equal]), ...
        'maximum_latent_telescoping_residual_J',max([all_rows.latent_telescoping_residual_J]), ...
        'hot_stability_bound',HeatDriveECC_ConstitutiveStabilityBound(options,1,dt), ...
        'cold_stability_bound',HeatDriveECC_ConstitutiveStabilityBound(options,3,dt), ...
        'frames',all_rows,'simulation_executed',false,'operating_point_loaded',false, ...
        'production_constitutive_code_changed',false,'source_state_edited',false, ...
        'production_recovery_allowed',false,'coupled_mesh_convergence_verified',false, ...
        'interpretation','Conservative bound and energy-accumulating ODE3 substeps tested only offline. New coupled numerical branch must qualify independently; never graft onto C82 or C200.');
    mkdir(output_root);fid=fopen(fullfile(output_root,'stable_constitutive_prototype.json'),'w','n','UTF-8');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));fprintf(fid,'%s\n',jsonencode(record,'PrettyPrint',true));
    fprintf('FINAL_JSON=%s\n',jsonencode(struct('phase_accuracy_pass',record.phase_accuracy_pass, ...
        'maximum_phase_difference',record.maximum_phase_difference,'phase_bounds_pass',record.all_phase_bounds_pass, ...
        'latent_telescoping_residual_J',record.maximum_latent_telescoping_residual_J, ...
        'hot_substeps',record.hot_stability_bound.substeps,'cold_substeps',record.cold_stability_bound.substeps)));
    assert(record.phase_accuracy_pass && record.all_phase_bounds_pass && record.all_energy_aliases_equal, ...
        'The offline prototype failed its stated local qualification.');
end

function result=file_hash(file)
    digest=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(file,'rb');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));while ~feof(fid),digest.update(fread(fid,8*1024*1024,'*uint8'));end
    result=upper(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

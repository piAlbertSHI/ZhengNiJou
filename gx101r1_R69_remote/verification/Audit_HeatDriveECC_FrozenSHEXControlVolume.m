function audit = Audit_HeatDriveECC_FrozenSHEXControlVolume( ...
        result_path, output_root)
% Reconstruct the SHEX sink-to-fluid heat flow from a frozen result.
%
% The SHEX sink node has one measured source branch, one thermal-mass
% storage term, and one downstream fluid branch. Therefore
% Q_sink_to_fluid = Q_source_to_sink - C_sink*dT_sink/dt.

    arguments
        result_path (1, :) char
        output_root (1, :) char
    end
    assert(isfile(result_path), 'HeatDriveECC:MissingFrozenResult', ...
        'Frozen production result is missing: %s', result_path);
    if ~isfolder(output_root)
        mkdir(output_root);
    end

    loaded = load(result_path, 'physical', 'summary', 'options', ...
        'provenance');
    required_package = {'physical','summary','options','provenance'};
    assert(all(isfield(loaded, required_package)), ...
        'HeatDriveECC:IncompleteFrozenResult', ...
        'Frozen result does not contain the required package fields.');
    p = loaded.physical;
    required_signals = {'time_s','SHEX_T_K','Q_SHEX_source_to_sink_W'};
    assert(all(isfield(p, required_signals)), ...
        'HeatDriveECC:MissingSHEXControlVolumeSignal', ...
        'Frozen result lacks a required SHEX control-volume signal.');
    perf = loaded.summary.performance;
    required_metrics = {'qian_window_start_s','qian_window_end_s', ...
        'periodic_steady_state','SHEX_source_heat_flow_direction_pass'};
    assert(all(isfield(perf, required_metrics)), ...
        'HeatDriveECC:MissingSHEXControlVolumeMetric', ...
        'Frozen result lacks a required SHEX performance metric.');
    assert(isfield(loaded.options.system, 'shex_sink_C_J_per_K'), ...
        'HeatDriveECC:MissingSHEXSinkCapacity', ...
        'SHEX sink heat capacity is not explicit in the result contract.');

    t = double(p.time_s(:));
    source = double(p.Q_SHEX_source_to_sink_W(:));
    sink_T = double(p.SHEX_T_K(:));
    assert(numel(t) == numel(source) && numel(t) == numel(sink_T), ...
        'HeatDriveECC:SHEXControlVolumeShapeMismatch', ...
        'SHEX time, source heat flow, and temperature shapes differ.');
    assert(all(isfinite(t)) && all(diff(t) >= 0.0), ...
        'HeatDriveECC:InvalidSHEXControlVolumeData', ...
        'SHEX time must be finite and nondecreasing.');
    raw_sample_count = numel(t);
    [t, unique_idx] = unique(t, 'last');
    source = source(unique_idx);
    sink_T = sink_T(unique_idx);
    duplicate_time_count = raw_sample_count - numel(t);
    assert(all(diff(t) > 0.0), ...
        'HeatDriveECC:InvalidSHEXControlVolumeTimeOrder', ...
        'SHEX time must be strictly increasing after event-point collapse.');

    start_s = double(perf.qian_window_start_s);
    end_s = double(perf.qian_window_end_s);
    idx = find(t >= start_s & t <= end_s);
    assert(numel(idx) >= 3 && abs(t(idx(1)) - start_s) <= 1.0e-9 && ...
        abs(t(idx(end)) - end_s) <= 1.0e-9, ...
        'HeatDriveECC:SHEXControlVolumeWindowMismatch', ...
        'The declared Qian window endpoints are not present in the result.');
    tw = t(idx);
    source_w = source(idx);
    sink_T_w = sink_T(idx);
    assert(all(isfinite(source_w)) && all(isfinite(sink_T_w)), ...
        'HeatDriveECC:NonfiniteSHEXControlVolumeWindow', ...
        'The declared SHEX audit window contains nonfinite data.');
    capacity = double(loaded.options.system.shex_sink_C_J_per_K);
    assert(isfinite(capacity) && capacity > 0.0, ...
        'HeatDriveECC:InvalidSHEXSinkCapacity', ...
        'SHEX sink heat capacity must be finite and positive.');

    storage_rate = capacity .* gradient(sink_T_w, tw);
    fluid_flow = source_w - storage_rate;
    duration_s = tw(end) - tw(1);
    source_energy_J = trapz(tw, source_w);
    storage_change_J = capacity * (sink_T_w(end) - sink_T_w(1));
    storage_gradient_energy_J = trapz(tw, storage_rate);
    fluid_energy_J = source_energy_J - storage_change_J;
    numerical_fluid_energy_J = trapz(tw, fluid_flow);
    derivative_residual_J = storage_gradient_energy_J - storage_change_J;
    balance_residual_J = source_energy_J - storage_change_J - ...
        numerical_fluid_energy_J;
    scale_J = max(abs(source_energy_J), eps);

    audit = struct();
    audit.schema = 'heatdrive_ecc_frozen_shex_control_volume_v1';
    audit.result_path = result_path;
    audit.authority = loaded.provenance.authority;
    audit.cycle_count = perf.cycle_count;
    audit.window_start_s = tw(1);
    audit.window_end_s = tw(end);
    audit.window_duration_s = duration_s;
    audit.window_cycles = perf.qian_window_cycles;
    audit.raw_sample_count = raw_sample_count;
    audit.duplicate_event_time_count = duplicate_time_count;
    audit.sink_capacity_J_per_K = capacity;
    audit.source_energy_J = source_energy_J;
    audit.sink_storage_change_J = storage_change_J;
    audit.sink_storage_gradient_energy_J = storage_gradient_energy_J;
    audit.sink_to_fluid_energy_J = fluid_energy_J;
    audit.source_heat_flow_mean_W = source_energy_J / duration_s;
    audit.sink_storage_rate_mean_W = storage_change_J / duration_s;
    audit.sink_to_fluid_heat_flow_mean_W = fluid_energy_J / duration_s;
    audit.sink_to_fluid_heat_flow_min_W = min(fluid_flow);
    audit.sink_to_fluid_heat_flow_max_W = max(fluid_flow);
    audit.sink_to_fluid_positive_fraction = mean(fluid_flow > 0.0);
    audit.transfer_ratio = fluid_energy_J / source_energy_J;
    audit.derivative_integration_residual_J = derivative_residual_J;
    audit.balance_residual_J = balance_residual_J;
    audit.balance_residual_relative = abs(balance_residual_J) / scale_J;
    audit.periodic_steady_state = logical(perf.periodic_steady_state);
    audit.source_direction_pass = logical( ...
        perf.SHEX_source_heat_flow_direction_pass);
    audit.sink_to_fluid_direction_pass = ...
        audit.sink_to_fluid_positive_fraction >= 0.95 && ...
        audit.sink_to_fluid_heat_flow_mean_W > 0.0;
    audit.topology_basis = [ ...
        'Frozen canonical SHEX node: measured source branch + ', ...
        'HotSinkMass storage + HotSinkFluidLink downstream branch'];
    audit.signal_status = 'balance_reconstructed_from_frozen_physical_logs';
    audit.direct_downstream_sensor_used = false;
    audit.system_energy_closure_complete = false;
    audit.system_energy_closure_status = [ ...
        'SHEX control volume closed; complete coupled-system boundary ', ...
        'still requires HHEX/CHEX/buffer/pipe thermal-flow closure'];
    audit.production_pass = audit.periodic_steady_state && ...
        audit.source_direction_pass && audit.sink_to_fluid_direction_pass && ...
        all(isfinite(struct2array(rmfield(audit, { ...
            'schema','result_path','authority','topology_basis', ...
            'signal_status','system_energy_closure_status'})))) && ...
        abs(derivative_residual_J) / scale_J <= 1.0e-9 && ...
        audit.balance_residual_relative <= 1.0e-9 && ...
        audit.transfer_ratio > 0.0 && audit.transfer_ratio <= 1.01;

    save(fullfile(output_root, 'shex_control_volume_audit.mat'), ...
        'audit', '-v7.3');
    write_summary_json(audit, output_root);
    write_sample_csv(tw, source_w, storage_rate, fluid_flow, output_root);
    plot_control_volume(tw, source_w, storage_rate, fluid_flow, ...
        audit, output_root);
    fprintf(['FROZEN_SHEX_CONTROL_VOLUME_PASS=%d source_W=%.12g ', ...
        'sink_to_fluid_W=%.12g ratio=%.12g residual=%.12g\n'], ...
        audit.production_pass, audit.source_heat_flow_mean_W, ...
        audit.sink_to_fluid_heat_flow_mean_W, audit.transfer_ratio, ...
        audit.balance_residual_relative);
end

function write_summary_json(audit, output_root)
    text = jsonencode(audit, PrettyPrint = true);
    fid = fopen(fullfile(output_root, ...
        'shex_control_volume_summary.json'), 'w');
    assert(fid >= 0, 'HeatDriveECC:CannotWriteSHEXSummary', ...
        'Cannot create SHEX control-volume JSON.');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', text);
    clear cleanup
end

function write_sample_csv(t, source, storage, fluid, output_root)
    target_count = min(2001, numel(t));
    pick = unique(round(linspace(1, numel(t), target_count)));
    table_out = table(t(pick), source(pick), storage(pick), fluid(pick), ...
        'VariableNames', {'time_s','source_to_sink_W', ...
        'sink_storage_rate_W','sink_to_fluid_W'});
    writetable(table_out, fullfile(output_root, ...
        'shex_control_volume_sample.csv'));
end

function plot_control_volume(t, source, storage, fluid, audit, output_root)
    last_start = t(end) - 10.0;
    idx = t >= last_start;
    phase = t(idx) - last_start;
    fig = figure('Visible', 'off', 'Color', 'w', ...
        'Position', [80 80 1120 760]);
    cleanup = onCleanup(@() close(fig));
    layout = tiledlayout(fig, 2, 1, 'TileSpacing', 'compact', ...
        'Padding', 'compact');

    ax1 = nexttile(layout, 1);
    plot(ax1, phase, source(idx), 'Color', [0.00 0.32 0.62], ...
        'LineWidth', 1.4, 'DisplayName', 'Source to sink');
    hold(ax1, 'on');
    plot(ax1, phase, fluid(idx), 'Color', [0.75 0.18 0.12], ...
        'LineWidth', 1.4, 'DisplayName', 'Sink to fluid');
    plot(ax1, phase, storage(idx), 'Color', [0.18 0.55 0.34], ...
        'LineWidth', 1.0, 'DisplayName', 'Sink storage rate');
    yline(ax1, 0.0, ':', 'Color', [0.35 0.35 0.35], ...
        'HandleVisibility', 'off');
    xlabel(ax1, 'Cycle phase (s)');
    ylabel(ax1, 'Heat flow (W)');
    title(ax1, '(a) Frozen C240 SHEX node balance, last cycle', ...
        'Color', 'k');
    legend_handle = legend(ax1, 'Location', 'northoutside', ...
        'Orientation', 'horizontal');
    set(legend_handle, 'Color', 'w', 'TextColor', 'k', ...
        'EdgeColor', [0.65 0.65 0.65]);
    grid(ax1, 'on'); box(ax1, 'on');

    ax2 = nexttile(layout, 2);
    means = [audit.source_heat_flow_mean_W, ...
        audit.sink_to_fluid_heat_flow_mean_W, ...
        audit.sink_storage_rate_mean_W];
    bars = bar(ax2, means, 0.62, 'FaceColor', 'flat');
    bars.CData = [0.00 0.32 0.62; 0.75 0.18 0.12; 0.18 0.55 0.34];
    set(ax2, 'XTickLabel', {'Source input','To fluid','Storage'});
    for idx_bar = 1:numel(means)
        offset = max(abs(means(1:2))) * 0.025;
        text(ax2, idx_bar, means(idx_bar) + offset, ...
            sprintf('%.6g W', means(idx_bar)), ...
            'HorizontalAlignment', 'center', 'Color', 'k', ...
            'FontSize', 9);
    end
    ylabel(ax2, 'Window mean (W)');
    title(ax2, sprintf(['(b) Last %d-cycle means; transfer ratio %.9f; ', ...
        'balance residual %.2e'], audit.window_cycles, ...
        audit.transfer_ratio, audit.balance_residual_relative), 'Color', 'k');
    grid(ax2, 'on'); box(ax2, 'on');
    set([ax1 ax2], 'FontName', 'Arial', 'FontSize', 10, ...
        'LineWidth', 0.8, 'TickDir', 'out', 'Color', 'w', ...
        'XColor', 'k', 'YColor', 'k', 'GridColor', [0.78 0.78 0.78], ...
        'GridAlpha', 0.55);

    exportgraphics(fig, fullfile(output_root, ...
        'Fig06_frozen_C240_SHEX_control_volume.png'), 'Resolution', 300);
    exportgraphics(fig, fullfile(output_root, ...
        'Fig06_frozen_C240_SHEX_control_volume.pdf'), ...
        'ContentType', 'vector');
    clear cleanup
end

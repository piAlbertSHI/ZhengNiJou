function record = Export_HeatDriveECC_LocalSolverContract(output_root, physical_path)
% Build-only inspection of actual physical-network solvers; no simulation.
    assert(~isfile(fullfile(output_root, 'local_solver_contract.json')), 'Do not overwrite solver evidence.');
    if ~isfolder(output_root), mkdir(output_root); end
    saved = load(physical_path, 'options');
    [model, options] = Build_HeatDriveECC_EighthRound_Simulink_Model(saved.options);
    cleanup = onCleanup(@() close_system(model, 0));
    paths = find_system(model, 'LookUnderMasks', 'all', 'FollowLinks', 'on', ...
        'MaskType', 'Solver Configuration');
    assert(~isempty(paths), 'No physical-network solver found.');
    rows = cell(size(paths));
    for k = 1:numel(paths)
        rows{k} = struct('block_path', paths{k}, ...
            'UseLocalSolver', get_param(paths{k}, 'UseLocalSolver'), ...
            'LocalSolverChoice', get_param(paths{k}, 'LocalSolverChoice'), ...
            'LocalSolverSampleTime', get_param(paths{k}, 'LocalSolverSampleTime'));
        assert(strcmp(rows{k}.UseLocalSolver, 'on') && ...
            strcmp(rows{k}.LocalSolverChoice, 'NE_BACKWARD_EULER_ADVANCER') && ...
            str2double(rows{k}.LocalSolverSampleTime) == .001, 'Unexpected local solver.');
    end
    record = struct('schema', 'heatdrive_ecc_local_solver_contract_v1', ...
        'saved_physical_path', physical_path, 'options_simscape', options.simscape, ...
        'global_solver', get_param(model, 'Solver'), 'global_fixed_step', get_param(model, 'FixedStep'), ...
        'global_fields_scope', 'Unconfigured model before SimulationInput overrides, not the executed solver settings', ...
        'simulation_input_solver', options.simulation.solver, 'simulation_input_fixed_step_s', options.simulation.fixed_step_s, ...
        'actual_solver_blocks', {rows}, 'actual_solver_contract_pass', true, 'simulation_run', false, ...
        'production_recovery_allowed', false, 'temporal_convergence_verified', false);
    fid = fopen(fullfile(output_root, 'local_solver_contract.json'), 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'Cannot write solver evidence.');
    file_cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(record, 'PrettyPrint', true));
    fprintf('LOCAL_SOLVER_CONTRACT_PASS=1 BLOCKS=%d SIMULATION_RUN=0\n', numel(paths));
end

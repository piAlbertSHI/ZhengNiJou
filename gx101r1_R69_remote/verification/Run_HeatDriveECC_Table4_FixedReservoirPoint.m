function state = Run_HeatDriveECC_Table4_FixedReservoirPoint(settings)
% Run one prescribed-Tc Qian Table 4 point to periodic steady state.

    if nargin < 1
        settings = struct();
    end
    root_dir = fileparts(fileparts(mfilename('fullpath')));
    defaults = struct( ...
        'Tchex_K', 276.95, ...
        'output_root', fullfile(root_dir, 'outputs', ...
            'qian_table4_fixed_Tc_276p95K'), ...
        'segment_cycles', 20, ...
        'maximum_cycles', 200, ...
        'required_consecutive_near_segments', 1000, ...
        'generate_intermediate_figures', false, ...
        'compact_superseded_segments', false, ...
        'resume_existing_state', true, ...
        'initial_prior_result_path', '', ...
        'initial_checkpoint_path', '', ...
        'initial_state_policy', 'unrestricted', ...
        'mainline_contract_path', '', ...
        'model_overrides', struct(), ...
        'checkpoint_transition_fields', {{}}, ...
        'checkpoint_append_signal_fields', {{}}, ...
        'branch_overrides', struct());
    settings = merge_structs(defaults, settings);
    validate_settings(settings);

    continuation = struct( ...
        'output_root', settings.output_root, ...
        'segment_cycles', settings.segment_cycles, ...
        'maximum_cycles', settings.maximum_cycles, ...
        'required_consecutive_near_segments', ...
            settings.required_consecutive_near_segments, ...
        'generate_intermediate_figures', ...
            settings.generate_intermediate_figures, ...
        'compact_superseded_segments', ...
            settings.compact_superseded_segments, ...
        'resume_existing_state', settings.resume_existing_state, ...
        'initial_prior_result_path', settings.initial_prior_result_path, ...
        'initial_checkpoint_path', settings.initial_checkpoint_path, ...
        'initial_state_policy', settings.initial_state_policy, ...
        'mainline_contract_path', settings.mainline_contract_path, ...
        'model_overrides', settings.model_overrides, ...
        'checkpoint_transition_fields', ...
            {settings.checkpoint_transition_fields}, ...
        'checkpoint_append_signal_fields', ...
            {settings.checkpoint_append_signal_fields}, ...
        'system_overrides', struct( ...
            'Tchex_K', settings.Tchex_K, ...
            'cold_boundary_mode', 'fixed_reservoir_temperature', ...
            'cold_load_mode', 'no_load', ...
            'cold_load_heat_W', 0.0), ...
        'branch_overrides', settings.branch_overrides);
    state = Run_HeatDriveECC_LongSteadyContinuation(continuation);

    manifest = struct( ...
        'schema', 'qian2019_table4_fixed_reservoir_point_v1', ...
        'Tchex_K', settings.Tchex_K, ...
        'cold_boundary_mode', 'fixed_reservoir_temperature', ...
        'state_status', state.status, ...
        'completed_cycles', state.current_cycles, ...
        'last_validated_result_path', state.prior_result_path, ...
        'last_validated_checkpoint_path', state.checkpoint_path, ...
        'last_attempt_cycles', get_field(state, 'last_attempt_cycles', ...
            state.current_cycles), ...
        'last_attempt_result_path', get_field(state, ...
            'last_attempt_result_path', state.prior_result_path), ...
        'created_at', char(datetime('now', ...
            'Format', 'yyyy-MM-dd HH:mm:ss')));
    save(fullfile(settings.output_root, ...
        'fixed_reservoir_point_manifest.mat'), 'manifest', 'settings');
    write_manifest(fullfile(settings.output_root, ...
        'fixed_reservoir_point_manifest.txt'), manifest);
end

function validate_settings(settings)
    if ~isscalar(settings.Tchex_K) || ~isfinite(settings.Tchex_K) || ...
            settings.Tchex_K < 240.15 || settings.Tchex_K > 303.15
        error('HeatDriveECC:InvalidFixedReservoirTemperature', ...
            'Tchex_K must be within the declared SE-fluid range [240.15, 303.15] K.');
    end
    if ~isempty(strtrim(char(string(settings.output_root)))) && ...
            ~exist(settings.output_root, 'dir')
        mkdir(settings.output_root);
    end
end

function write_manifest(path, manifest)
    fid = fopen(path, 'w', 'n', 'UTF-8');
    if fid < 0
        error('HeatDriveECC:FixedPointManifestOpenFailed', ...
            'Cannot write %s.', path);
    end
    cleaner = onCleanup(@() fclose(fid));
    fprintf(fid, 'schema=%s\n', manifest.schema);
    fprintf(fid, 'Tchex_K=%.12g\n', manifest.Tchex_K);
    fprintf(fid, 'cold_boundary_mode=%s\n', manifest.cold_boundary_mode);
    fprintf(fid, 'state_status=%s\n', manifest.state_status);
    fprintf(fid, 'completed_cycles=%d\n', manifest.completed_cycles);
    fprintf(fid, 'last_validated_result_path=%s\n', ...
        manifest.last_validated_result_path);
    fprintf(fid, 'last_validated_checkpoint_path=%s\n', ...
        manifest.last_validated_checkpoint_path);
    fprintf(fid, 'last_attempt_cycles=%d\n', manifest.last_attempt_cycles);
    fprintf(fid, 'last_attempt_result_path=%s\n', ...
        manifest.last_attempt_result_path);
    fprintf(fid, 'created_at=%s\n', manifest.created_at);
    clear cleaner
end

function value = get_field(s, name, fallback)
    if isfield(s, name)
        value = s.(name);
    else
        value = fallback;
    end
end

function out = merge_structs(out, overrides)
    names = fieldnames(overrides);
    for idx = 1:numel(names)
        name = names{idx};
        if isfield(out, name) && isstruct(out.(name)) && ...
                isstruct(overrides.(name))
            out.(name) = merge_structs(out.(name), overrides.(name));
        else
            out.(name) = overrides.(name);
        end
    end
end

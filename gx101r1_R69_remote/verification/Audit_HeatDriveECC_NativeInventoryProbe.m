function audit = Audit_HeatDriveECC_NativeInventoryProbe(output_root)
% Read native component states under an unchanged strict OP restore policy.
% Three-step diagnostic only: no probe Operating Point is saved or promoted.
    repo = fileparts(fileparts(mfilename('fullpath')));
    assert(~isfile(fullfile(output_root, 'native_inventory_probe.json')) && ...
        ~isfile(fullfile(output_root, 'native_inventory_probe.mat')), ...
        'HeatDriveECC:ExistingNativeProbe', 'Do not overwrite an existing probe.');
    authority = Resolve_HeatDriveECC_SourceHeatFlowRecovery(struct( ...
        'contract_path', fullfile(repo, 'verification', 'runtime_c180_recovery_contract.json'), ...
        'recovery_use', 'inventory_diagnostic', ...
        'verify_large_result_hash', true));
    prior = load(authority.result_path, 'options');
    checkpoint = load(authority.checkpoint_path, 'operating_point', 'checkpoint_meta');
    overrides = prior.options;
    overrides.cycle_count = authority.completed_cycles + 1;
    [model, options] = Build_HeatDriveECC_EighthRound_Simulink_Model(overrides);
    cleanup = onCleanup(@() close_system(model, 0));
    if ~isfolder(output_root), mkdir(output_root); end
    audit = struct('schema', 'heatdrive_ecc_native_inventory_probe_v2', ...
        'source_result_sha256', authority.result_sha256, ...
        'source_checkpoint_sha256', authority.checkpoint_sha256, ...
        'strict_restore_pass', false, 'probe_state_may_resume', false, ...
        'full_internal_state_mapping_verified', false, ...
        'start_time_s', checkpoint.checkpoint_meta.time_s, ...
        'stop_time_s', checkpoint.checkpoint_meta.time_s + 3 * options.simulation.fixed_step_s, ...
        'operspec_available', exist('operspec', 'file') ~= 0, ...
        'storage_blocks', {{}}, 'buffer_temperature_comparison', {{}}, ...
        'collection_pass', false, 'error_message', '');
    assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
    input = Simulink.SimulationInput(model);
    input = input.setModelParameter('StartTime', '0', ...
        'StopTime', num2str(audit.stop_time_s, '%.15g'), ...
        'Solver', options.simulation.solver, ...
        'FixedStep', num2str(options.simulation.fixed_step_s, '%.15g'), ...
        'SimulationMode', options.simulation.mode, ...
        'ReturnWorkspaceOutputs', 'on', 'CaptureErrors', 'on', ...
        'SaveTime', 'off', 'SaveOutput', 'off', 'SignalLogging', 'off', ...
        'SimscapeLogLimitData', 'on', 'SimscapeLogDataHistory', ...
            ceil(options.schedule.tau_cycle_s / options.simulation.fixed_step_s) + 2, ...
        'SaveState', 'on', 'StateSaveName', 'internal_state_log', ...
        'SaveFinalState', 'on', 'FinalStateName', 'xFinal', 'SaveOperatingPoint', 'on', ...
        'OperatingPointContentsChecksumMismatchMsg', 'error', ...
        'OperatingPointInterfaceChecksumMismatchMsg', 'error');
    input = input.setVariable('EIGHTH_ROUND_OPTIONS', options);
    input = input.setInitialState(checkpoint.operating_point);
    try
        output = sim(input);
        assert(isempty(output.ErrorMessage), 'HeatDriveECC:NativeProbeSimulationFailed', ...
            '%s', output.ErrorMessage);
        audit.strict_restore_pass = true;
        observation = Extract_HeatDriveECC_ObservedStates(output.internal_state_log, ...
            options.schedule.tau_cycle_s, 11);
        log = output.get('simlog');
        assert(isa(log, 'simscape.logging.Node'), 'Missing native Simscape log.');
        types = {'Pipe (TL)', 'Tank (TL)', 'Constant Volume Chamber (TL)', 'Thermal Mass'};
        for kind = 1:numel(types)
            blocks = find_system(model, 'LookUnderMasks', 'all', 'FollowLinks', 'on', ...
                'Type', 'Block', 'MaskType', types{kind});
            for k = 1:numel(blocks)
                path = blocks{k};
                node = simscape.logging.findNode(log, path);
                assert(~isempty(node), 'Missing native storage block: %s', path);
                variables = node.childIds;
                rows = {};
                for j = 1:numel(variables)
                    child = node.child(variables{j});
                    series = child.series;
                    if ~isempty(series) && series.points > 0
                        rows{end + 1} = struct('name', variables{j}, ...
                            'unit', series.unit, 'time_s', double(time(series)), ...
                            'values', double(values(series)), ...
                            'dimension', series.dimension); %#ok<AGROW>
                    end
                end
                audit.storage_blocks{end + 1} = struct('block_path', path, ...
                    'mask_type', types{kind}, 'child_variables', {variables}, ...
                    'reference_block', get_param(path, 'ReferenceBlock'), ...
                    'mask_parameters', read_storage_parameters(path), ...
                    'leaf_variables', {rows});
            end
        end
        tanks = {'SHEXFluidBuffer', 'HotFluidBuffer', ...
            'SMAHotFluidBuffer', 'ColdFluidBuffer'};
        signals = {'shex_buffer_temp_out', 'hot_buffer_temp_out', ...
            'sma_hot_buffer_temp_out', 'cold_buffer_temp_out'};
        for k = 1:numel(tanks)
            node = simscape.logging.findNode(log, [model '/' tanks{k}]);
            port = node.child('A');
            port_series = port.child('T').series;
            internal_series = node.child('T_I').series;
            measured = output.get(signals{k});
            assert(isstruct(measured) && isfield(measured, 'time'), ...
                'Expected Structure With Time for %s.', signals{k});
            t = double(time(port_series));
            assert(isequal(t(:), double(time(internal_series))) && ...
                isequal(t(:), double(measured.time(:))), ...
                'The temperature comparison requires identical sample times.');
            port_K = double(values(port_series, Units = 'K'));
            internal_K = double(values(internal_series, Units = 'K'));
            measured_K = double(measured.signals.values(:));
            audit.buffer_temperature_comparison{end + 1} = struct( ...
                'tank_path', [model '/' tanks{k}], 'signal_name', signals{k}, ...
                'time_s', t(:), 'port_A_T_K', port_K(:), ...
                'internal_T_I_K', internal_K(:), 'workspace_signal_K', measured_K, ...
                'max_signal_minus_port_abs_K', max(abs(measured_K - port_K(:))), ...
                'max_signal_minus_internal_abs_K', max(abs(measured_K - internal_K(:))), ...
                'signal_is_internal_temperature', false);
        end
        audit.storage_block_count = numel(audit.storage_blocks);
        audit.logged_state_groups = observation.logged_state_group_count;
        audit.logged_state_coordinates = sum(cellfun(@(s) s.channel_count, observation.states));
        audit.collection_pass = true;
        save(fullfile(output_root, 'native_inventory_probe.mat'), ...
            'audit', 'observation', '-v7.3');
    catch e
        audit.error_message = e.message;
        audit.collection_pass = false;
    end
    audit.collection_pass = isempty(audit.error_message);
    fid = fopen(fullfile(output_root, 'native_inventory_probe.json'), 'w', 'n', 'UTF-8');
    assert(fid >= 0, 'Cannot write native probe audit.');
    file_cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s\n', jsonencode(audit, 'PrettyPrint', true));
    clear file_cleanup cleanup
    fprintf('NATIVE_INVENTORY_PROBE_PASS=%d STRICT_RESTORE=%d\n', ...
        audit.collection_pass, audit.strict_restore_pass);
end

function parameters = read_storage_parameters(path)
% Keep original expressions and unit metadata; do not assume mask values are SI.
    dialog = get_param(path, 'DialogParameters');
    names = {'area', 'length', 'volume', 'mass', 'sp_heat'};
    parameters = struct();
    for k = 1:numel(names)
        name = names{k};
        if isfield(dialog, name)
            expression = get_param(path, name);
            value = slResolve(expression, path);
            unit_name = [name '_unit'];
            unit = '';
            if isfield(dialog, unit_name), unit = get_param(path, unit_name); end
            parameters.(name) = struct('expression', expression, ...
                'value', value, 'unit', unit);
        end
    end
end

function report = Audit_HeatDriveECC_CheckpointContract(checkpoint_path, ...
        prior_result_path, output_path, overrides)
% Compare a checkpoint, its bound result, and a proposed current contract.
% This is read-only: it does not run Simulink or import an Operating Point.

    arguments
        checkpoint_path (1,1) string
        prior_result_path (1,1) string
        output_path (1,1) string = ""
        overrides struct = struct()
    end

    checkpoint = load(checkpoint_path, 'checkpoint_meta');
    prior = load(prior_result_path, 'physical', 'options', 'provenance');
    required_checkpoint = {'checkpoint_meta'};
    required_prior = {'physical', 'options', 'provenance'};
    assert(all(isfield(checkpoint, required_checkpoint)), ...
        'HeatDriveECC:ContractAuditCheckpointFields', ...
        'Checkpoint is missing checkpoint_meta.');
    assert(all(isfield(prior, required_prior)), ...
        'HeatDriveECC:ContractAuditPriorFields', ...
        'Prior result is missing physical/options/provenance.');

    current_options = Build_HeatDriveECC_EighthRound_Defaults(overrides);
    transition_fields = get_struct_option(current_options.simulation, ...
        'checkpoint_transition_fields', {});
    checkpoint_contract = normalize_checkpoint_transition( ...
        normalize_controller_retune_contract(checkpoint.checkpoint_meta.contract), ...
        transition_fields);
    checkpoint_contract = normalize_checkpoint_compatibility_contract( ...
        checkpoint_contract);
    if ~isfield(checkpoint_contract, 'solid')
        checkpoint_contract.solid = prior.options.solid;
    end
    checkpoint_contract = normalize_checkpoint_transition( ...
        checkpoint_contract, transition_fields);

    current_contract = normalize_checkpoint_transition( ...
        checkpoint_contract_from_options(current_options), transition_fields);
    prior_options = prior.options;
    prior_options.model_path = current_options.model_path;
    prior_contract = normalize_checkpoint_transition( ...
        normalize_checkpoint_compatibility_contract( ...
        normalize_controller_retune_contract( ...
        checkpoint_contract_from_options(prior_options))), transition_fields);

    report = struct();
    report.schema = 'heatdrive_ecc_checkpoint_contract_diff_v1';
    report.generated_at = char(datetime('now', 'TimeZone', 'local', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX'));
    report.checkpoint_path = char(checkpoint_path);
    report.prior_result_path = char(prior_result_path);
    report.current_model_path = char(string(current_options.model_path));
    report.checkpoint_model_sha256 = get_field_or(checkpoint_contract, ...
        'model_file_sha256', '');
    report.current_model_sha256 = get_field_or(current_contract, ...
        'model_file_sha256', '');
    report.prior_result_end_time_s = prior.physical.time_s(end);
    report.checkpoint_time_s = checkpoint.checkpoint_meta.time_s;
    report.current_stop_time_s = current_options.simulation.stop_time_s;
    report.bound_prior_result_path = char(string( ...
        checkpoint.checkpoint_meta.prior_result_path));
    report.checkpoint_contract = checkpoint_contract;
    report.current_contract = current_contract;
    report.prior_contract = prior_contract;
    report.checkpoint_vs_current = diff_contracts(checkpoint_contract, ...
        current_contract, 'contract');
    report.prior_vs_current = diff_contracts(prior_contract, ...
        current_contract, 'contract');
    report.checkpoint_equals_current = isempty_diff( ...
        report.checkpoint_vs_current);
    report.prior_equals_current = isempty_diff(report.prior_vs_current);
    report.time_continuity_pass = abs(report.prior_result_end_time_s - ...
        report.checkpoint_time_s) <= 10 * eps(max(abs(report.prior_result_end_time_s), 1)) && ...
        abs(report.prior_result_end_time_s - ...
        prior.options.simulation.stop_time_s) <= ...
        10 * eps(max(abs(report.prior_result_end_time_s), 1));
    report.strict_contract_pass = report.checkpoint_equals_current && ...
        report.prior_equals_current && report.time_continuity_pass;
    report.recovery_authorized = false;
    report.authorization_note = ['This audit reports compatibility only. ', ...
        'It never authorizes state import or a production continuation.'];

    if strlength(output_path) > 0
        parent = fileparts(char(output_path));
        if ~isempty(parent) && ~exist(parent, 'dir')
            mkdir(parent);
        end
        fid = fopen(output_path, 'w', 'n', 'UTF-8');
        assert(fid >= 0, 'HeatDriveECC:ContractAuditOpenFailed', ...
            'Cannot open audit output: %s', output_path);
        cleanup = onCleanup(@() fclose(fid));
        fprintf(fid, '%s\n', jsonencode(report, 'PrettyPrint', true));
        clear cleanup
    end
end

function contract = checkpoint_contract_from_options(options)
    contract = struct();
    contract.model_name = options.model_name;
    contract.model_file_sha256 = file_sha256(options.model_path);
    contract.node_count = options.node_count;
    contract.solver = options.simulation.solver;
    contract.fixed_step_s = options.simulation.fixed_step_s;
    contract.simulation_mode = get_struct_option( ...
        options.simulation, 'mode', 'normal');
    contract.schedule = options.schedule.stage_durations_s;
    contract.geometry = options.geometry;
    contract.material = options.material;
    contract.fluid = options.fluid;
    contract.branch = options.branch;
    contract = normalize_controller_retune_contract(contract);
    contract.system = rmfield_if_present(options.system, ...
        {'cold_load_heat_reference_W', ...
        'cold_boundary_temperature_configurability_source', ...
        'cold_boundary_temperature_configurability'});
    contract.solid = options.solid;
    contract.constitutive = options.constitutive;
end


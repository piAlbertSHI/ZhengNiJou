function contract = normalize_checkpoint_compatibility_contract(contract)
    if isfield(contract, 'system')
        contract.system = rmfield_if_present(contract.system, ...
            {'cold_boundary_temperature_configurability_source', ...
            'cold_boundary_temperature_configurability'});
    end
end

function contract = normalize_checkpoint_transition(contract, fields)
    if isempty(fields)
        return
    end
    fields = cellstr(string(fields));
    supported = { ...
        'system.Tchex_K', 'branch.boundary_T_se_chex_K', ...
        'system.cold_boundary_temperature_configurability', ...
        'system.shex_sink_C_J_per_K', 'system.hot_sink_C_J_per_K', ...
        'system.cold_sink_C_J_per_K', 'system.se_buffer_volume_m3', ...
        'branch.connecting_pipe_volume_m3', ...
        'branch.sma_pump_manifold_volume_m3', ...
        'branch.UA_sma_shex_W_per_K', 'branch.UA_sma_the_W_per_K', ...
        'branch.UA_se_the_W_per_K', 'branch.UA_se_chex_W_per_K', ...
        'branch.sma_pipe_Nu', 'branch.se_pipe_Nu', ...
        'branch.se_natural_convection_UA_W_per_K', ...
        'branch.se_natural_thermal_gate_G_W_per_K', ...
        'branch.endpoint_UA_sma_shex_W_per_K', ...
        'branch.endpoint_UA_sma_the_W_per_K', ...
        'branch.endpoint_UA_se_the_W_per_K', ...
        'branch.endpoint_UA_se_chex_W_per_K', ...
        'branch.boundary_UA_shex_W_per_K', ...
        'branch.boundary_UA_the_W_per_K', ...
        'branch.boundary_UA_chex_W_per_K', ...
        'branch.m_dot_kg_per_s', 'branch.m_dot_se_the_kg_per_s', ...
        'branch.m_dot_se_chex_kg_per_s', 'solid.heat_recovery_efficiency', ...
        'material.SMA.Delta_h_J_per_kg', ...
        'material.SMA.Delta_s0_J_per_kgK', ...
        'material.SE.Delta_h_J_per_kg', ...
        'material.SE.Delta_s0_J_per_kgK'};
    unsupported = setdiff(fields, supported);
    assert(isempty(unsupported), ...
        'HeatDriveECC:ContractAuditUnsupportedTransition', ...
        'Unsupported transition field(s): %s.', strjoin(unsupported, ', '));
    for idx = 1:numel(fields)
        contract = replace_nested_field(contract, ...
            strsplit(fields{idx}, '.'), '<declared_parameter_transition>');
    end
end

function value = replace_nested_field(value, path, replacement)
    name = path{1};
    assert(isstruct(value) && isfield(value, name), ...
        'HeatDriveECC:ContractAuditMissingTransition', ...
        'Contract does not contain transition field %s.', strjoin(path, '.'));
    if isscalar(path)
        value.(name) = replacement;
    else
        value.(name) = replace_nested_field(value.(name), path(2:end), ...
            replacement);
    end
end

function diff = diff_contracts(left, right, prefix)
    diff = struct('left_only', {{}}, 'right_only', {{}}, ...
        'value_mismatch', {{} });
    if isstruct(left) && isscalar(left) && isstruct(right) && isscalar(right)
        names = union(fieldnames(left), fieldnames(right));
        for idx = 1:numel(names)
            name = names{idx};
            path = [prefix '.' name];
            in_left = isfield(left, name);
            in_right = isfield(right, name);
            if ~in_left
                diff.right_only{end+1} = path;
            elseif ~in_right
                diff.left_only{end+1} = path;
            else
                child = diff_contracts(left.(name), right.(name), path);
                diff = append_diff(diff, child);
            end
        end
    elseif ~isequaln(left, right)
        diff.value_mismatch{end+1} = struct( ...
            'path', prefix, 'left', value_text(left), ...
            'right', value_text(right));
    end
end

function out = append_diff(out, child)
    out.left_only = [out.left_only child.left_only];
    out.right_only = [out.right_only child.right_only];
    out.value_mismatch = [out.value_mismatch child.value_mismatch];
end

function tf = isempty_diff(diff)
    tf = isempty(diff.left_only) && isempty(diff.right_only) && ...
        isempty(diff.value_mismatch);
end

function text = value_text(value)
    try
        text = jsonencode(value);
    catch
        text = class(value);
    end
end

function value = get_field_or(value_struct, name, default_value)
    if isstruct(value_struct) && isfield(value_struct, name)
        value = value_struct.(name);
    else
        value = default_value;
    end
end

function value = get_struct_option(value_struct, name, default_value)
    if isstruct(value_struct) && isfield(value_struct, name)
        value = value_struct.(name);
    else
        value = default_value;
    end
end

function value = rmfield_if_present(value, names)
    present = intersect(fieldnames(value), names);
    if ~isempty(present)
        value = rmfield(value, present);
    end
end

function value = file_sha256(path)
    fid = fopen(path, 'rb');
    assert(fid >= 0, 'HeatDriveECC:ContractAuditModelHashFailed', ...
        'Cannot open model: %s', path);
    cleanup = onCleanup(@() fclose(fid));
    bytes = fread(fid, Inf, '*uint8');
    digest = java.security.MessageDigest.getInstance('SHA-256');
    digest.update(typecast(bytes, 'int8'));
    value = lower(reshape(dec2hex(typecast(digest.digest(), 'uint8'), 2).', 1, []));
    clear cleanup
end

function summary = Generate_GX101R1_Thermal_Object_Contract(exchange_options, outputs_dir)
% Generate the formal hot/cold boundary object contract for gx101r1.

    if nargin < 1 || isempty(exchange_options)
        exchange_options = struct();
    end
    if nargin < 2 || isempty(outputs_dir)
        outputs_dir = fullfile(pwd, 'Output', 'r11_static_object_contract');
    end
    if ~exist(outputs_dir, 'dir')
        mkdir(outputs_dir);
    end

    exchange_options = apply_default_contract_options(exchange_options);
    state_in = struct( ...
        'T', exchange_options.ambient_T_init * ones(51, 1), ...
        'xi', zeros(51, 1), ...
        'pressure_MPa', 0.0);
    hold_params = Build_Simulink_Exchange_Params(state_in, make_stage('hold_exchange', exchange_options), exchange_options);
    cooldown_params = Build_Simulink_Exchange_Params(state_in, make_stage('cooldown_exchange', exchange_options), exchange_options);

    rows = [
        object_row("HotSinkMass", hold_params.hot_sink_C_J_per_K, ...
        "finite hot-end thermal mass", "receiver: official hot end is updated by external hot-end mixer", ...
        "source-side object; not written from cooldown source-buffer probe", true, false, true, false, ...
        hold_params.hot_sink_ambient_G_W_per_K, NaN, ...
        "included in official hot-end control volume capacity; state writeback after hold only")

        object_row("HotFluidBuffer", hold_params.hot_fluid_buffer_C_J_per_K, ...
        "hot-loop buffer/source boundary", "co-updated with official hot end after hold", ...
        "stage4 source boundary; cooldown probe is not written back to official hot end", true, false, true, false, ...
        0.0, NaN, ...
        "included in official hot-end capacity; source-buffer pollution is not accepted as receiver energy")

        object_row("HotPipe/HHEX", hold_params.hot_pipe_or_HHEX_C_J_per_K, ...
        "hot-side pipe/HHEX fluid storage diagnostic", "diagnostic storage only; official heat is boundary enthalpy mixer", ...
        "diagnostic storage only", true, false, false, false, ...
        0.0, NaN, ...
        "included in hot-end effective capacity for mixer temperature update")

        object_row("ColdSinkMass", cooldown_params.cold_sink_C_J_per_K, ...
        "finite cold-end thermal mass", "frozen; stage2 cold source buffer is not official cold end", ...
        "receiver: official cold end is updated by external cold-end mixer", false, true, false, true, ...
        cooldown_params.cold_sink_ambient_G_W_per_K, cooldown_params.cold_sink_fluid_G_W_per_K, ...
        "stage2 drift must be numerical zero; stage4 cooldown writes official cold-end temperature")

        object_row("ColdFluidBuffer", cooldown_params.cold_fluid_buffer_C_J_per_K, ...
        "cold-loop buffer/source boundary", "stage2 upstream source buffer; heated probe is not written back", ...
        "co-updated with official cold end after cooldown", false, true, false, true, ...
        0.0, NaN, ...
        "included in official cold-end capacity; stage2 source-buffer warming is pollution if treated as receiver")

        object_row("ColdSinkPipe/CHEX", cooldown_params.cold_pipe_or_CHEX_C_J_per_K, ...
        "cold return pipe/CHEX storage diagnostic", "isolated from official stage2 cold end", ...
        "diagnostic storage plus mixer boundary enthalpy path", false, true, false, true, ...
        0.0, cooldown_params.cold_sink_fluid_G_W_per_K, ...
        "included in cold-end effective capacity for mixer temperature update")

        object_row("ExternalColdEndMixer", cooldown_params.cold_end_C_total_J_per_K, ...
        "official cold-end state for stage4", "inactive/frozen in hold", ...
        "official measured cold-end receiver from cold-return boundary enthalpy", false, true, false, true, ...
        0.0, NaN, ...
        "scheme B official cold end; prevents mixing entity storage and boundary enthalpy")

        object_row("ExternalHotEndMixer", hold_params.hot_end_C_total_J_per_K, ...
        "official hot-end state for stage2", "official measured hot-end receiver from hot-return boundary enthalpy", ...
        "inactive/frozen in cooldown", true, false, true, false, ...
        0.0, NaN, ...
        "r11 hot-end receiver; proves SMA heat rejection reaches official hot end")

        object_row("ColdLoadMass", cooldown_params.cold_load_C_J_per_K, ...
        "external cold load body", "no-load: isolated; load mode heat remains on cold load only", ...
        "load mode may couple to CHEX through stage4 gate", false, false, false, false, ...
        cooldown_params.cold_load_ambient_G_W_per_K, cooldown_params.cold_load_to_cold_sink_G_W_per_K, ...
        "not part of official no-load cold end; no-load must not pollute cold sink")
    ];

    table_out = struct2table(rows);
    table_out.equivalent_water_volume_ml = table_out.C_J_per_K ./ max(hold_params.rho_water * hold_params.cp_water, eps) * 1.0e6;
    csv_path = fullfile(outputs_dir, 'thermal_object_contract.csv');
    txt_path = fullfile(outputs_dir, 'thermal_object_contract.txt');
    mat_path = fullfile(outputs_dir, 'thermal_object_contract.mat');
    writetable(table_out, csv_path);
    write_contract_text(txt_path, table_out, hold_params, cooldown_params);
    summary = struct( ...
        'outputs_dir', outputs_dir, ...
        'csv_path', csv_path, ...
        'txt_path', txt_path, ...
        'mat_path', mat_path, ...
        'official_hot_end_definition', string(hold_params.official_hot_end_definition), ...
        'official_cold_end_definition', string(cooldown_params.official_cold_end_definition), ...
        'hot_end_C_total_J_per_K', hold_params.hot_end_C_total_J_per_K, ...
        'cold_end_C_total_J_per_K', cooldown_params.cold_end_C_total_J_per_K, ...
        'rows', rows);
    save(mat_path, 'summary', 'table_out');
    write_json(fullfile(outputs_dir, 'thermal_object_contract.json'), summary);
end

function options = apply_default_contract_options(options)
    defaults = struct( ...
        'ambient_T_init', 293.0, ...
        'hot_sink_T_init', 293.0, ...
        'cold_sink_T_init', 293.0, ...
        'cold_load_T_init', 293.0, ...
        'chip_T_init', 293.0, ...
        'cold_load_mode', 'no_load', ...
        'cold_load_heat_W', 0.0, ...
        'chip_heat_W', 0.0, ...
        'hot_sink_C_J_per_K', 41.8, ...
        'cold_sink_C_J_per_K', 4.18, ...
        'hot_sink_ambient_G_W_per_K', 0.05, ...
        'cold_sink_ambient_G_W_per_K', 1.0e-12, ...
        'cold_load_ambient_G_W_per_K', 1.0e-12, ...
        'chip_ambient_G_W_per_K', 1.0e-12, ...
        'flush_volume_target_ratio', 1.0, ...
        'hotflush_stop_time_s', 0.4, ...
        'coldflush_stop_time_s', 0.4, ...
        'exchange_backend_kind', 'simulink_directional_101');
    names = fieldnames(defaults);
    for idx = 1:numel(names)
        name = names{idx};
        if ~isfield(options, name) || isempty(options.(name))
            options.(name) = defaults.(name);
        end
    end
end

function stage = make_stage(stage_name, options)
    stage = struct();
    stage.stage_name = char(stage_name);
    stage.stage_kind = 'exchange';
    if strcmp(stage.stage_name, 'hold_exchange')
        stage.stop_time_s = options.hotflush_stop_time_s;
        stage.L_valve = [1 1 1 0 0 0];
    else
        stage.stop_time_s = options.coldflush_stop_time_s;
        stage.L_valve = [0 0 0 1 1 1];
    end
    stage.ambient_T_init = options.ambient_T_init;
    stage.hot_sink_T_in = options.hot_sink_T_init;
    stage.cold_sink_T_in = options.cold_sink_T_init;
    stage.cold_load_T_in = options.cold_load_T_init;
    stage.chip_T_in = options.cold_load_T_init;
    stage.hot_buffer_T_in = options.hot_sink_T_init;
    stage.cold_buffer_T_in = options.cold_sink_T_init;
end

function row = object_row(name, C, type, stage2_role, stage4_role, official_hot, official_cold, writeback_hold, writeback_cooldown, ambient_G, fluid_G, notes)
    row = struct( ...
        'object_name', string(name), ...
        'object_type', string(type), ...
        'C_J_per_K', C, ...
        'equivalent_water_volume_ml', NaN, ...
        'stage2_role', string(stage2_role), ...
        'stage4_role', string(stage4_role), ...
        'included_in_official_hot_end', logical(official_hot), ...
        'included_in_official_cold_end', logical(official_cold), ...
        'stage_end_writeback_allowed_after_hold', logical(writeback_hold), ...
        'stage_end_writeback_allowed_after_cooldown', logical(writeback_cooldown), ...
        'ambient_G_W_per_K', ambient_G, ...
        'fluid_coupling_G_W_per_K', fluid_G, ...
        'notes', string(notes));
end

function write_contract_text(path_value, table_out, hold_params, cooldown_params)
    fid = fopen(path_value, 'w', 'n', 'UTF-8');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, 'gx101r1 r11 thermal object contract\n');
    fprintf(fid, 'Official hot end: %s\n', hold_params.official_hot_end_definition);
    fprintf(fid, 'Official cold end: %s\n', cooldown_params.official_cold_end_definition);
    fprintf(fid, 'Hot end C_total = %.9g J/K (%.6g ml water equivalent)\n', ...
        hold_params.hot_end_C_total_J_per_K, hold_params.hot_end_effective_water_volume_ml);
    fprintf(fid, 'Cold end C_total = %.9g J/K (%.6g ml water equivalent)\n\n', ...
        cooldown_params.cold_end_C_total_J_per_K, cooldown_params.cold_end_effective_water_volume_ml);
    for idx = 1:height(table_out)
        fprintf(fid, '%s: C=%.9g J/K, equiv=%.6g ml, stage2=%s, stage4=%s, official_hot=%d, official_cold=%d\n', ...
            char(table_out.object_name(idx)), table_out.C_J_per_K(idx), table_out.equivalent_water_volume_ml(idx), ...
            char(table_out.stage2_role(idx)), char(table_out.stage4_role(idx)), ...
            table_out.included_in_official_hot_end(idx), table_out.included_in_official_cold_end(idx));
    end
end

function write_json(path_value, value)
    fid = fopen(path_value, 'w', 'n', 'UTF-8');
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid, '%s', jsonencode(value, 'PrettyPrint', true));
end

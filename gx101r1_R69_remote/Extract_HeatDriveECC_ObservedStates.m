function observation = Extract_HeatDriveECC_ObservedStates(states, tau_s, window_cycles)
% Preserve named numerical state traces, without treating coverage as steadiness.
    assert(isa(states, 'Simulink.SimulationData.Dataset'), ...
        'HeatDriveECC:ObservedStateDatasetRequired', 'A state Dataset is required.');
    validateattributes(tau_s, {'numeric'}, {'scalar','finite','positive'});
    validateattributes(window_cycles, {'numeric'}, {'scalar','finite','integer','positive'});
    count = states.numElements;
    assert(count > 0, 'HeatDriveECC:EmptyObservedStates', 'State Dataset is empty.');
    rows = cell(count, 1);
    bytes = 0;
    for k = 1:count
        state = states.getElement(k);
        series = state.Values;
        assert(isa(series, 'timeseries'), ...
            'HeatDriveECC:UnsupportedObservedStateType', ...
            'State %s is not a timeseries.', state.Name);
        t = double(series.Time(:));
        assert(~isempty(t) && all(isfinite(t)) && all(diff(t) >= 0), ...
            'HeatDriveECC:InvalidObservedStateTime', 'Invalid state time axis.');
        data = series.Data;
        if ~series.IsTimeFirst
            data = permute(data, [ndims(data), 1:(ndims(data) - 1)]);
        end
        data = reshape(double(data), numel(t), []);
        selected = t >= t(end) - window_cycles * tau_s - 10 * eps(t(end));
        data = data(selected, :);
        t = t(selected);
        assert(all(isfinite(data), 'all') && all(isfinite(t)), ...
            'HeatDriveECC:NonfiniteObservedState', 'State %s is nonfinite.', state.Name);
        rows{k} = struct('block_path', char(state.BlockPath.getBlock(1)), ...
            'state_name', char(state.Name), 'time_s', t, 'values', data, ...
            'unit', char(string(series.DataInfo.Units)), ...
            'channel_count', size(data, 2), ...
            'complete_requested_window', ...
                t(end) - t(1) >= window_cycles * tau_s - 10 * eps(t(end)));
        bytes = bytes + 8 * (numel(t) + numel(data));
    end
    observation = struct('schema', 'heatdrive_ecc_observed_state_traces_v1', ...
        'cycle_period_s', tau_s, 'requested_window_cycles', window_cycles, ...
        'logged_state_group_count', count, 'numeric_bytes', bytes, ...
        'states', {rows}, 'complete_internal_state_periodicity_verified', false, ...
        'scope', ['Numerical logged states only. Solver/Simscape packed-state ', ...
        'semantics and independent physical-state coverage must be audited.']);
end

function report_path = Write_HeatDriveECC_Simulink_Report(result, validation)
% Write the fourth-round Simulink 3-cycle audit report.

    root_dir = fileparts(mfilename('fullpath'));
    report_path = fullfile(root_dir, 'Agent2_第四轮Simulink三循环物理验证报告.txt');
    fid = fopen(report_path, 'w');
    if fid < 0
        error('Write_HeatDriveECC_Simulink_Report:CannotOpenReport', ...
            'Cannot open report file: %s', report_path);
    end
    cleaner = onCleanup(@() fclose(fid));

    opts = result.options;
    sumr = result.summary;
    eq = opts.equilibrium;

    fprintf(fid, 'Agent2 fourth-round Simulink 3-cycle physical validation report\n');
    fprintf(fid, 'Generated by: Validate_HeatDriveECC_Simulink_3Cycle\n');
    fprintf(fid, 'Report path: %s\n\n', report_path);

    fprintf(fid, '1. Run command and model\n');
    fprintf(fid, 'Run command: cd %s; summary = Validate_HeatDriveECC_Simulink_3Cycle();\n', root_dir);
    fprintf(fid, 'Model name: %s\n', result.model_name);
    fprintf(fid, 'Model path: %s\n', result.model_path);
    fprintf(fid, 'Core Simulink block: %s\n', sumr.core_block);
    fprintf(fid, 'Core block type: %s\n', sumr.core_block_type);
    fprintf(fid, 'Output directory: %s\n', result.output_dir);
    fprintf(fid, 'Trend plot: %s\n', result.trend_plot_path);
    fprintf(fid, 'Stage CSV: %s\n', result.stage_csv_path);
    fprintf(fid, 'Probe CSV: %s\n', result.probe_csv_path);
    fprintf(fid, 'Result MAT: %s\n\n', result.result_mat_path);

    fprintf(fid, '2. Model scope and exclusions\n');
    fprintf(fid, 'The delivered full-cycle entry runs the four-stage ECC sequence inside Simulink.\n');
    fprintf(fid, 'MATLAB is used only to configure parameters, build/start the Simulink model, collect outputs, audit equations, and write files.\n');
    fprintf(fid, 'The fourth-round model uses two 51-node 1D generic-area NiTi members: SMA actuator and SE refrigerant.\n');
    fprintf(fid, 'It does not use the round-plate u/w displacement route, radius, 101 diameter strip mapping, GlobalXi plate constitutive model, equivalent-pressure drive, or surrogate exchange as final physics.\n\n');

    fprintf(fid, '3. Paper parameters and timing\n');
    fprintf(fid, 'Article defaults: Sr/Sa=%.6g, Lr/La=%.6g, Tc=%.6g K, T0=%.6g K, eta_hr=%.6g.\n', ...
        opts.geometry.S_r_over_S_a, opts.geometry.L_r_over_L_a, ...
        opts.system.Tc_K, opts.system.T0_K, opts.system.eta_hr);
    fprintf(fid, 'Eq.23/Eq.24 derived SHEX heat duty Qh=%.9g W and cycle frequency nu=%.9g Hz.\n', ...
        eq.Qh_W, eq.nu_Hz);
    fprintf(fid, 'Cycle time tau=%.9g s. Stage durations [s]=[%.9g %.9g %.9g %.9g].\n', ...
        opts.schedule.tau_cycle_s, opts.schedule.stage_durations_s);
    fprintf(fid, 'Timing source: %s\n', opts.schedule.source);
    fprintf(fid, 'The legacy [0.1 0.4 0.1 0.4] stage timing is not used.\n\n');

    fprintf(fid, '4. Four-stage Simulink route logic\n');
    fprintf(fid, 'Stage 1 sma_heat_load: SHEX_to_SMA=1, THE_to_SMA=0, SE_to_THE=0, RHE_to_SE=0, mechanical coupling active=1.\n');
    fprintf(fid, 'Stage 2 se_reject_heat: SHEX_to_SMA=1, SE_to_THE=1, SMA/SE pumps on, dual channel prevents THE/RHE contamination.\n');
    fprintf(fid, 'Stage 3 sma_cool_unload: THE_to_SMA=1, SE heat-exchanger routes closed, mechanical coupling active=1.\n');
    fprintf(fid, 'Stage 4 se_absorb_heat: RHE_to_SE=1, SMA loop isolated, SE pump on.\n\n');

    fprintf(fid, '5. Three-cycle stage trends\n');
    fprintf(fid, 'cycle,stage,name,samples,Ta_start,Ta_end,Tr_start,Tr_end,xMa_start,xMa_end,xMr_start,xMr_end,sigmaR_start_MPa,sigmaR_end_MPa,Q_SHEX,Q_THE_SMA,Q_THE_SE,Q_RHE,max_eq7\n');
    for idx = 1:numel(sumr.stage_summaries)
        s = sumr.stage_summaries(idx);
        fprintf(fid, '%d,%d,%s,%d,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f\n', ...
            s.cycle_index, s.stage_id, s.stage_name, s.sample_count, ...
            s.start_T_a_mean_K, s.end_T_a_mean_K, ...
            s.start_T_r_mean_K, s.end_T_r_mean_K, ...
            s.start_xM_a_mean, s.end_xM_a_mean, ...
            s.start_xM_r_mean, s.end_xM_r_mean, ...
            s.start_sigma_r_Pa / 1.0e6, s.end_sigma_r_Pa / 1.0e6, ...
            s.mean_Q_shex_W, s.mean_Q_the_sma_W, ...
            s.mean_Q_the_se_W, s.mean_Q_rhe_W, s.max_eq7_scaled);
    end
    fprintf(fid, '\n');

    fprintf(fid, '6. Paper key data comparison\n');
    fprintf(fid, 'Th=%.9g K, MDTD=%.9g K, qa=%.9g J/kg, qr=%.9g J/kg.\n', ...
        eq.T_h_K, eq.MDTD_K, eq.qa_J_per_kg, eq.qr_J_per_kg);
    fprintf(fid, 'Qa=%.9g W, Qr=%.9g W, PECC=%.9g W, etaECC=%.9g.\n', ...
        eq.Qa_W, eq.Qr_W, eq.PECC_W, eq.etaECC);
    fprintf(fid, 'Output fields Qh/Qa/Qr/PECC/etaECC/nu are copied into every Simulink sample for audit consistency.\n\n');

    fprintf(fid, '7. Equation and hard-check audit\n');
    fprintf(fid, 'Output width: %d, expected width: %d.\n', sumr.output_width, sumr.expected_output_width);
    fprintf(fid, 'Samples: %d total; minimum per cycle-stage: %d.\n', sumr.sample_count, sumr.min_stage_sample_count);
    fprintf(fid, 'Eq.6 force residual max scaled=%.9g, max force residual=%.9g N.\n', ...
        sumr.max_eq6_scaled, sumr.max_force_residual_N);
    fprintf(fid, 'Eq.7 displacement residual max scaled=%.9g, max displacement residual=%.9g m.\n', ...
        sumr.max_eq7_scaled, sumr.max_disp_residual_m);
    fprintf(fid, 'Validation status: %s\n', pass_text(validation.passed));
    for idx = 1:numel(validation.checks)
        c = validation.checks(idx);
        fprintf(fid, '  - %s: %s (%s)\n', c.name, pass_text(c.passed), c.detail);
    end
    fprintf(fid, '\n');

    fprintf(fid, '8. Self-rework record\n');
    fprintf(fid, 'Initial Simulink MATLAB Function code generation could not infer the 773-column variable-size audit vector robustly, so the model was rebuilt with an Interpreted MATLAB Function block driven by the Simulink clock.\n');
    fprintf(fid, 'Early SE phase kinetics did not load/unload across the intended stage windows; the phase driving terms and stage targets were adjusted and revalidated in Simulink.\n');
    fprintf(fid, 'The mechanical solver now records Eq.6/Eq.7 residuals on every sample. Eq.6 is tight by construction; Eq.7 transient residual is reported separately from endpoint residual because the simplified stress command is event-driven in this first full-cycle Simulink prototype.\n\n');

    fprintf(fid, '9. Git status at validation time\n');
    [~, branch] = system('git branch --show-current');
    [~, status] = system('git status --short --branch');
    fprintf(fid, 'Branch: %s\n', strtrim(branch));
    fprintf(fid, '%s\n', status);

    delete(cleaner);
end

function text = pass_text(value)
    if value
        text = 'PASS';
    else
        text = 'FAIL';
    end
end

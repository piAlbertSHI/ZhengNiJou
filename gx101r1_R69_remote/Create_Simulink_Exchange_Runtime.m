function runtime = Create_Simulink_Exchange_Runtime(options)
% Create the runtime container used by Simulink-backed exchange stages.

    if nargin < 1 || isempty(options)
        options = struct();
    end

    this_dir = fileparts(mfilename('fullpath'));
    run_label = sanitize_run_label(get_option_field(options, 'run_label', 'default_run'));
    outputs_dir = get_option_field(options, 'outputs_dir', '');
    if isempty(outputs_dir)
        outputs_dir = fullfile(this_dir, 'outputs', run_label);
    elseif ~is_absolute_path(outputs_dir)
        outputs_dir = fullfile(this_dir, outputs_dir);
    end
    checkpoints_dir = fullfile(outputs_dir, 'simulink_exchange_checkpoints');
    figures_dir = fullfile(outputs_dir, 'simulink_exchange_figures');

    exchange_backend_kind = normalize_exchange_backend_kind(get_option_field(options, ...
        'exchange_backend_kind', 'simulink_axial_21'));
    model_path = get_option_field(options, 'model_path', '');
    if isempty(model_path)
        model_path = fullfile(this_dir, 'heatdrive_ecc_coupled_se21.slx');
    end
    [~, model_name] = fileparts(model_path);

    save_checkpoints = logical(get_option_field(options, 'save_checkpoints', true));
    save_plots = logical(get_option_field(options, 'save_plots', true));
    store_raw_simout = logical(get_option_field(options, 'store_raw_simout', false));
    use_fast_restart = logical(get_option_field(options, 'use_fast_restart', false));
    simulation_mode = char(string(get_option_field(options, 'simulation_mode', 'accelerator')));

    ambient_T_init = get_option_field(options, 'ambient_T_init', 293.0);
    hot_sink_T_init = get_option_field(options, 'hot_sink_T_init', ambient_T_init);
    cold_sink_T_init = get_option_field(options, 'cold_sink_T_init', ambient_T_init);
    cold_load_T_init = get_option_field(options, 'cold_load_T_init', ...
        get_option_field(options, 'chip_T_init', 293.0));
    chip_T_init = cold_load_T_init;

    ensure_dir(outputs_dir);
    if save_checkpoints
        ensure_dir(checkpoints_dir);
    end
    if save_plots
        ensure_dir(figures_dir);
    end

    runtime = struct( ...
        'model_path', model_path, ...
        'model_name', model_name, ...
        'exchange_backend_kind', exchange_backend_kind, ...
        'use_fast_restart', use_fast_restart, ...
        'simulation_mode', simulation_mode, ...
        'ambient_T_init', ambient_T_init, ...
        'hot_sink_temp_current', hot_sink_T_init, ...
        'cold_sink_temp_current', cold_sink_T_init, ...
        'chip_temp_current', chip_T_init, ...
        'cold_load_temp_current', cold_load_T_init, ...
        'hot_buffer_temp_current', hot_sink_T_init, ...
        'cold_buffer_temp_current', cold_sink_T_init, ...
        'hot_source_current', hot_sink_T_init, ...
        'last_hot_sink_temp_out', NaN, ...
        'last_cold_sink_temp_out', NaN, ...
        'last_chip_temp_out', NaN, ...
        'last_cold_load_temp_out', NaN, ...
        'last_hot_buffer_temp_out', NaN, ...
        'last_cold_buffer_temp_out', NaN, ...
        'last_hot_source_out', NaN, ...
        'last_stage_name', '', ...
        'cycle_index', get_option_field(options, 'cycle_index', 0), ...
        'stage_index', get_option_field(options, 'stage_index', 0), ...
        'run_label', run_label, ...
        'checkpoints_dir', checkpoints_dir, ...
        'figures_dir', figures_dir, ...
        'outputs_dir', outputs_dir, ...
        'store_raw_simout', store_raw_simout, ...
        'save_checkpoints', save_checkpoints, ...
        'save_plots', save_plots, ...
        'last_checkpoint_path', '', ...
        'pending_bridge_plan', struct(), ...
        'last_bridge_plan', struct(), ...
        'last_bridge_execution_report', struct(), ...
        'last_load_start_history_canonicalization_report', struct(), ...
        'bridge_latest_checkpoint_path', '');
end

function value = get_option_field(s, field_name, default_value)
    if isstruct(s) && isfield(s, field_name) && ~isempty(s.(field_name))
        value = s.(field_name);
    else
        value = default_value;
    end
end

function ensure_dir(dir_path)
    if ~exist(dir_path, 'dir')
        mkdir(dir_path);
    end
end

function label = sanitize_run_label(label)
    if isstring(label)
        label = char(label);
    end
    if ~ischar(label) || isempty(label)
        label = 'default_run';
    end
    label = regexprep(label, '[^a-zA-Z0-9_\-]+', '_');
    if isempty(label)
        label = 'default_run';
    end
end

function tf = is_absolute_path(path_text)
    if isstring(path_text)
        path_text = char(path_text);
    end
    tf = ischar(path_text) && ~isempty(path_text) && ...
        (~isempty(regexp(path_text, '^[a-zA-Z]:[\\/]', 'once')) || startsWith(path_text, '\\'));
end

function exchange_backend_kind = normalize_exchange_backend_kind(value)
    exchange_backend_kind = char(string(value));
    if isempty(strtrim(exchange_backend_kind)) || strcmpi(exchange_backend_kind, 'simulink_directional_101')
        exchange_backend_kind = 'simulink_axial_21';
    end
    if ~strcmp(exchange_backend_kind, 'simulink_axial_21')
        error('Create_Simulink_Exchange_Runtime:UnsupportedBackend', ...
            'Only the 21-node axial Simulink SE backend is supported, got %s.', exchange_backend_kind);
    end
end

function summary = Build_GlobalXi_Run_Validation_Summary(run_result)
% Build result-level validation summary for GlobalXi + Simulink101 runs.

    if nargin < 1 || isempty(run_result)
        run_result = struct();
    end

    cycle_results = reshape(get_field(run_result, 'cycle_results', struct([])), 1, []);
    config = get_field(run_result, 'config', struct());
    exchange_options = get_field(config, 'exchange_options', struct());
    expected_source = get_field(exchange_options, 'expected_accepted_temperature_source', ...
        'simulink_directional_101_compressed');
    expected_raw_nodes = get_field(exchange_options, 'expected_raw_tx_node_count', 101);
    expected_reconciled_nodes = get_field(exchange_options, 'expected_reconciled_tx_node_count', 51);
    expected_cold_load_heat_W = get_field(exchange_options, 'cold_load_heat_W', ...
        get_field(exchange_options, 'chip_heat_W', 1.0));
    expected_chip_heat_W = expected_cold_load_heat_W;
    expected_probe_sample_count = get_field(exchange_options, 'probe_sample_count', 50);
    expected_hot_sink_C_J_per_K = get_field(exchange_options, 'hot_sink_C_J_per_K', 41.8);
    expected_cold_sink_C_J_per_K = get_field(exchange_options, 'cold_sink_C_J_per_K', 4.18);
    expected_hot_sink_ambient_G_W_per_K = get_field(exchange_options, 'hot_sink_ambient_G_W_per_K', 0.05);
    expected_cold_sink_ambient_G_W_per_K = get_field(exchange_options, 'cold_sink_ambient_G_W_per_K', 1.0e-12);
    expected_cold_sink_ambient_G_hold_W_per_K = get_field(exchange_options, ...
        'cold_sink_ambient_G_hold_W_per_K', 1.0e-12);
    expected_cold_sink_ambient_G_cooldown_W_per_K = get_field(exchange_options, ...
        'cold_sink_ambient_G_cooldown_W_per_K', expected_cold_sink_ambient_G_W_per_K);
    expected_cold_load_ambient_G_W_per_K = get_field(exchange_options, 'cold_load_ambient_G_W_per_K', ...
        get_field(exchange_options, 'chip_ambient_G_W_per_K', 1.0e-12));
    expected_chip_ambient_G_W_per_K = get_field(exchange_options, 'chip_ambient_G_W_per_K', ...
        expected_cold_load_ambient_G_W_per_K);
    solver_options = get_field(config, 'solver_options', struct());
    solver_Pmax_Pa = get_field(solver_options, 'Pmax', NaN);
    solver_Pmax_MPa = solver_Pmax_Pa / 1.0e6;
    expected_cold_sink_fluid_G_hold_W_per_K = get_field(exchange_options, ...
        'cold_sink_fluid_G_hold_W_per_K', 1.0e-12);
    expected_cold_sink_fluid_G_cooldown_W_per_K = get_field(exchange_options, ...
        'cold_sink_fluid_G_cooldown_W_per_K', ...
        get_field(exchange_options, 'cold_sink_fluid_G_W_per_K', 500.0));
    expected_cold_load_G_hold_W_per_K = get_field(exchange_options, ...
        'cold_load_to_cold_sink_G_hold_W_per_K', 1.0e-12);
    expected_cold_load_G_cooldown_W_per_K = get_field(exchange_options, ...
        'cold_load_to_cold_sink_G_cooldown_W_per_K', ...
        get_field(exchange_options, 'cold_load_to_cold_sink_G_W_per_K', 0.4));
    if strcmp(get_field(exchange_options, 'cold_load_mode', 'constant_load'), 'no_load')
        expected_cold_load_heat_W = 0.0;
        expected_chip_heat_W = 0.0;
        expected_cold_load_G_hold_W_per_K = 1.0e-12;
        expected_cold_load_G_cooldown_W_per_K = 1.0e-12;
    end

    cycle_checks = repmat(empty_cycle_check(), 1, 0);
    warnings = {};
    cycles_with_pressure_compensation = [];
    cycles_with_reused_stage_results = [];
    contract_ok = true;
    physics_ok = true;

    for idx = 1:numel(cycle_results)
        check = validate_one_cycle(cycle_results(idx), expected_source, ...
            expected_raw_nodes, expected_reconciled_nodes, expected_chip_heat_W, ...
            expected_probe_sample_count, expected_hot_sink_C_J_per_K, ...
            expected_cold_sink_C_J_per_K, expected_cold_sink_fluid_G_hold_W_per_K, ...
            expected_cold_sink_fluid_G_cooldown_W_per_K, ...
            expected_cold_load_G_hold_W_per_K, expected_cold_load_G_cooldown_W_per_K);
        cycle_checks = append_struct_compatible(cycle_checks, check);
        contract_ok = contract_ok && check.contract_ok;
        physics_ok = physics_ok && check.physics_ok;
        warnings = [warnings, check.warning_reasons]; %#ok<AGROW>
        if check.pressure_control_compensation_used && isfinite(check.cycle_index)
            cycles_with_pressure_compensation(end + 1) = check.cycle_index; %#ok<AGROW>
        end
        if check.stage_result_reused_from_previous_cycle && isfinite(check.cycle_index)
            cycles_with_reused_stage_results(end + 1) = check.cycle_index; %#ok<AGROW>
        end
    end
    cycles_with_pressure_compensation = unique(cycles_with_pressure_compensation, 'stable');
    cycles_with_reused_stage_results = unique(cycles_with_reused_stage_results, 'stable');

    if isempty(cycle_results)
        contract_ok = false;
        physics_ok = false;
        warnings{end + 1} = 'no_cycle_results_available';
    end

    run_ok = logical(get_field(run_result, 'ok', false));
    if isempty(cycle_checks)
        energy_audit_ok = false;
        sma_htf_energy_audit_ok = false;
        measured_cold_end_energy_audit_ok = false;
        stage2_hot_end_energy_audit_ok = false;
        projection_energy_conservation_ok = false;
        system_energy_audit_ok = false;
        measured_cold_end_energy_policy_ok = false;
        system_energy_policy_ok = false;
        system_energy_residual_included_in_pass_fail = false;
        state_sync_contract_ok = false;
        pipe_cumulative_unreleased_not_growing_ok = false;
    else
        sma_htf_energy_audit_ok = all([cycle_checks.sma_htf_energy_closure_ok]);
        measured_cold_end_energy_audit_ok = all([cycle_checks.measured_cold_end_energy_audit_ok]);
        stage2_hot_end_energy_audit_ok = all([cycle_checks.stage2_hot_end_energy_audit_ok]);
        projection_energy_conservation_ok = all([cycle_checks.projection_energy_conservation_ok]);
        system_energy_audit_ok = all([cycle_checks.system_energy_audit_ok]);
        measured_cold_end_energy_policy_ok = all([cycle_checks.measured_cold_end_energy_policy_ok]);
        system_energy_policy_ok = all([cycle_checks.system_energy_policy_ok]);
        system_energy_residual_included_in_pass_fail = any([cycle_checks.system_energy_residual_included_in_pass_fail]);
        state_sync_contract_ok = all([cycle_checks.state_sync_contract_ok]);
        pipe_cumulative_unreleased_not_growing_ok = pipe_cumulative_not_growing(cycle_checks);
        energy_audit_ok = sma_htf_energy_audit_ok && measured_cold_end_energy_audit_ok && ...
            stage2_hot_end_energy_audit_ok && projection_energy_conservation_ok && ...
            system_energy_audit_ok && state_sync_contract_ok && pipe_cumulative_unreleased_not_growing_ok;
    end
    if energy_audit_ok
        energy_audit_status = 'projection_sma_htf_external_hot_end_external_cold_end_and_state_sync_chain_closed';
    else
        energy_audit_status = 'energy_chain_unclosed_projection_sma_htf_hot_end_cold_end_state_sync_or_system_gate_failed';
    end
    warnings = add_warning_if(warnings, ~pipe_cumulative_unreleased_not_growing_ok, ...
        'path_pipe_unreleased_energy_monotonically_growing_over_cycles');
    total_system_energy_residual_max_abs_J = max_cycle_abs_residual(cycle_checks);

    summary = struct( ...
        'schema_version', 'globalxi_sim101_validation_v3_sma_htf_energy_closure', ...
        'run_ok', run_ok, ...
        'solver_Pmax_Pa', solver_Pmax_Pa, ...
        'solver_Pmax_MPa', solver_Pmax_MPa, ...
        'solver_Nt', get_field(get_field(config, 'solver_options', struct()), 'Nt', NaN), ...
        'solver_Nt_unload', get_field(get_field(config, 'solver_options', struct()), 'Nt_unload', NaN), ...
        'contract_ok', contract_ok, ...
        'physics_ok', physics_ok, ...
        'overall_ok', run_ok && contract_ok && physics_ok, ...
        'energy_audit_ok', energy_audit_ok, ...
        'sma_htf_energy_audit_ok', sma_htf_energy_audit_ok, ...
        'measured_cold_end_energy_audit_ok', measured_cold_end_energy_audit_ok, ...
        'stage2_hot_end_energy_audit_ok', stage2_hot_end_energy_audit_ok, ...
        'projection_energy_conservation_ok', projection_energy_conservation_ok, ...
        'system_energy_audit_ok', system_energy_audit_ok, ...
        'measured_cold_end_energy_policy_ok', measured_cold_end_energy_policy_ok, ...
        'system_energy_policy_ok', system_energy_policy_ok, ...
        'state_sync_contract_ok', state_sync_contract_ok, ...
        'pipe_cumulative_unreleased_not_growing_ok', pipe_cumulative_unreleased_not_growing_ok, ...
        'system_energy_residual_included_in_pass_fail', system_energy_residual_included_in_pass_fail, ...
        'total_system_energy_residual_max_abs_J', total_system_energy_residual_max_abs_J, ...
        'energy_audit_status', energy_audit_status, ...
        'energy_audit_gap_explanation', energy_gap_explanation(), ...
        'expected_cold_load_heat_W', expected_cold_load_heat_W, ...
        'cold_load_heat_standard', sprintf('Configured cold-load heat input %.6g W; heat input is checked against each exchange-stage duration.', expected_cold_load_heat_W), ...
        'expected_hot_sink_C_J_per_K', expected_hot_sink_C_J_per_K, ...
        'expected_hot_sink_effective_water_volume_ml', expected_hot_sink_C_J_per_K / (998.0 * 4180.0) * 1.0e6, ...
        'expected_cold_sink_C_J_per_K', expected_cold_sink_C_J_per_K, ...
        'expected_cold_sink_effective_water_volume_ml', expected_cold_sink_C_J_per_K / (998.0 * 4180.0) * 1.0e6, ...
        'expected_cold_sink_fluid_G_hold_W_per_K', expected_cold_sink_fluid_G_hold_W_per_K, ...
        'expected_cold_sink_fluid_G_cooldown_W_per_K', expected_cold_sink_fluid_G_cooldown_W_per_K, ...
        'expected_hot_sink_ambient_G_W_per_K', expected_hot_sink_ambient_G_W_per_K, ...
        'expected_cold_sink_ambient_G_W_per_K', expected_cold_sink_ambient_G_W_per_K, ...
        'expected_cold_sink_ambient_G_hold_W_per_K', expected_cold_sink_ambient_G_hold_W_per_K, ...
        'expected_cold_sink_ambient_G_cooldown_W_per_K', expected_cold_sink_ambient_G_cooldown_W_per_K, ...
        'expected_cold_load_ambient_G_W_per_K', expected_cold_load_ambient_G_W_per_K, ...
        'expected_chip_ambient_G_W_per_K', expected_chip_ambient_G_W_per_K, ...
        'cold_side_ambient_G_semantics', 'cold_sink/cold_load ambient links are numerically disconnected with 1e-12 W/K when zero is avoided for Simscape robustness', ...
        'expected_cold_load_to_cold_sink_G_hold_W_per_K', expected_cold_load_G_hold_W_per_K, ...
        'expected_cold_load_to_cold_sink_G_cooldown_W_per_K', expected_cold_load_G_cooldown_W_per_K, ...
        'expected_chip_heat_W', expected_chip_heat_W, ...
        'chip_heat_standard', sprintf('Deprecated compatibility alias for cold-load heat input %.6g W.', expected_chip_heat_W), ...
        'expected_probe_sample_count', expected_probe_sample_count, ...
        'cycles_with_pressure_compensation', cycles_with_pressure_compensation, ...
        'cycles_with_reused_stage_results', cycles_with_reused_stage_results, ...
        'warning_count', numel(warnings), ...
        'warning_reasons', {warnings}, ...
        'expected_accepted_temperature_source', expected_source, ...
        'expected_raw_tx_node_count', expected_raw_nodes, ...
        'expected_reconciled_tx_node_count', expected_reconciled_nodes, ...
        'cycle_count', numel(cycle_results), ...
        'cycle_checks', cycle_checks, ...
        'recommendation', validation_recommendation(run_ok, contract_ok, physics_ok));
end

function check = validate_one_cycle(cycle_result, expected_source, expected_raw_nodes, expected_reconciled_nodes, ...
        expected_chip_heat_W, expected_probe_sample_count, expected_hot_sink_C_J_per_K, ...
        expected_cold_sink_C_J_per_K, expected_cold_sink_fluid_G_hold_W_per_K, ...
        expected_cold_sink_fluid_G_cooldown_W_per_K, ...
        expected_cold_load_G_hold_W_per_K, expected_cold_load_G_cooldown_W_per_K)
    reports = reshape(get_field(cycle_result, 'stage_reports', struct([])), 1, []);
    load_r = get_stage_report(reports, 'load_adiabatic');
    hold_r = get_stage_report(reports, 'hold_exchange');
    unload_r = get_stage_report(reports, 'unload_adiabatic');
    cooldown_r = get_stage_report(reports, 'cooldown_exchange');

    stage_count_ok = numel(reports) == 4;
    stage_kind_nonempty_ok = all(arrayfun(@(r) has_nonempty_field(r, 'stage_kind'), reports));
    side_mode_nonempty_ok = all(arrayfun(@(r) has_nonempty_field(r, 'side_thermal_state_mode'), reports));
    frozen_stages_ok = strcmp(get_field(load_r, 'side_thermal_state_mode', ''), 'frozen_side_state') && ...
        logical(get_field(load_r, 'frozen_side_state', false)) && ...
        strcmp(get_field(unload_r, 'side_thermal_state_mode', ''), 'frozen_side_state') && ...
        logical(get_field(unload_r, 'frozen_side_state', false));
    hold_side_mode = get_field(hold_r, 'side_thermal_state_mode', '');
    cooldown_side_mode = get_field(cooldown_r, 'side_thermal_state_mode', '');
    exchange_stage_modes_ok = any(strcmp(hold_side_mode, ...
        {'active_exchange_stage_cold_load_isolated', 'active_exchange_stage_isolated_chip'})) && ...
        any(strcmp(cooldown_side_mode, ...
        {'active_exchange_stage_cold_load_to_CHEX', 'active_exchange_stage_chip_cooling'}));
    accepted_source_ok = strcmp(get_field(hold_r, 'accepted_temperature_source', ''), expected_source) && ...
        strcmp(get_field(cooldown_r, 'accepted_temperature_source', ''), expected_source);
    node_contract_ok = get_field(hold_r, 'raw_tx_node_count', NaN) == expected_raw_nodes && ...
        get_field(cooldown_r, 'raw_tx_node_count', NaN) == expected_raw_nodes && ...
        get_field(hold_r, 'reconciled_tx_node_count', NaN) == expected_reconciled_nodes && ...
        get_field(cooldown_r, 'reconciled_tx_node_count', NaN) == expected_reconciled_nodes;
    hold_probe_timeseries_ok = validate_probe_timeseries_report(hold_r, expected_probe_sample_count);
    cooldown_probe_timeseries_ok = validate_probe_timeseries_report(cooldown_r, expected_probe_sample_count);
    probe_timeseries_ok = hold_probe_timeseries_ok && cooldown_probe_timeseries_ok;
    effective_heat_capacity_ok = all(isfinite([ ...
        get_field(hold_r, 'hot_sink_effective_C_J_per_K', NaN), ...
        get_field(hold_r, 'cold_sink_effective_C_J_per_K', NaN), ...
        get_field(cooldown_r, 'hot_sink_effective_C_J_per_K', NaN), ...
        get_field(cooldown_r, 'cold_sink_effective_C_J_per_K', NaN), ...
        get_field(hold_r, 'hot_sink_effective_water_volume_ml', NaN), ...
        get_field(hold_r, 'cold_sink_effective_water_volume_ml', NaN)])) && ...
        has_nonempty_field(hold_r, 'hot_sink_C_semantics') && ...
        has_nonempty_field(cooldown_r, 'cold_sink_C_semantics');
    hot_sink_capacity_value_ok = abs(get_field(hold_r, 'hot_sink_effective_C_J_per_K', NaN) - expected_hot_sink_C_J_per_K) < 1.0e-9 && ...
        abs(get_field(cooldown_r, 'hot_sink_effective_C_J_per_K', NaN) - expected_hot_sink_C_J_per_K) < 1.0e-9;
    cold_sink_capacity_value_ok = abs(get_field(hold_r, 'cold_sink_effective_C_J_per_K', NaN) - expected_cold_sink_C_J_per_K) < 1.0e-9 && ...
        abs(get_field(cooldown_r, 'cold_sink_effective_C_J_per_K', NaN) - expected_cold_sink_C_J_per_K) < 1.0e-9;
    cold_sink_fluid_G_value_ok = abs(get_field(hold_r, 'cold_sink_fluid_G_W_per_K', NaN) - expected_cold_sink_fluid_G_hold_W_per_K) < 1.0e-9 && ...
        abs(get_field(cooldown_r, 'cold_sink_fluid_G_W_per_K', NaN) - expected_cold_sink_fluid_G_cooldown_W_per_K) < 1.0e-9;
    hold_cold_sink_drift_K = get_field(hold_r, 'cold_sink_temp_out', NaN) - ...
        get_field(hold_r, 'cold_sink_temp_in', NaN);
    hold_cold_sink_frozen_tolerance_K = 1.0e-4;
    hold_cold_sink_frozen_ok = isfinite(hold_cold_sink_drift_K) && ...
        abs(hold_cold_sink_drift_K) <= hold_cold_sink_frozen_tolerance_K && ...
        abs(get_field(hold_r, 'cold_sink_delta_energy_J', NaN)) <= ...
        max(1.0e-6, expected_cold_sink_C_J_per_K * hold_cold_sink_frozen_tolerance_K * 1.01);
    cooldown_cold_sink_drift_K = get_field(cooldown_r, 'cold_sink_temp_out', NaN) - ...
        get_field(cooldown_r, 'cold_sink_temp_in', NaN);
    cooldown_Q_sma_htf_stage4_for_ratio = get_field(cooldown_r, 'Q_sma_htf_stage4_J', ...
        get_field(cooldown_r, 'Q_sma_htf_J', NaN));
    if isfinite(cooldown_Q_sma_htf_stage4_for_ratio) && abs(cooldown_Q_sma_htf_stage4_for_ratio) > 1.0e-12
        cooldown_cold_sink_abs_receive_ratio_vs_Q_sma_htf = ...
            abs(get_field(cooldown_r, 'cold_sink_delta_energy_J', NaN)) / ...
            abs(cooldown_Q_sma_htf_stage4_for_ratio);
    else
        cooldown_cold_sink_abs_receive_ratio_vs_Q_sma_htf = NaN;
    end
    cycle_index = get_field(cycle_result, 'cycle_index', NaN);
    hold_flow_control_mode = char(string(get_field(hold_r, 'flow_control_mode', '')));
    cooldown_flow_control_mode = char(string(get_field(cooldown_r, 'flow_control_mode', '')));
    pi_flow_control_mode = strcmpi(strtrim(hold_flow_control_mode), 'pressure_pi_feedback_v1') && ...
        strcmpi(strtrim(cooldown_flow_control_mode), 'pressure_pi_feedback_v1');
    cold_end_required_numeric = [ ...
        get_field(cooldown_r, 'Q_sma_sensible_stage4_J', NaN), ...
        get_field(cooldown_r, 'Q_sma_latent_stage4_J', NaN), ...
        get_field(cooldown_r, 'Q_sma_total_stage4_J', NaN), ...
        get_field(cooldown_r, 'Q_sma_htf_stage4_J', get_field(cooldown_r, 'Q_sma_htf_J', NaN)), ...
        get_field(cooldown_r, 'Q_stage4_SMA_to_HTF_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_CHEX_in_to_out_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_CHEX_inlet_boundary_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_CHEX_outlet_boundary_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_cold_sink_mass_delta_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_cold_fluid_buffer_delta_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_cold_pipe_or_CHEX_delta_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_cold_entity_storage_sum_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_direct_cold_entity_gap_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_SMA_to_CHEX_transit_storage_J', NaN), ...
        get_field(cooldown_r, 'cold_end_delivery_with_transit_storage_ratio', NaN), ...
        get_field(cooldown_r, 'Q_stage4_CHEX_energy_residual_J', NaN), ...
        get_field(cooldown_r, 'Q_stage4_CHEX_energy_residual_ratio', NaN), ...
        get_field(cooldown_r, 'Q_CHEX_energy_residual_required_to_close_J', NaN), ...
        get_field(cooldown_r, 'unresolved_CHEX_storage_or_loss_J', NaN), ...
        get_field(cooldown_r, 'unresolved_CHEX_storage_or_loss_ratio', NaN), ...
        get_field(cooldown_r, 'Q_stage4_SMA_to_cold_entity_delivery_ratio', NaN), ...
        get_field(cooldown_r, 'Q_stage4_CHEX_to_cold_entity_closure_ratio', NaN), ...
        get_field(cooldown_r, 'Q_sma_to_htf_ratio', NaN), ...
        get_field(cooldown_r, 'Q_cold_sink_mass_received_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_fluid_buffer_received_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_pipe_or_CHEX_storage_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_return_boundary_enthalpy_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_return_positive_warm_slug_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_return_negative_cooling_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_end_received_measured_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_end_received_ideal_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_end_storage_sum_J', NaN), ...
        get_field(cooldown_r, 'Q_cold_end_official_J', NaN), ...
        get_field(cooldown_r, 'Q_hidden_buffer_stage4_J', NaN), ...
        get_field(cooldown_r, 'cold_end_delivery_ratio_measured', NaN), ...
        get_field(cooldown_r, 'cold_end_delivery_ratio_ideal', NaN), ...
        get_field(cooldown_r, 'Q_pipe_carryover_to_next_stage_J', NaN), ...
        get_field(cooldown_r, 'Q_unaccounted_stage4_J', NaN), ...
        get_field(cooldown_r, 'Q_unaccounted_stage4_ratio', NaN), ...
        get_field(cooldown_r, 'cold_end_missing_energy_J', NaN), ...
        get_field(cooldown_r, 'cold_end_temp_in', NaN), ...
        get_field(cooldown_r, 'cold_end_temp_out', NaN), ...
        get_field(cooldown_r, 'cold_end_C_total_J_per_K', NaN), ...
        get_field(cooldown_r, 'cold_end_effective_water_volume_ml', NaN)];
    cold_end_chain_fields_ok = all(isfinite(cold_end_required_numeric)) && ...
        has_nonempty_field(cooldown_r, 'official_cold_end_definition') && ...
        has_nonempty_field(cooldown_r, 'cold_end_temperature_source') && ...
        has_nonempty_field(cooldown_r, 'cold_side_state_sync_policy') && ...

function gate = dynamic_delta_t_gate(stage_report)
    gate = struct( ...
        'gate_ok', false, ...
        'predicted_delta_T_K', NaN, ...
        'delta_T_fluid_bound_K', get_field(stage_report, 'DeltaT_fluid_bound_K', NaN), ...
        'delta_T_ratio', NaN, ...
        'q_sma_htf_delta_T_K', NaN, ...
        'q_sma_htf_delta_T_ratio', NaN);
    c_sma = get_field(stage_report, 'C_sma_J_per_K', NaN);
    c_flush = get_field(stage_report, 'C_flush_J_per_K', NaN);
    t_sma_initial = get_field(stage_report, 'T_sma_initial_avg_K', NaN);
    t_fluid_in = get_field(stage_report, 'T_fluid_in_avg_K', NaN);
    if all(isfinite([c_sma, c_flush, t_sma_initial, t_fluid_in])) && (c_sma + c_flush) > 0
        gate.predicted_delta_T_K = -(t_fluid_in - t_sma_initial) * c_sma / (c_sma + c_flush);
    end
    if isfinite(gate.delta_T_fluid_bound_K) && isfinite(gate.predicted_delta_T_K) && ...
            abs(gate.predicted_delta_T_K) > eps
        gate.delta_T_ratio = gate.delta_T_fluid_bound_K / gate.predicted_delta_T_K;
    end
    q_sma_htf = get_field(stage_report, 'Q_sma_htf_stage4_J', get_field(stage_report, 'Q_sma_htf_J', NaN));
    if isfinite(q_sma_htf) && isfinite(c_flush) && abs(c_flush) > eps
        gate.q_sma_htf_delta_T_K = -q_sma_htf / c_flush;
    end
    if isfinite(gate.q_sma_htf_delta_T_K) && isfinite(gate.predicted_delta_T_K) && ...
            abs(gate.predicted_delta_T_K) > eps
        gate.q_sma_htf_delta_T_ratio = gate.q_sma_htf_delta_T_K / gate.predicted_delta_T_K;
    end
    gate.gate_ok = isfinite(gate.delta_T_ratio) && gate.delta_T_ratio >= 0.70 && gate.delta_T_ratio <= 1.10;
end

function tf = theory_bound_gate_ok(stage_report)
    predictive_bound = get_field(stage_report, 'Q_predictive_exchange_bound_J', ...
        get_field(stage_report, 'Q_lumped_predictive_bound_J', NaN));
    exchange_closure = get_field(stage_report, 'Q_sma_exchange_closure_J', ...
        get_field(stage_report, 'Q_boundary_plus_active_path_pipe_J', NaN));
    ratio = get_field(stage_report, 'Q_actual_to_predictive_bound_ratio', ...
        get_field(stage_report, 'boundary_plus_active_path_pipe_to_predictive_bound_ratio', NaN));
    state_delta = get_field(stage_report, 'Q_sma_state_J', NaN);
    legacy_bound = get_field(stage_report, 'Q_lumped_0p4_bound_J', NaN);
    method = lower(char(string(get_field(stage_report, 'Q_predictive_exchange_bound_method', ...
        get_field(stage_report, 'Q_lumped_bound_method', '')))));
    self_referenced_bound = all(isfinite([legacy_bound, state_delta])) && ...
        abs(legacy_bound - state_delta) <= max(1.0e-9, 1.0e-6 * max(abs(state_delta), 1.0));
    independent_bound_ok = isfinite(predictive_bound) && abs(predictive_bound) > 1.0e-12 && ...
        isfinite(exchange_closure) && ~self_referenced_bound && ...
        ~contains(method, 'implemented_directional_101_state_delta');
    tf = independent_bound_ok && isfinite(ratio) && ratio >= 0.50;
end

function tf = ratio_in_range(value, lower_bound, upper_bound)
    tf = isfinite(value) && value >= lower_bound && value <= upper_bound;
end

function value = ratio_to_target(actual_value, target_value)
    if isfinite(actual_value) && isfinite(target_value) && abs(target_value) > eps
        value = actual_value / target_value;
    else
        value = NaN;
    end
end

function tf = signed_energy_consistent(reference_J, entity_J, zero_tol_J)
    if nargin < 3
        zero_tol_J = 1.0e-9;
    end
    tf = isfinite(reference_J) && isfinite(entity_J) && ...
        (abs(reference_J) <= zero_tol_J || abs(entity_J) <= zero_tol_J || sign(reference_J) == sign(entity_J));
end

function tf = pipe_cumulative_not_growing(cycle_checks)
    if numel(cycle_checks) < 3
        tf = true;
        return;
    end
    stage2 = abs([cycle_checks.hold_stage2_path_pipe_unreleased_cumulative_J]);
    stage4 = abs([cycle_checks.cooldown_stage4_path_pipe_unreleased_cumulative_J]);
    tf = ~strictly_increasing_finite(stage2) && ~strictly_increasing_finite(stage4);
end

function tf = strictly_increasing_finite(values)
    values = values(isfinite(values));
    tf = numel(values) >= 3 && all(diff(values) > 1.0e-9);
end


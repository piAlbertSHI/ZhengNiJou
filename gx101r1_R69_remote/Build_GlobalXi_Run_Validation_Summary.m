function array_out = append_struct_compatible(array_in, item)
    if isempty(array_in)
        array_out = item;
        return;
    end

    array_out = array_in;
    array_fields = fieldnames(array_out);
    item_fields = fieldnames(item);
    for idx = 1:numel(item_fields)
        name = item_fields{idx};
        if ~isfield(array_out, name)
            [array_out.(name)] = deal([]);
        end
    end
    for idx = 1:numel(array_fields)
        name = array_fields{idx};
        if ~isfield(item, name)
            item.(name) = [];
        end
    end
    array_out(end + 1) = item;
end

function report = get_stage_report(reports, stage_name)
    report = struct();
    for idx = 1:numel(reports)
        if strcmp(get_field(reports(idx), 'stage_name', ''), stage_name)
            report = reports(idx);
            return;
        end
    end
end

function tf = has_nonempty_field(s, field_name)
    tf = isstruct(s) && isfield(s, field_name) && ~isempty(s.(field_name));
    if tf && ischar(s.(field_name))
        tf = ~isempty(strtrim(s.(field_name)));
    end
end

function value = get_field(s, field_name, default_value)
    if isstruct(s) && isfield(s, field_name) && ~isempty(s.(field_name))
        value = s.(field_name);
    else
        value = default_value;
    end
end

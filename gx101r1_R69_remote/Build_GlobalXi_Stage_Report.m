function report = merge_hook_fields(report, hook_report)
    fields = fieldnames(report);
    for idx = 1:numel(fields)
        name = fields{idx};
        if strcmp(name, 'checkpoint_path') || strcmp(name, 'output_checkpoint_path')
            continue;
        end
        if isstruct(hook_report) && isfield(hook_report, name) && ~isempty(hook_report.(name))
            report.(name) = hook_report.(name);
        end
    end
    if isstruct(hook_report) && isfield(hook_report, 'checkpoint_path')
        report.simulink_checkpoint_path = hook_report.checkpoint_path;
    end
    report.checkpoint_report = strip_large_hook_fields(hook_report);
end


function report = Build_GlobalXi_Stage_Report(stage_name, cycle_index, stage_index, ...
        checkpoint_path, solver_result, hook_report, checkpoint_report)
% Build a fixed-schema report for one GlobalXi/Simulink cycle stage.

    if nargin < 5 || isempty(solver_result)
        solver_result = struct();
    end
    if nargin < 6 || isempty(hook_report)
        hook_report = struct();
    end
    if nargin < 7 || isempty(checkpoint_report)
        checkpoint_report = struct();
    end

    checkpoint_path = char(string(checkpoint_path));
    state_summary = summarize_checkpoint(checkpoint_path);
    metrics = get_struct_field(solver_result, 'summary_metrics', struct());

    report = default_stage_report();
    report.cycle_index = cycle_index;
    report.stage_index = stage_index;
    report.stage_name = char(string(stage_name));
    report.ok = get_struct_field(solver_result, 'ok', true);
    report.failure_reason = get_struct_field(solver_result, 'failure_reason', '');
    report.checkpoint_path = checkpoint_path;
    report.input_checkpoint_path = get_struct_field(checkpoint_report, 'source_checkpoint_path', '');
    report.output_checkpoint_path = checkpoint_path;
    report.exchange_checkpoint_path = get_struct_field(checkpoint_report, 'exchange_checkpoint_path', '');
    report.balanced_checkpoint_path = get_struct_field(checkpoint_report, 'balanced_checkpoint_path', '');
    report.restart_checkpoint_path = get_struct_field(checkpoint_report, 'restart_checkpoint_path', checkpoint_path);
    report.restart_balance_strategy = get_struct_field(checkpoint_report, 'restart_balance_strategy', '');
    report.restart_balance_ok = get_struct_field(checkpoint_report, 'restart_balance_ok', false);
    report.balanced_changed = get_struct_field(checkpoint_report, 'balanced_changed', false);
    report.exchange_to_restart_max_abs_delta_Y = get_struct_field(checkpoint_report, 'exchange_to_restart_max_abs_delta_Y', NaN);
    report.temperature_only_update = get_struct_field(checkpoint_report, 'temperature_only_update', false);
    report.max_abs_delta_T_K = get_struct_field(checkpoint_report, 'max_abs_delta_T_K', NaN);
    report.mean_delta_T_K = get_struct_field(checkpoint_report, 'mean_delta_T_K', NaN);
    report = merge_checkpoint_fields(report, checkpoint_report);
    report.profile = state_summary.profile;
    report.profile_summary = state_summary.summary;
    report.final_pressure_MPa = get_struct_field(state_summary.summary, 'pressure_MPa', ...
        get_struct_field(metrics, 'global_xi_time_final_pressure_MPa', NaN));
    report.avg_T_K = get_struct_field(state_summary.summary, 'avg_T_K', NaN);
    report.center_T_K = get_struct_field(state_summary.summary, 'center_T_K', NaN);
    report.edge_T_K = get_struct_field(state_summary.summary, 'edge_T_K', NaN);
    report.avg_xi = get_struct_field(state_summary.summary, 'avg_xi', NaN);
    report.max_xi = get_struct_field(state_summary.summary, 'max_xi', NaN);
    report.center_deflection_mm = get_struct_field(state_summary.summary, 'center_deflection_mm', NaN);
    report.peak_abs_deflection_mm = get_struct_field(state_summary.summary, 'peak_abs_deflection_mm', NaN);
    report.plate_radius_m = get_struct_field(state_summary.summary, 'plate_radius_m', NaN);
    report.plate_thickness_m = get_struct_field(state_summary.summary, 'plate_thickness_m', NaN);
    report.center_deflection_over_thickness = get_struct_field(state_summary.summary, 'center_deflection_over_thickness', NaN);
    report.peak_abs_deflection_over_thickness = get_struct_field(state_summary.summary, 'peak_abs_deflection_over_thickness', NaN);
    report.center_deflection_over_radius = get_struct_field(state_summary.summary, 'center_deflection_over_radius', NaN);
    report.peak_abs_deflection_over_radius = get_struct_field(state_summary.summary, 'peak_abs_deflection_over_radius', NaN);
    report.solver_summary = get_struct_field(solver_result, 'summary', '');
    report.solver_metrics = metrics;
    report = merge_work_metrics(report, metrics);

    report = apply_mechanical_stage_defaults(report);
    report = merge_hook_fields(report, hook_report);
end

function report = merge_checkpoint_fields(report, checkpoint_report)
    if ~isstruct(checkpoint_report)
        return;
    end
    fields = fieldnames(report);
    protected = {'checkpoint_path', 'output_checkpoint_path', 'profile', ...
        'profile_summary', 'solver_metrics', 'checkpoint_report'};
    for idx = 1:numel(fields)
        name = fields{idx};
        if any(strcmp(name, protected))
            continue;
        end
        if isfield(checkpoint_report, name) && ~isempty(checkpoint_report.(name))
            report.(name) = checkpoint_report.(name);
        end
    end
end

function report = merge_work_metrics(report, metrics)
    report.work_signed_J = get_struct_field(metrics, 'work_signed_J', report.work_signed_J);
    report.W_load_signed_J = get_struct_field(metrics, 'W_load_signed_J', report.W_load_signed_J);
    report.W_load_input_J = get_struct_field(metrics, 'W_load_input_J', report.W_load_input_J);
    report.W_unload_signed_J = get_struct_field(metrics, 'W_unload_signed_J', report.W_unload_signed_J);
    report.W_unload_recovered_J = get_struct_field(metrics, 'W_unload_recovered_J', report.W_unload_recovered_J);
    report.V_deflect_start_m3 = get_struct_field(metrics, 'V_deflect_start_m3', report.V_deflect_start_m3);
    report.V_deflect_end_m3 = get_struct_field(metrics, 'V_deflect_end_m3', report.V_deflect_end_m3);
    report.V_deflect_delta_m3 = get_struct_field(metrics, 'V_deflect_delta_m3', report.V_deflect_delta_m3);
    report.work_complete = get_struct_field(metrics, 'work_complete', report.work_complete);
    report.work_accepted_step_count = get_struct_field(metrics, 'work_accepted_step_count', report.work_accepted_step_count);
    report.work_history_available = get_struct_field(metrics, 'work_history_available', report.work_history_available);
    report.work_history_point_count = get_struct_field(metrics, 'work_history_point_count', report.work_history_point_count);
    report.work_history_trapz_J = get_struct_field(metrics, 'work_history_trapz_J', report.work_history_trapz_J);
    report.work_history_online_diff_J = get_struct_field(metrics, 'work_history_online_diff_J', report.work_history_online_diff_J);
    report.work_sign_convention = get_struct_field(metrics, 'work_sign_convention', report.work_sign_convention);
    report.work_cop_convention = get_struct_field(metrics, 'work_cop_convention', report.work_cop_convention);
    report.Nt = get_struct_field(metrics, 'global_xi_time_Nt', report.Nt);
    report.Nt_unload = get_struct_field(metrics, 'global_xi_time_Nt_unload', report.Nt_unload);
    if strcmp(report.stage_name, 'load_adiabatic')
        report.Nt_used = report.Nt;
    elseif strcmp(report.stage_name, 'unload_adiabatic')
        report.Nt_used = report.Nt_unload;
        report.Nt_unload_used = report.Nt_unload;
        report.Nt_unload_original = report.Nt_unload;
    end
end

function report = apply_mechanical_stage_defaults(report)
    switch report.stage_name
        case 'load_adiabatic'
            report.stage_kind = 'globalxi_adiabatic_closed';
            report.L_valve = zeros(1, 6);
            report.L_valve_target = zeros(1, 6);
            report.L_valve_initial = zeros(1, 6);
            report.exchange_startup_profile = 'closed_stage_no_exchange';
            report.startup_smoothing_reason = 'mechanical adiabatic stage does not call Simulink exchange';
            report.valve_names = {'V1_cold_inlet', 'V2_hot_return', 'V3_sma_to_hot', ...
                'V4_hot_inlet', 'V5_cold_return', 'V6_sma_to_chip_cold'};
            report.flow_path_name = 'all_valves_closed';
            report.flow_path_description = 'All valves closed; hot sink, cold sink and cold load are frozen in this mechanical stage.';
            report.stop_time_s = 0.1;
        case 'unload_adiabatic'
            report.stage_kind = 'globalxi_adiabatic_closed';
            report.L_valve = zeros(1, 6);
            report.L_valve_target = zeros(1, 6);
            report.L_valve_initial = zeros(1, 6);
            report.exchange_startup_profile = 'closed_stage_no_exchange';
            report.startup_smoothing_reason = 'mechanical adiabatic stage does not call Simulink exchange';
            report.valve_names = {'V1_cold_inlet', 'V2_hot_return', 'V3_sma_to_hot', ...
                'V4_hot_inlet', 'V5_cold_return', 'V6_sma_to_chip_cold'};
            report.flow_path_name = 'all_valves_closed';
            report.flow_path_description = 'All valves closed; hot sink, cold sink and cold load are frozen in this mechanical stage.';
            report.stop_time_s = 0.1;
    end
end


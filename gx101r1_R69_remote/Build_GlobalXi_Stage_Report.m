    profile_summary = struct( ...
        'pressure_MPa', state_std.pressure_MPa, ...
        'avg_T_K', area_average(T, grid), ...
        'center_T_K', T(1), ...
        'edge_T_K', T(end), ...
        'min_T_K', min(T), ...
        'max_T_K', max(T), ...
        'avg_xi', area_average(xi, grid), ...
        'max_xi', max(xi), ...
        'center_deflection_mm', 1.0e3 * center_deflection_m, ...
        'peak_abs_deflection_mm', 1.0e3 * peak_abs_deflection_m, ...
        'plate_radius_m', plate_radius_m, ...
        'plate_thickness_m', plate_thickness_m, ...
        'center_deflection_over_thickness', safe_ratio(center_deflection_m, plate_thickness_m), ...
        'peak_abs_deflection_over_thickness', safe_ratio(peak_abs_deflection_m, plate_thickness_m), ...
        'center_deflection_over_radius', safe_ratio(center_deflection_m, plate_radius_m), ...
        'peak_abs_deflection_over_radius', safe_ratio(peak_abs_deflection_m, plate_radius_m));
    summary.profile = profile;
    summary.summary = profile_summary;
end

function hook_report = strip_large_hook_fields(hook_report)
    if ~isstruct(hook_report)
        hook_report = struct();
        return;
    end
    large_fields = {'simOut', 'state_out', 'bridge_plan', 'directional_backend_T_strip_101_in', ...
        'directional_backend_T_strip_101_out', 'Tx51', 'T_x_out_101', 'T_r_compressed'};
    for idx = 1:numel(large_fields)
        if isfield(hook_report, large_fields{idx})
            hook_report = rmfield(hook_report, large_fields{idx});
        end
    end
end

function ratio = safe_ratio(value, denominator)
    if isfinite(value) && isfinite(denominator) && abs(denominator) > eps
        ratio = value / denominator;
    else
        ratio = NaN;
    end
end

function avg = area_average(values, grid)
    r = grid.r(:);
    weights = r;
    weights(1) = grid.dr / 4;
    if sum(weights) <= 0
        avg = mean(values(:));
    else
        avg = sum(values(:) .* weights(:)) / sum(weights);
    end
end

function value = get_struct_field(s, field_name, default_value)
    if isstruct(s) && isfield(s, field_name) && ~isempty(s.(field_name))
        value = s.(field_name);
    else
        value = default_value;
    end
end

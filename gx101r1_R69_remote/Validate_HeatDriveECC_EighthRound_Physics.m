function audit = Validate_HeatDriveECC_EighthRound_Physics(input_value)
% Validate one physical Simscape run. Default execution is three cycles.

    if nargin < 1 || isempty(input_value)
        result = Run_HeatDriveECC_EighthRound_Simulink_Cycles( ...
            struct('cycle_count', 3));
    elseif isstruct(input_value) && isfield(input_value, 'physical')
        result = input_value;
    elseif isstruct(input_value)
        result = Run_HeatDriveECC_EighthRound_Simulink_Cycles(input_value);
    else
        error('Validate:EighthRound:BadInput', ...
            'Input must be a run result or an overrides structure.');
    end

    result.summary = Summarize_HeatDriveECC_EighthRound_Output( ...
        result.physical, result.options);

    checks = hard_checks(result);
    audit = struct();
    audit.result = result;
    audit.checks = checks;
    audit.passed = all_checks_pass(checks);
    audit.coupled_mechanism_pass = audit.passed;
    audit.strict_table4_reproduction_applicable = ...
        result.options.validation.strict_table4_reproduction_applicable;
    audit.strict_table4_reproduction_evaluated = ...
        result.options.validation.strict_table4_reproduction_evaluated;
    audit.strict_table4_reproduction_pass = false;
    audit.all_required_pass = audit.passed && ...
        audit.strict_table4_reproduction_evaluated && ...
        audit.strict_table4_reproduction_pass;
    audit.outputs = write_audit_outputs(result, checks, audit.passed);
    fprintf('Physical Simscape validation passed: %d\n', audit.passed);
    fprintf('Validation report: %s\n', audit.outputs.report_path);
    error_on_failure = true;
    if isfield(result.options.validation, 'error_on_mechanism_failure')
        error_on_failure = logical( ...
            result.options.validation.error_on_mechanism_failure);
    end
    if ~audit.passed && error_on_failure
        error('Validate:EighthRound:PhysicalCheckFailed', ...
            'Physical Simscape checks failed. See %s.', ...
            audit.outputs.report_path);
    end
end

function checks = hard_checks(result)
    p = result.physical;
    s = result.summary;
    o = result.options;
    v = o.validation;
    cycles = s.cycle;
    signed_sma = [cycles.stage1_SMA_core_mean_signed_flow_kgps, ...
        cycles.stage2_SMA_core_mean_signed_flow_kgps, ...
        cycles.stage3_SMA_core_mean_signed_flow_kgps, ...
        cycles.stage4_SMA_core_mean_signed_flow_kgps];
    signed_se = [cycles.stage2_SE_core_mean_signed_flow_kgps, ...
        cycles.stage4_SE_core_mean_signed_flow_kgps];
    % Qian's prescribed active flow applies after valve commutation. The
    % intentional zero-pressure switch window is a numerical/topological
    % transient and must not dilute the active-flow contract.
    active_sma = abs(signed_sma);
    active_se = abs(signed_se);
    inactive_se = [cycles.inactive_SE_mean_abs_flow_kgps];
    cross_route_se = [cycles.stage2_closed_stage4_route_mean_abs_flow_kgps, ...
        cycles.stage4_closed_stage2_route_mean_abs_flow_kgps];
    target_sma = mean([o.branch.m_dot_sma_shex_kg_per_s, ...
        o.branch.m_dot_sma_the_kg_per_s]);
    target_se = mean([o.branch.m_dot_se_the_kg_per_s, ...
        o.branch.m_dot_se_chex_kg_per_s]);

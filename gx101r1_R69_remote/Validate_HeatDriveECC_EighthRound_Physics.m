    checks.cycle_state_continuity = ...
        s.max_cycle_boundary_SMA_state_jump <= 0.05 && ...
        s.max_cycle_boundary_SE_state_jump <= 0.05;
    checks.cycle_temperature_continuity = ...
        s.max_cycle_boundary_SMA_temperature_jump_K <= 2.0 && ...
        s.max_cycle_boundary_SE_temperature_jump_K <= 2.0;
    checks.pressure_commands_logged = ...
        any(abs(p.pressure_command_SMA_MPa) > 0.0) && ...
        any(abs(p.pressure_command_SE_MPa) > 0.0);
    switch_times_s = zeros(0, 1);
    switch_delay_s = o.branch.stage_command_ramp_s / 3.0;
    stage2_end_s = sum(o.schedule.stage_durations_s(1:2));
    for cycle_idx = 0:(o.cycle_count - 1)
        switch_times_s(end + 1, 1) = cycle_idx * ...
            o.schedule.tau_cycle_s + stage2_end_s + switch_delay_s; %#ok<AGROW>
        stage4_switch_s = (cycle_idx + 1) * o.schedule.tau_cycle_s + ...
            switch_delay_s;
        if stage4_switch_s <= p.time_s(end)
            switch_times_s(end + 1, 1) = stage4_switch_s; %#ok<AGROW>
        end
    end
    switch_pressure_error_MPa = zeros(size(switch_times_s));
    switch_samples_present = true;
    for switch_idx = 1:numel(switch_times_s)
        [sample_error_s, sample_idx] = min(abs( ...
            p.time_s - switch_times_s(switch_idx)));
        switch_samples_present = switch_samples_present && ...
            sample_error_s <= 0.51 * o.simulation.fixed_step_s;
        switch_pressure_error_MPa(switch_idx) = abs( ...
            p.pressure_command_SMA_MPa(sample_idx) - ...
            o.branch.sma_valve_switch_pressure_MPa);
    end
    pump_manifold_probe_names = { ...
        'probe_sma_stage13_pump_outlet_T_K', ...
        'sma_hold_pipe_node21_fluid_temp_out', ...
        'sma_cooldown_pipe_node01_fluid_temp_out'};
    pump_manifold_probes_present = all(cellfun( ...
        @(name) isfield(p.probes, name), pump_manifold_probe_names));
    pump_manifold_max_T_K = inf;
    if pump_manifold_probes_present
        pump_manifold_max_T_K = max(cellfun( ...
            @(name) max(p.probes.(name)), pump_manifold_probe_names));
    end

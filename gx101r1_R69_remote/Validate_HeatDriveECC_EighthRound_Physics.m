    stage_duration_s = reshape( ...
        o.schedule.stage_durations_s(p.stage_id(:)), [], 1);
    route_core = p.stage_elapsed_s >= route_guard_s & ...
        p.stage_elapsed_s <= stage_duration_s - route_guard_s;

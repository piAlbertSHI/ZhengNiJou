function audit = Validate_HeatDriveECC_EighthRound_Physics(input_value)
% Validate one physical Simscape run. Default execution is two cycles.

    if nargin < 1 || isempty(input_value)
        result = Run_HeatDriveECC_EighthRound_Simulink_Cycles( ...
            struct('cycle_count', 2));
    elseif isstruct(input_value) && isfield(input_value, 'physical')
        result = input_value;
    elseif isstruct(input_value)
        result = Run_HeatDriveECC_EighthRound_Simulink_Cycles(input_value);
    else
        error('Validate:EighthRound:BadInput', ...
            'Input must be a run result or an overrides structure.');
    end

    checks = hard_checks(result);
    audit = struct();
    audit.result = result;
    audit.checks = checks;
    audit.passed = all_checks_pass(checks);
    audit.outputs = write_audit_outputs(result, checks, audit.passed);
    fprintf('Physical Simscape validation passed: %d\n', audit.passed);
    fprintf('Validation report: %s\n', audit.outputs.report_path);
    if ~audit.passed
        error('Validate:EighthRound:PhysicalCheckFailed', ...
            'Physical Simscape checks failed. See %s.', ...
            audit.outputs.report_path);
    end
end

function checks = hard_checks(result)
    p = result.physical;
    s = result.summary;
    o = result.options;
    v = o.validation;
    cycles = s.cycle;
    active_sma = [cycles.stage1_SMA_mean_abs_flow_kgps, ...
        cycles.stage3_SMA_mean_abs_flow_kgps];
    active_se = [cycles.stage2_SE_mean_abs_flow_kgps, ...
        cycles.stage4_SE_mean_abs_flow_kgps];
    inactive_sma = [cycles.inactive_SMA_mean_abs_flow_kgps];
    inactive_se = [cycles.inactive_SE_mean_abs_flow_kgps];
    target = o.branch.m_dot_kg_per_s;

    checks = struct();
    checks.used_real_sim_call = result.used_simulink_sim && ...
        p.sim_call_count == 1;
    checks.physical_authority = strcmp(result.authority, ...
        v.required_authority);
    checks.no_legacy_surrogate = ...
        ~result.legacy_surrogate_used_for_results && ...
        ~p.legacy_surrogate_used_for_results;
    checks.requested_cycle_count = numel(cycles) == o.cycle_count && ...
        max(p.cycle_index) == o.cycle_count;
    checks.all_required_finite = s.all_required_finite;
    checks.samples_per_stage = s.stage_sample_min >= ...
        v.min_samples_per_stage;
    checks.node_count = size(p.SMA_T_21_K, 2) == 21 && ...
        size(p.SE_T_21_K, 2) == 21;
    checks.temperature_range = s.min_temperature_K >= ...
        v.min_temperature_K && s.max_temperature_K <= v.max_temperature_K;
    checks.phase_fraction_bounds = all(p.xM_SMA_21(:) >= -1.0e-9) && ...
        all(p.xM_SMA_21(:) <= 1.0 + 1.0e-9) && ...
        all(p.xM_SE_21(:) >= -1.0e-9) && ...
        all(p.xM_SE_21(:) <= 1.0 + 1.0e-9);
    checks.stress_bound = max(s.max_abs_sigma_SMA_Pa, ...
        s.max_abs_sigma_SE_Pa) <= v.max_abs_stress_Pa;
    checks.flow_bound = s.max_abs_flow_kgps <= ...
        v.max_abs_flow_over_target * target;
    checks.SMA_active_routes = all(active_sma > 0.10 * target);
    checks.SE_active_routes = all(active_se > 0.10 * target);
    checks.SMA_inactive_isolation = mean(inactive_sma) < ...
        0.20 * mean(active_sma);
    checks.SE_inactive_isolation = mean(inactive_se) < ...
        0.20 * mean(active_se);
    checks.SMA_phase_swing = max([cycles.xM_SMA_swing]) >= ...
        v.min_sma_phase_swing;
    checks.SE_phase_swing = max([cycles.xM_SE_swing]) >= 0.50;
    checks.nominal_SMA_stress = relerr( ...
        max([cycles.sigma_SMA_max_MPa]), ...
        o.material.SMA.nominal_stress_Pa / 1.0e6) <= 0.35;
    checks.cycle_state_continuity = ...
        s.max_cycle_boundary_SMA_state_jump <= 0.05 && ...
        s.max_cycle_boundary_SE_state_jump <= 0.05;
    checks.cycle_temperature_continuity = ...
        s.max_cycle_boundary_SMA_temperature_jump_K <= 2.0 && ...
        s.max_cycle_boundary_SE_temperature_jump_K <= 2.0;
    checks.pressure_commands_logged = ...
        any(abs(p.pressure_command_SMA_MPa) > 0.0) && ...
        any(abs(p.pressure_command_SE_MPa) > 0.0);
    checks.pump_work_nonnegative = all([cycles.pump_work_SMA_J] >= 0.0) && ...
        all([cycles.pump_work_SE_J] >= 0.0);
    checks.probes_present = s.probe_count >= 20;
end

function outputs = write_audit_outputs(result, checks, passed)
    out_dir = result.output_dir;
    outputs = struct();
    outputs.cycle_summary_csv = fullfile(out_dir, 'cycle_physical_summary.csv');
    outputs.stage_probe_csv = fullfile(out_dir, ...
        'stage_temperature_probes_50samples.csv');
    outputs.parameter_contract_csv = fullfile(out_dir, ...
        'xu2019_table5_parameter_contract.csv');
    outputs.report_path = fullfile(out_dir, 'physical_validation_report.txt');
    writetable(cycle_summary_table(result), outputs.cycle_summary_csv);
    writetable(stage_probe_table(result, 50), outputs.stage_probe_csv);
    writetable(parameter_contract_table(result.options), ...
        outputs.parameter_contract_csv);
    write_report(outputs.report_path, result, checks, passed, outputs);
end

function T = cycle_summary_table(result)
    c = result.summary.cycle(:);
    T = struct2table(c);
end

function T = stage_probe_table(result, sample_count)
    p = result.physical;
    o = result.options;
    probe_names = p.probe_names(:).';
    rows = cell(o.cycle_count * 4 * sample_count, 5 + numel(probe_names));
    row = 0;
    for cycle_idx = 1:o.cycle_count
        cycle_base = (cycle_idx - 1) * o.schedule.tau_cycle_s;
        for stage_idx = 1:4
            t0 = cycle_base + o.schedule.stage_start_s(stage_idx);
            t1 = cycle_base + o.schedule.stage_end_s(stage_idx);
            tq = linspace(t0, t1, sample_count).';
            for sample_idx = 1:sample_count
                row = row + 1;
                rows{row, 1} = cycle_idx;
                rows{row, 2} = stage_idx;
                rows{row, 3} = sample_idx;
                rows{row, 4} = tq(sample_idx);
                rows{row, 5} = (tq(sample_idx) - t0) / max(t1 - t0, eps);
            end
            for probe_idx = 1:numel(probe_names)
                values = interp1(p.time_s, p.probes.(probe_names{probe_idx}), ...
                    tq, 'linear', 'extrap');
                rows((row - sample_count + 1):row, 5 + probe_idx) = ...
                    num2cell(values);
            end
        end
    end
    variable_names = [{'cycle_index','stage_id','sample_index', ...
        'time_s','stage_fraction'}, probe_names];
    variable_names = matlab.lang.makeUniqueStrings( ...
        matlab.lang.makeValidName(variable_names));
    T = cell2table(rows, 'VariableNames', variable_names);
end


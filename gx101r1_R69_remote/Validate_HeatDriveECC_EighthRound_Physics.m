        abs(p.mdot_SMA_stage1_route_kgps(stage1_route_inactive)); ...
        abs(p.mdot_SMA_stage3_route_kgps(stage3_route_inactive))]);
    settled_sma = route_core & p.stage_elapsed_s >= 1.0;
    settled_sma_flow = p.mdot_SMA_kgps(settled_sma);
    settled_sma_pressure = p.pressure_command_SMA_MPa(settled_sma);
    sma_pressure_at_limit = ...
        abs(settled_sma_pressure - o.branch.sma_pressure_pi_min_MPa) <= ...
            1.0e-9 | ...
        abs(settled_sma_pressure - o.branch.pressure_pi_max_MPa) <= 1.0e-9;

    checks = struct();

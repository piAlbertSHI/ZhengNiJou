function [minimum_K, maximum_K] = probe_temperature_range(physical)
    minimum_K = Inf;
    maximum_K = -Inf;
    if ~isfield(physical, 'probes') || isempty(physical.probes)
        minimum_K = NaN;
        maximum_K = NaN;
        return;
    end
    names = fieldnames(physical.probes);
    for idx = 1:numel(names)
        values = physical.probes.(names{idx});
        if isnumeric(values) && ~isempty(values)
            minimum_K = min(minimum_K, min(values(:)));
            maximum_K = max(maximum_K, max(values(:)));
        end
    end
end

function [minimum_K, maximum_K, count] = ...
        domain_probe_temperature_range(physical, tokens)
    minimum_K = Inf;
    maximum_K = -Inf;
    count = 0;
    if ~isfield(physical, 'probes') || isempty(physical.probes)
        minimum_K = NaN;
        maximum_K = NaN;
        return;
    end
    names = fieldnames(physical.probes);
    for idx = 1:numel(names)
        if ~any(startsWith(names{idx}, tokens, 'IgnoreCase', true))
            continue;
        end
        values = physical.probes.(names{idx});
        if isnumeric(values) && ~isempty(values)
            minimum_K = min(minimum_K, min(values(:)));
            maximum_K = max(maximum_K, max(values(:)));
            count = count + 1;
        end
    end
    if count == 0
        minimum_K = NaN;
        maximum_K = NaN;
    end
end


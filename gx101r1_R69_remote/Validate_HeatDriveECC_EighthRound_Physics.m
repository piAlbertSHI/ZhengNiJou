function tf = all_checks_pass(checks)
    values = struct2cell(checks);
    tf = all(cellfun(@(x) islogical(x) && isscalar(x) && x, values));
end

function value = relerr(actual, target)
    value = abs(actual - target) / max(abs(target), eps);
end

function sigma_a_Pa = full_transform_compatibility_stress(options)
% Qian Eqs. (5)-(8) at xA,SMA=1 and xM,SE=1 for the active geometry.
    g = options.geometry;
    sma = options.material.SMA;
    se = options.material.SE;
    force_ratio = g.S_r_m2 / g.S_a_m2;
    numerator_m = g.L_a_m * sma.epsilon_T - ...
        g.L_r_m * se.epsilon_T;
    denominator_m_per_Pa = ...
        g.L_a_m * force_ratio / sma.E_m_Pa + ...
        g.L_r_m / se.E_m_Pa;
    sigma_r_Pa = numerator_m / max(denominator_m_per_Pa, eps);
    sigma_a_Pa = force_ratio * sigma_r_Pa;
end

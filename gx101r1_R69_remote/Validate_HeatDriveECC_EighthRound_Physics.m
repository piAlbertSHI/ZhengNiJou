        'SMA_Hmax'; 'SMA_Hcur_at_136MPa'; 'SMA_Delta_s_J_per_kgK'; ...
        'SMA_Delta_h_J_per_kg'; 'SMA_nominal_stress_Pa'; ...
        'S_over_ratio'; 'L_over_ratio'; 'SHEX_C_J_per_K'; ...
        'HHEX_C_J_per_K'; 'CHEX_C_J_per_K'; 'fluid_mass_total_kg'; ...
        'target_mdot_kgps'; 'cycle_time_s'; 'stage1_s'; 'stage2_s'; ...
        'stage3_s'; 'stage4_s'};

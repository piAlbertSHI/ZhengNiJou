function T = stage_probe_table(result, sample_count)
    p = result.physical;
    o = result.options;
    probe_names = p.probe_names(:).';
    rows = cell(o.cycle_count * 4 * sample_count, 5 + numel(probe_names));
    row = 0;
    for cycle_idx = 1:o.cycle_count
        cycle_base = (cycle_idx - 1) * o.schedule.tau_cycle_s;
        for stage_idx = 1:4
            t0 = cycle_base + o.schedule.stage_start_s(stage_idx);
            t1 = cycle_base + o.schedule.stage_end_s(stage_idx);
            tq = linspace(t0, t1, sample_count).';
            for sample_idx = 1:sample_count
                row = row + 1;
                rows{row, 1} = cycle_idx;
                rows{row, 2} = stage_idx;
                rows{row, 3} = sample_idx;
                rows{row, 4} = tq(sample_idx);
                rows{row, 5} = (tq(sample_idx) - t0) / max(t1 - t0, eps);
            end
            for probe_idx = 1:numel(probe_names)
                values = interp1(p.time_s, p.probes.(probe_names{probe_idx}), ...
                    tq, 'linear', 'extrap');
                rows((row - sample_count + 1):row, 5 + probe_idx) = ...
                    num2cell(values);
            end
        end
    end
    variable_names = [{'cycle_index','stage_id','sample_index', ...
        'time_s','stage_fraction'}, probe_names];
    variable_names = matlab.lang.makeUniqueStrings( ...
        matlab.lang.makeValidName(variable_names));
    T = cell2table(rows, 'VariableNames', variable_names);
end


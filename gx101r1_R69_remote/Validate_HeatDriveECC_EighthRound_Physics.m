        o.material.SMA.T_Ms_K; o.material.SMA.T_Mf_K; ...
        o.material.SMA.T_As_K; o.material.SMA.T_Af_K; ...
        o.material.SMA.Hmax_initial; o.material.SMA.Hcur_nominal; ...
        o.material.SMA.Delta_s0_J_per_kgK; ...
        o.material.SMA.Delta_h_J_per_kg; o.material.SMA.nominal_stress_Pa; ...
        o.geometry.S_r_over_S_a; o.geometry.L_r_over_L_a; ...
        o.system.shex_sink_C_J_per_K; o.system.hot_sink_C_J_per_K; ...
        o.system.cold_sink_C_J_per_K; o.branch.fluid_mass_total_kg; ...
        o.branch.m_dot_kg_per_s; o.schedule.tau_cycle_s; ...
        o.schedule.stage_durations_s(:)];
    T = table(string(names), values, 'VariableNames', {'parameter','value_SI'});
end

function write_report(path, result, checks, passed, outputs)
    o = result.options;
    s = result.summary;
    fid = fopen(path, 'w', 'n', 'UTF-8');
    if fid < 0
        error('Validate:EighthRound:ReportOpenFailed', ...
            'Cannot open validation report: %s', path);
    end
    cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
    fprintf(fid, 'Xu2019 Table 5 coupled Simscape physical validation\n');
    fprintf(fid, 'generated: %s\n', datestr(now, 31));
    fprintf(fid, 'passed: %d\n', passed);
    fprintf(fid, 'authority: %s\n', result.authority);
    fprintf(fid, 'legacy surrogate used: %d\n', ...
        result.legacy_surrogate_used_for_results);
    fprintf(fid, 'sim calls: %d\n', result.physical.sim_call_count);
    fprintf(fid, 'walltime_s: %.6f\n\n', result.physical.walltime_s);
    fprintf(fid, 'Parameter anchor\n');
    fprintf(fid, '  SMA: %s\n', o.material.SMA.name);
    fprintf(fid, '  net volume: %.12g m3; scale: %.12g\n', ...
        o.geometry.net_sma_volume_m3, o.geometry.volume_scale_vs_previous);
    fprintf(fid, '  mass: %.12g kg; Hcur(136 MPa): %.12g\n', ...
        o.equilibrium.m_a_kg, o.material.SMA.Hcur_nominal);
    fprintf(fid, '  Delta_s0: %.12g J/kg/K; Delta_h: %.12g J/kg\n', ...
        o.material.SMA.Delta_s0_J_per_kgK, ...
        o.material.SMA.Delta_h_J_per_kg);
    fprintf(fid, '  S_r/S_a: %.12g; L_r/L_a: %.12g\n', ...
        o.geometry.S_r_over_S_a, o.geometry.L_r_over_L_a);
    fprintf(fid, '  SHEX/HHEX/CHEX C: %.12g / %.12g / %.12g J/K\n', ...
        o.system.shex_sink_C_J_per_K, o.system.hot_sink_C_J_per_K, ...
        o.system.cold_sink_C_J_per_K);
    fprintf(fid, '  T source/HHEX/CHEX: %.6f / %.6f / %.6f K\n', ...
        o.system.Tshex_source_K, o.system.Thhex_K, o.system.Tchex_K);
    fprintf(fid, '  cycle/stages: %.9f / [%s] s\n\n', ...
        o.schedule.tau_cycle_s, num2str(o.schedule.stage_durations_s, ' %.9f'));
    fprintf(fid, 'Checks\n');
    names = fieldnames(checks);
    for idx = 1:numel(names)
        fprintf(fid, '  %-38s %d\n', names{idx}, checks.(names{idx}));
    end
    fprintf(fid, '\nCycle results\n');
    for idx = 1:numel(s.cycle)
        c = s.cycle(idx);
        fprintf(fid, ['  C%d SMA %.4f->%.4f K, SE %.4f->%.4f K, ', ...
            'SHEX dT=%+.6f K, HHEX dT=%+.6f K, CHEX dT=%+.6f K\n'], ...
            c.cycle_index, c.SMA_start_K, c.SMA_end_K, ...
            c.SE_start_K, c.SE_end_K, c.delta_SHEX_K, ...
            c.delta_HHEX_K, c.delta_CHEX_K);
        fprintf(fid, ['     xM swing SMA/SE %.6f/%.6f, stress max ', ...
            'SMA/SE %.4f/%.4f MPa, pump work %.6g/%.6g J\n'], ...
            c.xM_SMA_swing, c.xM_SE_swing, c.sigma_SMA_max_MPa, ...
            c.sigma_SE_max_MPa, c.pump_work_SMA_J, c.pump_work_SE_J);
    end
    fprintf(fid, '\nLiterature comparison boundary\n');
    fprintf(fid, '  quantitative_literature_reproduction_evaluated: %d\n', ...
        s.quantitative_literature_reproduction_evaluated);
    fprintf(fid, '  reason: %s\n', ...
        s.quantitative_literature_reproduction_reason);
    fprintf(fid, '\nOutputs\n');
    fprintf(fid, '  %s\n  %s\n  %s\n', outputs.cycle_summary_csv, ...
        outputs.stage_probe_csv, outputs.parameter_contract_csv);
end

function tf = all_checks_pass(checks)
    values = struct2cell(checks);
    tf = all(cellfun(@(x) islogical(x) && isscalar(x) && x, values));
end

function value = relerr(actual, target)
    value = abs(actual - target) / max(abs(target), eps);
end

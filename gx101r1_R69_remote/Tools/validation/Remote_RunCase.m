function summary = Remote_RunCase(repoRoot, outDir, tag, nCycles, vStar, savePlots, stageTime_s)
% Remote production runner for R72/R69 symmetric cold-end baseline.

if nargin < 1 || strlength(string(repoRoot)) == 0
    repoRoot = pwd;
end
if nargin < 2 || strlength(string(outDir)) == 0
    outDir = fullfile(repoRoot, 'Output', 'remote_case');
end
if nargin < 3 || strlength(string(tag)) == 0
    tag = 'remote_case';
end
if nargin < 4 || isempty(nCycles)
    nCycles = 50;
end
if nargin < 5 || isempty(vStar)
    vStar = 1.0;
end
if nargin < 6 || isempty(savePlots)
    savePlots = false;
end
if nargin < 7 || isempty(stageTime_s)
    stageTime_s = 0.40;
end

repoRoot = char(string(repoRoot));
outDir = char(string(outDir));
tag = char(string(tag));
ensure_dir(outDir);

restoredefaultpath;
addpath(repoRoot, '-begin');
addpath(fullfile(repoRoot, 'Tools', 'validation'), '-begin');

exchange_options = build_exchange_options(repoRoot, outDir, tag, vStar, stageTime_s);
run_options = struct( ...
    'nCycles', nCycles, ...
    'run_label', tag, ...
    'outputs_dir', outDir, ...
    'save_checkpoints', true, ...
    'save_plots', logical(savePlots), ...
    'store_raw_simout', false, ...
    'batch_light_mode', true, ...
    'force_rebuild_model', false, ...
    'exchange_options', exchange_options);

write_json(fullfile(outDir, 'run_options_input.json'), run_options);
save(fullfile(outDir, 'run_options_input.mat'), 'run_options');

runner_error = '';
console_text = '';
ticRun = tic;
try
    console_text = evalc('run_result = Run_GlobalXi_Simulink_Cycles(run_options);');
catch ME
    runner_error = getReport(ME, 'extended', 'hyperlinks', 'off');
    run_result = struct('ok', false, 'failure_reason', ME.message, ...
        'cycle_results', struct([]), 'validation_summary', struct());
end
walltime_s = toc(ticRun);

write_text(fullfile(outDir, 'console.txt'), console_text);
if ~isempty(runner_error)
    write_text(fullfile(outDir, 'runner_error.txt'), runner_error);
end
save(fullfile(outDir, 'result.mat'), 'run_options', 'run_result', ...
    'runner_error', 'console_text', '-v7.3');

validation_summary = struct();
try
    validation_summary = Build_GlobalXi_Run_Validation_Summary(run_result);
    write_json(fullfile(outDir, 'validation_summary.json'), validation_summary);
catch ME
    write_text(fullfile(outDir, 'validation_summary_error.txt'), ...
        getReport(ME, 'extended', 'hyperlinks', 'off'));
end

try
    Summarize_GX101R1_NoLoad_Energy_Table(fullfile(outDir, 'result.mat'), outDir);
catch ME
    write_text(fullfile(outDir, 'energy_table_error.txt'), ...
        getReport(ME, 'extended', 'hyperlinks', 'off'));
end

rows = stage_rows(run_result);
if ~isempty(rows)
    writetable(struct2table(rows), fullfile(outDir, 'stages.csv'));
end
summary = summarize_case(tag, outDir, nCycles, vStar, stageTime_s, walltime_s, rows, ...
    runner_error, console_text, validation_summary);
write_json(fullfile(outDir, 'summary.json'), summary);
write_markdown(fullfile(outDir, 'summary.md'), summary, rows);
disp(jsonencode(summary));
end


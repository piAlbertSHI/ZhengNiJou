    'simulink_codegen_cache_root', fullfile(outDir, 'codegen', 'cache'), ...
    'simulink_solver', 'ode23t', ...
    'simulink_solver_reltol', 1.0e-2, ...
    'simulink_solver_abstol', 1.0e-3, ...
    'simulink_solver_max_step', 0.4, ...
    'simulink_solver_initial_step', 'auto', ...
    'simulink_zero_cross', 'on', ...
    'simscape_local_solver_enabled', false, ...
    'force_rebuild_model', false);
end

function rows = stage_rows(run_result)
rows = struct([]);
cycles = reshape(get_field(run_result, 'cycle_results', struct([])), 1, []);
for cidx = 1:numel(cycles)
    reports = reshape(get_field(cycles(cidx), 'stage_reports', struct([])), 1, []);
    for ridx = 1:numel(reports)
        r = reports(ridx);
        rows = append_struct(rows, struct( ...
            'cycle_index', get_field(cycles(cidx), 'cycle_index', cidx), ...
            'stage_index', get_field(r, 'stage_index', ridx), ...
            'stage_name', char(string(get_field(r, 'stage_name', ''))), ...
            'ok', logical(get_field(r, 'ok', false)), ...
            'stage_walltime_s', get_field(r, 'stage_walltime_s', NaN), ...
            'simulink_walltime_s', get_field(r, 'simulink_walltime_s', NaN), ...
            'actual_active_flush_volume_ratio', get_field(r, 'actual_active_flush_volume_ratio', NaN), ...
            'V_star_vs_SMA', get_field(r, 'V_star_vs_SMA', NaN), ...
            'cold_sink_temp_out_K', get_field(r, 'cold_sink_temp_out', NaN), ...
            'hot_sink_temp_out_K', get_field(r, 'hot_sink_temp_out', NaN), ...
            'Q_stage4_SMA_to_HTF_J', get_field(r, 'Q_stage4_SMA_to_HTF_J', NaN), ...
            'Q_stage4_CHEX_in_to_out_J', get_field(r, 'Q_stage4_CHEX_in_to_out_J', NaN), ...
            'Q_stage4_CHEX_energy_residual_abs_J', get_field(r, 'Q_stage4_CHEX_energy_residual_abs_J', NaN), ...
            'Q_stage4_CHEX_energy_residual_abs_limit_J', get_field(r, 'Q_stage4_CHEX_energy_residual_abs_limit_J', NaN), ...
            'stage4_CHEX_entity_balance_ok', logical(get_field(r, 'stage4_CHEX_entity_balance_ok', false)), ...
            'stage4_cold_chain_residual_ok', logical(get_field(r, 'stage4_cold_chain_residual_ok', false)), ...
            'sma_to_CHEX_transport_ratio_observed', get_field(r, 'sma_to_CHEX_transport_ratio_observed', NaN), ...
            'stage4_cold_chain_primary_bottleneck', char(string(get_field(r, 'stage4_cold_chain_primary_bottleneck', ''))), ...
            'cold_pipe_state_writeback_source', char(string(get_field(r, 'cold_pipe_state_writeback_source', ''))), ...
            'retry_count', normalize_retry(get_field(r, 'actual_flush_pressure_control_trial_count', NaN)), ...
            'compensation_used', logical(get_field(r, 'pressure_control_compensation_used', false)), ...
            'reused_result_used', logical(get_field(r, 'stage_result_reused_from_previous_cycle', false)), ...
            'solver_min_step_warning', contains(lower(char(string(get_field(r, 'solver_warning', '')))), 'min') ));
    end
end
end

function summary = summarize_case(tag, outDir, nCycles, vStar, stageTime_s, walltime_s, rows, runner_error, console_text, validation_summary)
summary = struct();
summary.runner = 'Remote_RunCase_R72';
summary.tag = tag;
summary.out_dir = outDir;
summary.nCycles = nCycles;
summary.V_star = vStar;
summary.stage_time_s = stageTime_s;
summary.total_walltime_s = walltime_s;
summary.runner_error = runner_error;
summary.stage_count = numel(rows);
summary.retry_count = max_finite([rows.retry_count]);
summary.compensation_count = sum([rows.compensation_used]);
summary.reused_count = sum([rows.reused_result_used]);
summary.min_step_warning = contains(lower(console_text), 'minimum step') || ...
    contains(lower(console_text), 'min step') || any([rows.solver_min_step_warning]);
summary.validation_physics_ok = logical(get_field(validation_summary, 'physics_ok', false));
summary.validation_contract_ok = logical(get_field(validation_summary, 'contract_ok', false));
summary.measured_cold_end_energy_policy_ok = logical(get_field(validation_summary, ...
    'measured_cold_end_energy_policy_ok', false));
summary.warning_reasons = get_field(validation_summary, 'warning_reasons', {});
summary.cold_sink_final_K = last_finite([rows.cold_sink_temp_out_K]);
summary.cold_sink_delta_K = 293.0 - summary.cold_sink_final_K;
summary.hot_sink_final_K = last_finite([rows.hot_sink_temp_out_K]);
summary.max_stage_walltime_s = max_finite([rows.stage_walltime_s]);
summary.max_simulink_walltime_s = max_finite([rows.simulink_walltime_s]);
summary.stage4_CHEX_entity_balance_all_ok = all([rows.stage4_CHEX_entity_balance_ok] | ...
    ~strcmp({rows.stage_name}, 'cooldown_exchange'));
summary.stage4_cold_chain_residual_all_ok = all([rows.stage4_cold_chain_residual_ok] | ...
    ~strcmp({rows.stage_name}, 'cooldown_exchange'));
summary.all_ok = isempty(runner_error) && ~isempty(rows) && all([rows.ok]) && ...
    summary.compensation_count == 0 && summary.reused_count == 0 && ~summary.min_step_warning && ...
    summary.measured_cold_end_energy_policy_ok;
end

function write_markdown(pathValue, summary, rows)
fid = fopen(pathValue, 'w', 'n', 'UTF-8');
assert(fid > 0, 'Failed to open %s', pathValue);
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '# %s\n\n', summary.tag);
fprintf(fid, '- V*: %.4g\n', summary.V_star);
fprintf(fid, '- nCycles: %d\n', summary.nCycles);
fprintf(fid, '- total_walltime_s: %.3f\n', summary.total_walltime_s);
fprintf(fid, '- all_ok: %d\n', summary.all_ok);
fprintf(fid, '- measured_cold_end_energy_policy_ok: %d\n', summary.measured_cold_end_energy_policy_ok);
fprintf(fid, '- retry/comp/reused: %.0f / %.0f / %.0f\n', ...
    summary.retry_count, summary.compensation_count, summary.reused_count);
fprintf(fid, '- cold_sink_final_K: %.6f\n', summary.cold_sink_final_K);
fprintf(fid, '- cold_sink_delta_K: %.6f\n\n', summary.cold_sink_delta_K);
if ~isempty(rows)
    fprintf(fid, '| cycle | stage | walltime_s | flush | cold_K | hot_K | CHEX_balance | transport_ratio | bottleneck |\n');
    fprintf(fid, '|---:|---|---:|---:|---:|---:|---:|---:|---|\n');
    for idx = 1:numel(rows)
        r = rows(idx);
        fprintf(fid, '| %d | %s | %.2f | %.3f | %.3f | %.3f | %d | %.3f | %s |\n', ...
            r.cycle_index, r.stage_name, r.stage_walltime_s, ...
            r.actual_active_flush_volume_ratio, r.cold_sink_temp_out_K, ...
            r.hot_sink_temp_out_K, r.stage4_CHEX_entity_balance_ok, ...
            r.sma_to_CHEX_transport_ratio_observed, r.stage4_cold_chain_primary_bottleneck);
    end
end
end

function value = get_field(s, fieldName, defaultValue)
if isstruct(s) && isfield(s, fieldName)
    value = s.(fieldName);
else
    value = defaultValue;
end
end

function rows = append_struct(rows, row)
if isempty(rows)
    rows = row;
else
    rows(end + 1) = row;
end
end

function value = normalize_retry(value)
if ~isfinite(value)
    value = 0;
end
end

function value = max_finite(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = last_finite(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = values(end);
end
end

function ensure_dir(pathValue)
if ~exist(pathValue, 'dir')
    mkdir(pathValue);
end
end

function write_json(pathValue, value)
fid = fopen(pathValue, 'w', 'n', 'UTF-8');
assert(fid > 0, 'Failed to open %s', pathValue);
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', jsonencode(value, PrettyPrint=true));
end

function write_text(pathValue, textValue)
fid = fopen(pathValue, 'w', 'n', 'UTF-8');
assert(fid > 0, 'Failed to open %s', pathValue);
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', char(string(textValue)));
end

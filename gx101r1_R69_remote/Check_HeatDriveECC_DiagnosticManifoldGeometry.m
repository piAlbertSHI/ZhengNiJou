function allowed = Check_HeatDriveECC_DiagnosticManifoldGeometry(options)
% Preserve the nominal geometry unless an explicit cold intervention declares it.
    volume=options.branch.sma_pump_manifold_volume_m3;
    nominal=options.branch.connecting_pipe_flow_area_m2*options.branch.connecting_pipe_length_m;
    allowed=abs(volume-nominal)<1e-15;
    if allowed, return; end
    branch=options.branch;validation=options.validation;
    allowed=isfield(branch,'cold_manifold_inventory_volume_factor') && ...
        isnumeric(branch.cold_manifold_inventory_volume_factor) && ...
        isscalar(branch.cold_manifold_inventory_volume_factor) && ...
        ismember(branch.cold_manifold_inventory_volume_factor,[1 0.1]) && ...
        isfield(validation,'sensitivity_mode') && validation.sensitivity_mode && ...
        isfield(validation,'sensitivity_declared_transition_fields') && ...
        isequal(validation.sensitivity_declared_transition_fields,{'branch.sma_pump_manifold_volume_m3'}) && ...
        branch.independent_conservative_chamber_diagnostic && ...
        ~options.simulation.persist_model_configuration && isempty(options.simulation.resume_checkpoint_path) && ...
        abs(volume-nominal*branch.cold_manifold_inventory_volume_factor)<1e-15;
end

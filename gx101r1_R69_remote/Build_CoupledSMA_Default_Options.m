function options = Build_CoupledSMA_Default_Options(overrides)
% Build default options for the coupled single-stage SMA runner.

    if nargin < 1 || isempty(overrides)
        overrides = struct();
    end

    root_dir = fileparts(mfilename('fullpath'));
    outputs_dir = fullfile(root_dir, 'outputs_coupled_single');

    options = struct();
    options.root_dir = root_dir;
    options.n_cycles = 1;
    options.outputs_dir = outputs_dir;
    options.save_checkpoints = true;
    options.save_plots = false;
    options.store_raw_simout = false;

    options.refrigerant = build_refrigerant_options();
    options.actuator = build_actuator_options();
    options.coupling = build_coupling_options(options.refrigerant.solver_options);
    options.stage_schedule = build_stage_schedule_options();
    options.exchange_options = build_exchange_options(root_dir, outputs_dir);
    options.solver_options = build_coupled_solver_options();
    options.validation_options = build_validation_options();

    options = merge_structs_recursive(options, overrides);
end


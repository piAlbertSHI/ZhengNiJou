function audit = audit_se_double_acting_piston_topology(model_name)
% Verify endpoint-to-endpoint inventory transfer for the SE regenerator.
% Stage 2 transfers Cold chamber -> SE -> HHEX -> Hot chamber. Stage 4
% transfers the same inventory back through SE and CHEX. The two pressure
% source blocks are the hydraulic faces of one double-acting piston and
% must receive the same physical-signal command.

    root = [model_name '/'];
    names = struct( ...
        'cold_chamber', [root 'ColdFluidBuffer'], ...
        'hot_chamber', [root 'HotFluidBuffer'], ...
        'cold_junction', [root 'SE_ColdChamberJunction'], ...
        'hot_junction', [root 'SE_HotChamberJunction'], ...
        'stage2_source', [root 'SE_Stage2_PistonPressureSource'], ...
        'stage4_source', [root 'SE_Stage4_PistonPressureSource'], ...
        'stage2_inlet', [root 'V1_cold_inlet'], ...
        'stage2_return', [root 'V2_hot_return'], ...
        'stage4_inlet', [root 'V4_hot_inlet'], ...
        'stage4_return', [root 'V5_cold_return'], ...
        'command', [root 'PressurePI_SimulinkPS']);
    paths = struct2cell(names);
    blocks_present = all(cellfun(@exist_block, paths));
    route_connections_ok = false;
    source_face_orientation_ok = false;
    command_shared = false;
    obsolete_common_manifold_absent = ...
        ~exist_block([root 'T-Junction (TL)']) && ...
        ~exist_block([root 'T-Junction (TL)1']) && ...
        ~exist_block([root 'T-Junction (TL)2']) && ...
        ~exist_block([root 'T-Junction (TL)3']) && ...
        ~exist_block([root 'Pressure Source (TL)']);
    chambers_not_directly_short_circuited = false;
    if blocks_present
        route_connections_ok = ...
            blocks_directly_connected(names.cold_chamber, ...
                names.cold_junction) && ...
            blocks_directly_connected(names.cold_junction, ...
                names.stage2_source) && ...
            blocks_directly_connected(names.stage2_source, ...
                names.stage2_inlet) && ...
            blocks_directly_connected(names.stage4_return, ...
                names.cold_junction) && ...
            blocks_directly_connected(names.hot_chamber, ...
                names.hot_junction) && ...
            blocks_directly_connected(names.hot_junction, ...
                names.stage4_source) && ...
            blocks_directly_connected(names.stage4_source, ...
                names.stage4_inlet) && ...
            blocks_directly_connected(names.stage2_return, ...
                names.hot_junction);
        % With the retained negative pressure command, each pressure source
        % drives liquid from RConn1 to LConn1.  Pin the chamber to RConn1
        % and the route inlet valve to LConn1 so a visually connected model
        % cannot silently reverse the endpoint inventory transfer.
        source_face_orientation_ok = ...
            conserving_port_connected_to(names.stage2_source, ...
                'RConn', 1, names.cold_junction) && ...
            conserving_port_connected_to(names.stage2_source, ...
                'LConn', 1, names.stage2_inlet) && ...
            conserving_port_connected_to(names.stage4_source, ...
                'RConn', 1, names.hot_junction) && ...
            conserving_port_connected_to(names.stage4_source, ...
                'LConn', 1, names.stage4_inlet);
        command_shared = blocks_directly_connected( ...
            names.command, names.stage2_source) && ...
            blocks_directly_connected(names.command, names.stage4_source);
        chambers_not_directly_short_circuited = ...
            ~blocks_directly_connected(names.cold_chamber, ...
                names.hot_chamber) && ...
            ~blocks_directly_connected(names.cold_chamber, ...
                names.stage2_inlet) && ...
            ~blocks_directly_connected(names.hot_chamber, ...
                names.stage4_inlet);
    end
    audit = struct( ...
        'blocks_present', blocks_present, ...
        'route_connections_ok', route_connections_ok, ...
        'source_face_orientation_ok', source_face_orientation_ok, ...
        'command_shared', command_shared, ...
        'obsolete_common_manifold_absent', ...
            obsolete_common_manifold_absent, ...
        'chambers_not_directly_short_circuited', ...
            chambers_not_directly_short_circuited, ...
        'physical_interpretation', ...
            'one_double_acting_piston_two_hydraulic_source_faces');
    audit.ok = audit.blocks_present && audit.route_connections_ok && ...
        audit.source_face_orientation_ok && ...
        audit.command_shared && audit.obsolete_common_manifold_absent && ...
        audit.chambers_not_directly_short_circuited;
end

function tf = conserving_port_connected_to(block_path, port_kind, ...
        port_index, target_path)
    tf = false;
    block_handle = getSimulinkBlockHandle(block_path);
    target_handle = getSimulinkBlockHandle(target_path);
    if block_handle <= 0 || target_handle <= 0
        return;
    end
    ports = get_param(block_handle, 'PortHandles');
    if ~isfield(ports, port_kind) || numel(ports.(port_kind)) < port_index
        return;
    end
    port_handle = ports.(port_kind)(port_index);
    line_handle = get_param(port_handle, 'Line');
    if isempty(line_handle) || line_handle == -1
        return;
    end
    source_ports = get_param(line_handle, 'SrcPortHandle');
    destination_ports = get_param(line_handle, 'DstPortHandle');
    connected_ports = [source_ports(:); destination_ports(:)];
    for idx = 1:numel(connected_ports)
        if connected_ports(idx) == port_handle || connected_ports(idx) <= 0
            continue;
        end
        if strcmp(get_param(connected_ports(idx), 'Parent'), target_path)
            tf = true;
            return;
        end
    end
end

function tf = blocks_directly_connected(block_a, block_b)
    handle_a = getSimulinkBlockHandle(block_a);
    handle_b = getSimulinkBlockHandle(block_b);
    tf = false;
    if handle_a <= 0 || handle_b <= 0
        return;
    end
    connectivity = get_param(handle_a, 'PortConnectivity');
    for idx = 1:numel(connectivity)
        neighbors = [connectivity(idx).SrcBlock(:); ...
            connectivity(idx).DstBlock(:)];
        if any(neighbors == handle_b)
            tf = true;
            return;
        end
    end
end

function block_path = locate_block_by_name(model_name, block_name)
    matches = find_system(model_name, 'LookUnderMasks', 'all', ...
        'FollowLinks', 'on', 'Type', 'Block', 'Name', block_name);
    if numel(matches) ~= 1
        error('Build:ECC:EndpointChannelCount', ...
            'Expected one %s block, found %d.', block_name, numel(matches));
    end
    block_path = matches{1};
end

function contract = component_pipe_UA_contract(model_name, options, ...
        component_name, prefix, flow_area_m2, hydraulic_diameter_m, ...
        length_m, Nu, fluid_k_W_per_mK, expected_UA_W_per_K)
    wetted_perimeter_m = 4.0 * flow_area_m2 / hydraulic_diameter_m;
    calculated_UA_W_per_K = Nu * fluid_k_W_per_mK / ...
        hydraulic_diameter_m * wetted_perimeter_m * length_m;
    expected_masks = struct( ...
        'length', sprintf('%s_article_pipe_segment_l', prefix), ...
        'area', sprintf('%s_article_pipe_fa', prefix), ...
        'Dh', sprintf('%s_article_pipe_Dh', prefix), ...
        'length_add', '0', ...
        'Nu_lam', sprintf('%s_article_Nu', prefix));
    masks_ok = true;
    routes = {'HoldPipe', 'CooldownPipe'};
    if strcmp(component_name, 'SE')
        routes = {'HoldPipe'};
    end
    for idx = 1:options.node_count
        for route = routes
            block_path = sprintf('%s/%s/%s_%03d', model_name, ...
                component_name, route{1}, idx);
            names = fieldnames(expected_masks);
            for name_idx = 1:numel(names)
                parameter = names{name_idx};
                masks_ok = masks_ok && strcmp(strtrim(get_param(block_path, parameter)), ...
                    expected_masks.(parameter));
            end
        end
    end
    relative_error = abs(calculated_UA_W_per_K - expected_UA_W_per_K) / ...
        max(abs(expected_UA_W_per_K), eps);
    contract = struct( ...
        'expected_UA_W_per_K', expected_UA_W_per_K, ...
        'calculated_UA_W_per_K', calculated_UA_W_per_K, ...
        'relative_error', relative_error, ...
        'flow_area_m2', flow_area_m2, ...
        'hydraulic_diameter_m', hydraulic_diameter_m, ...
        'length_m', length_m, ...
        'Nu', Nu, ...
        'fluid_k_W_per_mK', fluid_k_W_per_mK, ...
        'masks_ok', masks_ok, ...
        'ok', masks_ok && relative_error <= 1.0e-10);
end

function audit = configure_dual_fluid_topology(model_name)
    % Qian uses water for SMA/SHEX and glycol-water for SE/HHEX/CHEX.
    % The HHEX already contains separate HotPipe and SMAHotPipe channels;
    % split only their formerly shared top-level hot buffer node.
    hot_buffer = [model_name '/HotFluidBuffer'];
    sma_buffer = [model_name '/SMAHotFluidBuffer'];
    if ~exist_block(sma_buffer)
        add_block(hot_buffer, sma_buffer, ...
            'MakeNameUnique', 'off', ...
            'Position', [1580 875 1630 925]);
    end

    settings_blocks = thermal_liquid_settings_blocks(model_name);
    if isempty(settings_blocks)
        error('Build:ECC:MissingThermalLiquidSettings', ...
            'The canonical model has no Thermal Liquid Settings block.');
    end
    sma_settings = [model_name '/SMA_ThermalLiquidSettings'];
    if ~exist_block(sma_settings)
        add_block(settings_blocks{1}, sma_settings, ...
            'MakeNameUnique', 'off', ...
            'Position', [1460 875 1520 935]);
    end

    hhex = find_hhex_parent(model_name);
    sma_v2 = [model_name '/SMA_V2_HHEX_to_pump'];
    if ~blocks_share_conserving_network(hhex, sma_buffer)
        delete_conserving_branch(hhex, 'LConn', 2);
    end
    if ~blocks_share_conserving_network(sma_v2, sma_buffer)
        delete_conserving_branch(sma_v2, 'LConn', 1);
    end

    connect_conserving_ports(model_name, sma_settings, 'RConn', 1, ...
        sma_buffer, 'LConn', 1);
    connect_conserving_ports(model_name, hhex, 'LConn', 2, ...
        sma_buffer, 'LConn', 1);
    connect_conserving_ports(model_name, sma_v2, 'LConn', 1, ...
        sma_buffer, 'LConn', 1);
    add_sma_hot_buffer_temperature_probe(model_name, sma_buffer);

    audit = struct( ...
        'schema_version', 'qian2019_dual_fluid_topology_audit_v1', ...
        'sma_settings_path', sma_settings, ...
        'se_settings_path', settings_blocks{1}, ...
        'sma_hot_buffer_path', sma_buffer, ...
        'hhex_path', hhex, ...
        'ok', false);
end

function audit = audit_dual_fluid_topology(model_name, audit)
    settings_blocks = thermal_liquid_settings_blocks(model_name);
    sma_settings = [model_name '/SMA_ThermalLiquidSettings'];
    se_settings = setdiff(settings_blocks, {sma_settings}, 'stable');
    if numel(se_settings) ~= 1
        audit.ok = false;
        audit.settings_count = numel(settings_blocks);
        audit.failure_reason = sprintf( ...
            'Expected one SMA and one SE settings block; found %d total.', ...
            numel(settings_blocks));
        return;
    end

    sma_buffer = [model_name '/SMAHotFluidBuffer'];
    se_buffer = [model_name '/HotFluidBuffer'];
    sma_v2 = [model_name '/SMA_V2_HHEX_to_pump'];
    se_v4 = [model_name '/V4_hot_inlet'];
    hhex = find_hhex_parent(model_name);
    audit.settings_count = numel(settings_blocks);
    audit.se_settings_path = se_settings{1};
    audit.sma_domain_connected = ...
        blocks_share_conserving_network(sma_settings, sma_buffer) && ...
        blocks_share_conserving_network(sma_settings, sma_v2) && ...
        blocks_share_conserving_network(sma_settings, hhex);
    audit.se_domain_connected = ...
        blocks_share_conserving_network(se_settings{1}, se_buffer) && ...
        blocks_share_conserving_network(se_settings{1}, se_v4);
    audit.domains_hydraulically_isolated = ...
        ~blocks_share_conserving_network(sma_settings, se_settings{1}) && ...
        ~blocks_share_conserving_network(sma_buffer, se_buffer) && ...
        ~blocks_share_conserving_network(sma_v2, se_v4);
    audit.buffer_probe_present = ...
        exist_block([model_name '/SMAHotFluidBufferTempSensor']) && ...
        exist_block([model_name '/ToWorkspace_sma_hot_buffer_temp_out']);
    audit.ok = audit.settings_count == 2 && ...
        audit.sma_domain_connected && audit.se_domain_connected && ...
        audit.domains_hydraulically_isolated && audit.buffer_probe_present;
    if audit.ok
        audit.failure_reason = '';
    else
        audit.failure_reason = ...
            'Two-domain connectivity or SMA hot-buffer probe audit failed.';
    end
end

function add_sma_hot_buffer_temperature_probe(model_name, sma_buffer)
    source_sensor = [model_name '/HotFluidBufferTempSensor'];

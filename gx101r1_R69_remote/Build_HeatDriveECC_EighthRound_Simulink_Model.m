        audit.pressure.pressure_source_power_ok && ...
        audit.pressure.quasisteady_pipes_ok && ...
        audit.pressure.valve_commands_interpolated_ok && ...
        audit.pressure.independent_controller_limits.ok && ...
        audit.SMA_pump_manifolds.ok && ...
        minimum_estimated_pressure_MPa > ...
        options.validation.minimum_valid_liquid_pressure_MPa;
    audit.ok = audit.SMA.ok && audit.SE.ok && ...
        audit.SE_shared_regenerator.ok && ...
        audit.SE_double_acting_piston.ok && audit.HHEX.ok && ...
        audit.pressure.ok && audit.thermal_gates.ok && ...
        audit.solid_axial_conduction.ok;
    audit.source = options.branch.article_pipe_geometry_source;
end

function audit = audit_solid_axial_conduction(model_name, options)
    audit = struct();
    audit.enabled = logical(options.solid.axial_conduction_enabled);
    components = {'SMA','sma',options.geometry.S_a_m2, ...
            options.geometry.L_a_m,options.solid.k_sma_W_per_mK; ...
        'SE','se',options.geometry.S_r_m2,options.geometry.L_r_m, ...
            options.solid.k_se_W_per_mK};
    all_ok = audit.enabled;
    for component_idx = 1:size(components, 1)
        component = components{component_idx, 1};
        prefix = components{component_idx, 2};
        area_m2 = components{component_idx, 3};
        length_m = components{component_idx, 4};
        conductivity_W_per_mK = components{component_idx, 5};
        inner = sprintf('%s/%s/Subsystem2', model_name, component);
        blocks = find_system(inner, 'RegExp', 'on', 'SearchDepth', 1, ...
            'Type', 'Block', ...
            'Name', '^AxialConduction_[0-9]{3}_[0-9]{3}$');
        masks_ok = numel(blocks) == options.node_count - 1;
        connections_ok = masks_ok;
        for idx = 1:(options.node_count - 1)
            block_path = sprintf('%s/AxialConduction_%03d_%03d', ...
                inner, idx, idx + 1);
            node_a = sprintf('%s/NodeMass_%02d', inner, idx);
            node_b = sprintf('%s/NodeMass_%02d', inner, idx + 1);
            masks_ok = masks_ok && exist_block(block_path) && ...
                strcmp(get_param(block_path, 'thermal_type'), ...
                    'foundation.enum.ConstantVariableTabulated.Constant') && ...
                strcmp(get_param(block_path, 'wall_geometry'), ...
                    'foundation.enum.ConductionWallGeometry.Planar') && ...
                strcmp(get_param(block_path, 'area'), ...
                    sprintf('%s_solid_axial_area_m2', prefix)) && ...
                strcmp(get_param(block_path, 'thickness'), ...

function [model_name, options] = Build_HeatDriveECC_EighthRound_Simulink_Model(overrides)
% Build the Simulink mainline model for the 51-node heat-driven ECC system.
%
% The visible Simulink topology is intentionally kept in this same model:
%   Stage 1: PSC/SHEX -> SMA actuator
%   Stage 2: SE refrigerant -> HHEX/THE
%   Stage 3: SMA actuator -> HHEX/THE
%   Stage 4: CHEX/RHE cold load -> SE refrigerant
% The interpreted 51-node core remains the numerical kernel, but the .slx
% no longer hides all flow routing inside a single block.

    if nargin < 1
        overrides = struct();
    end
    options = Build_HeatDriveECC_EighthRound_Defaults(overrides);
    model_name = options.model_name;
    model_path = options.model_path;

    assignin('base', 'EIGHTH_ROUND_OPTIONS', options);
    load_system('simulink');
    interpreted_block = find_interpreted_matlab_block();

    if bdIsLoaded(model_name)
        set_param(model_name, 'Dirty', 'off');
        close_system(model_name, 0);
    end
    if exist(model_path, 'file')
        delete(model_path);
    end

    new_system(model_name);
    load_system(model_name);
    set_param(model_name, ...
        'Solver', options.simulation.solver, ...
        'FixedStep', num2str(options.simulation.fixed_step_s, '%.15g'), ...
        'StopTime', num2str(options.simulation.stop_time_s, '%.15g'), ...
        'SaveTime', 'on', ...
        'TimeSaveName', 'tout', ...
        'ReturnWorkspaceOutputs', 'on');

    add_four_stage_route_topology(model_name);

    add_block('simulink/Sources/Clock', [model_name '/Simulink_Time_s'], ...
        'Position', [70 560 100 590]);
    add_block(interpreted_block, [model_name '/MechanicalCouplingSolver_51Node'], ...
        'Position', [170 535 380 615]);
    set_param([model_name '/MechanicalCouplingSolver_51Node'], ...
        'MATLABFcn', 'HeatDriveECC_EighthRound_SimulinkStep', ...
        'OutputDimensions', sprintf('%d', options.output.output_width), ...
        'OutputSignalType', 'real', ...
        'Output1D', 'on', ...
        'SampleTime', num2str(options.simulation.fixed_step_s, '%.15g'));
    add_block('simulink/Sinks/To Workspace', [model_name '/EighthRound_Yout'], ...
        'Position', [470 555 575 595]);
    set_param([model_name '/EighthRound_Yout'], ...
        'VariableName', options.simulation.output_variable, ...
        'SaveFormat', 'Array', ...
        'MaxDataPoints', 'inf', ...
        'SampleTime', '-1');

    add_line(model_name, 'Simulink_Time_s/1', 'MechanicalCouplingSolver_51Node/1');
    add_line(model_name, 'MechanicalCouplingSolver_51Node/1', 'EighthRound_Yout/1');
    save_system(model_name, model_path);
end

function add_four_stage_route_topology(model_name)
    add_model_note(model_name);

    add_block('simulink/Ports & Subsystems/Subsystem', ...
        [model_name '/Article_FourStage_Route_Controller'], ...
        'Position', [45 45 255 130], ...
        'ForegroundColor', 'black', ...
        'BackgroundColor', 'lightBlue');
    route_controller = [model_name '/Article_FourStage_Route_Controller'];
    set_param(route_controller, 'MaskDisplay', ...
        sprintf(['disp(''Article four-stage route controller'');\n', ...
        'disp(''S1 SHEX->SMA, S2 SE->HHEX, S3 SMA->HHEX, S4 RHE->SE'');']));

    add_route_gate(model_name, 'Gate_S1_SHEX_to_SMA', [45 185 85 215], 'Stage 1 enable');
    add_route_gate(model_name, 'Gate_S2_SE_to_HHEX', [45 285 85 315], 'Stage 2 enable');
    add_route_gate(model_name, 'Gate_S3_SMA_to_HHEX', [45 385 85 415], 'Stage 3 enable');
    add_route_gate(model_name, 'Gate_S4_RHE_to_SE', [45 485 85 515], 'Stage 4 enable');

    add_component(model_name, 'PSC_WasteHeat_and_SHEX', [135 165 275 235], ...
        {'route_in'}, {'hot_htf_to_sma'}, 'orange', ...
        'PSC waste heat / SHEX hot source');
    add_component(model_name, 'SMA_Load_Pump_and_Valve', [320 165 475 235], ...
        {'from_shex'}, {'to_sma_load'}, 'yellow', ...
        'SMA loop pump + S1 valve');
    add_component(model_name, 'SMA_Actuator_51Node', [525 185 705 405], ...
        {'load_from_shex','reject_to_hhex'}, ...
        {'loaded_return','cooled_return'}, 'green', ...
        '51-node SMA actuator thermal/mechanical object');
    add_component(model_name, 'SMA_Return_to_SHEX_Buffer', [760 165 930 235], ...
        {'from_sma'}, {'return_to_shex'}, 'white', ...
        'SMA hot-source return buffer');

    add_component(model_name, 'SE_Refrigerant_51Node', [525 285 705 515], ...
        {'reject_to_hhex','absorb_from_rhe'}, ...
        {'hot_return','cold_return'}, 'cyan', ...
        '51-node SE refrigerant thermal/mechanical object');
    add_component(model_name, 'SE_Hot_Pump_and_Valve', [320 265 475 335], ...
        {'from_se_hot'}, {'to_hhex_se'}, 'yellow', ...
        'SE hot-side pump + S2 valve');
    add_component(model_name, 'HHEX_THE_SE_Side', [760 265 930 335], ...
        {'from_se'}, {'return_to_se'}, 'red', ...
        'THE/HHEX branch for SE heat rejection');
    add_component(model_name, 'SMA_Hot_Pump_and_Valve', [320 365 475 435], ...
        {'from_sma_hot'}, {'to_hhex_sma'}, 'yellow', ...
        'SMA hot-side pump + S3 valve');
    add_component(model_name, 'HHEX_THE_SMA_Side', [760 365 930 435], ...
        {'from_sma'}, {'return_to_sma'}, 'red', ...
        'THE/HHEX branch for SMA cooling');
    add_component(model_name, 'CHEX_RHE_ColdLoad', [135 465 275 535], ...
        {'route_in'}, {'cold_htf_to_se'}, 'lightBlue', ...
        'CHEX/RHE cold-load branch');
    add_component(model_name, 'SE_Cold_Pump_and_Valve', [320 465 475 535], ...
        {'from_rhe'}, {'to_se_cold'}, 'yellow', ...
        'SE cold-side pump + S4 valve');
    add_component(model_name, 'SE_Return_to_RHE_Buffer', [760 465 930 535], ...
        {'from_se'}, {'return_to_rhe'}, 'white', ...
        'SE cold-load return buffer');

    add_route_end(model_name, 'End_S1_SHEX_Return', [985 190 1015 220]);
    add_route_end(model_name, 'End_S2_HHEX_SE_Return', [985 290 1015 320]);
    add_route_end(model_name, 'End_S3_HHEX_SMA_Return', [985 390 1015 420]);
    add_route_end(model_name, 'End_S4_RHE_Return', [985 490 1015 520]);

    add_named_line(model_name, 'Gate_S1_SHEX_to_SMA/1', ...
        'PSC_WasteHeat_and_SHEX/1', 'S1 route enable', 'orange');
    add_named_line(model_name, 'PSC_WasteHeat_and_SHEX/1', ...
        'SMA_Load_Pump_and_Valve/1', 'S1 hot HTF from SHEX', 'orange');
    add_named_line(model_name, 'SMA_Load_Pump_and_Valve/1', ...
        'SMA_Actuator_51Node/1', 'S1 SHEX -> SMA actuator', 'orange');
    add_named_line(model_name, 'SMA_Actuator_51Node/1', ...
        'SMA_Return_to_SHEX_Buffer/1', 'S1 SMA return', 'orange');
    add_named_line(model_name, 'SMA_Return_to_SHEX_Buffer/1', ...
        'End_S1_SHEX_Return/1', 'S1 return to SHEX', 'orange');

    add_named_line(model_name, 'Gate_S2_SE_to_HHEX/1', ...
        'SE_Refrigerant_51Node/1', 'S2 loaded SE outlet', 'red');
    add_named_line(model_name, 'SE_Refrigerant_51Node/1', ...
        'SE_Hot_Pump_and_Valve/1', 'S2 SE -> hot pump', 'red');
    add_named_line(model_name, 'SE_Hot_Pump_and_Valve/1', ...
        'HHEX_THE_SE_Side/1', 'S2 SE -> THE/HHEX', 'red');
    add_named_line(model_name, 'HHEX_THE_SE_Side/1', ...
        'End_S2_HHEX_SE_Return/1', 'S2 SE hot return isolated', 'red');

    add_named_line(model_name, 'Gate_S3_SMA_to_HHEX/1', ...
        'SMA_Actuator_51Node/2', 'S3 SMA outlet after unloading', 'red');
    add_named_line(model_name, 'SMA_Actuator_51Node/2', ...
        'SMA_Hot_Pump_and_Valve/1', 'S3 SMA -> hot pump', 'red');
    add_named_line(model_name, 'SMA_Hot_Pump_and_Valve/1', ...
        'HHEX_THE_SMA_Side/1', 'S3 SMA -> THE/HHEX', 'red');
    add_named_line(model_name, 'HHEX_THE_SMA_Side/1', ...
        'End_S3_HHEX_SMA_Return/1', 'S3 SMA hot return isolated', 'red');

    add_named_line(model_name, 'Gate_S4_RHE_to_SE/1', ...
        'CHEX_RHE_ColdLoad/1', 'S4 route enable', 'blue');
    add_named_line(model_name, 'CHEX_RHE_ColdLoad/1', ...
        'SE_Cold_Pump_and_Valve/1', 'S4 cold HTF from CHEX/RHE', 'blue');
    add_named_line(model_name, 'SE_Cold_Pump_and_Valve/1', ...
        'SE_Refrigerant_51Node/2', 'S4 RHE -> SE refrigerant', 'blue');
    add_named_line(model_name, 'SE_Refrigerant_51Node/2', ...
        'SE_Return_to_RHE_Buffer/1', 'S4 SE return to cold branch', 'blue');
    add_named_line(model_name, 'SE_Return_to_RHE_Buffer/1', ...
        'End_S4_RHE_Return/1', 'S4 return to CHEX/RHE', 'blue');

    add_probe_panel(model_name);
end

function add_model_note(model_name)
    note = sprintf(['Visible topology is the required four-stage ECC flow route.\n', ...
        'Numerical 51-node state propagation is still performed by MechanicalCouplingSolver_51Node.\n', ...
        'Do not compare Qh/Qr until the visible route is promoted from signal topology to physical branch blocks.']);
    annotation = Simulink.Annotation(model_name, note);
    annotation.Position = [45 5 780 35];
end

function add_route_gate(model_name, name, pos, label)
    add_block('simulink/Sources/Constant', [model_name '/' name], ...
        'Position', pos, ...
        'Value', '1', ...
        'BackgroundColor', 'lightBlue');
    set_param([model_name '/' name], 'Name', name);
    annotation = Simulink.Annotation(model_name, label);
    annotation.Position = [pos(1) pos(2)-20 pos(1)+120 pos(2)-2];
end

function add_component(model_name, name, pos, in_names, out_names, color, label)
    block_path = [model_name '/' name];
    add_block('simulink/Ports & Subsystems/Subsystem', block_path, ...
        'Position', pos, ...
        'BackgroundColor', color);
    set_param(block_path, 'MaskDisplay', sprintf('disp(''%s'');', label));

    ports = max(numel(in_names), numel(out_names));
    configure_passthrough_ports(block_path, in_names, out_names, ports);
end

function configure_passthrough_ports(block_path, in_names, out_names, ports)
    if ports < 1
        return;
    end
    try
        delete_line(block_path, 'In1/1', 'Out1/1');
    catch
    end
    if ports >= 1
        set_param([block_path '/In1'], 'Name', in_names{1}, ...
            'Position', [35 40 65 54]);
        set_param([block_path '/Out1'], 'Name', out_names{1}, ...
            'Position', [150 40 180 54]);
    end
    for idx = 2:ports
        y = 40 + 45 * (idx - 1);
        add_block('simulink/Sources/In1', sprintf('%s/%s', block_path, in_names{idx}), ...
            'Position', [35 y 65 y+14]);
        add_block('simulink/Sinks/Out1', sprintf('%s/%s', block_path, out_names{idx}), ...
            'Position', [150 y 180 y+14]);
    end
    for idx = 1:ports
        add_line(block_path, sprintf('%s/1', in_names{idx}), ...
            sprintf('%s/1', out_names{idx}), 'autorouting', 'on');
    end
end

function add_route_end(model_name, name, pos)
    add_block('simulink/Sinks/Terminator', [model_name '/' name], ...
        'Position', pos);
end

function add_named_line(model_name, src, dst, label, color)
    line_handle = add_line(model_name, src, dst, 'autorouting', 'on');
    set_param(line_handle, 'Name', label);
    try
        set_param(line_handle, 'ForegroundColor', color);
    catch
    end
end


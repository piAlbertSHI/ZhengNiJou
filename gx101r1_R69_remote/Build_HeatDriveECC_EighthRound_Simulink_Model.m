        'SE_natural_relative_error', natural_relative_error);
    audit.thermal_gates.ok = gate_masks_ok && ...
        gate_count == 3 * options.node_count && ...
        options.branch.thermal_gate_min_conductivity_W_per_mK < ...
            options.branch.se_pipe_thermal_gate_inactive_G_W_per_K && ...
        natural_relative_error <= 1.0e-10;
    audit.pressure.ok = p0_block_count > 0 && p0_masks_ok && ...

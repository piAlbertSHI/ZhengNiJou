function options = Configure_HeatDriveECC_PressureCommandDomain(model, options)
% Opt-in diagnostic safety closure; tighten commands, never expand fluid tables.
    if isfield(options.branch,'pressure_command_domain_closure_enabled')
        validateattributes(options.branch.pressure_command_domain_closure_enabled, ...
            {'logical'},{'scalar'});
    end
    if ~isfield(options.branch,'pressure_command_domain_closure_enabled') || ...
            ~options.branch.pressure_command_domain_closure_enabled
        assert(~isfield(options.validation,'pressure_command_domain_contract'), ...
            'A stale domain closure contract cannot be reused with closure disabled.');
        return;
    end
    assert(islogical(options.branch.pressure_command_domain_closure_enabled) && ...
        isscalar(options.branch.pressure_command_domain_closure_enabled) && ...
        isfield(options.branch,'pressure_command_domain_margin_MPa'), ...
        'Require an explicit logical domain closure and declared pressure headroom.');
    margin = options.branch.pressure_command_domain_margin_MPa;
    validateattributes(margin,{'numeric'},{'scalar','finite','positive','<=',0.1});
    domain = options.validation.dual_fluid_domain_audit;
    assert(domain.ok, 'Pressure closure requires independently identified fluid domains.');
    settings = {domain.sma_settings_path, domain.se_settings_path};
    rows = cell(2,1); lower = zeros(1,2); upper = zeros(1,2);
    for k=1:2
        block=settings{k};
        minimum=slResolve(get_param(block,'p_min_1D'),block);
        maximum=slResolve(get_param(block,'p_max_1D'),block);
        lower(k)=value(simscape.Value(minimum,get_param(block,'p_min_1D_unit')),'MPa');
        upper(k)=value(simscape.Value(maximum,get_param(block,'p_max_1D_unit')),'MPa');
        rows{k}=struct('settings_path',block,'minimum_MPa',lower(k),'maximum_MPa',upper(k));
    end
    floor=max([lower,options.validation.minimum_valid_liquid_pressure_MPa]);
    ceiling=min(upper);
    datum=options.branch.network_absolute_pressure_MPa;
    before=struct('fallback_min_MPa',options.branch.pressure_pi_min_MPa, ...
        'sma_min_MPa',options.branch.sma_pressure_pi_min_MPa, ...
        'se_min_MPa',options.branch.se_pressure_pi_min_MPa, ...
        'maximum_MPa',options.branch.pressure_pi_max_MPa);
    common=HeatDriveECC_PressureCommandInterval(datum,floor,ceiling,margin, ...
        [before.fallback_min_MPa,before.maximum_MPa]);
    sma=HeatDriveECC_PressureCommandInterval(datum,floor,ceiling,margin, ...
        [before.sma_min_MPa,before.maximum_MPa]);
    se=HeatDriveECC_PressureCommandInterval(datum,floor,ceiling,margin, ...
        [before.se_min_MPa,before.maximum_MPa]);
    options.branch.pressure_pi_min_MPa=common(1);
    options.branch.sma_pressure_pi_min_MPa=sma(1);
    options.branch.se_pressure_pi_min_MPa=se(1);
    options.branch.pressure_pi_max_MPa=min([common(2),sma(2),se(2)]);
    options.branch.sma_pressure_integrator_min_MPa=min(sma(1)-[ ...
        options.branch.sma_stage1_pressure_bias_MPa,options.branch.sma_stage3_pressure_bias_MPa]);
    options.branch.se_stage2_pressure_integrator_min_MPa=se(1)-options.branch.se_stage2_pressure_bias_MPa;
    options.branch.se_stage4_pressure_integrator_min_MPa=se(1)-options.branch.se_stage4_pressure_bias_MPa;
    options.branch.se_pressure_integrator_min_MPa=min([ ...
        options.branch.se_stage2_pressure_integrator_min_MPa, ...
        options.branch.se_stage4_pressure_integrator_min_MPa]);
    options.validation.pressure_command_domain_contract=struct( ...
        'schema','heatdrive_ecc_pressure_command_domain_v1','fluid_domains',{rows}, ...
        'datum_MPa',datum,'minimum_absolute_MPa',floor,'maximum_absolute_MPa',ceiling, ...
        'declared_margin_MPa',margin,'requested',before, ...
        'fallback_interval_MPa',common,'sma_interval_MPa',sma,'se_interval_MPa',se, ...
        'physical_tables_modified',false,'controller_gains_modified',false, ...
        'integrator_states_modified',false,'simulation_executed',false, ...
        'runtime_all_port_pressure_verified',false,'production_recovery_allowed',false);
    assert(bdIsLoaded(model), 'The inspected model is not loaded.');
end

function summary = Summarize_HeatDriveECC_EighthRound_Output(physical, options)
% Summarize only the physical Simscape and coupled constitutive logs.

    required_authority = 'physical_simscape_to_workspace_logs';
    if ~isstruct(physical) || ~isfield(physical, 'authority') || ...
            ~strcmp(physical.authority, required_authority)
        error('Summarize:EighthRound:NonPhysicalAuthority', ...
            'Summary input must be the physical Simscape log structure.');
    end

    t = physical.time_s(:);
    cycle = physical.cycle_index(:);
    stage = physical.stage_id(:);
    ncycles = options.cycle_count;
    sma_mean = mean(physical.SMA_T_21_K, 2);
    se_mean = mean(physical.SE_T_21_K, 2);
    xA_mean = mean(physical.xM_SMA_21, 2);
    xR_mean = mean(physical.xM_SE_21, 2);
    sigmaA_mean = mean(physical.sigma_SMA_21_Pa, 2);
    sigmaR_mean = mean(physical.sigma_SE_21_Pa, 2);

    summary = struct();
    summary.authority = physical.authority;
    summary.legacy_surrogate_used_for_results = false;
    summary.sim_call_count = physical.sim_call_count;
    summary.walltime_s = physical.walltime_s;
    summary.samples = numel(t);
    summary.stage_sample_min = min_stage_samples(stage, cycle, ncycles);
    summary.probe_count = numel(physical.probe_names);
    summary.all_required_finite = required_fields_finite(physical);
    summary.max_SMA_node_spread_K = max(row_range(physical.SMA_T_21_K));
    summary.max_SE_node_spread_K = max(row_range(physical.SE_T_21_K));
    summary.min_temperature_K = min([physical.SMA_T_21_K(:); ...
        physical.SE_T_21_K(:); physical.SHEX_T_K(:); ...
        physical.HHEX_T_K(:); physical.CHEX_T_K(:)]);
    summary.max_temperature_K = max([physical.SMA_T_21_K(:); ...
        physical.SE_T_21_K(:); physical.SHEX_T_K(:); ...
        physical.HHEX_T_K(:); physical.CHEX_T_K(:)]);
    if isfield(physical, 'probes') && ~isempty(physical.probes)
        probe_values = struct2cell(physical.probes);
        probe_values = probe_values(cellfun(@isnumeric, probe_values));
        if ~isempty(probe_values)
            summary.min_probe_temperature_K = min(cellfun(@(v) min(v(:)), probe_values));
            summary.max_probe_temperature_K = max(cellfun(@(v) max(v(:)), probe_values));
        else
            summary.min_probe_temperature_K = NaN;
            summary.max_probe_temperature_K = NaN;
        end
    else
        summary.min_probe_temperature_K = NaN;
        summary.max_probe_temperature_K = NaN;
    end
    summary.max_abs_sigma_SMA_Pa = max(abs(physical.sigma_SMA_21_Pa(:)));
    summary.max_abs_sigma_SE_Pa = max(abs(physical.sigma_SE_21_Pa(:)));
    sigma_sma_mean_Pa = mean(physical.sigma_SMA_21_Pa, 2);
    sigma_se_mean_Pa = mean(physical.sigma_SE_21_Pa, 2);
    epsilon_sma_mean = mean(physical.epsilon_SMA_21, 2);
    epsilon_se_mean = mean(physical.epsilon_SE_21, 2);
    force_residual_N = sigma_sma_mean_Pa .* options.geometry.S_a_m2 - ...
        sigma_se_mean_Pa .* options.geometry.S_r_m2;
    displacement_residual_m = options.geometry.L_a_m .* epsilon_sma_mean - ...
        options.geometry.L_r_m .* epsilon_se_mean;
    summary.max_eq6_scaled = max(abs(force_residual_N) ./ ...
        max(abs(sigma_se_mean_Pa .* options.geometry.S_r_m2), 1.0e-9));
    summary.max_eq7_scaled = max(abs(displacement_residual_m) ./ ...
        max(abs(options.geometry.L_r_m .* epsilon_se_mean), 1.0e-9));
    summary.max_force_residual_N = max(abs(force_residual_N));
    summary.max_displacement_residual_m = max(abs(displacement_residual_m));
    summary.max_abs_flow_kgps = max(abs([physical.mdot_SMA_kgps; ...
        physical.mdot_SE_stage2_in_kgps; physical.mdot_SE_stage2_out_kgps; ...
        physical.mdot_SE_stage4_in_kgps; physical.mdot_SE_stage4_out_kgps]));
    summary.max_inactive_thermal_path_heat_W = ...
        max_inactive_thermal_path_heat(physical, options);
    summary.max_cycle_boundary_SMA_state_jump = ...
        max_boundary_jump(t, physical.xM_SMA_21, options.schedule.tau_cycle_s, ncycles);
    summary.max_cycle_boundary_SE_state_jump = ...
        max_boundary_jump(t, physical.xM_SE_21, options.schedule.tau_cycle_s, ncycles);
    summary.max_cycle_boundary_SMA_temperature_jump_K = ...
        max_boundary_jump(t, physical.SMA_T_21_K, options.schedule.tau_cycle_s, ncycles);
    summary.max_cycle_boundary_SE_temperature_jump_K = ...
        max_boundary_jump(t, physical.SE_T_21_K, options.schedule.tau_cycle_s, ncycles);

    summary.cycle = repmat(empty_cycle(), ncycles, 1);
    for c = 1:ncycles
        idx = cycle == c;
        idx1 = idx & stage == 1;
        idx2 = idx & stage == 2;
        idx3 = idx & stage == 3;
        idx4 = idx & stage == 4;
        hot_half_elapsed_s = physical.stage_elapsed_s;
        hot_half_elapsed_s(idx2) = options.schedule.stage_durations_s(1) + ...
            physical.stage_elapsed_s(idx2);
        cold_half_elapsed_s = physical.stage_elapsed_s;
        cold_half_elapsed_s(idx4) = options.schedule.stage_durations_s(3) + ...
            physical.stage_elapsed_s(idx4);
        idx_hot_half = idx1 | idx2;
        idx_cold_half = idx3 | idx4;
        transition_guard_s = get_branch_scalar(options, ...
            'stage_command_ramp_s', 0.0);
        idx2_core = idx2 & physical.stage_elapsed_s >= transition_guard_s;
        idx1_core = idx1 & physical.stage_elapsed_s >= transition_guard_s;
        idx3_core = idx3 & physical.stage_elapsed_s >= transition_guard_s;
        idx4_core = idx4 & physical.stage_elapsed_s >= transition_guard_s;
        item = empty_cycle();
        item.cycle_index = c;
        item.SMA_start_K = first_value(sma_mean, idx);
        item.SMA_end_K = last_value(sma_mean, idx);
        item.SMA_min_K = min(sma_mean(idx));
        item.SMA_max_K = max(sma_mean(idx));
        item.SE_start_K = first_value(se_mean, idx);
        item.SE_end_K = last_value(se_mean, idx);
        item.SE_min_K = min(se_mean(idx));
        item.SE_max_K = max(se_mean(idx));
        item.SHEX_start_K = first_value(physical.SHEX_T_K, idx);
        item.SHEX_end_K = last_value(physical.SHEX_T_K, idx);
        item.HHEX_start_K = first_value(physical.HHEX_T_K, idx);
        item.HHEX_end_K = last_value(physical.HHEX_T_K, idx);
        item.CHEX_start_K = first_value(physical.CHEX_T_K, idx);
        item.CHEX_end_K = last_value(physical.CHEX_T_K, idx);
        item.delta_SHEX_K = item.SHEX_end_K - item.SHEX_start_K;
        item.delta_HHEX_K = item.HHEX_end_K - item.HHEX_start_K;
        item.delta_CHEX_K = item.CHEX_end_K - item.CHEX_start_K;
        item.SHEX_storage_J = options.system.shex_sink_C_J_per_K * item.delta_SHEX_K;
        item.HHEX_storage_J = options.system.hot_sink_C_J_per_K * item.delta_HHEX_K;
        item.CHEX_storage_J = options.system.cold_sink_C_J_per_K * item.delta_CHEX_K;
        item.xM_SMA_min = min(xA_mean(idx));
        item.xM_SMA_max = max(xA_mean(idx));
        item.xM_SE_min = min(xR_mean(idx));
        item.xM_SE_max = max(xR_mean(idx));
        item.xM_SMA_swing = item.xM_SMA_max - item.xM_SMA_min;
        item.xM_SE_swing = item.xM_SE_max - item.xM_SE_min;
        % Historical field names retain stage1/stage3 for compatibility,
        % but Qian Table 4 prescribes 5 s SMA heating and cooling.  Events
        % are therefore timed over the complete hot (S1+S2) and cold
        % (S3+S4) half-cycles, with elapsed time measured from S1/S3 start.
        item.stage1_SMA_loading_onset_s = first_event_time( ...
            hot_half_elapsed_s, xA_mean <= 0.99, idx_hot_half);
        item.stage1_SE_loading_onset_s = first_event_time( ...
            hot_half_elapsed_s, xR_mean >= 0.01, idx_hot_half);
        item.stage1_SMA_loading_completion_s = first_event_time( ...
            hot_half_elapsed_s, xA_mean <= 0.01, idx_hot_half);
        item.stage1_SE_loading_completion_s = first_event_time( ...
            hot_half_elapsed_s, xR_mean >= 0.99, idx_hot_half);
        item.stage3_SMA_unloading_onset_s = first_event_time( ...
            cold_half_elapsed_s, xA_mean >= 0.01, idx_cold_half);
        item.stage3_SE_unloading_onset_s = first_event_time( ...
            cold_half_elapsed_s, xR_mean <= 0.99, idx_cold_half);
        item.stage3_SMA_unloading_completion_s = first_event_time( ...
            cold_half_elapsed_s, xA_mean >= 0.99, idx_cold_half);
        item.stage3_SE_unloading_completion_s = first_event_time( ...
            cold_half_elapsed_s, xR_mean <= 0.01, idx_cold_half);
        item.sigma_SMA_max_MPa = max(abs(sigmaA_mean(idx))) / 1.0e6;
        item.sigma_SE_max_MPa = max(abs(sigmaR_mean(idx))) / 1.0e6;
        item.stage1_end_sigma_SMA_MPa = last_value(sigmaA_mean, idx1) / 1.0e6;
        item.stage1_end_sigma_SE_MPa = last_value(sigmaR_mean, idx1) / 1.0e6;
        item.hot_half_end_sigma_SMA_MPa = ...
            last_value(sigmaA_mean, idx_hot_half) / 1.0e6;
        item.hot_half_end_sigma_SE_MPa = ...
            last_value(sigmaR_mean, idx_hot_half) / 1.0e6;
        item.hot_half_end_xM_SMA = last_value(xA_mean, idx_hot_half);
        item.hot_half_end_xM_SE = last_value(xR_mean, idx_hot_half);
        item.Q_constitutive_SMA_J = integrate_signal(t, ...
            sum(physical.Q_SMA_constitutive_21_W, 2), idx);
        item.Q_constitutive_SE_J = integrate_signal(t, ...
            sum(physical.Q_SE_constitutive_21_W, 2), idx);
        item.latent_source_SMA_J = options.equilibrium.m_a_kg * ...
            options.material.SMA.Delta_h_J_per_kg * ...
            (last_value(xA_mean, idx) - first_value(xA_mean, idx));
        item.latent_source_SE_J = options.equilibrium.m_r_kg * ...
            options.material.SE.Delta_h_J_per_kg * ...
            (last_value(xR_mean, idx) - first_value(xR_mean, idx));
        stage_masks = {idx1, idx2, idx3, idx4};
        stage_decomposition_residuals = zeros(4, 2);
        for stage_idx = 1:4
            stage_mask = stage_masks{stage_idx};
            prefix = sprintf('stage%d_', stage_idx);
            item.([prefix 'latent_source_SMA_J']) = ...
                options.equilibrium.m_a_kg * ...
                options.material.SMA.Delta_h_J_per_kg * ...
                (last_value(xA_mean, stage_mask) - ...
                first_value(xA_mean, stage_mask));
            item.([prefix 'latent_source_SE_J']) = ...
                options.equilibrium.m_r_kg * ...
                options.material.SE.Delta_h_J_per_kg * ...
                (last_value(xR_mean, stage_mask) - ...
                first_value(xR_mean, stage_mask));
            [item.([prefix 'mechanical_source_SMA_J']), ...
                item.([prefix 'mechanical_source_SE_J'])] = ...
                direct_internal_mechanical_sources(physical, options, stage_mask);
            item.([prefix 'Q_constitutive_SMA_J']) = integrate_signal(t, ...
                sum(physical.Q_SMA_constitutive_21_W, 2), stage_mask);
            item.([prefix 'Q_constitutive_SE_J']) = integrate_signal(t, ...
                sum(physical.Q_SE_constitutive_21_W, 2), stage_mask);
            stage_decomposition_residuals(stage_idx, 1) = ...
                decomposition_residual_fraction( ...
                item.([prefix 'Q_constitutive_SMA_J']), ...
                item.([prefix 'latent_source_SMA_J']), ...
                item.([prefix 'mechanical_source_SMA_J']));
            stage_decomposition_residuals(stage_idx, 2) = ...
                decomposition_residual_fraction( ...
                item.([prefix 'Q_constitutive_SE_J']), ...
                item.([prefix 'latent_source_SE_J']), ...
                item.([prefix 'mechanical_source_SE_J']));
        end
        item.max_stage_constitutive_decomposition_residual_fraction = ...
            max(stage_decomposition_residuals, [], 'all');
        [item.mechanical_source_SMA_J, item.mechanical_source_SE_J] = ...
            direct_internal_mechanical_sources(physical, options, idx);
        item.mechanical_source_net_J = item.mechanical_source_SMA_J + ...
            item.mechanical_source_SE_J;
        item.mechanical_source_balance_fraction = abs( ...
            item.mechanical_source_net_J) / max(abs( ...
            item.mechanical_source_SMA_J) + abs( ...
            item.mechanical_source_SE_J), eps);
        item.Q_pipe_to_SMA_J = integrate_signal(t, sum( ...
            physical.Q_SMA_hold_pipe_to_solid_21_W + ...
            physical.Q_SMA_cooldown_pipe_to_solid_21_W, 2), idx);
        item.Q_pipe_to_SE_J = integrate_signal(t, sum( ...
            physical.Q_SE_hold_pipe_to_solid_21_W + ...
            physical.Q_SE_cooldown_pipe_to_solid_21_W, 2), idx);
        item.delta_U_sensible_SMA_J = options.equilibrium.m_a_kg * ...
            options.material.SMA.cp_J_per_kgK * ...
            (item.SMA_end_K - item.SMA_start_K);
        item.delta_U_sensible_SE_J = options.equilibrium.m_r_kg * ...
            options.material.SE.cp_J_per_kgK * ...
            (item.SE_end_K - item.SE_start_K);
        item.energy_residual_SMA_J = item.delta_U_sensible_SMA_J - ...
            item.Q_pipe_to_SMA_J - item.Q_constitutive_SMA_J;
        item.energy_residual_SE_J = item.delta_U_sensible_SE_J - ...
            item.Q_pipe_to_SE_J - item.Q_constitutive_SE_J;
        item.energy_residual_SMA_fraction = residual_fraction( ...
            item.energy_residual_SMA_J, item.delta_U_sensible_SMA_J, ...
            item.Q_pipe_to_SMA_J, item.Q_constitutive_SMA_J);
        item.energy_residual_SE_fraction = residual_fraction( ...
            item.energy_residual_SE_J, item.delta_U_sensible_SE_J, ...
            item.Q_pipe_to_SE_J, item.Q_constitutive_SE_J);
        item.pump_work_SMA_J = integrate_signal(t, ...
            physical.pump_power_SMA_W, idx);
        item.pump_work_SE_J = integrate_signal(t, ...
            physical.pump_power_SE_W, idx);
        item.stage1_SMA_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SMA_kgps), idx1);
        item.stage2_SMA_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SMA_kgps), idx2);
        item.stage2_SE_in_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SE_stage2_in_kgps), idx2);
        item.stage2_SE_out_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SE_stage2_out_kgps), idx2);
        item.stage3_SMA_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SMA_kgps), idx3);
        item.stage4_SMA_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SMA_kgps), idx4);
        item.stage4_SE_in_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SE_stage4_in_kgps), idx4);
        item.stage4_SE_out_transported_mass_kg = integrate_signal(t, ...
            abs(physical.mdot_SE_stage4_out_kgps), idx4);
        item.stage1_SMA_mean_abs_flow_kgps = masked_mean_abs( ...
            physical.mdot_SMA_kgps, idx1);
        item.stage2_SMA_mean_abs_flow_kgps = masked_mean_abs( ...
            physical.mdot_SMA_kgps, idx2);
        item.stage2_SE_mean_abs_flow_kgps = masked_mean_abs( ...
            physical.mdot_SE_stage2_in_kgps, idx2);
        item.stage3_SMA_mean_abs_flow_kgps = masked_mean_abs( ...
            physical.mdot_SMA_kgps, idx3);
        item.stage4_SMA_mean_abs_flow_kgps = masked_mean_abs( ...
            physical.mdot_SMA_kgps, idx4);
        item.stage4_SE_mean_abs_flow_kgps = masked_mean_abs( ...
            physical.mdot_SE_stage4_in_kgps, idx4);
        item.stage1_SMA_core_mean_signed_flow_kgps = masked_mean( ...
            physical.mdot_SMA_kgps, idx1_core);
        item.stage2_SMA_core_mean_signed_flow_kgps = masked_mean( ...
            physical.mdot_SMA_kgps, idx2_core);
        item.stage2_SE_core_mean_signed_flow_kgps = masked_mean( ...
            physical.mdot_SE_stage2_in_kgps, idx2_core);
        item.stage3_SMA_core_mean_signed_flow_kgps = masked_mean( ...
            physical.mdot_SMA_kgps, idx3_core);
        item.stage4_SMA_core_mean_signed_flow_kgps = masked_mean( ...
            physical.mdot_SMA_kgps, idx4_core);
        item.stage4_SE_core_mean_signed_flow_kgps = masked_mean( ...
            physical.mdot_SE_stage4_in_kgps, idx4_core);
        item.stage2_closed_stage4_route_mean_abs_flow_kgps = mean([ ...
            masked_mean_abs(physical.mdot_SE_stage4_in_kgps, idx2_core), ...
            masked_mean_abs(physical.mdot_SE_stage4_out_kgps, idx2_core)]);
        item.stage4_closed_stage2_route_mean_abs_flow_kgps = mean([ ...
            masked_mean_abs(physical.mdot_SE_stage2_in_kgps, idx4_core), ...
            masked_mean_abs(physical.mdot_SE_stage2_out_kgps, idx4_core)]);
        item.inactive_SE_mean_abs_flow_kgps = mean(abs([ ...
            physical.mdot_SE_stage2_in_kgps(idx1 | idx3); ...
            physical.mdot_SE_stage4_in_kgps(idx1 | idx3)]));
        idx_hot_half = idx1 | idx2;
        idx_ambient_half = idx3 | idx4;
        item.hot_half_HHEX_SMA_buffer_peak_K = max( ...
            physical.SMA_HHEX_buffer_T_K(idx_hot_half));
        item.hot_half_HHEX_SMA_buffer_rise_K = ...
            item.hot_half_HHEX_SMA_buffer_peak_K - ...
            first_value(physical.SMA_HHEX_buffer_T_K, idx_hot_half);
        item.ambient_half_SHEX_buffer_peak_K = max( ...
            physical.SHEX_buffer_T_K(idx_ambient_half));
        item.ambient_half_SHEX_buffer_above_source_K = ...
            item.ambient_half_SHEX_buffer_peak_K - options.system.Tshex_source_K;
        summary.cycle(c) = item;
    end
    summary.max_SMA_solid_energy_residual_fraction = ...
        max([summary.cycle.energy_residual_SMA_fraction]);
    summary.max_SE_solid_energy_residual_fraction = ...
        max([summary.cycle.energy_residual_SE_fraction]);

    summary.anchor = struct();
    summary.anchor.paper = ...
        'Qian et al., Energy 182 (2019), Table 2/Table 4/Fig. 3';
    summary.anchor.material = options.material.SMA.name;
    summary.anchor.net_SMA_volume_m3 = options.geometry.net_sma_volume_m3;
    summary.anchor.volume_scale = options.geometry.volume_scale_vs_previous;
    summary.anchor.nominal_SMA_stress_MPa = ...
        options.material.SMA.nominal_stress_Pa / 1.0e6;
    summary.anchor.Hcur_nominal = options.material.SMA.Hcur_nominal;
    summary.anchor.Delta_s0_J_per_kgK = options.material.SMA.Delta_s0_J_per_kgK;
    summary.anchor.Delta_h_J_per_kg = options.material.SMA.Delta_h_J_per_kg;
    summary.anchor.thermal_cycle_min_K = options.material.SMA.thermal_cycle_min_K;
    summary.anchor.thermal_cycle_max_K = options.material.SMA.thermal_cycle_max_K;
    summary.performance = build_performance_observation(summary.cycle, ...
        physical, options);
    summary.quantitative_literature_reproduction_evaluated = ...
        summary.performance.periodic_steady_state && ...
        strcmpi(strtrim(summary.performance.cold_load_mode), 'no_load');
    summary.quantitative_literature_reproduction_pass = ...
        summary.quantitative_literature_reproduction_evaluated && ...
        summary.performance.no_load_lift_relative_error <= ...
        get_validation_limit(options, ...
        'max_table4_no_load_lift_relative_error', 0.05);
    summary.quantitative_literature_reproduction_reason = ...
        performance_scope_reason(summary.performance, options);
end

function maximum_W = max_inactive_thermal_path_heat(physical, options)
    maximum_W = 0.0;
    guard_s = get_branch_scalar(options, 'stage_command_ramp_s', 0.0) + ...
        max(options.simulation.fixed_step_s, eps);
    inactive_by_stage = {
        physical.Q_SMA_cooldown_pipe_to_solid_21_W
        physical.Q_SMA_cooldown_pipe_to_solid_21_W
        physical.Q_SMA_hold_pipe_to_solid_21_W
        physical.Q_SMA_hold_pipe_to_solid_21_W};
    for stage_idx = 1:4
        mask = physical.stage_id == stage_idx & ...
            physical.stage_elapsed_s >= guard_s;
        if ~any(mask)
            maximum_W = Inf;
            return;
        end
        for route_idx = 1:size(inactive_by_stage, 2)
            q_W = sum(inactive_by_stage{stage_idx, route_idx}, 2);
            maximum_W = max(maximum_W, max(abs(q_W(mask))));
        end
    end
end

function value = get_branch_scalar(options, field_name, fallback)
    if isfield(options, 'branch') && isfield(options.branch, field_name) && ...
            isnumeric(options.branch.(field_name)) && ...
            isscalar(options.branch.(field_name)) && ...
            isfinite(options.branch.(field_name))
        value = max(double(options.branch.(field_name)), 0.0);
    else
        value = fallback;
    end
end

function observation = build_performance_observation(cycles, physical, options)
    last = cycles(end);
    observation = struct();
    observation.cycle_count = options.cycle_count;
    observation.cold_load_mode = char(string(options.system.cold_load_mode));
    observation.cold_load_heat_W = options.system.cold_load_heat_W;
    observation.endpoint_lift_HHEX_minus_CHEX_K = ...
        last.HHEX_end_K - last.CHEX_end_K;
    observation.reference_lift_T0_minus_CHEX_K = ...
        options.system.T0_K - last.CHEX_end_K;
    qian = qian_eq9_eq10_metrics(physical, options);
    observation.qian_window_cycles = qian.window_cycles;
    observation.qian_window_start_s = qian.window_start_s;
    observation.qian_window_end_s = qian.window_end_s;
    observation.temperature_lift_eq9_K = qian.temperature_lift_eq9_K;
    observation.cooling_power_eq10_W = qian.cooling_power_eq10_W;
    observation.specific_cooling_eq10_W_per_g = ...
        qian.specific_cooling_eq10_W_per_g;
    observation.qian_outlet_probe_contract = qian.outlet_probe_contract;
    observation.target_no_load_lift_K = ...
        options.validation.table4_max_no_load_lift_K;
    observation.no_load_lift_relative_error = abs( ...
        observation.temperature_lift_eq9_K - ...
        observation.target_no_load_lift_K) / ...
        max(abs(observation.target_no_load_lift_K), eps);
    observation.no_load_lift_relative_error_limit = ...
        get_validation_limit(options, ...
        'max_table4_no_load_lift_relative_error', 0.05);
    observation.periodic_window_cycles = min(numel(cycles), 10);
    if observation.periodic_window_cycles >= 2
        periodic_cycles = cycles((end - observation.periodic_window_cycles + 1):end);
        previous = cycles(end - 1);
        endpoint_history = [[periodic_cycles.SMA_end_K].', ...
            [periodic_cycles.SE_end_K].', [periodic_cycles.SHEX_end_K].', ...
            [periodic_cycles.HHEX_end_K].', [periodic_cycles.CHEX_end_K].'];
        observation.last_cycle_endpoint_drift_K = max(abs( ...
            diff(endpoint_history, 1, 1)), [], 'all');
        observation.last_cycle_CHEX_drift_K = ...
            last.CHEX_end_K - previous.CHEX_end_K;
        observation.last_cycle_HHEX_drift_K = ...
            last.HHEX_end_K - previous.HHEX_end_K;
        phase_history = [[periodic_cycles.xM_SMA_min].', ...
            [periodic_cycles.xM_SMA_max].', [periodic_cycles.xM_SE_min].', ...
            [periodic_cycles.xM_SE_max].'];
        observation.last_cycle_phase_drift = max(abs( ...
            diff(phase_history, 1, 1)), [], 'all');
        observation.last_cycle_same_phase_temperature_drift_K = ...
            same_phase_temperature_drift(physical, options, ...
                observation.periodic_window_cycles);
        observation.last_cycle_same_phase_phase_drift = ...
            same_phase_phase_drift(physical, options, ...
                observation.periodic_window_cycles);
    else
        observation.last_cycle_endpoint_drift_K = Inf;
        observation.last_cycle_CHEX_drift_K = Inf;
        observation.last_cycle_HHEX_drift_K = Inf;
        observation.last_cycle_phase_drift = Inf;
        observation.last_cycle_same_phase_temperature_drift_K = Inf;
        observation.last_cycle_same_phase_phase_drift = Inf;
    end
    observation.periodic_endpoint_limit_K = ...
        get_validation_limit(options, 'max_periodic_endpoint_drift_K', 0.05);
    observation.periodic_same_phase_temperature_limit_K = ...
        get_validation_limit(options, ...
            'max_periodic_same_phase_temperature_drift_K', 0.05);
    observation.periodic_phase_limit = ...
        get_validation_limit(options, 'max_periodic_phase_drift', 1.0e-4);
    observation.periodic_steady_state = options.cycle_count >= 10 && ...
        observation.last_cycle_endpoint_drift_K <= ...
            observation.periodic_endpoint_limit_K && ...
        observation.last_cycle_same_phase_temperature_drift_K <= ...
            observation.periodic_same_phase_temperature_limit_K && ...
        observation.last_cycle_phase_drift <= observation.periodic_phase_limit && ...
        observation.last_cycle_same_phase_phase_drift <= ...
            observation.periodic_phase_limit;
end

function metrics = qian_eq9_eq10_metrics(physical, options)
% Qian 2019 Eq.9/Eq.10 use HTF outlet temperatures over ten cycles.
% The canonical SLX pipe names follow block-port orientation, opposite to
% active flow in stages 2/4.  During active flow, the named "inlet" probes
% are the physical outlets after HHEX/CHEX, as verified by their approach
% to the corresponding exchanger-mass temperatures.

    metrics = struct();
    metrics.window_cycles = min(options.cycle_count, 10);
    metrics.window_end_s = options.cycle_count * options.schedule.tau_cycle_s;
    metrics.window_start_s = metrics.window_end_s - ...
        metrics.window_cycles * options.schedule.tau_cycle_s;
    metrics.temperature_lift_eq9_K = NaN;
    metrics.cooling_power_eq10_W = NaN;
    metrics.specific_cooling_eq10_W_per_g = NaN;
    metrics.outlet_probe_contract = [ ...
        'Tout_HHEX=hot_hx_inlet_fluid_temp_out; ', ...
        'Tout_CHEX=cold_hx_inlet_fluid_temp_out; ', ...
        'Tin_CHEX=cold_hx_outlet_fluid_temp_out; ', ...
        'names follow block-port orientation, active flow is reversed'];
    required = {'hot_hx_inlet_fluid_temp_out', ...
        'cold_hx_inlet_fluid_temp_out', ...
        'cold_hx_outlet_fluid_temp_out'};
    if ~isfield(physical, 'probes') || ...
            ~all(cellfun(@(name) isfield(physical.probes, name), required))
        return;
    end

    t = physical.time_s(:);
    idx = t >= metrics.window_start_s - eps(metrics.window_end_s) & ...
        t <= metrics.window_end_s + eps(metrics.window_end_s);
    duration_s = metrics.window_cycles * options.schedule.tau_cycle_s;
    if nnz(idx) < 2 || duration_s <= 0.0
        return;
    end
    T_out_hhex_K = physical.probes.hot_hx_inlet_fluid_temp_out(:);
    T_out_chex_K = physical.probes.cold_hx_inlet_fluid_temp_out(:);
    T_in_chex_K = physical.probes.cold_hx_outlet_fluid_temp_out(:);
    metrics.temperature_lift_eq9_K = trapz(t(idx), ...
        T_out_hhex_K(idx) - T_out_chex_K(idx)) / duration_s;

    cold_route_mdot_kgps = abs(physical.mdot_SE_stage4_in_kgps(:)) .* ...
        double(physical.stage_id(:) == 4);
    cooling_power_W = cold_route_mdot_kgps .* ...
        options.system.cp_fluid_J_per_kgK .* ...
        (T_out_chex_K - T_in_chex_K);
    metrics.cooling_power_eq10_W = trapz(t(idx), cooling_power_W(idx)) / ...
        duration_s;
    metrics.specific_cooling_eq10_W_per_g = ...
        metrics.cooling_power_eq10_W / ...
        max(options.equilibrium.m_r_kg * 1.0e3, eps);
end

function drift_K = same_phase_temperature_drift(physical, options, window_cycles)
    tau = options.schedule.tau_cycle_s;
    phase = linspace(0.0, tau, 401).';
    fields = {'SMA_T_21_K','SE_T_21_K','SHEX_T_K','HHEX_T_K','CHEX_T_K'};
    drift_K = 0.0;
    first_cycle = options.cycle_count - window_cycles + 1;
    for cycle_idx = (first_cycle + 1):options.cycle_count
        previous_start = (cycle_idx - 2) * tau;
        current_start = (cycle_idx - 1) * tau;
        for field_idx = 1:numel(fields)
            values = physical.(fields{field_idx});
            previous_values = interp1(physical.time_s, values, ...
                previous_start + phase, 'linear', 'extrap');
            current_values = interp1(physical.time_s, values, ...
                current_start + phase, 'linear', 'extrap');
            drift_K = max(drift_K, max(abs( ...
                current_values(:) - previous_values(:))));
        end
    end
end

function drift = same_phase_phase_drift(physical, options, window_cycles)
    tau = options.schedule.tau_cycle_s;
    phase = linspace(0.0, tau, 401).';
    fields = {'xM_SMA_21','xM_SE_21'};
    drift = 0.0;
    first_cycle = options.cycle_count - window_cycles + 1;
    for cycle_idx = (first_cycle + 1):options.cycle_count
        previous_start = (cycle_idx - 2) * tau;
        current_start = (cycle_idx - 1) * tau;
        for field_idx = 1:numel(fields)
            values = physical.(fields{field_idx});
            previous_values = interp1(physical.time_s, values, ...
                previous_start + phase, 'linear', 'extrap');
            current_values = interp1(physical.time_s, values, ...
                current_start + phase, 'linear', 'extrap');
            drift = max(drift, max(abs( ...
                current_values(:) - previous_values(:))));
        end
    end
end

function value = get_validation_limit(options, field_name, fallback)
    if isfield(options, 'validation') && ...
            isfield(options.validation, field_name) && ...
            ~isempty(options.validation.(field_name))
        value = options.validation.(field_name);
    else
        value = fallback;
    end
end

function value = residual_fraction(residual, stored, exchanged, constitutive)
    scale = max([abs(stored), abs(exchanged), abs(constitutive), 1.0]);
    value = abs(residual) / scale;
end

function value = decomposition_residual_fraction(constitutive, latent, mechanical)
    residual = constitutive - latent - mechanical;
    scale = max([abs(constitutive), abs(latent), abs(mechanical), 1.0]);
    value = abs(residual) / scale;
end

function reason = performance_scope_reason(observation, options)
    mode = strtrim(observation.cold_load_mode);
    if strcmpi(mode, 'no_load')
        if observation.periodic_steady_state
            reason = sprintf([ ...
                '%d-cycle no-load observation reached the declared periodic ', ...
                'gate. Its Qian Eq.9 outlet-temperature lift is %.6g K ', ...
                'versus the Table 4 no-load target %.6g K (relative error ', ...
                '%.6g, limit %.6g). The independent Table 4 zero-lift SCP ', ...
                'case is outside this no-load evaluation.'], ...
                options.cycle_count, ...
                observation.temperature_lift_eq9_K, ...
                observation.target_no_load_lift_K, ...
                observation.no_load_lift_relative_error, ...
                observation.no_load_lift_relative_error_limit);
        else
            reason = sprintf([ ...
                '%d-cycle no-load observation has not reached the declared ', ...
                'periodic gate over the last %d cycles (endpoint drift ', ...
                '%.6g K, same-phase temperature ', ...
                'drift %.6g K, same-phase phase-fraction drift %.6g). The ', ...
                '%.6g K Qian Eq.9 outlet-temperature lift is transient and ', ...
                'must not be compared as a final Table 4 result.'], ...
                options.cycle_count, ...
                observation.periodic_window_cycles, ...
                observation.last_cycle_endpoint_drift_K, ...
                observation.last_cycle_same_phase_temperature_drift_K, ...
                observation.last_cycle_same_phase_phase_drift, ...
                observation.temperature_lift_eq9_K);
        end
    else
        reason = sprintf([ ...
            '%d-cycle %s observation is not a complete Table 4 reproduction. ', ...
            'Periodic steady state and paired no-load/zero-lift cases are ', ...
            'required.'], options.cycle_count, observation.cold_load_mode);
    end
end


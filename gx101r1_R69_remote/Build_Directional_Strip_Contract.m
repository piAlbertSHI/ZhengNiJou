function directional_contract = Build_Directional_Strip_Contract(stage_name, strip_geometry)
% Build the AF-1 directional 101-strip exchange contract for one stage.

    if nargin < 2 || isempty(strip_geometry)
        strip_geometry = Build_Diameter_Strip_Geometry();
    end

    stage_name = char(string(stage_name));
    switch stage_name
        case 'hold_exchange'
            inlet_index = strip_geometry.cold_side_index;
            outlet_index = strip_geometry.hot_side_index;
            flow_direction = 'left_to_right';
            entry_boundary_name = 'cold_side';
            exit_boundary_name = 'hot_side';
            march_order = strip_geometry.left_to_right_order(:);

        case 'cooldown_exchange'
            inlet_index = strip_geometry.hot_side_index;
            outlet_index = strip_geometry.cold_side_index;
            flow_direction = 'right_to_left';
            entry_boundary_name = 'hot_side';
            exit_boundary_name = 'cold_side';
            march_order = strip_geometry.right_to_left_order(:);

        otherwise
            error('Build_Directional_Strip_Contract:UnsupportedStage', ...
                'Unsupported directional strip stage: %s', stage_name);
    end

    directional_contract = struct( ...
        'stage_name', stage_name, ...
        'strip_count', strip_geometry.strip_count, ...
        'x_strip_m', strip_geometry.x_strip_m(:), ...
        'strip_index', strip_geometry.strip_index(:), ...
        'cold_side_index', strip_geometry.cold_side_index, ...
        'hot_side_index', strip_geometry.hot_side_index, ...
        'inlet_index', inlet_index, ...
        'outlet_index', outlet_index, ...
        'flow_direction', flow_direction, ...
        'entry_boundary_name', entry_boundary_name, ...
        'exit_boundary_name', exit_boundary_name, ...
        'march_order', march_order, ...
        'contract_kind', 'directional_101');
end

function out = merge_structs(out, in)
    if ~isstruct(out)
        out = struct();
    end
    if ~isstruct(in)
        return;
    end
    names = fieldnames(in);
    for idx = 1:numel(names)
        out.(names{idx}) = in.(names{idx});
    end
end

function s = merge_defaults(s, defaults)
    if ~isstruct(s)
        s = struct();
    end
    names = fieldnames(defaults);
    for idx = 1:numel(names)
        name = names{idx};
        if ~isfield(s, name) || isempty(s.(name))
            s.(name) = defaults.(name);
        end
    end
end


function reasons = compare_numeric_option(reasons, old_s, new_s, field_name, tolerance)
    old_value = get_field(old_s, field_name, NaN);
    new_value = get_field(new_s, field_name, NaN);
    if ~(isnumeric(old_value) && isnumeric(new_value) && isscalar(old_value) && isscalar(new_value) && ...
            isfinite(old_value) && isfinite(new_value) && abs(old_value - new_value) <= tolerance)
        reasons{end + 1} = sprintf('%s mismatch: old=%s new=%s', field_name, ...
            compact_value(old_value), compact_value(new_value));
    end
end

function reasons = compare_string_option(reasons, old_s, new_s, field_name)
    old_value = char(string(get_field(old_s, field_name, '')));
    new_value = char(string(get_field(new_s, field_name, '')));
    if ~strcmp(old_value, new_value)
        reasons{end + 1} = sprintf('%s mismatch: old=%s new=%s', field_name, old_value, new_value);
    end
end

function reasons = compare_logical_option(reasons, old_s, new_s, field_name)
    old_value = logical(get_field(old_s, field_name, false));
    new_value = logical(get_field(new_s, field_name, false));
    if old_value ~= new_value
        reasons{end + 1} = sprintf('%s mismatch: old=%d new=%d', field_name, old_value, new_value);
    end
end

function text = compact_value(value)
    if isnumeric(value) && isscalar(value)
        text = sprintf('%.16g', value);
    else
        text = char(string(value));
    end
end


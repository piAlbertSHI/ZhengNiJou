function [cycle_index, stage_name, stage_index, inference_source] = infer_failure_location( ...
        latest_checkpoint, runtime)
    cycle_index = get_field(runtime, 'cycle_index', NaN);
    stage_index = get_field(runtime, 'stage_index', NaN);
    inference_source = 'runtime';
    checkpoint_name = checkpoint_file_name(latest_checkpoint);
    if isempty(checkpoint_name)
        stage_name = stage_name_from_index(stage_index);
        return;
    end

    token = regexp(checkpoint_name, '^cycle(\d+)_(.+)\.mat$', 'tokens', 'once');
    if ~isempty(token)
        cycle_index = str2double(token{1});
        suffix = token{2};
        switch suffix
            case 'load_end'
                stage_name = 'hold_exchange';
                stage_index = 2;
            case {'hold_end', 'hold_restart_balanced'}
                stage_name = 'unload_adiabatic';
                stage_index = 3;
            case 'unload_end'
                stage_name = 'cooldown_exchange';
                stage_index = 4;
            case {'cooldown_end', 'cooldown_restart_balanced'}
                stage_name = 'load_adiabatic';
                stage_index = 1;
                cycle_index = cycle_index + 1;
            otherwise
                stage_name = stage_name_from_index(stage_index);
        end
        inference_source = ['checkpoint_suffix:', suffix];
        return;
    end

    token = regexp(checkpoint_name, '^cycle_(\d+)_stage_(\d+)_(.+)\.mat$', 'tokens', 'once');
    if ~isempty(token)
        cycle_index = str2double(token{1});
        completed_stage_index = str2double(token{2});
        if completed_stage_index >= 4
            cycle_index = cycle_index + 1;
            stage_index = 1;
        else
            stage_index = completed_stage_index + 1;
        end
        stage_name = stage_name_from_index(stage_index);
        inference_source = ['stage_checkpoint:', token{3}];
        return;
    end

    stage_name = stage_name_from_index(stage_index);
end

function name = checkpoint_file_name(path_value)
    if isempty(path_value)
        name = '';
        return;
    end
    [~, base, ext] = fileparts(path_value);
    name = [base, ext];
end

function stage_name = stage_name_from_index(stage_index)
    names = {'load_adiabatic', 'hold_exchange', 'unload_adiabatic', 'cooldown_exchange'};
    if isfinite(stage_index) && stage_index >= 1 && stage_index <= numel(names)
        stage_name = names{stage_index};
    else
        stage_name = '';
    end
end


function [unload_result, retry_report] = run_unloading_with_retry(unload_options)
    original_Nt_unload = get_field(unload_options, 'Nt_unload', get_field(unload_options, 'Nt', 960));
    retry_enabled = logical(get_field(unload_options, 'enable_unload_retry', true));
    retry_values = get_field(unload_options, 'unload_retry_Nt_unload_values', original_Nt_unload);
    retry_values = unique([original_Nt_unload, retry_values(:).'], 'stable');
    retry_values = retry_values(isfinite(retry_values) & retry_values >= original_Nt_unload);
    if isempty(retry_values)
        retry_values = original_Nt_unload;
    end
    if ~retry_enabled
        retry_values = original_Nt_unload;
    end

    attempts = repmat(empty_unload_retry_attempt(), 1, 0);
    unload_result = struct();
    first_failure_reason = '';
    for idx = 1:numel(retry_values)
        attempt_options = unload_options;
        attempt_options.Nt_unload = retry_values(idx);
        attempt_tic = tic;
        attempt_result = Run_GlobalXi_Unloading_Prototype(attempt_options);
        attempt_walltime_s = toc(attempt_tic);
        attempt = summarize_unload_retry_attempt(idx, retry_values(idx), attempt_result, attempt_walltime_s);
        attempts(end + 1) = attempt; %#ok<AGROW>
        unload_result = attempt_result;
        if isstruct(attempt_result) && isfield(attempt_result, 'ok') && attempt_result.ok
            break;
        end
        if isempty(first_failure_reason)
            first_failure_reason = get_field(attempt_result, 'failure_reason', 'unknown');
        end
    end

    used_Nt_unload = retry_values(min(numel(attempts), numel(retry_values)));
    retry_used = numel(attempts) > 1;
    retry_report = struct( ...
        'mechanical_retry_used', retry_used, ...
        'retry_used', retry_used, ...
        'retry_count', max(numel(attempts) - 1, 0), ...
        'mechanical_retry_reason', first_failure_reason, ...
        'Nt_unload_original', original_Nt_unload, ...
        'Nt_unload_used', used_Nt_unload, ...
        'unload_retry_attempts', attempts);
end

function attempt = empty_unload_retry_attempt()
    attempt = struct( ...
        'attempt_index', NaN, ...
        'Nt_unload', NaN, ...
        'ok', false, ...
        'failure_reason', '', ...
        'final_pressure_MPa', NaN, ...
        'work_complete', false, ...
        'work_accepted_step_count', NaN, ...
        'walltime_s', NaN);
end

function attempt = summarize_unload_retry_attempt(attempt_index, Nt_unload, result, walltime_s)
    metrics = get_field(result, 'summary_metrics', struct());
    attempt = struct( ...
        'attempt_index', attempt_index, ...
        'Nt_unload', Nt_unload, ...
        'ok', isstruct(result) && isfield(result, 'ok') && result.ok, ...
        'failure_reason', get_field(result, 'failure_reason', ''), ...
        'final_pressure_MPa', get_field(get_field(result, 'final_state', struct()), 'pressure_MPa', NaN), ...
        'work_complete', get_field(metrics, 'work_complete', false), ...
        'work_accepted_step_count', get_field(metrics, 'work_accepted_step_count', NaN), ...
        'walltime_s', walltime_s);
end


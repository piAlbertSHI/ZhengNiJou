function ratio = safe_abs_ratio(numerator, denominator)
    if isfinite(numerator) && isfinite(denominator) && abs(denominator) > 1.0e-12
        ratio = abs(numerator) / abs(denominator);
    else
        ratio = NaN;
    end
end


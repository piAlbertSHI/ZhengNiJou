function [stage_name, stage_index] = failure_stage_from_error(message)
    message = char(string(message));
    stage_names = {'unload_adiabatic', 'load_adiabatic', 'hold_exchange', 'cooldown_exchange'};
    stage_indices = [3, 1, 2, 4];
    stage_name = '';
    stage_index = NaN;
    for idx = 1:numel(stage_names)
        if contains(message, stage_names{idx})
            stage_name = stage_names{idx};
            stage_index = stage_indices(idx);
            return;
        end
    end
end


function W_total = build_cop_work_total(load_r, unload_r, hold_r, cold_r)
    W_load = get_field(load_r, 'W_load_input_J', NaN);
    if ~isfinite(W_load)
        W_load = abs(get_field(load_r, 'work_signed_J', NaN));
    end
    W_unload_signed = get_field(unload_r, 'W_unload_signed_J', NaN);
    if ~isfinite(W_unload_signed)
        recovered = get_field(unload_r, 'W_unload_recovered_J', NaN);
        if isfinite(recovered)
            W_unload_signed = -abs(recovered);
        end
    end
    W_pump = finite_sum([ ...
        abs(get_field(hold_r, 'Wpump_estimated_J', NaN)), ...
        abs(get_field(cold_r, 'Wpump_estimated_J', NaN))]);
    if isfinite(W_load) && isfinite(W_unload_signed)
        W_total = W_load - W_unload_signed + W_pump;
    else
        W_total = NaN;
    end
end

function value = finite_sum(values)
    values = values(isfinite(values));
    if isempty(values)
        value = 0.0;
    else
        value = sum(values);
    end
end


function assign_accelerator_prewarm_workspace_vars(model_path, config, exchange_options)
    local_options = exchange_options;
    local_options.model_path = model_path;
    if ~isfield(local_options, 'outputs_dir') || isempty(local_options.outputs_dir)
        local_options.outputs_dir = config.outputs_dir;
    end
    stage_info = struct('stage_name', 'cooldown_exchange', 't_start', 0.6, 't_end', 1.0);
    stage_config = Resolve_Exchange_Stage_Config(stage_info, local_options);
    state_in = struct('T', 293.0 * ones(51, 1));
    sim_params = Build_Simulink_Exchange_Params(state_in, stage_config, local_options);
    if ~isfield(sim_params, 'mdot_source_kgps')
        sim_params.mdot_source_kgps = sim_params.mdot_target_kgps;
    end
    names = fieldnames(sim_params);
    for idx = 1:numel(names)
        assignin('base', names{idx}, sim_params.(names{idx}));
    end
end

function runtime = restore_runtime_from_resume(runtime, resume_context)
    side_state = resume_context.side_state;
    fields = fieldnames(side_state);
    for idx = 1:numel(fields)
        runtime.(fields{idx}) = side_state.(fields{idx});
    end
    runtime.hot_source_current = runtime.hot_sink_temp_current;
    runtime.last_hot_sink_temp_out = runtime.hot_sink_temp_current;
    runtime.last_cold_sink_temp_out = runtime.cold_sink_temp_current;
    runtime.last_chip_temp_out = runtime.chip_temp_current;
    runtime.last_cold_load_temp_out = get_field(runtime, 'cold_load_temp_current', runtime.chip_temp_current);
    runtime.last_hot_buffer_temp_out = runtime.hot_buffer_temp_current;
    runtime.last_cold_buffer_temp_out = runtime.cold_buffer_temp_current;
    runtime.last_hot_source_out = runtime.hot_sink_temp_current;
    runtime.last_stage_name = 'cooldown_exchange';
    runtime.cycle_index = resume_context.prior_last_cycle_index;
    runtime.stage_index = 4;
    runtime.last_checkpoint_path = resume_context.start_checkpoint_path;
end

function [side_state, report] = recover_resume_side_state(prior_run_result, last_cycle_index)
    final_hot = get_field(prior_run_result, 'final_hot_sink_temp', NaN);
    final_cold = get_field(prior_run_result, 'final_cold_sink_temp', NaN);
    final_chip = get_field(prior_run_result, 'final_cold_load_temp', ...
        get_field(prior_run_result, 'final_chip_temp', NaN));
    cycle_results = reshape(get_field(prior_run_result, 'cycle_results', struct([])), 1, []);
    last_cycle = get_cycle_result_by_index(cycle_results, last_cycle_index);
    cooldown_report = get_stage_report(get_field(last_cycle, 'stage_reports', struct([])), 'cooldown_exchange');

    hot = get_field(cooldown_report, 'hot_sink_temp_out', final_hot);
    cold = get_field(cooldown_report, 'cold_sink_temp_out', final_cold);
    chip = get_field(cooldown_report, 'cold_load_temp_out', ...
        get_field(cooldown_report, 'chip_temp_out', final_chip));
    hot_buffer = get_field(cooldown_report, 'hot_buffer_temp_out', hot);
    cold_buffer = get_field(cooldown_report, 'cold_buffer_temp_out', cold);
    values = [hot, cold, chip, hot_buffer, cold_buffer];
    if any(~isfinite(values))
        error('Run_GlobalXi_Simulink_Cycles:ResumeSideStateMissing', ...
            'Could not recover finite hot/cold/chip/buffer state from the previous run.');
    end

    side_state = struct( ...
        'hot_sink_temp_current', hot, ...
        'cold_sink_temp_current', cold, ...
        'chip_temp_current', chip, ...
        'cold_load_temp_current', chip, ...
        'hot_buffer_temp_current', hot_buffer, ...
        'cold_buffer_temp_current', cold_buffer);
    report = struct( ...
        'source_cycle_index', last_cycle_index, ...
        'source_stage_name', 'cooldown_exchange', ...
        'hot_sink_source', source_label(cooldown_report, 'hot_sink_temp_out', prior_run_result, 'final_hot_sink_temp'), ...
        'cold_sink_source', source_label(cooldown_report, 'cold_sink_temp_out', prior_run_result, 'final_cold_sink_temp'), ...
        'chip_source', source_label(cooldown_report, 'chip_temp_out', prior_run_result, 'final_chip_temp'), ...
        'cold_load_source', source_label(cooldown_report, 'cold_load_temp_out', prior_run_result, 'final_cold_load_temp'), ...
        'hot_buffer_source', buffer_source_label(cooldown_report, 'hot_buffer_temp_out'), ...
        'cold_buffer_source', buffer_source_label(cooldown_report, 'cold_buffer_temp_out'), ...
        'official_cold_end_definition', get_field(cooldown_report, 'official_cold_end_definition', ''), ...
        'cold_end_temp_out', get_field(cooldown_report, 'cold_end_temp_out', NaN), ...
        'cold_end_C_total_J_per_K', get_field(cooldown_report, 'cold_end_C_total_J_per_K', NaN), ...
        'cold_end_effective_water_volume_ml', get_field(cooldown_report, 'cold_end_effective_water_volume_ml', NaN), ...
        'cold_side_state_sync_policy', get_field(cooldown_report, 'cold_side_state_sync_policy', ''), ...
        'hot_sink_temp_current', hot, ...
        'cold_sink_temp_current', cold, ...
        'chip_temp_current', chip, ...
        'cold_load_temp_current', chip, ...
        'hot_buffer_temp_current', hot_buffer, ...
        'cold_buffer_temp_current', cold_buffer);
end

function label = source_label(stage_report, stage_field, run_result, final_field)
    if isstruct(stage_report) && isfield(stage_report, stage_field) && isfinite(stage_report.(stage_field))
        label = ['stage_report.', stage_field];
    elseif isstruct(run_result) && isfield(run_result, final_field) && isfinite(run_result.(final_field))
        label = ['run_result.', final_field];
    else
        label = 'missing';
    end
end

function label = buffer_source_label(stage_report, stage_field)
    if isstruct(stage_report) && isfield(stage_report, stage_field) && isfinite(stage_report.(stage_field))
        label = ['stage_report.', stage_field];
    else
        label = 'matched_sink_fallback';
    end
end


function run_result = Run_GlobalXi_Simulink_Cycles(options)
% Run GlobalXi loading/unloading coupled to the Simulink101 exchange model.

    if nargin < 1 || isempty(options)
        options = struct();
    end

    root_dir = fileparts(mfilename('fullpath'));
    addpath(root_dir, '-begin');

    config = normalize_run_config(options, root_dir);
    resume_context = load_resume_context(config);
    config = finalize_resume_config(config, resume_context);
    ensure_dir(config.outputs_dir);
    ensure_dir(config.checkpoints_dir);
    ensure_dir(config.figures_dir);

    [stage_descriptors, ~] = Build_FourStage_Cycle_Schedule(config.schedule_options);
    runtime = Create_Simulink_Exchange_Runtime(config.exchange_options);
    runtime.checkpoints_dir = config.checkpoints_dir;
    runtime.figures_dir = config.figures_dir;
    runtime.outputs_dir = config.outputs_dir;
    runtime.save_checkpoints = config.save_checkpoints;
    runtime.save_plots = config.save_plots;
    runtime.store_raw_simout = config.store_raw_simout;
    if config.is_resume
        runtime = restore_runtime_from_resume(runtime, resume_context);
    end

    run_tic = tic;
    run_result = struct();
    run_result.ok = false;
    run_result.failure_reason = '';
    run_result.config = config;
    run_result.stage_descriptors = stage_descriptors;
    run_result.cycle_results = struct([]);
    run_result.cycle_diagnostics = struct([]);
    run_result.final_state = struct();
    run_result.final_checkpoint_path = '';
    run_result.final_hot_sink_temp = NaN;
    run_result.final_cold_sink_temp = NaN;
    run_result.final_chip_temp = NaN;
    run_result.final_cold_load_temp = NaN;
    run_result.outputs_dir = config.outputs_dir;
    run_result.physics_ok = false;
    run_result.validation_summary = struct();
    run_result.total_walltime_s = NaN;
    run_result.prior_walltime_s = config.prior_walltime_s;
    run_result.resume_walltime_s = NaN;
    run_result.plot_walltime_s = NaN;
    run_result.accelerator_prewarm_report = struct();
    run_result.failure_context = struct();
    run_result.resume_metadata = config.resume_metadata;
    if config.is_resume
        run_result.cycle_results = reshape(resume_context.prior_cycle_results, 1, []);
        run_result.cycle_diagnostics = reshape(resume_context.prior_cycle_diagnostics, 1, []);
        run_result.final_checkpoint_path = resume_context.start_checkpoint_path;
        run_result.final_state = resume_context.prior_final_state;
        run_result.final_hot_sink_temp = resume_context.side_state.hot_sink_temp_current;
        run_result.final_cold_sink_temp = resume_context.side_state.cold_sink_temp_current;
        run_result.final_chip_temp = resume_context.side_state.chip_temp_current;
        run_result.final_cold_load_temp = resume_context.side_state.cold_load_temp_current;
    end

    save(fullfile(config.outputs_dir, 'run_config.mat'), 'config');
    prewarm_report = prewarm_accelerator_cache_if_requested(config);
    run_result.accelerator_prewarm_report = prewarm_report;

    current_restart_checkpoint = config.initial_restart_checkpoint;
    try
        for cycle_index = config.start_cycle_index:config.end_cycle_index
            [cycle_result, runtime, current_restart_checkpoint] = run_one_cycle( ...
                cycle_index, current_restart_checkpoint, runtime, config, stage_descriptors);
            run_result.cycle_results = append_struct(run_result.cycle_results, cycle_result);
            run_result.cycle_diagnostics = append_struct( ...
                run_result.cycle_diagnostics, build_cycle_diagnostics(cycle_result, runtime));
            run_result = attach_validation_summary(run_result);
            save_progress(run_result, config);
        end

        run_result.ok = true;
        run_result.final_checkpoint_path = current_restart_checkpoint;
        run_result.final_state = GlobalXi_Checkpoint_To_Simulink_State(current_restart_checkpoint);
        run_result.final_hot_sink_temp = runtime.hot_sink_temp_current;
        run_result.final_cold_sink_temp = runtime.cold_sink_temp_current;
        run_result.final_chip_temp = runtime.chip_temp_current;
        run_result.final_cold_load_temp = get_field(runtime, 'cold_load_temp_current', runtime.chip_temp_current);
        if config.stop_after_stage_index < 4
            run_result.plot_info = struct('skipped', true, ...
                'reason', 'stop_after_stage_index requested stage-only diagnostic run');
            run_result.plot_walltime_s = 0;
        else
            plot_tic = tic;
            run_result.plot_info = Plot_GlobalXi_Simulink_Cycle_Results(run_result);
            run_result.plot_walltime_s = toc(plot_tic);
        end
        run_result.resume_walltime_s = toc(run_tic);
        run_result.total_walltime_s = run_result.prior_walltime_s + run_result.resume_walltime_s;
        run_result = attach_validation_summary(run_result);
        save_progress(run_result, config);
    catch ME
        run_result.ok = false;
        run_result.failure_reason = ME.message;
        run_result.final_checkpoint_path = current_restart_checkpoint;
        if ~isempty(current_restart_checkpoint) && exist(current_restart_checkpoint, 'file')
            run_result.final_state = GlobalXi_Checkpoint_To_Simulink_State(current_restart_checkpoint);
        end
        run_result.final_hot_sink_temp = get_field(runtime, 'hot_sink_temp_current', NaN);
        run_result.final_cold_sink_temp = get_field(runtime, 'cold_sink_temp_current', NaN);
        run_result.final_chip_temp = get_field(runtime, 'chip_temp_current', NaN);
        run_result.final_cold_load_temp = get_field(runtime, 'cold_load_temp_current', run_result.final_chip_temp);
        run_result.resume_walltime_s = toc(run_tic);
        run_result.total_walltime_s = run_result.prior_walltime_s + run_result.resume_walltime_s;
        run_result.failure_context = build_failure_context(ME, config, ...
            current_restart_checkpoint, runtime);
        run_result = attach_validation_summary(run_result);
        save_progress(run_result, config);
    end
end

function [cycle_result, runtime, next_restart_checkpoint] = run_one_cycle( ...
        cycle_index, restart_checkpoint, runtime, config, stage_descriptors)

    cycle_tic = tic;
    cycle_result = struct( ...
        'cycle_index', cycle_index, ...
        'ok', false, ...
        'failure_reason', '', ...
        'stage_reports', empty_stage_reports(), ...
        'load_result', struct(), ...
        'unload_result', struct(), ...
        'checkpoints', struct(), ...
        'timing', struct());
    runtime.cycle_index = cycle_index;
    runtime.stage_index = 0;
    runtime.failed_stage_partial_checkpoint = '';
    runtime.failed_stage_name = '';
    runtime.failed_stage_index = NaN;
    runtime.last_successful_checkpoint = restart_checkpoint;
    runtime.last_successful_restart_checkpoint = restart_checkpoint;

    load_tic = tic;
    runtime.stage_index = 1;
    load_checkpoint_path = stage_checkpoint_path(config, cycle_index, 'load_end');
    load_options = config.solver_options;
    load_options.save_checkpoint_path = load_checkpoint_path;
    if ~isempty(restart_checkpoint)
        load_options.initial_checkpoint = restart_checkpoint;
    end
    load_result = Run_GlobalXi_Time_Loading_Prototype(load_options);
    load_walltime_s = toc(load_tic);
    cycle_result.load_result = strip_solver_result(load_result);
    closed_load_report = build_closed_stage_side_report(runtime, stage_descriptors(1), config.exchange_options);
    closed_load_report.stage_walltime_s = load_walltime_s;
    closed_load_report.mechanical_walltime_s = load_walltime_s;
    load_stage_report = Build_GlobalXi_Stage_Report('load_adiabatic', cycle_index, 1, ...
        load_checkpoint_path, load_result, closed_load_report, struct('output_checkpoint_path', load_checkpoint_path));
    cycle_result.stage_reports = append_struct(cycle_result.stage_reports, load_stage_report);
    if ~(isstruct(load_result) && isfield(load_result, 'ok') && load_result.ok)
        runtime.failed_stage_partial_checkpoint = load_checkpoint_path;
        runtime.failed_stage_name = 'load_adiabatic';
        runtime.failed_stage_index = 1;
        save_failed_cycle_partial_diagnostics(config, cycle_result, runtime, ...
            'load_adiabatic', 1, load_checkpoint_path);
        assert_stage_ok(load_result, 'load_adiabatic');
    end
    runtime.last_successful_checkpoint = load_checkpoint_path;
    runtime.last_successful_restart_checkpoint = load_checkpoint_path;
    runtime.last_stage_name = 'load_adiabatic';
    if config.stop_after_stage_index <= 1
        cycle_result.checkpoints = struct('load_end', load_checkpoint_path);
        cycle_result.timing = struct('load_walltime_s', load_walltime_s, ...
            'cycle_walltime_s', toc(cycle_tic));
        cycle_result.ok = true;
        next_restart_checkpoint = load_checkpoint_path;
        return;
    end

    hold_tic = tic;
    runtime.cycle_index = cycle_index;
    runtime.stage_index = 2;
    exchange_options = config.exchange_options;
    exchange_options.runtime = runtime;
    try
        hold_hook = Run_Simulink_Exchange_Hook( ...
            GlobalXi_Checkpoint_To_Simulink_State(load_checkpoint_path), stage_descriptors(2), exchange_options);
    catch ME
        runtime.failed_stage_name = 'hold_exchange';
        runtime.failed_stage_index = 2;
        runtime.failed_stage_partial_checkpoint = '';
        save_failed_cycle_partial_diagnostics(config, cycle_result, runtime, ...
            'hold_exchange', 2, '');
        rethrow(ME);
    end
    runtime = hold_hook.runtime_out;
    hold_checkpoint_path = stage_checkpoint_path(config, cycle_index, 'hold_end');
    hold_metadata = struct('stage_name', 'hold_exchange', ...
        'pressure_MPa', load_result.final_state.pressure_MPa, ...
        'time_s', stage_descriptors(2).t_end, ...
        'balance_options', get_field(config.exchange_options, 'restart_balance_options', struct()));
    [~, ~, hold_checkpoint_report] = Build_GlobalXi_Checkpoint_From_Exchanged_T( ...
        load_checkpoint_path, hold_hook.T_out, hold_checkpoint_path, hold_metadata);
    hold_restart_checkpoint_path = stage_checkpoint_path(config, cycle_index, 'hold_restart_balanced');
    [~, ~, hold_balance_report] = Build_GlobalXi_Restart_Balance_Checkpoint( ...
        load_checkpoint_path, hold_checkpoint_path, hold_restart_checkpoint_path, hold_metadata);
    hold_stage_checkpoint_report = merge_structs(hold_checkpoint_report, hold_balance_report);
    hold_walltime_s = toc(hold_tic);
    hold_hook_report = hold_hook.hook_report;
    hold_hook_report.stage_walltime_s = hold_walltime_s;
    hold_hook_report.exchange_walltime_s = hold_walltime_s;
    cycle_result.stage_reports = append_struct(cycle_result.stage_reports, ...
        Build_GlobalXi_Stage_Report('hold_exchange', cycle_index, 2, ...
        hold_checkpoint_path, struct('ok', true, 'summary_metrics', struct()), ...
        hold_hook_report, hold_stage_checkpoint_report));
    runtime.last_successful_checkpoint = hold_checkpoint_path;
    runtime.last_successful_restart_checkpoint = hold_restart_checkpoint_path;
    runtime.last_stage_name = 'hold_exchange';
    if config.stop_after_stage_index <= 2
        cycle_result.checkpoints = struct( ...
            'load_end', load_checkpoint_path, ...
            'hold_end', hold_checkpoint_path, ...
            'hold_restart_balanced', hold_restart_checkpoint_path);
        cycle_result.timing = struct( ...
            'load_walltime_s', load_walltime_s, ...
            'hold_walltime_s', hold_walltime_s, ...
            'cycle_walltime_s', toc(cycle_tic));
        cycle_result.ok = true;
        next_restart_checkpoint = hold_restart_checkpoint_path;
        return;
    end

    unload_tic = tic;
    runtime.stage_index = 3;
    unload_checkpoint_path = stage_checkpoint_path(config, cycle_index, 'unload_end');
    unload_options = config.solver_options;
    unload_options.initial_checkpoint = hold_restart_checkpoint_path;
    unload_options.save_checkpoint_path = unload_checkpoint_path;
    [unload_result, unload_retry_report] = run_unloading_with_retry(unload_options);
    unload_walltime_s = toc(unload_tic);
    cycle_result.unload_result = strip_solver_result(unload_result);
    closed_unload_report = build_closed_stage_side_report(runtime, stage_descriptors(3), config.exchange_options);
    closed_unload_report = merge_structs(closed_unload_report, unload_retry_report);
    closed_unload_report.stage_walltime_s = unload_walltime_s;
    closed_unload_report.mechanical_walltime_s = unload_walltime_s;
    unload_stage_report = Build_GlobalXi_Stage_Report('unload_adiabatic', cycle_index, 3, ...
        unload_checkpoint_path, unload_result, closed_unload_report, struct('output_checkpoint_path', unload_checkpoint_path));
    cycle_result.stage_reports = append_struct(cycle_result.stage_reports, unload_stage_report);
    if ~(isstruct(unload_result) && isfield(unload_result, 'ok') && unload_result.ok)
        runtime.failed_stage_partial_checkpoint = unload_checkpoint_path;
        runtime.failed_stage_name = 'unload_adiabatic';
        runtime.failed_stage_index = 3;
        save_failed_cycle_partial_diagnostics(config, cycle_result, runtime, ...
            'unload_adiabatic', 3, unload_checkpoint_path);
        assert_stage_ok(unload_result, 'unload_adiabatic');
    end
    runtime.last_successful_checkpoint = unload_checkpoint_path;
    runtime.last_successful_restart_checkpoint = unload_checkpoint_path;
    runtime.last_stage_name = 'unload_adiabatic';
    if config.stop_after_stage_index <= 3
        cycle_result.checkpoints = struct( ...
            'load_end', load_checkpoint_path, ...
            'hold_end', hold_checkpoint_path, ...
            'hold_restart_balanced', hold_restart_checkpoint_path, ...
            'unload_end', unload_checkpoint_path);
        cycle_result.timing = struct( ...
            'load_walltime_s', load_walltime_s, ...
            'hold_walltime_s', hold_walltime_s, ...
            'unload_walltime_s', unload_walltime_s, ...
            'cycle_walltime_s', toc(cycle_tic));
        cycle_result.ok = true;
        next_restart_checkpoint = unload_checkpoint_path;
        return;
    end

    cooldown_tic = tic;
    runtime.cycle_index = cycle_index;
    runtime.stage_index = 4;
    exchange_options = config.exchange_options;
    exchange_options.runtime = runtime;
    try
        cooldown_hook = Run_Simulink_Exchange_Hook( ...
            GlobalXi_Checkpoint_To_Simulink_State(unload_checkpoint_path), stage_descriptors(4), exchange_options);
    catch ME
        runtime.failed_stage_name = 'cooldown_exchange';
        runtime.failed_stage_index = 4;
        runtime.failed_stage_partial_checkpoint = '';
        save_failed_cycle_partial_diagnostics(config, cycle_result, runtime, ...
            'cooldown_exchange', 4, '');
        rethrow(ME);
    end
    runtime = cooldown_hook.runtime_out;
    cooldown_checkpoint_path = stage_checkpoint_path(config, cycle_index, 'cooldown_end');
    cooldown_metadata = struct('stage_name', 'cooldown_exchange', ...
        'pressure_MPa', unload_result.final_state.pressure_MPa, ...
        'time_s', stage_descriptors(4).t_end, ...
        'target_pressure_MPa', 0.0, ...
        'balance_options', get_field(config.exchange_options, 'restart_balance_options', struct()));
    [~, ~, cooldown_checkpoint_report] = Build_GlobalXi_Checkpoint_From_Exchanged_T( ...
        unload_checkpoint_path, cooldown_hook.T_out, cooldown_checkpoint_path, cooldown_metadata);
    cooldown_restart_checkpoint_path = stage_checkpoint_path(config, cycle_index, 'cooldown_restart_balanced');
    [~, ~, cooldown_balance_report] = Build_GlobalXi_Restart_Balance_Checkpoint( ...
        unload_checkpoint_path, cooldown_checkpoint_path, cooldown_restart_checkpoint_path, cooldown_metadata);
    cooldown_stage_checkpoint_report = merge_structs(cooldown_checkpoint_report, cooldown_balance_report);
    cooldown_walltime_s = toc(cooldown_tic);
    cooldown_hook_report = cooldown_hook.hook_report;
    cooldown_hook_report.stage_walltime_s = cooldown_walltime_s;
    cooldown_hook_report.exchange_walltime_s = cooldown_walltime_s;
    cycle_result.stage_reports = append_struct(cycle_result.stage_reports, ...
        Build_GlobalXi_Stage_Report('cooldown_exchange', cycle_index, 4, ...
        cooldown_checkpoint_path, struct('ok', true, 'summary_metrics', struct()), ...
        cooldown_hook_report, cooldown_stage_checkpoint_report));
    runtime.last_successful_checkpoint = cooldown_checkpoint_path;
    runtime.last_successful_restart_checkpoint = cooldown_restart_checkpoint_path;
    runtime.last_stage_name = 'cooldown_exchange';

    cycle_result.checkpoints = struct( ...
        'load_end', load_checkpoint_path, ...
        'hold_end', hold_checkpoint_path, ...
        'hold_restart_balanced', hold_restart_checkpoint_path, ...
        'unload_end', unload_checkpoint_path, ...
        'cooldown_end', cooldown_checkpoint_path, ...
        'cooldown_restart_balanced', cooldown_restart_checkpoint_path);
    cycle_result.timing = struct( ...
        'load_walltime_s', load_walltime_s, ...
        'hold_walltime_s', hold_walltime_s, ...
        'unload_walltime_s', unload_walltime_s, ...
        'cooldown_walltime_s', cooldown_walltime_s, ...
        'cycle_walltime_s', toc(cycle_tic));
    cycle_result.ok = true;
    next_restart_checkpoint = cooldown_restart_checkpoint_path;
end

function resume_context = load_resume_context(config)
    resume_context = empty_resume_context();
    if ~config.is_resume
        return;
    end
    if ~strcmp(config.resume_mode, 'new_output')
        error('Run_GlobalXi_Simulink_Cycles:UnsupportedResumeMode', ...
            'Only resume_mode=''new_output'' is supported in this version.');
    end
    resume_path = char(string(config.resume_from_run_result));
    if ~is_absolute_path(resume_path)
        resume_path = fullfile(config.root_dir, resume_path);
    end
    if ~exist(resume_path, 'file')
        error('Run_GlobalXi_Simulink_Cycles:ResumeFileMissing', ...
            'resume_from_run_result does not exist: %s', resume_path);
    end
    prior_run_result = load_run_result_file(resume_path);
    prior_cycle_results = reshape(get_field(prior_run_result, 'cycle_results', struct([])), 1, []);
    if isempty(prior_cycle_results)
        error('Run_GlobalXi_Simulink_Cycles:ResumeNoCycles', ...
            'The resume run_result contains no cycle_results.');
    end
    prior_cycle_diagnostics = reshape(get_field(prior_run_result, 'cycle_diagnostics', struct([])), 1, []);
    prior_last_cycle_index = max(arrayfun(@(c) get_field(c, 'cycle_index', NaN), prior_cycle_results));
    if ~isfinite(prior_last_cycle_index)
        prior_last_cycle_index = numel(prior_cycle_results);
    end

    start_checkpoint_path = get_field(prior_run_result, 'final_checkpoint_path', '');
    if isempty(start_checkpoint_path)
        last_cycle = get_cycle_result_by_index(prior_cycle_results, prior_last_cycle_index);
        checkpoints = get_field(last_cycle, 'checkpoints', struct());
        start_checkpoint_path = get_field(checkpoints, 'cooldown_restart_balanced', '');
    end
    if isempty(start_checkpoint_path) || ~exist(start_checkpoint_path, 'file')
        error('Run_GlobalXi_Simulink_Cycles:ResumeCheckpointMissing', ...
            'Could not locate the final cooldown restart checkpoint for resume.');
    end

    [side_state, side_state_report] = recover_resume_side_state(prior_run_result, prior_last_cycle_index);
    config_mismatch_reasons = compare_resume_config(prior_run_result, config);
    if config.strict_config_match && ~isempty(config_mismatch_reasons)
        error('Run_GlobalXi_Simulink_Cycles:ResumeConfigMismatch', ...
            'Resume config mismatch: %s', strjoin(config_mismatch_reasons, '; '));
    end

    resume_context.is_resume = true;
    resume_context.resume_from_run_result = resume_path;
    resume_context.prior_run_result = prior_run_result;
    resume_context.prior_cycle_results = prior_cycle_results;
    resume_context.prior_cycle_diagnostics = prior_cycle_diagnostics;
    resume_context.prior_last_cycle_index = prior_last_cycle_index;
    resume_context.prior_walltime_s = get_field(prior_run_result, 'total_walltime_s', 0.0);
    resume_context.start_checkpoint_path = start_checkpoint_path;
    resume_context.prior_final_state = get_field(prior_run_result, 'final_state', struct());
    resume_context.side_state = side_state;
    resume_context.side_state_report = side_state_report;
    resume_context.config_mismatch_reasons = config_mismatch_reasons;
end

function config = finalize_resume_config(config, resume_context)
    if config.is_resume
        if isempty(config.additional_cycles)
            config.additional_cycles = config.nCycles;
        end
        if ~(isnumeric(config.additional_cycles) && isscalar(config.additional_cycles) && ...
                isfinite(config.additional_cycles) && config.additional_cycles > 0)
            error('Run_GlobalXi_Simulink_Cycles:InvalidAdditionalCycles', ...
                'additional_cycles must be a positive scalar for resume mode.');
        end
        config.additional_cycles = round(config.additional_cycles);
        config.prior_cycle_count = resume_context.prior_last_cycle_index;
        config.start_cycle_index = resume_context.prior_last_cycle_index + 1;
        config.end_cycle_index = config.start_cycle_index + config.additional_cycles - 1;
        config.total_target_cycles = resume_context.prior_last_cycle_index + config.additional_cycles;
        config.nCycles = config.total_target_cycles;
        config.initial_restart_checkpoint = resume_context.start_checkpoint_path;
        config.prior_walltime_s = resume_context.prior_walltime_s;
        config.resume_metadata = struct( ...
            'is_resume', true, ...
            'resume_from_run_result', resume_context.resume_from_run_result, ...
            'resume_mode', config.resume_mode, ...
            'strict_config_match', config.strict_config_match, ...
            'prior_cycle_count', resume_context.prior_last_cycle_index, ...
            'additional_cycles', config.additional_cycles, ...
            'start_cycle_index', config.start_cycle_index, ...
            'end_cycle_index', config.end_cycle_index, ...
            'start_checkpoint_path', resume_context.start_checkpoint_path, ...
            'config_match_ok', isempty(resume_context.config_mismatch_reasons), ...
            'config_mismatch_reasons', {resume_context.config_mismatch_reasons}, ...
            'side_state_report', resume_context.side_state_report);
    else
        config.additional_cycles = 0;
        config.prior_cycle_count = 0;
        config.start_cycle_index = 1;
        config.end_cycle_index = config.nCycles;
        config.total_target_cycles = config.nCycles;
        config.initial_restart_checkpoint = '';
        config.prior_walltime_s = 0.0;
        config.resume_metadata = struct( ...
            'is_resume', false, ...
            'resume_from_run_result', '', ...
            'resume_mode', '', ...
            'strict_config_match', config.strict_config_match, ...
            'prior_cycle_count', 0, ...
            'additional_cycles', 0, ...
            'start_cycle_index', 1, ...
            'end_cycle_index', config.nCycles, ...
            'start_checkpoint_path', '', ...
            'config_match_ok', true, ...
            'config_mismatch_reasons', {{}}, ...
            'side_state_report', struct());
    end
end

function context = empty_resume_context()
    context = struct();
    context.is_resume = false;
    context.resume_from_run_result = '';
    context.prior_run_result = struct();
    context.prior_cycle_results = struct([]);
    context.prior_cycle_diagnostics = struct([]);
    context.prior_last_cycle_index = 0;
    context.prior_walltime_s = 0.0;
    context.start_checkpoint_path = '';
    context.prior_final_state = struct();
    context.side_state = struct();
    context.side_state_report = struct();
    context.config_mismatch_reasons = {};
end

function report = prewarm_accelerator_cache_if_requested(config)
    exchange_options = get_field(config, 'exchange_options', struct());
    simulation_mode = lower(strtrim(char(string(get_field(exchange_options, 'simulation_mode', '')))));
    requested = logical(get_field(exchange_options, 'prewarm_accelerator_cache', false)) && ...
        strcmp(simulation_mode, 'accelerator');
    report = struct( ...
        'requested', requested, ...
        'success', false, ...
        'skipped_reason', '', ...
        'model_name', '', ...
        'model_path', '', ...
        'cache_folder', '', ...
        'codegen_folder', '', ...
        'walltime_s', NaN, ...
        'error_identifier', '', ...
        'error_message', '', ...
        'model_parameters', struct());
    if ~requested
        if logical(get_field(exchange_options, 'prewarm_accelerator_cache', false)) && ...
                any(strcmp(simulation_mode, {'rapid-accelerator', 'rapid_accelerator', 'rapid'}))
            report.skipped_reason = 'rapid_accelerator_abandoned_r37_variable_step_incompatible';
        else
            report.skipped_reason = 'prewarm_not_requested_or_non_accelerator_mode';
        end
        return;
    end

    model_path = char(string(get_field(exchange_options, 'model_path', ...
        fullfile(config.root_dir, 'nixunhuan_solver101_internal.slx'))));
    if ~is_absolute_path(model_path)
        model_path = fullfile(config.root_dir, model_path);
    end
    [~, model_name] = fileparts(model_path);
    cache_root = get_field(exchange_options, 'simulink_codegen_cache_root', '');
    if isempty(cache_root)
        cache_root = get_field(exchange_options, 'codegen_cache_root', '');
    end
    if isempty(cache_root)
        cache_root = fullfile(config.outputs_dir, 'codegen');
    else
        cache_root = char(string(cache_root));
    end
    cache_folder = fullfile(cache_root, 'cache');
    codegen_folder = fullfile(cache_root, 'codegen');
    report.model_name = model_name;
    report.model_path = model_path;
    report.cache_folder = cache_folder;
    report.codegen_folder = codegen_folder;

    prewarm_tic = tic;
    try
        if ~exist(cache_folder, 'dir')
            mkdir(cache_folder);
        end
        if ~exist(codegen_folder, 'dir')
            mkdir(codegen_folder);
        end
        Simulink.fileGenControl('set', ...
            'CacheFolder', cache_folder, ...
            'CodeGenFolder', codegen_folder, ...
            'createDir', true);
        assign_accelerator_prewarm_workspace_vars(model_path, config, exchange_options);
        load_system(model_path);
        prewarm_stop_time_s = get_field(exchange_options, 'accelerator_prewarm_stop_time_s', 0.001);
        simIn = Simulink.SimulationInput(model_name);
        simIn = simIn.setModelParameter('SimulationMode', 'accelerator');
        simIn = simIn.setModelParameter('StopTime', num2str(prewarm_stop_time_s));
        [simIn, report.model_parameters] = apply_accelerator_prewarm_model_parameters(simIn, exchange_options);
        sim(simIn);
        report.success = true;
    catch ME
        report.error_identifier = ME.identifier;
        report.error_message = ME.message;
    end
    report.walltime_s = toc(prewarm_tic);
end


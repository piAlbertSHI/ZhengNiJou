        failure_stage = explicit_stage;
        failure_stage_index = explicit_stage_index;
        if isfinite(get_field(runtime, 'cycle_index', NaN))
            failure_cycle = get_field(runtime, 'cycle_index', failure_cycle);
        end
        inference_source = ['error_message:', explicit_stage];
